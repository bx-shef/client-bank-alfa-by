// Единый источник правды о маршрутах приложения и о том, какие из них ПУБЛИЧНЫЕ (#425).
//
// Зачем отдельный модуль, а не список в `nuxt.config.ts`: одни и те же маршруты нужны в четырёх
// местах — пререндер, `sitemap.xml`, `robots.txt` и `noindex` на служебных страницах. Стоит им
// разъехаться, и ошибка получается тихой в обе стороны: sitemap с несуществующим URL (поисковик
// видит 404 и теряет доверие к карте) либо служебная страница, которую никто не закрыл и она уходит
// в выдачу. Сверку держит тест `tests/seoMetaPlacement.test.ts` («каждая страница объявлена ЛИБО
// публичной, ЛИБО служебной»): он сопоставляет этот список с реальными файлами в `app/pages/**` и
// падает, когда добавили страницу и забыли её классифицировать.
//
// ⚠ Импортируется из `nuxt.config.ts` — поэтому здесь НЕЛЬЗЯ использовать авто-импорты Nuxt,
// алиасы (`~/`) и рантайм-API. Только чистые константы и чистые функции.

/** Публичные страницы: индексируются, попадают в sitemap. */
export const PUBLIC_ROUTES = ['/', '/partners', '/help'] as const

/**
 * Служебные страницы: пререндерятся (нужны как статика для iframe портала и для оператора),
 * но индексироваться не должны.
 *
 * ⚠ Они отдаются обычным публичным HTTP — «непубличная» здесь значит «не для поиска», а не
 * «недоступна». Настоящая граница доступа — фрейм-токен на сервере и сессия оператора; `noindex`
 * лишь убирает их из выдачи, где они были бы дублями сниппета лендинга.
 */
export const SERVICE_ROUTES = ['/app', '/install', '/import', '/settings', '/queues', '/login'] as const

/**
 * Что перечислить в `nitro.prerender.routes`.
 *
 * `/` не включаем: он корень обхода (`crawlLinks: true`), и Nuxt берёт его сам. Остальное с лендинга
 * ссылками не достижимо — краулер туда не дойдёт, поэтому маршруты задаются явно.
 */
export const PRERENDER_ROUTES: string[] = [...SERVICE_ROUTES, ...PUBLIC_ROUTES.filter(r => r !== '/')]

/** Абсолютный URL страницы для canonical / sitemap / og:url. Пустой `siteUrl` → пустая строка:
 *  относительный canonical бессмыслен, а выдумывать домен опаснее, чем не ставить тег вовсе. */
export function absoluteUrl(siteUrl: string, route: string): string {
  const base = (siteUrl || '').trim().replace(/\/+$/, '')
  if (!base) return ''
  // Корень отдаём как «https://host/», остальное — без хвостового слеша: одна форма на весь сайт,
  // иначе canonical сам начнёт плодить дубли, ради борьбы с которыми его и ставят.
  return route === '/' ? `${base}/` : `${base}${route}`
}
