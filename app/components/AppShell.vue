<script setup lang="ts">
// Общая оболочка служебных экранов: `<B24App>` (темы, тосты, локаль b24ui) плюс контейнер страницы.
//
// ⚠ Живёт отдельным компонентом, а не копией в каждом layout'е: решений тут немного, но каждое
// оплачено измерением (см. `overflow-x-clip` ниже), и разъехавшаяся копия воспроизвела бы дефект
// ровно в половине приложения — то есть там, где его никто не искал бы.
import { ru } from '@bitrix24/b24ui-nuxt/locale'
</script>

<template>
  <B24App :locale="ru">
    <!-- ⚠ `overflow-x-clip`, а НЕ `overflow-x-hidden` (#530). Горизонтальное переполнение оба
         режут одинаково, но `hidden` вдобавок делает элемент СКРОЛЛПОРТОМ (CSS: при
         `overflow-x: hidden` вычисленный `overflow-y` перестаёт быть `visible`), а `clip` — нет.
         Замерено: под `hidden` любой `position: sticky` на всех служебных страницах молча
         переставал липнуть — он привязывался к этому контейнеру, а тот, будучи `min-h-screen`,
         сам никогда не прокручивается (прокручивается документ). Полоса разделов настроек уезжала
         вместе со страницей: после прокрутки на 900 px её верх оказывался на −740. -->
    <!-- ⚠ Ни `w-screen`, ни `bg-…` здесь БОЛЬШЕ НЕТ, и оба ушли по измеренной причине (#532).
         `bg-(--ui-color-base-bg)` — токена с таким именем в теме b24ui не существует вовсе (есть
         `--ui-color-bg-content-primary`/`-secondary` и шкала `base-0…90`), поэтому объявление
         вычислялось в `transparent`: замерено на собранной статике — `background-color` контейнера
         `rgba(0,0,0,0)`, фон рисует `body` из `main.css` (он же красит обе темы). Класс был
         украшением, которое ВЫГЛЯДЕЛО семантическим токеном.
         `w-screen` — это `100vw`, а он по спецификации считается «как если бы полос прокрутки не
         было»: на десктопе с классической полосой контейнер оказывается шире вьюпорта ровно на её
         ширину, и страница едет по горизонтали. У блочного `div` `w-full` — и так поведение по
         умолчанию, так что замена ничего не добавляет и ничего не ломает.
         ⚠ Проверить это здесь НЕ УДАЛОСЬ: headless-браузер во всех режимах отдаёт ОВЕРЛЕЙНЫЕ
         полосы (замерено: ширина полосы 0 при вертикальной прокрутке), и по той же причине
         визуальные эталоны CI такой дефект не поймают. Механизм известен из спецификации, цена
         правки нулевая — поэтому правим, но честно помечаем, что это не наблюдение. -->
    <div class="min-h-screen w-full overflow-x-clip">
      <slot />
    </div>
  </B24App>
</template>
