import { readonly, ref, type Ref } from 'vue'

// «Этот фрейм сейчас уедет на экран слайдера» — общий признак между мидлваром
// (`01.appSlider.global.ts`), который решение принимает, и страницей `/app`, которую портал
// открыл по дороге.
//
// ⚠ Заведён не ради косметики. Редирект фрейма слайдера отложен до `onNuxtReady`, а значит `/app`
// успевает смонтироваться и запустить свой `onMounted` — и он НЕ отменяется уходом со страницы.
// Дальше порядок детерминирован не в нашу пользу: `/app` перед `parent.setTitle` делает два
// сетевых запроса, `/settings` ставит свой заголовок сразу, — и вернувшийся позже `/app`
// перекрывает его обратно на «Выписка по счёту», а `fitWindow()` подгоняет высоту слайдера под
// вёрстку страницы, которой на экране уже нет. Снаружи это выглядит как «настройки открылись под
// чужим заголовком». Заодно снимается вспышка чужого экрана и три холостых запроса (у не-админа
// один из них — заведомый 403) на каждое открытие слайдера.
//
// Клиентский синглтон: страницы приложения client-only (SSG, layout `portal`), на сервере этот
// модуль не исполняется, поэтому межзапросной утечки состояния нет.
const target = ref<string | null>(null)

export function useSliderRedirect(): {
  /** Маршрут, на который фрейм уедет, либо `null`. */
  target: Readonly<Ref<string | null>>
  /** Объявить, что фрейм уезжает: вызывает мидлвар, ДО монтирования страницы. */
  claim: (route: string) => void
} {
  return {
    target: readonly(target),
    claim: (route: string) => {
      target.value = route
    }
  }
}
