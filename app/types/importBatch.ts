// Результат ОДНОЙ ручной загрузки файла (#417) — контракт между backend и UI.
//
// Зачем отдельно от `ImportRunSummary` (последний прогон портала): тот один на портал и
// перезаписывается любым прогоном — в том числе автоопросом банка, — поэтому по нему нельзя
// сказать, что стало с ФАЙЛОМ, который сотрудник только что загрузил. Раньше UI отвечал ему
// «принято в обработку» и замолкал навсегда: запись в CRM идёт в фоне, и узнать её исход было
// нельзя ни из интерфейса, ни вообще.

/**
 * Состояние загрузки:
 * - `queued` — файл принят, воркер до него ещё не дошёл;
 * - `ok` — разобран и обработан (счётчики заполнены);
 * - `error` — не разобран или обработка упала (`error` несёт причину).
 *
 * Промежуточного «разбирается» нет намеренно: между постановкой в очередь и итогом у нас нет
 * честного признака прогресса, а рисовать его — то же враньё, что и удалённый демо-мок (#415).
 */
export type ImportBatchState = 'queued' | 'ok' | 'error'

export interface ImportBatchResult {
  /** Ключ загрузки — sha256 содержимого файла (его же отдаёт `POST /api/import`). */
  batchId: string
  state: ImportBatchState
  /** Имя файла, как его прислал браузер (для подписи в списке). */
  fileName: string
  /** Операций разобрано сервером (авторитетный разбор, не браузерный предпросмотр). */
  operations: number
  /** Дел записано в CRM. */
  created: number
  /** Отправлено уведомлений в чат (⊆ created). */
  notified: number
  /** Операций, по которым не нашлась компания-плательщик. */
  unmatched: number
  /** Причина, если `state === 'error'`. */
  error: string
  /** Когда запись последний раз обновлялась (ISO). */
  updatedAt: string | null
}
