// Сообщение администратору, когда не удалось добавить счёт к подключению (#23).
//
// Отдельный чистый модуль по той же причине, что и `setAccountError.ts`: `frameFetchError`
// подклеил бы английский текст сервера, а здесь ровно тот случай, ради которого сообщение и
// читают — исходы РАЗНЫЕ, и каждый требует своего следующего шага, а не общего «попробуйте ещё».
//
// ⚠ Три из четырёх отказов отвечают 409, и слить их в один текст было бы худшим решением: «счёт
// уже подключён» лечится другим номером, «список устарел» — обновлением страницы, а «подключение
// заведено до поддержки нескольких счетов» — повторным подключением, то есть походом ВЛАДЕЛЬЦА
// СЧЁТА в интернет-банк. Одинаковая фраза на все три отправила бы человека не туда дважды из трёх.
// Различить их можно только по телу ответа, поэтому здесь смотрят и на него.

/** HTTP-статус из отказа `$fetch` (FetchError) либо axios-подобной ошибки. */
export function addAccountErrorStatus(e: unknown): number | undefined {
  const err = e as { statusCode?: number, response?: { status?: number } } | null | undefined
  return err?.statusCode ?? err?.response?.status
}

/** Текст ошибки, который вернул сервер (для разведения одинаковых статусов). */
function serverError(e: unknown): string {
  const err = e as { data?: { error?: unknown } } | null | undefined
  return typeof err?.data?.error === 'string' ? err.data.error : ''
}

/** Текст для администратора по ответу `/api/bank/add-account`. */
export function addAccountErrorMessage(e: unknown): string {
  const status = addAccountErrorStatus(e)
  const reason = serverError(e)
  // ⚠ Цена названа честно: «подключите заново» здесь означает поход ВЛАДЕЛЬЦА СЧЁТА в интернет-банк.
  // Умолчать об этом — то же самое, что молчать про пропущенные дни на паузе (#576).
  if (status === 409 && reason.includes('predates')) {
    return 'Это подключение сделано до появления нескольких счетов на одно разрешение банка. '
      + 'Чтобы добавлять счета без повторного входа, подключите банк заново — потребуется '
      + 'однократная авторизация владельца счёта в интернет-банке.'
  }
  if (status === 409 && reason.includes('out of date')) {
    return 'Список устарел — обновите страницу и повторите.'
  }
  // Случай в интерфейсе недостижим (кнопка скрыта), но текст читают именно тогда, когда
  // недостижимое случилось, — поэтому он говорит и ГДЕ искать.
  if (status === 409 && reason.includes('choose the account')) {
    return 'Сначала укажите номер счёта у самого подключения — в строке выше, — а потом добавляйте следующие.'
  }
  // ⚠ «Выберите другой номер» — совет для опечатки. Если номер тот самый, он оставлял в тупике.
  if (status === 409) return 'Этот счёт уже есть в списке подключённых выше — добавлять его повторно не нужно.'
  // Слово в слово с 409 «список устарел»: действие одно и то же, а кнопки «обновить список» в
  // интерфейсе нет вовсе — значит и звать её нельзя.
  if (status === 404) return 'Подключение не найдено — возможно, его уже отключили. Обновите страницу.'
  if (status === 403) return 'Добавлять счета может только администратор портала.'
  // ⚠ 503 — «сейчас занято, через несколько секунд пройдёт» (строку держит обновление токена), а не
  // тупик: смешать его с 409 значит приучить либо повторять там, где повтор бесполезен, либо
  // сдаваться там, где хватило бы второго клика (#509).
  if (status === 503) return 'Подключение сейчас обновляется — повторите через несколько секунд.'
  // ⚠ Самая вероятная причина 400 — скопированный из реквизитов номер С ПРОБЕЛАМИ, то есть ровно та
  // форма, в которой он там и лежит. «Допустимы буквы и цифры» человек читает, глядя на буквы и
  // цифры, и остаётся в тупике.
  if (status === 400) {
    return 'В номере есть посторонние символы. Оставьте только буквы и цифры — уберите пробелы, '
      + 'дефисы и другие разделители.'
  }
  // ⚠ У фолбэка обязан быть ВЫХОД: «попробуйте ещё раз» на втором повторе не даёт ничего.
  return 'Не удалось добавить счёт. Проверьте состояние подключения в списке выше, а если не '
    + 'получается — подключите банк заново.'
}
