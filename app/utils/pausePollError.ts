// Сообщение администратору, когда не удалось переключить паузу автоопроса (#576).
//
// Отдельно от `frameFetchError` по той же причине, что `disconnectError.ts`/`setAccountError.ts`:
// тот подклеивает английский текст сервера, а среди исходов есть советы, ради которых сообщение и
// читают. Форма та же: статус → текст, чисто и под тестом.

import { disconnectErrorStatus } from './disconnectError'

/**
 * Текст по статусу ответа `/api/bank/pause`.
 *
 * ⚠ 404 и 409 значат РАЗНОЕ, и слить их нельзя. 409 — «строка изменилась под вами» (подключению
 * назначили счёт, пока список висел на экране): список надо обновить, подключение живо. 404 —
 * подключения больше нет вовсе (кто-то отключил его из другой вкладки): обновление списка покажет
 * пустое место, и ставить на паузу уже нечего. Один текст на оба случая отправил бы человека
 * обновлять список ради строки, которой не существует.
 *
 * ⚠ Текст говорит про ДЕЙСТВИЕ, а не про состояние: администратор нажал переключатель и хочет
 * знать, что делать дальше, а не какой у нас код ответа.
 */
export function pausePollErrorMessage(e: unknown, paused: boolean): string {
  const status = disconnectErrorStatus(e)
  const what = paused ? 'приостановить опрос' : 'возобновить опрос'
  if (status === 409) return 'Список устарел: подключение успело измениться. Обновите список и повторите.'
  if (status === 404) return 'Подключение уже отключено — обновите список.'
  if (status === 403) return 'Управлять опросом банка может только администратор портала.'
  if (status === 400) return `Не удалось ${what}: обновите список и повторите.`
  return `Не удалось ${what} — попробуйте ещё раз.`
}
