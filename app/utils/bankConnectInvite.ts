// Сообщение, которым администратор передаёт подключение банка ВЛАДЕЛЬЦУ СЧЁТА (#19). Чистое ядро:
// текст собирается здесь, транспорт — у вызывающего (`server/utils/bankInviteSend.ts`).
//
// ⚠ ДВА БАНКА — ДВА РАЗНЫХ СООБЩЕНИЯ, и это не оформление. У Приора подключение завершает САМ
// владелец счёта: он открывает ссылку, входит в интернет-банк и подтверждает согласие, — поэтому
// в сообщении главное ссылка и её срок. У Альфы (#488) подключение идёт КЛЮЧОМ API: владелец
// счёта выпускает ключ в своём кабинете и сам вставляет его на нашем экране внутри портала, поэтому
// в сообщении главное — шаги кабинета банка. Одно «универсальное» сообщение на оба банка врало бы
// ровно половине получателей.
//
// ⚠ ТЕКСТ НАШ ЦЕЛИКОМ — ни одного поля, которое пишет плательщик или банк. Поэтому
// `neutralizeBb` здесь не нужен (ему нечего нейтрализовать), а вот подставляемые значения
// проверяются: негодные ⇒ `null`, сообщение не собирается. Полуверная инструкция — это человек,
// который сходил в банк зря.
//
// ⚠ СРОК НАЗЫВАЕТСЯ ТОЛЬКО ДЛИТЕЛЬНОСТЬЮ — «около N минут с момента отправки», и НИКОГДА стенным
// временем (решение владельца, 2026-09-13). Первая редакция добавляла «до 08:15 по Минску»: банки
// белорусские, и казалось, что так удобнее. Но получатель — сотрудник портала, а он может сидеть
// где угодно, хоть на Чукотке, и время чужого пояса он прочитает как своё. Длительность верна в
// любом поясе, а отсчитывать её есть от чего: рядом стоит время сообщения в чате.

import { BANK_LABELS } from './bankLabels'
import type { ChatAttach, ChatAttachment, ChatImageBlock } from './chatAttach'
import type { BankProviderId } from '../types/statement'

/** Ссылка годна к отправке: абсолютная https и без пробелов (перенос строки в мессенджере ломает
 *  её молча, а «почти ссылка» выглядит как наша поломка). */
function isSendableLink(url: string): boolean {
  return /^https:\/\/[^\s/]+\/\S*$/i.test(url.trim())
}

export interface PriorInviteInput {
  /** Готовый authorize-URL банка. */
  link: string
  /** Сколько ссылка живёт, в минутах — то же число, что видит админ на экране. */
  ttlMin: number
}

/** Адрес внутри BB-кода `[URL=…]`: квадратная скобка в нём закрыла бы тег раньше времени, и хвост
 *  ссылки уехал бы в текст — молча и в чужой чат. У адреса Приора скобок нет (параметры кодирует
 *  `URLSearchParams`), но правило стоит здесь, а не на доверии к вызывающему. */
function bbLinkTarget(url: string): string {
  return url.replace(/\[/g, '%5B').replace(/\]/g, '%5D')
}

/**
 * Приглашение для Приорбанка: шаги от ссылки до страницы возврата, срок ссылки и прямое «пароль
 * вводится только на сайте банка». Негодная ссылка ⇒ `null`.
 *
 * ⚠ ССЫЛКА СПРЯТАНА ПОД ТЕКСТ, и это не украшение. Адрес авторизации несёт подписанный запрос к
 * банку и занимает больше двух тысяч знаков (замерено: 2219), то есть голой строкой в чате это три
 * десятка строк сплошных символов, в которых теряются сами шаги. Домен при этом НАЗВАН в тексте
 * ссылки: сообщение просит ввести пароль от банка, и человек вправе видеть, куда его ведут, не
 * наводя мышь (на телефоне навести нечем).
 *
 * ⚠ Шаг 4 называет страницы возврата ДОСЛОВНО — это заголовки из `bankConnectCallback.ts`, и
 * синхронность держит тест. Без этого шага владелец счёта оставался один на один со страницей
 * «Осталось выбрать счёт в настройках приложения», то есть с делом, которое ему не по правам: счёт
 * выбирает администратор.
 */
export function buildPriorInvite(input: PriorInviteInput): string | null {
  const link = (input.link ?? '').trim()
  if (!isSendableLink(link)) return null
  let host: string
  try {
    host = new URL(link).hostname
  } catch {
    return null
  }
  const ttl = Number.isFinite(input.ttlMin) && input.ttlMin > 0 ? Math.round(input.ttlMin) : 0
  const lines = [
    `[B]Подключение банка «${BANK_LABELS['prior-by']}» к Битрикс24[/B]`,
    'Администратор портала настраивает импорт выписки. Нужно ваше подтверждение как владельца счёта.'
  ]
  // ⚠ Срок — ДО шагов: пятнадцать минут это мало, и узнать о них стоит прежде, чем начинать.
  // Строка условна, а пустые строки ниже — нет: они разделяют блоки. Поэтому добавляем по условию,
  // а не фильтруем список от пустых (фильтр слепил бы инструкцию в сплошной абзац).
  if (ttl) lines.push(`[B]Ссылка действует около ${ttl} минут с момента отправки этого сообщения.[/B]`)
  lines.push(
    '',
    `1. Откройте [URL=${bbLinkTarget(link)}]страницу входа Приорбанка (${host})[/URL].`,
    '2. Войдите логином и паролем от интернет-банка Приорбанка.',
    '3. Подтвердите доступ приложения к выписке по счёту.',
    '4. Откроется страница «Банк подключён» — это всё, вкладку можно закрыть. Счёт в приложении выберет администратор.',
    '',
    `${ttl ? 'Не успели или увидели' : 'Увидели'} «Не удалось подключить» — попросите администратора прислать новую ссылку.`,
    'Пароль от интернет-банка вводится только на сайте банка: приложение его не видит и не хранит.'
  )
  return lines.join('\n')
}

export interface AlfaInviteInput {
  /** Наш `client_id`, который банк спрашивает при выпуске ключа. */
  clientId: string
  /** ВНУТРЕННЯЯ ссылка портала на экран ввода ключа (`/marketplace/view/<код>/?params[place]=…`).
   *  Пусто ⇒ сообщение не собирается: без неё ключ некуда девать, кроме как переслать в чат. */
  link: string
  /** Сколько ссылка живёт, в часах. */
  ttlHours: number
}

/** Проверенные поля приглашения Альфы или `null`. Общая для обеих раскладок: негодный ввод обязан
 *  давать один и тот же отказ, с картинками ли собираем сообщение или без. */
function alfaInviteFields(input: AlfaInviteInput): { clientId: string, link: string, ttl: number } | null {
  const clientId = (input.clientId ?? '').trim()
  if (!clientId || /\s/.test(clientId)) return null
  const link = (input.link ?? '').trim()
  if (!isSendableLink(link)) return null
  const ttl = Number.isFinite(input.ttlHours) && input.ttlHours > 0 ? Math.round(input.ttlHours) : 0
  return { clientId, link, ttl }
}

/**
 * Шаги выпуска ключа — ОДИН источник на обе раскладки сообщения.
 *
 * ⚠ Шаги ДОСЛОВНО повторяют надписи кабинета банка — ровно как в карточке подключения. Пересказ
 * своими словами («сгенерируйте токен») заставляет искать несуществующий пункт меню.
 * ⚠ Две копии шагов разошлись бы молча, и заметить это можно было бы только на отказе портала,
 * когда уходит запасной текст, — то есть в случае, который никто не видит.
 * ⚠ Различаются раскладки одним словом: без картинок ссылка стоит ПОСЛЕ шагов, с картинками — в
 * тексте сообщения, то есть НАД вложением с шагами.
 */
function alfaKeySteps(clientId: string, linkIs: 'ниже' | 'выше'): string[] {
  return [
    '1. Войдите в [B]Альфа Бизнес Онлайн[/B].',
    '2. [B]Настройки[/B] → вкладка [B]Open API[/B] → кнопка [B]«Сгенерировать ключ API»[/B].',
    `3. [B]НАЗВАНИЕ[/B] — любое понятное (например, «Подключение к Б24»), [B]CLIENT ID[/B] — ${clientId}, [B]ТИП КЛЮЧА[/B] — [B]Постоянный ключ[/B].`,
    '4. Согласитесь с условиями и нажмите [B]«Сгенерировать ключ»[/B].',
    '5. Раскройте строку ключа и нажмите [B]«Скопировать ключ»[/B].',
    `6. Откройте ссылку ${linkIs} и вставьте ключ в поле. Готово.`
  ]
}

const ALFA_INVITE_TITLE = `[B]Ключ API «${BANK_LABELS['alfa-by']}» для Битрикс24[/B]`

/** Предупреждения после ссылки — общие для обеих раскладок: ссылка в обеих стоит НАД ними. */
function alfaInviteWarnings(ttl: number): string[] {
  // ⚠ Ключ НИКОМУ НЕ ПЕРЕСЫЛАЕТСЯ, и это главное отличие от первой редакции, где шаг 5 гласил
  // «передайте его администратору портала». Ключ бессрочен и не ротируется: посланный в чат, он
  // остаётся в истории портала навсегда, а отозвать его можно только в кабинете банка. Теперь он
  // вводится там же, где выпущен, — и админ его не видит вовсе.
  const lines = ['[B]Ключ никому не пересылайте[/B] — ни в чат, ни администратору: вставьте его сами по ссылке выше. Он открывает доступ к выписке по счёту.']
  if (ttl) lines.push(`Ссылка действует около ${ttl} ч. Если не успели — попросите администратора прислать новую.`)
  lines.push('Ключ бессрочный — заблокировать или отозвать его можно в любой момент там же, в кабинете банка.')
  return lines
}

/**
 * Приглашение для Альфа-Банка ПОЛНЫМ ТЕКСТОМ: вступление, шаги, ссылка, предупреждения.
 *
 * Уходит само по себе, когда картинки приложить нельзя (адрес приложения непригоден для ссылки), и
 * запасным текстом, когда портал вложение с шагами отверг (`buildAlfaInviteGuide`).
 *
 * ⚠ Без `client_id` сообщение не собирается: без него владелец счёта дойдёт до формы банка и
 * встанет на обязательном поле.
 */
export function buildAlfaInvite(input: AlfaInviteInput): string | null {
  const f = alfaInviteFields(input)
  if (!f) return null
  return [
    ALFA_INVITE_TITLE,
    'Администратор портала настраивает импорт выписки. Нужно, чтобы вы выпустили ключ API в кабинете банка и вставили его на своём экране — ссылка в конце.',
    '',
    ...alfaKeySteps(f.clientId, 'ниже'),
    '',
    f.link,
    '',
    ...alfaInviteWarnings(f.ttl)
  ].join('\n')
}

/** Одна картинка шага для вложения в сообщение. Размеры зашиты рядом с файлом намеренно: Битрикс24
 *  просит `WIDTH`/`HEIGHT`, чтобы не дёргать вёрстку чата на догрузке, а узнать их из PNG на лету
 *  нам негде — сообщение собирается на сервере, без доступа к статике лендинга. */
export interface GuideShot {
  /** Путь внутри статики лендинга, без ведущей косой черты. */
  readonly file: string
  readonly width: number
  readonly height: number
  /** Подпись в чате. */
  readonly name: string
  /** После какого шага инструкции стоит снимок — номер шага из `alfaKeySteps`. */
  readonly afterStep: number
}

/**
 * Картинки к инструкции Альфы (#19) — СКРИНШОТЫ КАБИНЕТА БАНКА со стрелками на нужные кнопки,
 * присланные владельцем 2026-09-17 («эти скриншоты нужно в инструкцию внести»).
 *
 * ⚠ НЕ ПЕРЕРИСОВЫВАТЬ. Первая редакция (#726) заменила их нарисованными схемами «в нашей
 * стилистике» — по доводам агента (чужой портал, форк со своим `client_id`), которые владелец не
 * спрашивал и не принимал; он вернул скриншоты. Что показывать получателю — решение владельца.
 * Снимки лежат как присланы: первый и третий пришли в WebP и переведены в PNG без потерь
 * (пиксели те же), второй — байт в байт.
 *
 * ⚠ На втором снимке виден НАШ `client_id` — тот же, что сообщение называет текстом. Клон со
 * своим `client_id` обязан заменить снимки своими, иначе картинка разойдётся с текстом.
 * ⚠ Идентификатор ключа на третьем снимке замаскирован владельцем; счетов, УНП и имён на снимках
 * нет. Это важно: репозиторий публичный, и `public/guide/` уезжает в него как есть.
 *
 * ⚠ Имена файлов НОВЫЕ, а не прежние `alfa-key-N.png`: под прежним адресом лежала нарисованная
 * картинка, и новое сообщение не должно получить её из чьего-нибудь кэша.
 *
 * ⚠ Список ЗАКРЫТ и сверяется с содержимым `public/guide/` тестом: ссылка на несуществующий файл
 * в чате клиента — это битая картинка НАВСЕГДА, сообщение задним числом не правится.
 */
export const ALFA_KEY_SHOTS: readonly GuideShot[] = [
  { file: 'guide/alfa-cabinet-1.png', width: 1361, height: 993, name: 'Шаг 2 — Настройки → Open API → «Сгенерировать ключ API»', afterStep: 2 },
  { file: 'guide/alfa-cabinet-2.png', width: 692, height: 741, name: 'Шаги 3–4 — форма «Генерация ключа API»', afterStep: 4 },
  { file: 'guide/alfa-cabinet-3.png', width: 1633, height: 998, name: 'Шаг 5 — раскройте строку ключа → «Скопировать ключ»', afterStep: 5 }
]

/** Инструкция Альфы с картинками: короткий текст и вложение с шагами. */
export interface AlfaInviteGuide {
  /** Текст сообщения: вступление, ссылка, предупреждения. Шагов в нём НЕТ — они во вложении. */
  text: string
  /** Шаги вперемешку со снимками + полный текст на случай, когда портал вложение отверг. */
  attachment: ChatAttachment
}

/**
 * Инструкция Альфы с картинками (#19): шаги переезжают во вложение, и за шагом сразу идёт его
 * снимок; в тексте сообщения остаются вступление, ссылка и предупреждения (решение владельца
 * 2026-09-26, вариант «шаг — снимок»).
 *
 * ⚠ Прежняя раскладка — шаги текстом, а все три снимка одним блоком `IMAGE` в конце — на живом
 * портале рисовала их плиткой в ряд с обрезкой (замер владельца 2026-09-26): стрелки на кнопки
 * уходили за край, и связь «какой снимок к какому шагу» читатель восстанавливал сам.
 *
 * @param siteUrl публичный адрес статики (`NUXT_PUBLIC_SITE_URL`). Пусто или не абсолютный https ⇒
 *        `null`: вызывающий шлёт полный текст `buildAlfaInvite` без картинок.
 *
 * ⚠ НЕ «почти ссылка». Битрикс тянет картинку САМ и по относительному или http-адресу покажет
 * пустое место в чате клиента — молча и навсегда. Поэтому проверка тут такая же строгая, как у
 * `isSendableLink`.
 *
 * ⚠ `PREVIEW` = `LINK` осознанно: уменьшенных копий мы не держим, а поле рекомендовано заполнять —
 * без него часть клиентов берёт `LINK` сама, часть не показывает превью вовсе.
 */
export function buildAlfaInviteGuide(input: AlfaInviteInput, siteUrl: string): AlfaInviteGuide | null {
  const f = alfaInviteFields(input)
  const fallbackText = buildAlfaInvite(input)
  if (!f || !fallbackText) return null
  const base = (siteUrl ?? '').trim().replace(/\/+$/, '')
  if (!/^https:\/\/[^\s/]+(\/[^\s]*)?$/i.test(base)) return null

  const image = (shot: GuideShot): ChatImageBlock => {
    const link = `${base}/${shot.file}`
    return { IMAGE: [{ NAME: shot.name, LINK: link, PREVIEW: link, WIDTH: shot.width, HEIGHT: shot.height }] }
  }
  // Шаги копятся в текстовый блок, пока за очередным шагом не встанет снимок. ⚠ Строки блока
  // склеиваются `[BR]`, а не `\n`: во вложении перенос строки — BB-код, а не символ.
  const attach: ChatAttach = []
  let pending: string[] = []
  alfaKeySteps(f.clientId, 'выше').forEach((line, i) => {
    pending.push(line)
    const shot = ALFA_KEY_SHOTS.find(s => s.afterStep === i + 1)
    if (!shot) return
    attach.push({ MESSAGE: pending.join('[BR]') }, image(shot))
    pending = []
  })
  if (pending.length) attach.push({ MESSAGE: pending.join('[BR]') })

  const text = [
    ALFA_INVITE_TITLE,
    'Администратор портала настраивает импорт выписки. Нужно, чтобы вы выпустили ключ API в кабинете банка (по шагам ниже) и вставили его на своём экране по этой ссылке:',
    '',
    f.link,
    '',
    ...alfaInviteWarnings(f.ttl)
  ].join('\n')
  return { text, attachment: { attach, fallbackText } }
}

/** Что отправляем по конкретному банку. Исчерпывающий разбор: новый подключаемый банк не
 *  скомпилируется, пока ему не напишут собственный текст. */
export function buildBankInvite(
  provider: BankProviderId,
  input: { prior?: PriorInviteInput, alfa?: AlfaInviteInput }
): string | null {
  switch (provider) {
    case 'prior-by':
      return input.prior ? buildPriorInvite(input.prior) : null
    case 'alfa-by':
      return input.alfa ? buildAlfaInvite(input.alfa) : null
    case 'manual':
      // Ручная загрузка файла — банка нет, приглашать некуда.
      return null
  }
}
