// Сообщение, которым администратор передаёт подключение банка ВЛАДЕЛЬЦУ СЧЁТА (#19). Чистое ядро:
// текст собирается здесь, транспорт — у вызывающего (`server/utils/bankInviteSend.ts`).
//
// ⚠ ДВА БАНКА — ДВА РАЗНЫХ СООБЩЕНИЯ, и это не оформление. У Приора подключение завершает САМ
// владелец счёта: он открывает ссылку, входит в интернет-банк и подтверждает согласие, — поэтому
// в сообщении главное ссылка и её срок. У Альфы (#488) подключение идёт КЛЮЧОМ API: владелец
// счёта выпускает ключ в своём кабинете и отдаёт его администратору, ссылки не существует вовсе.
// Одно «универсальное» сообщение на оба банка врало бы ровно половине получателей.
//
// ⚠ ТЕКСТ НАШ ЦЕЛИКОМ — ни одного поля, которое пишет плательщик или банк. Поэтому
// `neutralizeBb` здесь не нужен (ему нечего нейтрализовать), а вот подставляемые значения
// проверяются: негодные ⇒ `null`, сообщение не собирается. Полуверная инструкция — это человек,
// который сходил в банк зря.
//
// ⚠ СРОК НАЗЫВАЕТСЯ ТОЛЬКО ДЛИТЕЛЬНОСТЬЮ — «около N минут с момента отправки», и НИКОГДА стенным
// временем (решение владельца, 2026-09-13). Первая редакция добавляла «до 08:15 по Минску»: банки
// белорусские, и казалось, что так удобнее. Но получатель — сотрудник портала, а он может сидеть
// где угодно, хоть на Чукотке, и время чужого пояса он прочитает как своё. Длительность верна в
// любом поясе, а отсчитывать её есть от чего: рядом стоит время сообщения в чате.

import { BANK_LABELS } from './bankLabels'
import type { BankProviderId } from '../types/statement'

/** Ссылка годна к отправке: абсолютная https и без пробелов (перенос строки в мессенджере ломает
 *  её молча, а «почти ссылка» выглядит как наша поломка). */
function isSendableLink(url: string): boolean {
  return /^https:\/\/[^\s/]+\/\S*$/i.test(url.trim())
}

export interface PriorInviteInput {
  /** Готовый authorize-URL банка. */
  link: string
  /** Сколько ссылка живёт, в минутах — то же число, что видит админ на экране. */
  ttlMin: number
}

/**
 * Приглашение для Приорбанка: ссылка, срок, и прямое «пароль вводится только на сайте банка».
 * Негодная ссылка ⇒ `null`.
 */
export function buildPriorInvite(input: PriorInviteInput): string | null {
  const link = (input.link ?? '').trim()
  if (!isSendableLink(link)) return null
  const ttl = Number.isFinite(input.ttlMin) && input.ttlMin > 0 ? Math.round(input.ttlMin) : 0
  const lines = [
    `[B]Подключение «${BANK_LABELS['prior-by']}» к Битрикс24[/B]`,
    'Администратор портала настраивает импорт выписки. Нужно ваше подтверждение как владельца счёта.',
    '',
    '1. Откройте ссылку ниже.',
    '2. Войдите в интернет-банк.',
    '3. Подтвердите доступ приложения к выписке по счёту.',
    '',
    link,
    ''
  ]
  // ⚠ Строка срока УСЛОВНА, а пустые строки выше — нет: они разделяют блоки. Поэтому добавляем
  // по условию, а не фильтруем список от пустых (фильтр слепил бы инструкцию в сплошной абзац).
  if (ttl) lines.push(`[B]Ссылка действует около ${ttl} минут с момента отправки этого сообщения.[/B] Если не успели — попросите администратора прислать новую.`)
  lines.push('Пароль от интернет-банка вводится только на сайте банка: приложение его не видит и не хранит.')
  return lines.join('\n')
}

export interface AlfaInviteInput {
  /** Наш `client_id`, который банк спрашивает при выпуске ключа. */
  clientId: string
  /** ВНУТРЕННЯЯ ссылка портала на экран ввода ключа (`/marketplace/view/<код>/?params[place]=…`).
   *  Пусто ⇒ сообщение не собирается: без неё ключ некуда девать, кроме как переслать в чат. */
  link: string
  /** Сколько ссылка живёт, в часах. */
  ttlHours: number
}

/**
 * Приглашение для Альфа-Банка: инструкция по выпуску ключа API.
 *
 * ⚠ Шаги ДОСЛОВНО повторяют надписи кабинета банка — ровно как в карточке подключения. Пересказ
 * своими словами («сгенерируйте токен») заставляет искать несуществующий пункт меню.
 * ⚠ Без `client_id` сообщение не собирается: без него владелец счёта дойдёт до формы банка и
 * встанет на обязательном поле.
 */
export function buildAlfaInvite(input: AlfaInviteInput): string | null {
  const clientId = (input.clientId ?? '').trim()
  if (!clientId || /\s/.test(clientId)) return null
  const link = (input.link ?? '').trim()
  if (!isSendableLink(link)) return null
  const ttl = Number.isFinite(input.ttlHours) && input.ttlHours > 0 ? Math.round(input.ttlHours) : 0
  const lines = [
    `[B]Ключ API «${BANK_LABELS['alfa-by']}» для Битрикс24[/B]`,
    'Администратор портала настраивает импорт выписки. Нужно, чтобы вы выпустили ключ API в кабинете банка и вставили его на своём экране — ссылка в конце.',
    '',
    '1. Войдите в [B]Альфа Бизнес Онлайн[/B].',
    '2. [B]Настройки[/B] → вкладка [B]Open API[/B] → кнопка [B]«Сгенерировать ключ API»[/B].',
    `3. [B]НАЗВАНИЕ[/B] — любое понятное (например, «Подключение к Б24»), [B]CLIENT ID[/B] — ${clientId}, [B]ТИП КЛЮЧА[/B] — [B]Постоянный ключ[/B].`,
    '4. Согласитесь с условиями и нажмите [B]«Сгенерировать ключ»[/B].',
    '5. Раскройте строку ключа и нажмите [B]«Скопировать ключ»[/B].',
    '6. Откройте ссылку ниже и вставьте ключ в поле. Готово.',
    '',
    link,
    ''
  ]
  // ⚠ Ключ НИКОМУ НЕ ПЕРЕСЫЛАЕТСЯ, и это главное отличие от первой редакции, где шаг 5 гласил
  // «передайте его администратору портала». Ключ бессрочен и не ротируется: посланный в чат, он
  // остаётся в истории портала навсегда, а отозвать его можно только в кабинете банка. Теперь он
  // вводится там же, где выпущен, — и админ его не видит вовсе.
  lines.push('[B]Ключ никому не пересылайте[/B] — ни в чат, ни администратору: вставьте его сами по ссылке выше. Он открывает доступ к выписке по счёту.')
  if (ttl) lines.push(`Ссылка действует около ${ttl} ч. Если не успели — попросите администратора прислать новую.`)
  lines.push('Ключ бессрочный — заблокировать или отозвать его можно в любой момент там же, в кабинете банка.')
  return lines.join('\n')
}

/** Одна картинка шага для вложения в сообщение. Размеры зашиты рядом с файлом намеренно: Битрикс24
 *  просит `WIDTH`/`HEIGHT`, чтобы не дёргать вёрстку чата на догрузке, а узнать их из PNG на лету
 *  нам негде — сообщение собирается на сервере, без доступа к статике лендинга. */
export interface GuideShot {
  /** Путь внутри статики лендинга, без ведущей косой черты. */
  readonly file: string
  readonly width: number
  readonly height: number
  /** Подпись в чате. */
  readonly name: string
}

/**
 * Картинки к инструкции Альфы (#19). Генерируются `pnpm guide:shots` в `public/guide/`.
 *
 * ⚠ КАРТИНКИ НАРИСОВАНЫ, А НЕ СФОТОГРАФИРОВАНЫ, и это не про удобство. Они уезжают в чат ЧУЖОГО
 * портала, значит обязаны быть (а) нашими навсегда, (б) без единого реального ключа, счёта и
 * названия компании и (в) одинаковыми для всех порталов, включая форк со своим `client_id`.
 * Снимок настоящего кабинета не проходит ни по одному пункту: он несёт данные того, кто его снял,
 * а поле CLIENT ID на нём спорило бы с тем значением, которое сообщение называет ТЕКСТОМ.
 *
 * ⚠ ЗНАЧЕНИЯ `client_id` В КАРТИНКЕ НЕТ — оно разное у каждой установки и живёт в тексте. Вшитое
 * в PNG, оно молча устарело бы у всех, кроме нас.
 *
 * ⚠ Список ЗАКРЫТ и сверяется с содержимым `public/guide/` тестом: ссылка на несуществующий файл
 * в чате клиента — это битая картинка НАВСЕГДА, сообщение задним числом не правится.
 */
export const ALFA_KEY_SHOTS: readonly GuideShot[] = [
  { file: 'guide/alfa-key-1.png', width: 960, height: 460, name: 'Шаг 1 — Настройки → Open API' },
  { file: 'guide/alfa-key-2.png', width: 960, height: 560, name: 'Шаг 2 — Генерация ключа API' },
  { file: 'guide/alfa-key-3.png', width: 960, height: 440, name: 'Шаг 3 — Скопировать ключ' }
]

/** Вложение сообщения Битрикс24 (`ATTACH`) — ровно тот кусок формата, который мы используем. */
export interface ChatImageAttach {
  IMAGE: { NAME: string, LINK: string, PREVIEW: string, WIDTH: number, HEIGHT: number }[]
}

/**
 * Вложение с картинками шагов для инструкции Альфы.
 *
 * @param siteUrl публичный адрес статики (`NUXT_PUBLIC_SITE_URL`). Пусто или не абсолютный https ⇒
 *        `null`: картинок не будет, текст уйдёт как прежде.
 *
 * ⚠ НЕ «почти ссылка». Битрикс тянет картинку САМ и по относительному или http-адресу покажет
 * пустое место в чате клиента — молча и навсегда. Поэтому проверка тут такая же строгая, как у
 * `isSendableLink`, и отрицательный ответ (`null`) — штатный: приложение, собранное без
 * `NUXT_PUBLIC_SITE_URL`, просто шлёт текст.
 *
 * ⚠ `PREVIEW` = `LINK` осознанно: уменьшенных копий мы не держим, а поле рекомендовано заполнять —
 * без него часть клиентов берёт `LINK` сама, часть не показывает превью вовсе.
 */
export function buildAlfaInviteAttach(siteUrl: string): ChatImageAttach | null {
  const base = (siteUrl ?? '').trim().replace(/\/+$/, '')
  if (!/^https:\/\/[^\s/]+(\/[^\s]*)?$/i.test(base)) return null
  return {
    IMAGE: ALFA_KEY_SHOTS.map((shot) => {
      const link = `${base}/${shot.file}`
      return { NAME: shot.name, LINK: link, PREVIEW: link, WIDTH: shot.width, HEIGHT: shot.height }
    })
  }
}

/** Что отправляем по конкретному банку. Исчерпывающий разбор: новый подключаемый банк не
 *  скомпилируется, пока ему не напишут собственный текст. */
export function buildBankInvite(
  provider: BankProviderId,
  input: { prior?: PriorInviteInput, alfa?: AlfaInviteInput }
): string | null {
  switch (provider) {
    case 'prior-by':
      return input.prior ? buildPriorInvite(input.prior) : null
    case 'alfa-by':
      return input.alfa ? buildAlfaInvite(input.alfa) : null
    case 'manual':
      // Ручная загрузка файла — банка нет, приглашать некуда.
      return null
  }
}
