// Продление токена фрейма Bitrix24 — чистое правило «пора ли» и «когда проснуться».
//
// ⚠ ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО, если SDK продлевает сам. Продлевает — но только у СВОИХ вызовов, и
// код видно (`core/http/abstract-http.mjs`): `_ensureAuth` перед каждым запросом смотрит
// `getAuthData()` и на `false` зовёт `refreshAuth()`, а `_makeRequestWithAuthRetry` повторяет
// запрос после 401 `expired_token`/`invalid_token`. Новый `AUTH_ID` ложится в тот же
// `AuthManager` (`frame/auth.mjs`), поэтому ЛЮБОЙ вызов через `$b24` освежает общий токен.
//
// ⚠ Беда в том, что на портальных страницах таких вызовов НЕТ. После рукопожатия всё идёт
// `$fetch`'ем на наш backend с токеном, прочитанным руками (`useFrameAuth`), — то есть ни
// проактивная ветка, ни реактивная не срабатывают никогда. Замерено владельцем 2026-09-10:
// вкладка настроек повисела без действий, и три блока разом сказали «invalid frame token for this
// portal» — фоновые опросы ушли со сгоревшим токеном.
//
// ⚠ Продлеваем РАНЬШЕ срока, а не по факту отказа. У SDK порог — `getAuthData() === false`, то
// есть срок УЖЕ вышел; между этим мгновением и ближайшим фоновым опросом есть дыра, и она и
// наблюдалась. Запас в минутах эту дыру закрывает и стоит одного `postMessage` родителю — REST
// здесь не тратится вовсе.
//
// ⚠ Таймера ОДНОГО НЕ ХВАТИТ, и это главная причина, по которой рядом обязателен
// `visibilitychange`: браузеры душат таймеры в фоновых вкладках (минутный клэмп, а замороженную
// вкладку будят уже по возвращении). Ровно этот сценарий владелец и описал — «долго сидел и
// ничего не трогал». Проверка при возврате на вкладку несущая, а не «на всякий случай».

/** Продлеваем, когда до конца срока осталось меньше этого. */
export const FRAME_REFRESH_MARGIN_MS = 5 * 60_000

/** Границы сна между проверками: чаще незачем, реже — рискуем проспать короткий срок. */
export const FRAME_PULSE_MIN_MS = 30_000
export const FRAME_PULSE_MAX_MS = 10 * 60_000

/**
 * Пора ли продлевать токен.
 *
 * `expiresSec` — поле `expires` из `getAuthData()` (СЕКУНДЫ эпохи, так его отдаёт SDK).
 *
 * ⚠ Неизвестный срок — это ДА, а не НЕТ. Токена нет (`getAuthData()` вернул `false`), поле пустое
 * или нечисловое — все три случая означают «ручаться не за что», а цена ошибки несимметрична:
 * лишнее продление стоит одного сообщения родительскому окну, пропущенное — экрана «не удалось»
 * у человека, который ничего не делал.
 */
export function frameTokenDue(expiresSec: number | undefined, nowMs: number): boolean {
  if (!Number.isFinite(expiresSec) || (expiresSec as number) <= 0) return true
  return (expiresSec as number) * 1000 - nowMs <= FRAME_REFRESH_MARGIN_MS
}

/**
 * Через сколько проснуться для следующей проверки.
 *
 * Целимся в момент «конец срока минус запас»: при часовом токене это одно пробуждение в час, а не
 * шестьдесят. Клампы держат оба края — короткий срок не проспим, длинный не будем дёргать зря.
 */
export function frameTokenDelayMs(expiresSec: number | undefined, nowMs: number): number {
  if (!Number.isFinite(expiresSec) || (expiresSec as number) <= 0) return FRAME_PULSE_MIN_MS
  const untilRefresh = (expiresSec as number) * 1000 - nowMs - FRAME_REFRESH_MARGIN_MS
  return Math.min(FRAME_PULSE_MAX_MS, Math.max(FRAME_PULSE_MIN_MS, untilRefresh))
}
