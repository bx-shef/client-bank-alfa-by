// Временный ключ подключения — счёт ещё не выбран (#407).
//
// Ключ хранилища банк-токенов — `(member_id, provider, account_key)`, то есть без счёта строку
// положить некуда. При этом порядок «сначала банк, потом счёт» правильнее: до авторизации админ не
// обязан помнить IBAN, а после неё счёт можно выбрать из списка, который отдал сам банк.
//
// Поэтому подключение без счёта приземляется под ВРЕМЕННЫЙ ключ, а UI показывает такую строку как
// «счёт не выбран» и просит выбрать. Ключ обязан быть уникальным на каждое подключение: два
// параллельных connect'а одного админа иначе перезаписали бы друг друга — берём nonce из
// подписанного state, он ровно для этого и генерируется.

/** Префикс временного ключа. Начинается с `~`, которого нет в номерах счетов (только буквы и
 *  цифры), поэтому спутать временный ключ с настоящим невозможно ни визуально, ни кодом. */
export const PENDING_ACCOUNT_PREFIX = '~pending:'

/** Временный ключ для подключения, у которого счёт ещё не выбран. */
export function provisionalAccountKey(nonce: string): string {
  return `${PENDING_ACCOUNT_PREFIX}${nonce}`
}

/** Это подключение ещё ждёт выбора счёта? */
export function isPendingAccountKey(key: string): boolean {
  return key.startsWith(PENDING_ACCOUNT_PREFIX)
}
