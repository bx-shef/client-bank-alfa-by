// Загрузчик pdf.js для БРАУЗЕРА (#737) — предпросмотр на `/import` и демо лендинга.
//
// ⚠ Сборок pdf.js две, и путать их нельзя: здесь обычная (`pdfjs-dist`), в воркере на сервере —
// `legacy` (`server/utils/pdfjsServer.ts`). У серверной нет воркера и она рассчитана на Node,
// у этой воркер обязателен. Один файл на обе среды означал бы, что бандлер тащит в браузер
// серверную ветку (и наоборот), поэтому их два — см. соседний модуль.
//
// ⚠ Флага «запретить eval» в этой версии pdf.js НЕТ и он не нужен: библиотека отказалась от
// `Function`-сборки шрифтовых программ, то есть работает под нашим строгим `script-src 'self'`
// без послаблений. Не возвращать сюда `isEvalSupported` — его просто не существует, и попытка
// передать его не собирается по типам.
//
// ⚠ Импорт ДИНАМИЧЕСКИЙ, тем же приёмом, что у ECharts: pdf.js весит заметно, а нужен он только
// тому, кто принёс PDF. Статический импорт утяжелил бы стартовый чанк лендинга каждому
// посетителю ради формата, который откроет меньшинство.

import type { PdfDocumentLike, PdfLoader } from '~/utils/pdfExtract'

/** Поднять документ pdf.js в браузере. */
export const loadPdfInBrowser: PdfLoader = async (data) => {
  const pdfjs = await import('pdfjs-dist')
  // ⚠ Воркер адресуется через `new URL(..., import.meta.url)`: так бандлер сам кладёт файл
  // воркера в сборку и подставляет его настоящий путь. Ссылка на CDN была бы зависимостью от
  // чужой сети (и упёрлась бы в наш CSP, где `script-src 'self'`), а путь строкой разъехался бы
  // с хешированным именем файла при первой же сборке.
  pdfjs.GlobalWorkerOptions.workerSrc = new URL(
    'pdfjs-dist/build/pdf.worker.mjs',
    import.meta.url
  ).toString()
  const doc = await pdfjs.getDocument({
    data,
    // ⚠ Отрисовку шрифтов выключаем: нам нужен ТЕКСТ и его координаты, а установка шрифтов в
    // документ — лишняя работа и лишний повод упереться в CSP страницы.
    disableFontFace: true
  }).promise
  return doc as unknown as PdfDocumentLike
}
