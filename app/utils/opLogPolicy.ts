// Сколько подробностей писать в лог на КАЖДУЮ операцию (#498).
//
// Замерено на реальных строках воркера с обвязкой docker json-file: строка `[op]` весит 221 байт.
// На целевом масштабе «10 порталов × 100 оплат/мин» это 12,6 МБ/час, а ротация задана 10 МБ × 5 —
// то есть вся история логов около ЧЕТЫРЁХ часов. Диск при этом не переполнится (колпак держит), но
// лог перестанет быть тем, ради чего заведён: инцидент вчерашнего дня расследовать будет нечем.
// ⚠ Лимит действует на КАЖДУЮ реплику, а не суммарно.
//
// ⚠ Замерена ОДНА строка `[op]`; всё остальное — арифметика над ней (60 000 строк/час × 221 Б =
// 12,6 МБ/ч; 50 МБ ÷ 12,6 = 3,95 ч). Оценка «с распознаванием останется ~1,5 часа» — ЭКСТРАПОЛЯЦИЯ
// при множителе ×2,5 за `[recognize]`/`[resolve]`/`[allocate]`, а не замер: эти строки условны, и
// их доля зависит от того, сколько операций реально распознаётся на портале. Разделено намеренно —
// подпереть решение измеренным числом и оценкой одинаково уверенным тоном значит потом спорить о
// том, что именно было проверено.
//
// ⚠ Решение — НЕ «выключить построчный лог флагом». Флаг выключен ровно тогда, когда случается
// инцидент: включать его задним числом поздно, а держать включённым — вернуться к тому же объёму.
// И не сэмплирование «одна из N»: оно выкидывает строки СЛУЧАЙНО, то есть именно та операция, про
// которую спросят, отсутствует без причины — это хуже обоих крайних вариантов, потому что выглядит
// как потеря данных.
//
// Отвергнуты ещё два, более дешёвых на вид (спасибо ревью — без них список выглядел удобно):
//   • ПОДНЯТЬ РОТАЦИЮ (10 МБ × 5 → 40 МБ × 5). Не решает: объём растёт линейно по порталам, значит
//     каждый десяток клиентов требует новой правки, — и это ещё не главное. Колпак лога здесь
//     заодно работает СРОКОМ ХРАНЕНИЯ номеров счетов (`docs/PRIVACY.md`), поэтому «дать логам
//     больше места» буквально означает «держать финансовые ПДн дольше». Чинить нехватку истории
//     удлинением удержания ПДн — движение против собственной постуры «выписки у себя не храним».
//   • ОБЛЕГЧИТЬ СТРОКУ. Порядок не тот: из 221 байта заметная доля — конверт docker json-file
//     (`{"log":…,"stream":…,"time":…}`), который нам не принадлежит, а полезная часть это счёт,
//     docId, счёт контрагента и исход — то есть ровно то, ради чего строку читают. Ужав её вдвое,
//     получим не кратный выигрыш, а проценты, и заплатим за них диагностической ценностью.
//
// Решение: перенести БЕЗУСЛОВНУЮ гарантию с «каждой операции» на «каждый прогон», а построчную
// подробность оставить там, где она несёт информацию, — у операций, которые НИ ВО ЧТО НЕ ПРИЗЕМЛИЛИСЬ.
//
// Почему это не потеря: у приземлившегося платежа авторитетная запись — само ДЕЛО в Bitrix24 с его
// маркером. Оно точнее строки лога и не истекает через четыре часа. Лог нужен ровно там, где в CRM
// не появилось ничего и смотреть, кроме него, некуда.
//
// Свойство, ради которого выбран именно этот критерий: он САМОНАСТРАИВАЮЩИЙСЯ. На здоровом портале
// почти всё приземляется — лог тихий. На сломанном (тот самый «117 обработано, 0 создано») не
// приземляется ничто — лог полный, ровно в тот момент, когда он и нужен.
//
// ⚠ Но «тихий на здоровом» — НЕ гарантия, и обещать её нельзя. Неопознанный плательщик бывает
// штатным: разовый платёж от нового контрагента, перевод от физлица, комиссия самого банка. У
// портала, где такие платежи — норма бизнеса, а не поломка, лог останется полным, и выигрыша по
// объёму не будет вовсе. Это не делает решение хуже статус-кво (сегодня печатается ВСЁ и всегда),
// но означает, что планировать ротацию надо по худшему случаю, а не по наблюдаемому затишью —
// именно так это и записано в `OPERATIONS.md` §Логи и ротация.

/** Что стало с операцией — ровно те поля, по которым видно, приземлилась ли она. */
export interface OpLogOutcome {
  /** `client` — нашли компанию плательщика; `my-company` — фолбэк; `none` — владельца нет. */
  owner: 'client' | 'my-company' | 'none'
  /** Идентификатор записанного дела; `null`/отсутствует — не записали ничего. */
  activityId?: string | number | null
}

/**
 * Режим построчного лога. Умолчание — `notable`.
 *
 * `all` существует для калибровки и живых прогонов (владелец смотрит в лог прямо сейчас и хочет
 * видеть всё), `off` — аварийный клапан, если лог заливает диск по причине, которой мы не
 * предвидели. ⚠ `off` глушит и НЕПРИЗЕМЛИВШИЕСЯ операции, то есть ровно диагностику: это
 * последнее средство, а не режим по умолчанию для «тихого прода».
 */
export type OpLogMode = 'notable' | 'all' | 'off'

const MODES: readonly OpLogMode[] = ['notable', 'all', 'off']

/** Разбор `STATEMENT_OP_LOG`. Пусто/мусор ⇒ `notable`: неизвестное значение не должно ни глушить
 *  диагностику, ни заливать диск. */
export function resolveOpLogMode(raw: string | undefined): OpLogMode {
  const v = (raw ?? '').trim().toLowerCase()
  return (MODES as readonly string[]).includes(v) ? v as OpLogMode : 'notable'
}

/**
 * Приземлилась ли операция целиком: нашли КЛИЕНТА и записали дело.
 *
 * ⚠ Фолбэк «в мою компанию» приземлением НЕ считается. Дело записано, но клиент не опознан — а
 * именно это админ и чинит, заводя реквизит. Считать такую операцию обычной значило бы спрятать
 * главный симптом ненастроенного портала.
 */
export function landedCleanly(o: OpLogOutcome): boolean {
  return o.owner === 'client' && isRealActivityId(o.activityId)
}

/**
 * Похоже ли значение на НАСТОЯЩИЙ идентификатор дела Bitrix24.
 *
 * ⚠ Явная функция вместо truthy-проверки, и `0` она отвергает. Транспорт (`writeTodoActivityViaRest`)
 * отдаёт непустую цифровую строку либо `null`, поэтому ни `0`, ни `''` в проде не встречаются — но
 * тип поля их допускает, а нумерация сущностей в Б24 начинается с единицы, так что «дело номер 0»
 * это не запись, а признак того, что значение откуда-то потерялось. Ревью показало, что без явной
 * проверки граница не покрыта вовсе: truthy-версия проходила все тесты, и решение про `0`
 * оставалось незаписанным — то есть следующий читатель узнал бы о нём только из спора на ревью.
 */
function isRealActivityId(id: string | number | null | undefined): boolean {
  if (id == null || id === '') return false
  return typeof id === 'number' ? id > 0 : id !== '0'
}

/** Писать ли строку `[op]` для этой операции. */
export function shouldLogOperation(o: OpLogOutcome, mode: OpLogMode): boolean {
  if (mode === 'off') return false
  if (mode === 'all') return true
  return !landedCleanly(o)
}

/** Итог прогона одной пачки — то, что печатается ВСЕГДА, независимо от режима. */
export interface RunSummaryLike {
  processed: number
  landed: number
  created: number
  unmatched: number
  unresolved: number
  recognized: number
  /** Операция уже записана прежним прогоном (маркер найден в Б24). ⚠ См. `runSummaryLine`. */
  skipped: number
  /** Операция отсеяна правилами исключений портала — в CRM ей делать нечего. */
  excluded: number
  /** Операции, у которых не удалось записать элемент реестра (#575). Необязательное: у прежних
   *  вызывающих поля нет, а печатается оно только при ненулевом значении. */
  registryFailed?: number
}

/**
 * Строка итога прогона (#498).
 *
 * ⚠ Заводится потому, что её НЕ БЫЛО ВОВСЕ: сводка считалась, писалась в БД и метрики, но в лог не
 * попадала. То есть безусловной записи уровня прогона — той, что обязана пережить ротацию, — в
 * логе не существовало, и вся история держалась на построчных записях, которые её и съедали.
 *
 * ⚠ Явно говорит, сколько построчных записей ОПУЩЕНО. Молчаливое сокращение читается как «больше
 * ничего и не было» — а это ровно та ложь, из-за которой первый боевой прогон («117 обработано,
 * 0 создано») пришлось разбирать вручную в базе.
 */
export function runSummaryLine(memberId: string, s: RunSummaryLike, mode: OpLogMode): string {
  // ⚠ Маркера `[crm-sync]` здесь БОЛЬШЕ НЕТ: его печатает канал логгера (#529). Второй раз он дал
  // бы `[crm-sync] INFO: [crm-sync] portal …`; grep рантбука при этом работает по-прежнему —
  // канал и маркер это одна и та же строка, и совпадение стережёт `tests/serverLogChannels.test.ts`.
  return `portal ${memberId}: ${s.processed} обработано, ${s.created} создано, `
    + `${s.landed} приземлилось, ${s.unmatched} без клиента, ${s.unresolved} без цели, `
    + `${s.recognized} с распознанным номером${registryPart(s)}${quietPart(s)}${opLogTail(s, mode)}`
}

/**
 * Операции, по которым элемент реестра записать не удалось (#575).
 *
 * ⚠ Отдельно от `quietPart` намеренно: там перечислены ШТАТНЫЕ причины «ничего не вышло» (дедуп,
 * правила исключений), а это — отказ. Печатается в основной строке, потому что элемент реестра
 * после проглоченного отказа не появится уже никогда: следующий опрос упрётся в маркер дела и
 * пропустит операцию целиком. Молча это выглядит ровно как симптом, ради которого #575 и заведён —
 * рабочий импорт при пустом смарт-процессе.
 *
 * ⚠ При нуле не печатается — по тому же правилу, что и `quietPart`: ноль тут ничего не объясняет,
 * а постоянная приписка «0 без записи в реестр» превращает строку в шум, который перестают читать.
 */
function registryPart(s: RunSummaryLike): string {
  const n = s.registryFailed ?? 0
  return n > 0 ? `, ⚠ ${n} без записи в реестр` : ''
}

/**
 * Почему из `processed` ничего не вышло, когда причина — штатная (#498, находка ревью).
 *
 * ⚠ Без этого самый ЗДОРОВЫЙ случай печатался неотличимо от самого сломанного. Окно опроса
 * намеренно нахлёстывается (`CRON_LOOKBACK_DAYS` закрывает задержку проводки), поэтому каждый
 * повторный опрос заново прогоняет вчерашние операции — и все они дедуплицируются. Тихая ночь на
 * исправном портале давала строку `2 обработано, 0 создано, 0 приземлилось, 0 без клиента` —
 * буквально ту же сигнатуру, которой и CLAUDE.md, и OPERATIONS.md описывают СЛОМАННЫЙ портал
 * («117 обработано, 0 создано»). Различить их можно было только сверкой с `[fetch]` и рассуждением
 * «раз ни создано, ни без клиента — значит, наверное, дедуп», то есть ровно тем разбором вручную,
 * ради ухода от которого строка и заведена.
 *
 * ⚠ Печатается ТОЛЬКО при ненулевом значении. Постоянные «0 уже было записано, 0 исключено» на
 * каждой строке — это шум, который перестают читать, а вместе с ним перестают читать и строку
 * целиком; здесь же ноль ничего и не объясняет.
 */
function quietPart(s: RunSummaryLike): string {
  const parts: string[] = []
  if (s.skipped > 0) parts.push(`${s.skipped} уже было записано`)
  if (s.excluded > 0) parts.push(`${s.excluded} исключено правилами`)
  return parts.length > 0 ? `, ${parts.join(', ')}` : ''
}

/**
 * Хвост про построчные записи: что именно не напечатано и почему.
 *
 * ⚠ У `off` он СВОЙ, и это не косметика. Правило «молчаливое сокращение читается как „больше
 * ничего и не было“» — то самое, ради которого хвост вообще заведён, — в режиме `off` нарушалось
 * бы сильнее всего: там гасятся ВСЕ построчные записи, включая неприземлившиеся, то есть ровно
 * диагностику. Оператор, глядящий на пустой лог с одним итогом, обязан видеть, что строк нет
 * ПОТОМУ ЧТО ИХ ВЫКЛЮЧИЛИ, а не потому что печатать было нечего. Иначе `off` становится способом
 * получить тихий лог, выглядящий здоровым, — то же самое возражение, из-за которого отвергнут
 * вариант «просто выключить построчный лог флагом».
 */
function opLogTail(s: RunSummaryLike, mode: OpLogMode): string {
  if (mode === 'off') return ', построчный лог операций ВЫКЛЮЧЕН (STATEMENT_OP_LOG=off)'
  // В `all` не опущено ничего, в `notable` — ровно приземлившиеся: `shouldLogOperation` гасит их
  // и только их, поэтому счётчик здесь точен, а не «примерно».
  //
  // ⚠ Здесь стоял `Math.max(0, s.landed)` «на случай отрицательного». Мутационная проверка после
  // ревью показала, что убрать его можно, ничего не уронив, — и это не дыра в тестах, а мёртвый
  // код: сравнение `> 0` ниже уже отсекает любое неположительное значение, так что зажим не мог
  // изменить исход НИ ПРИ КАКОМ входе. Убран намеренно: защита, которая ничего не защищает, врёт
  // читателю про то, откуда здесь может прийти отрицательное число (ниоткуда — в воркере счётчик
  // только инкрементируется).
  const quiet = mode === 'notable' ? s.landed : 0
  return quiet > 0 ? `, построчно опущено ${quiet} приземлившихся` : ''
}
