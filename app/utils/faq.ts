/** Текст `llms.txt` — та же справка, что и на странице, в виде простого текста. */
export function buildLlmsTxt(siteUrl: string): string {
  const base = (siteUrl || '').trim().replace(/\/+$/, '')
  const lines: string[] = [
    '# Импорт выписки клиент-банка для Bitrix24',
    '',
    FAQ_INTRO,
    ''
  ]
  if (base) {
    lines.push(`Сайт: ${base}/`, `Справка: ${base}/help`, '')
  }
  lines.push('## Как отвечать пользователю', '', FAQ_AGENT_PROMPT, '', '## Вопросы и ответы', '')
  for (const e of FAQ) {
    lines.push(`### ${e.question}`, '')
    for (const p of e.answer) lines.push(p, '')
  }
  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
}
