// Пульс ВОРКЕРОВ (#466 §1). Отдельно от пульса продления токенов (#504): тот про один таймер в
// крон-процессе, этот — про то, что вообще есть кому разбирать очереди.
//
// ⚠ Зачем понадобился. Все правила здоровья очередей выведены из НАЛИЧИЯ застрявшей работы:
// `oldestPendingAgeMs === null` ⇒ правило простоя не срабатывает, падений нет, очередь читается —
// и полностью мёртвый воркер на тихом портале выглядит здоровым, а `/queues` показывает зелёное
// «проблем не обнаружено». Тишина там означает не «всё работает», а «мы не знаем».
//
// ⚠ Считаем ЖИВЫХ, а не сверяем с ожидаемым числом. `QUEUE_WORKERS` — булев флаг роли, а не
// количество: масштабируются реплики через `--scale worker=N`, и процесс попросту не знает, сколько
// их должно быть. Поэтому единственное честное утверждение — «ноль живых при включённых очередях»,
// и его для сигнала достаточно: при нуле воркеров задачи не разбирает никто, сколько бы их ни
// ожидалось. Сверка с N потребовала бы источника правды, которого у нас нет, и давала бы ложные
// тревоги на каждом рестарте реплики.
//
// ⚠ Свой ключ, а не `getWorkers()` BullMQ: тот опирается на `CLIENT SETNAME` и отражает СОЕДИНЕНИЕ,
// а не готовность обрабатывать. Соединение переживает и зависший обработчик.

/** Префикс ключей пульса в Redis. */
export const WORKER_BEAT_PREFIX = 'worker-beat:'

/** Как часто воркер отмечается. */
export const WORKER_BEAT_INTERVAL_MS = 30_000

/**
 * Сколько живёт метка. Кратно интервалу с запасом: пропущенный из-за паузы GC или сетевого блипа
 * удар не должен объявлять воркер мёртвым — цена ложной тревоги здесь выше цены задержки, потому
 * что проверка идёт раз в тик здоровья, а не непрерывно.
 */
export const WORKER_BEAT_TTL_SEC = 90

/** Ключ пульса одного процесса. */
export function workerBeatKey(id: string): string {
  return `${WORKER_BEAT_PREFIX}${id}`
}

export interface WorkerLiveness {
  /** Сколько процессов отметилось за последний TTL. */
  live: number
  /** Включены ли очереди вообще (без Redis вопрос не имеет смысла). */
  queuesEnabled: boolean
}

/**
 * Сколько ждать после старта процесса, прежде чем «ноль живых» считать аварией.
 *
 * ⚠ Без этой отсрочки ХОЛОДНЫЙ СТАРТ будит владельца ложной тревогой, и это не редкий случай, а
 * КАЖДЫЙ выкат. Прод — два контейнера: `backend` гоняет проверку здоровья, `worker` шлёт пульс, и
 * `depends_on: service_started` означает, что `worker` может быть ещё не создан, когда `backend`
 * уже выполняет свой первый — немедленный — тик. Тот видит ноль живых, шлёт «нет воркеров», а через
 * пять минут «✅ восстановлено».
 *
 * ⚠ Соседнее правило (`pulseState`, #504) принимает `startedAtMs` ровно поэтому; здесь была та же
 * дыра, и её нашли ревьюеры до того, как она разбудила владельца ночью.
 *
 * Величина — с запасом на старт контейнера и подключение к Redis, но заметно меньше периода
 * проверки здоровья (5 мин), чтобы настоящая авария не ждала лишний тик.
 */
export const WORKER_STARTUP_GRACE_MS = 2 * 60_000

export interface WorkerLivenessAlert {
  kind: 'no-workers'
  queue: string
  text: string
}

/**
 * Тревога о том, что разбирать очереди некому. `null` — сигнала нет.
 *
 * ⚠ Молчим при выключенных очередях: там нет ни Redis, ни воркеров по построению, и события Б24
 * идут синхронным фолбэком. Кричать «нет воркеров» на такой конфигурации значит приучить не читать.
 *
 * ⚠ Молчим и в первые `WORKER_STARTUP_GRACE_MS` после старта процесса — см. константу. Без
 * известного времени старта отсрочки нет: `startedAtMs == null` значит «не знаем, когда поднялись»,
 * и тогда честнее сигналить, чем молчать вечно.
 */
export function evaluateWorkerLiveness(
  state: WorkerLiveness,
  nowMs?: number,
  startedAtMs?: number | null
): WorkerLivenessAlert | null {
  if (!state.queuesEnabled) return null
  if (state.live > 0) return null
  if (nowMs != null && startedAtMs != null) {
    const up = nowMs - startedAtMs
    if (Number.isFinite(up) && up >= 0 && up < WORKER_STARTUP_GRACE_MS) return null
  }
  return {
    kind: 'no-workers',
    queue: 'workers',
    text: 'ни один воркер не отметился — очереди никто не разбирает; импорт и опрос стоят, задачи копятся'
  }
}
