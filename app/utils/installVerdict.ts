// Вердикт установки (#410) — чистое ядро.
//
// Установка была устроена так, что почти всё «best-effort»: не выдали право — установка всё равно
// «Готово», не зарегистрировался триггер — тоже «Готово». Список недостающих прав рисовался, но
// внутри СВЁРНУТОЙ панели «Диагностика» мелкими бейджами, то есть практически никогда не читался.
// В результате портал считался установленным, а часть функций молча не работала — ровно так и
// вскрылось, что провижининг смарт-процессов падает без `userfieldconfig` (#408).
//
// Здесь решается ровно одно: чем закончилась установка и что с этим делать. Без I/O — вход уже
// собран вызывающим.

export type InstallVerdictLevel = 'ok' | 'degraded' | 'failed'

export interface InstallIssue {
  /** Короткая суть проблемы. */
  title: string
  /** Что сделать. Пусто — если от админа ничего не требуется. */
  action: string
}

export interface InstallVerdict {
  level: InstallVerdictLevel
  title: string
  issues: InstallIssue[]
}

/** Что серверная часть знает о нашем портале (#413).
 *  `ok` — увидела его; `portal-missing` — событие установки до неё не дошло; `down` — сама
 *  недоступна; `unknown` — проверить не удалось (не судим). */
export type BackendState = 'ok' | 'portal-missing' | 'down' | 'unknown'

export interface InstallOutcome {
  /** Установка дошла до `installFinish` (иначе она провалена целиком). */
  finished: boolean
  /** Права, которые приложение запрашивает, но портал не выдал. */
  missingScopes: readonly string[]
  /** Результат регистрации триггера: '' — не пытались, 'ok' — успех, иначе текст ошибки. */
  trigger: string
  /** Best-effort chat-bot registration (#496): '' = not attempted, 'ok', otherwise an error. */
  bot?: string
  /** Видит ли backend наш портал (#413). Не задано ⇒ 'unknown' — молчим, а не пугаем. */
  backend?: BackendState
}

/**
 * Отобразить HTTP-код зонда `/api/setup-status` в состояние серверной части (#413). Чистая —
 * поэтому покрыта тестами: перепутанные 409/403 или инверсия ветки 5xx прошли бы CI незаметно, а
 * цена ошибки — ложный приказ переустановить приложение.
 *
 * 200 — портал известен; 403 — тоже известен (обе 403-ветки роута достижимы ТОЛЬКО после успешного
 * поиска портала по домену); 409 — строки портала нет; 0 или 5xx — сама серверная часть недоступна;
 * всё прочее — не судим.
 */
export function mapProbeStatus(code: number): BackendState {
  if (code === 200 || code === 403) return 'ok'
  if (code === 409) return 'portal-missing'
  if (code === 0 || code >= 500) return 'down'
  return 'unknown'
}

/**
 * Свести исход установки к вердикту. Три уровня, потому что «установилось» и «работает» —
 * разные вещи: `failed` (не установилось), `degraded` (установилось, но часть возможностей
 * выключена) и `ok`. Именно различия между двумя последними и не хватало.
 */
export function installVerdict(outcome: InstallOutcome): InstallVerdict {
  if (!outcome.finished) {
    return {
      level: 'failed',
      title: 'Установка не завершена',
      issues: [{
        title: 'Приложение не зарегистрировалось в портале.',
        action: 'Повторите установку. Если повторяется — проверьте, что портал доступен и у вас права администратора.'
      }]
    }
  }

  const issues: InstallIssue[] = []

  if (outcome.missingScopes.length > 0) {
    issues.push({
      title: `Портал не выдал права: ${outcome.missingScopes.join(', ')}.`,
      // Права выдаются при согласии на установку, поэтому «переустановить» — единственное
      // действие, доступное админу портала; из настроек приложения это не чинится.
      action: 'Часть функций без них не работает. Переустановите приложение и подтвердите запрошенные права.'
    })
  }

  // Событие `ONAPPINSTALL` идёт мимо iframe — исходящим вебхуком портала на наш backend, и именно
  // оно приносит токены. Если оно не дошло, портал «установлен», а серверная часть о нём не знает:
  // ни опроса, ни записи в CRM. Снаружи это выглядит как полностью успешная установка (#413).
  if (outcome.backend === 'portal-missing') {
    issues.push({
      title: 'Серверная часть приложения пока не подтвердила установку.',
      // НЕ «переустановите»: событие доставляется асинхронно и запись делает фоновый воркер после
      // сетевой проверки, поэтому задержка при занятой очереди — норма, а не поломка. Приказ
      // переустановить на здоровой установке был бы хуже молчания.
      action: 'Обновите эту страницу через минуту. Если сообщение осталось — импорт не заработает, сообщите владельцу приложения.'
    })
  } else if (outcome.backend === 'down') {
    issues.push({
      title: 'Серверная часть приложения недоступна.',
      action: 'Это на стороне владельца приложения — сообщите ему. Настройки портала здесь ни при чём.'
    })
  }

  if (outcome.trigger && outcome.trigger !== 'ok') {
    issues.push({
      title: 'Не зарегистрирован триггер автоматизации «платёж получен».',
      action: 'Автозапуск роботов по приходу денег работать не будет. Остальное — будет. Повторите установку позже.'
    })
  }

  // ⚠ Формулировка намеренно мягче триггера: без бота приложение НЕ теряет ничего, кроме подписи —
  // сообщения продолжают приходить, просто от имени сотрудника (#496, фолбэк в `postChatMessage`).
  // Написать здесь тревожно значило бы отправлять админа чинить то, что не сломано: на бесплатном
  // тарифе Bitrix24 бот недоступен в принципе, и переустановка этого не изменит.
  if (outcome.bot && outcome.bot !== 'ok') {
    issues.push({
      title: 'Не зарегистрирован чат-бот приложения.',
      action: 'Сообщения в чаты будут приходить от имени сотрудника, а не от приложения. На работу импорта это не влияет; на бесплатных тарифах Bitrix24 бот недоступен.'
    })
  }

  if (issues.length === 0) {
    return { level: 'ok', title: 'Приложение установлено', issues: [] }
  }
  return {
    level: 'degraded',
    title: 'Установлено, но часть возможностей выключена',
    issues
  }
}
