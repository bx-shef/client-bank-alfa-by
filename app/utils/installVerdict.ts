// Вердикт установки (#410) — чистое ядро.
//
// Установка была устроена так, что почти всё «best-effort»: не выдали право — установка всё равно
// «Готово», не зарегистрировался триггер — тоже «Готово». Список недостающих прав рисовался, но
// внутри СВЁРНУТОЙ панели «Диагностика» мелкими бейджами, то есть практически никогда не читался.
// В результате портал считался установленным, а часть функций молча не работала — ровно так и
// вскрылось, что провижининг смарт-процессов падает без `userfieldconfig` (#408).
//
// Здесь решается ровно одно: чем закончилась установка и что с этим делать. Без I/O — вход уже
// собран вызывающим.

export type InstallVerdictLevel = 'ok' | 'degraded' | 'failed'

export interface InstallIssue {
  /** Короткая суть проблемы. */
  title: string
  /** Что сделать. Пусто — если от админа ничего не требуется. */
  action: string
}

export interface InstallVerdict {
  level: InstallVerdictLevel
  title: string
  issues: InstallIssue[]
}

export interface InstallOutcome {
  /** Установка дошла до `installFinish` (иначе она провалена целиком). */
  finished: boolean
  /** Права, которые приложение запрашивает, но портал не выдал. */
  missingScopes: readonly string[]
  /** Результат регистрации триггера: '' — не пытались, 'ok' — успех, иначе текст ошибки. */
  trigger: string
}

/**
 * Свести исход установки к вердикту. Три уровня, потому что «установилось» и «работает» —
 * разные вещи: `failed` (не установилось), `degraded` (установилось, но часть возможностей
 * выключена) и `ok`. Именно различия между двумя последними и не хватало.
 */
export function installVerdict(outcome: InstallOutcome): InstallVerdict {
  if (!outcome.finished) {
    return {
      level: 'failed',
      title: 'Установка не завершена',
      issues: [{
        title: 'Приложение не зарегистрировалось в портале.',
        action: 'Повторите установку. Если повторяется — проверьте, что портал доступен и у вас права администратора.'
      }]
    }
  }

  const issues: InstallIssue[] = []

  if (outcome.missingScopes.length > 0) {
    issues.push({
      title: `Портал не выдал права: ${outcome.missingScopes.join(', ')}.`,
      // Права выдаются при согласии на установку, поэтому «переустановить» — единственное
      // действие, доступное админу портала; из настроек приложения это не чинится.
      action: 'Часть функций без них не работает. Переустановите приложение и подтвердите запрошенные права.'
    })
  }

  if (outcome.trigger && outcome.trigger !== 'ok') {
    issues.push({
      title: 'Не зарегистрирован триггер автоматизации «платёж получен».',
      action: 'Автозапуск роботов по приходу денег работать не будет. Остальное — будет. Повторите установку позже.'
    })
  }

  if (issues.length === 0) {
    return { level: 'ok', title: 'Приложение установлено', issues: [] }
  }
  return {
    level: 'degraded',
    title: 'Установлено, но часть возможностей выключена',
    issues
  }
}
