/**
 * Epoch ms, когда подключение стало ИЗМЕРЕННО мёртвым, или `null`, если такого не случилось.
 *
 * «Измеренно» — это не наша догадка, а факт, который можно назвать датой:
 *   • истёкшее СОГЛАСИЕ банка (#503) — дату выдал сам банк (`consentExpiresAt`);
 *   • Альфа старше своего ИЗМЕРЕННОГО срока refresh — смерть в `connectedAt + TTL`.
 *
 * ⚠ Приор по ДОГАДКЕ о сроке refresh сюда НЕ попадает никогда (`BANK_REFRESH_TTL_MEASURED['prior-by']`
 * = false): хоронить по угаданному сроку значит удалять живое. Его смерть засчитывается только через
 * истёкшее согласие — то есть по дате банка.
 *
 * ⚠ Голое `no-refresh` (банк не выдал токен продления) — тоже НЕ смерть сама по себе: когда именно
 * такая строка «умерла», неизвестно, а access-токен истекает не тогда, когда умирает пара. Она
 * становится измеренно-мёртвой только если у неё вдобавок истекло согласие — тогда сработает ветка
 * согласия.
 *
 * ⚠ Если сработали ОБА условия — берём БОЛЕЕ РАННЕЕ: подключение мертво с первого из них.
 */
export function bankDeathSinceMs(c: ConnectionLike, nowMs: number): number | null {
  const marks: number[] = []
  // Согласие — дата самого банка. `consentExpired` уже проверяет `> 0` и конечность.
  if (consentExpired(c, nowMs) && typeof c.consentExpiresAt === 'number') marks.push(c.consentExpiresAt)
  // Измеренный TTL — только для провайдеров, чей срок мы ЗНАЕМ (Альфа). Догадка (Приор) исключена.
  const ttlMs = (BANK_REFRESH_TTL_SEC[c.provider] ?? 0) * 1000
  if (ttlMs > 0 && BANK_REFRESH_TTL_MEASURED[c.provider] && Number.isFinite(c.connectedAt)) {
    const deathAt = c.connectedAt + ttlMs
    if (nowMs >= deathAt) marks.push(deathAt)
  }
  return marks.length ? Math.min(...marks) : null
}

/** Сколько ЦЕЛЫХ дней подключение измеренно-мёртво (для строки оператора). `null` — не мёртво. */
export function bankDeadForDays(deathSinceMs: number | null, nowMs: number): number | null {
  if (deathSinceMs === null) return null
  return Math.max(0, Math.floor((nowMs - deathSinceMs) / 86_400_000))
}

/** Нижняя граница порога — опустить ниже нельзя никакой настройкой (та же, что у #574). */
export const MIN_BANK_REAP_DAYS = 14
/** Значение по умолчанию: месяц измеренной смерти. */
export const DEFAULT_BANK_REAP_DAYS = 30

/**
 * Порог из env: целое число дней, клампится ВВЕРХ от пола.
 *
 * ⚠ Кламп только вверх: занизить порог — единственный способ превратить уборщик в оружие; завысить
 * безвредно. Мусор/пустое/ноль дают умолчание, а не 0 (`Number('')` = 0 означал бы «стирать сразу»).
 */
export function resolveBankReapDays(raw: string | undefined): number {
  const n = Number(String(raw ?? '').trim())
  if (!Number.isFinite(n) || n <= 0) return DEFAULT_BANK_REAP_DAYS
  return Math.max(MIN_BANK_REAP_DAYS, Math.floor(n))
}

/** Сколько строк максимум стираем за один прогон — тот же смысл, что у #574: не про нагрузку, а про
 *  КЛАСС ошибок. Если правило однажды сочтёт мёртвым живое, потолок делает «снесли пятерых» видимым,
 *  а не «снесли всех за тик». */
export const MAX_BANK_REAP_PER_RUN = 5

/** Что уборщик сделал за прогон — для строки лога и экрана оператора. */
export interface BankReapFacts {
  /** Сколько строк измеренно-мертвы дольше порога. */
  candidates: number
  /** Сколько реально стёрто. */
  reaped: number
  /** Сколько удалений не прошло (отказ базы). */
  failed: number
  /** Сколько строк к моменту удаления изменились под нами (выбрали счёт / отключили) — не ошибка. */
  skipped: number
  /** Упёрлись в потолок за прогон. */
  capped: boolean
  /** Сработал предохранитель по доле флота — не стёрли НИЧЕГО. */
  breach: boolean
  /** Порог в днях. */
  days: number
}

/**
 * Строка лога о прогоне.
 *
 * ⚠ Печатается ВСЕГДА, даже когда стирать нечего: молчащий уборщик неотличим от невзведённого.
 * Единица — ПОДКЛЮЧЕНИЕ (строка), а не портал: у одного клиента их может быть несколько.
 */
export function bankReaperLogLine(f: BankReapFacts): string {
  if (f.breach) {
    return `порог ${f.days} дн.: измеренно-мёртвых подключений ${f.candidates} — это слишком большая `
      + `доля всех подключений, НИЧЕГО не стёрто. Похоже на нашу поломку, а не на уход клиентов`
  }
  const head = `порог ${f.days} дн.: кандидатов ${f.candidates}`
  const cap = f.capped ? `, за прогон стёрто не больше ${MAX_BANK_REAP_PER_RUN} — остальные в следующий` : ''
  const bad = f.failed ? `, НЕ УДАЛОСЬ стереть ${f.failed}` : ''
  // «Изменились под нами» — не ошибка и не отказ базы: строку успели переразметить или отключить.
  const sk = f.skipped ? `, ${f.skipped} изменились под нами (пропущены)` : ''
  return `${head}, стёрто ${f.reaped}${bad}${sk}${cap}`
}

