// Чистое ядро уборщика МЁРТВЫХ БАНК-ПОДКЛЮЧЕНИЙ у ЖИВОГО портала (#599, хвост #574).
//
// ⚠ Отличие от портального уборщика (`portalReaper.ts`) названо прямо, чтобы их не путать:
//   • портал стирается ЦЕЛИКОМ (`deletePortal`) — здесь стирается ОДНА строка `bank_tokens`,
//     портал остаётся жив;
//   • сигнал у портала — событие `invalid_grant` без своей метки времени, поэтому там нужна
//     колонка `grant_revoked_at`. Здесь смерть ВЫВОДИТСЯ из уже хранимых полей (срок согласия от
//     банка или измеренный TTL Альфы), поэтому НОВОЙ КОЛОНКИ НЕТ и «когда умерло» считается на лету.
//
// ⚠ Удаление здесь БЕЗ флага (в отличие от #574): клиентов на боевом ещё нет, расстраивать некого,
// а держать мёртвые строки бессрочно — накопление мусора и шума. Но приватностный довод слабее, чем
// у #574, ровно потому, что refresh УЖЕ отвергнут банком: доступа к счёту по этой строке у нас
// фактически нет. Поэтому предохранители те же (порог, потолок за прогон, доля флота), а флага —
// нет.
//
// ⚠ Асимметрия цены та же, что везде в этом домене: «подержали мёртвую строку лишнюю неделю» —
// шум; «стёрли ЖИВОЕ подключение» — потеря доступа, за которым стоит поход ВЛАДЕЛЬЦА СЧЁТА в
// интернет-банк. Поэтому стираем ТОЛЬКО измеренно-мёртвые и никогда — по догадке о сроке.

import { BANK_REFRESH_TTL_SEC, BANK_REFRESH_TTL_MEASURED, consentExpired, type ConnectionLike } from './bankTokenLifetime'

// Общие с портальным уборщиком части — берём их, а не копируем: политика «когда пора» и «не слишком
// ли большая доля флота» одна и та же, расходится только ЕДИНИЦА счёта (там порталы, здесь строки).
