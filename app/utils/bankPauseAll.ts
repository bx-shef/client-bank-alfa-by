// Чистое ядро массового переключения паузы опроса (#581).
//
// ⚠ Пауза остаётся ПЕР-СЧЁТ, и это не компромисс, а верный примитив: «пауза портала» = пауза
// каждого счёта, обратное неверно — у клиента бывает один шумный счёт и один нужный. Здесь только
// украшение поверх него: одно нажатие вместо четырёх. Никакого второго уровня состояния не
// заводится, в хранилище по-прежнему один флаг на строку.
//
// ⚠ Решение «что делать и с какими строками» вынесено сюда, а не в компонент, ровно потому, что
// именно в нём ошибаются: пропустить незавершённые подключения, выбрать направление по смешанному
// состоянию, не показать кнопку, когда переключать нечего. Цикл по сети остаётся в композабле.

import { isPendingAccountKey } from './bankAccountKey'
import { pluralRu } from './importStatus'

/** Минимум, который ядру нужен от строки подключения. */
export interface PausableAccount {
  accountKey: string
  pollPaused?: boolean
}

export interface PauseAllPlan<T extends PausableAccount> {
  /** `true` — ставим на паузу, `false` — возобновляем. */
  paused: boolean
  /** Строки, которые надо переключить: только те, что сейчас в противоположном состоянии. */
  rows: T[]
  /** Подпись кнопки. */
  label: string
}

/**
 * Что сделает кнопка «всё» при текущем списке. `null` — кнопку показывать НЕ надо.
 *
 * ⚠ Незавершённые подключения (`~pending:`) исключаются полностью: у них паузы нет и быть не может
 * — опрашивать по такому ключу нечего, банк такого «номера» не знает. Включив их, мы слали бы
 * заведомо бессмысленные запросы и портили счёт «сколько не вышло».
 *
 * ⚠ Одно подключение кнопку НЕ показывает: ради одной строки, у которой переключатель уже стоит
 * рядом, вторая кнопка сверху — лишний элемент, который надо прочитать и сопоставить с первым.
 *
 * ⚠ Смешанное состояние (часть на паузе) даёт «Приостановить всё», а не «Возобновить всё».
 * Намерение, ради которого кнопка заведена, — «слишком много операций, выключить»; из смешанного
 * состояния к нему ведёт пауза. Обратный выбор означал бы, что один приостановленный счёт
 * переворачивает смысл кнопки для остальных трёх.
 *
 * ⚠ Переключаются ТОЛЬКО строки в противоположном состоянии. Слать «поставь на паузу» уже
 * приостановленному счёту не вредно, но это лишний запрос в задросселированную зону и лишний шанс
 * получить 409 на строке, которую никто не трогал.
 */
export function planPauseAll<T extends PausableAccount>(accounts: readonly T[]): PauseAllPlan<T> | null {
  const real = accounts.filter(a => !isPendingAccountKey(a.accountKey))
  if (real.length < 2) return null
  const allPaused = real.every(a => a.pollPaused === true)
  const paused = !allPaused
  const rows = real.filter(a => (a.pollPaused === true) !== paused)
  if (rows.length === 0) return null
  return { paused, rows, label: paused ? 'Приостановить всё' : 'Возобновить всё' }
}

/**
 * Итог массового переключения одной строкой.
 *
 * ⚠ Частичный отказ обязан быть ВИДЕН. Показать «готово», когда из четырёх переключились три, —
 * это ровно та ложь, из-за которой потом ищут поломку в банке: администратор уверен, что опрос
 * выключен, а один счёт продолжает заводить дела.
 *
 * ⚠ Ничего не вышло вовсе — тоже отдельный текст: «0 из 4» и «ошибка» читаются одинаково плохо,
 * если не сказать прямо, что состояние не изменилось.
 */
export function pauseAllSummary(done: number, failed: number, paused: boolean): string {
  const verb = paused ? 'приостановлен' : 'возобновлён'
  if (failed === 0) return `Опрос ${verb} по ${done} ${pluralAccounts(done)}.`
  if (done === 0) return `Не удалось переключить ни одно подключение — состояние не изменилось. Список обновлён, попробуйте ещё раз.`
  return `Опрос ${verb} по ${done} ${pluralAccounts(done)}, а ${failed} не переключилось. Список обновлён — проверьте оставшиеся строки.`
}

/** Склонение «подключение» в дательном. ⚠ Через ОБЩИЙ `pluralRu`, а не свой `=== 1`: ручной
 *  суррогат в этом проекте уже давал «5 портала(ов)», и его пришлось выкорчёвывать. */
function pluralAccounts(n: number): string {
  return pluralRu(n, ['подключению', 'подключениям', 'подключениям'])
}
