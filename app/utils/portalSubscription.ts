// Подписка портала на REST API Bitrix24 истекла (#614) — чистое правило.
//
// ⚠ Клиент НЕ МОЖЕТ починить это сам, и это определяет всю конструкцию. Приложение открывается
// ВНУТРИ Битрикса: при мёртвой подписке админ до интерфейса не доберётся, значит и «Отключить»
// нажать не сможет. Поэтому состояние выводится в консоль ОПЕРАТОРА, а через короткий срок
// подключение отключается автоматически — иначе оно висело бы вечно.
//
// ⚠ Чем это вредно, пока висит: портал продолжает опрашивать банк (`accountsForPolling` про REST
// не знает) и продлевать банковский токен — то есть тратит лимит банка и гонится за refresh с
// другими порталами, у которых тот же счёт (#615). Записать при этом он не может НИЧЕГО.

/**
 * Сообщение об истёкшей подписке на REST.
 *
 * ⚠ Регуляркой по ТЕКСТУ, а не по коду ошибки, и это вынужденно: Bitrix24 отдаёт этот отказ без
 * машинного кода — в живом логе 2026-08-25 он пришёл строкой `Subscription has been ended`.
 * Сравнивать приходится с тем, что есть; зато строка стабильна и не локализуется.
 */
export const SUBSCRIPTION_ENDED_RE = /subscription\s+has\s+been\s+ended/i

/** Похоже ли, что портал потерял доступ к REST по подписке. Принимает `unknown` — приходит из `catch`. */
export function isSubscriptionEnded(e: unknown): boolean {
  const text = typeof e === 'string' ? e : (e as { message?: unknown } | null | undefined)?.message
  return typeof text === 'string' && SUBSCRIPTION_ENDED_RE.test(text)
}

/**
 * Через сколько дней молчания отключать банковские подключения портала.
 *
 * ⚠ ЧЕТЫРЕ, а не месяц — решение владельца 2026-08-25: «по сути клиент ничего не теряет, только
 * переподключить всё». Плата за отключение — повторная авторизация владельца счёта в интернет-банке;
 * она названа и принята. Держать дольше значило бы месяцами тратить лимит банка и ломать чужие
 * подключения к тому же счёту ради портала, который всё это время ничего не записывает.
 */
export const SUBSCRIPTION_CUTOFF_DAYS = 4

/**
 * Сколько дней подписка мертва. `0`/отсутствие метки — не мертва.
 *
 * ⚠ Дробное НЕ округляем вверх: «мертва 4 дня» должно означать прошедшие четверо суток, иначе
 * отключение случится раньше названного срока — а оно необратимо для клиента.
 */
export function deadDays(endedAtMs: number | null | undefined, nowMs: number): number {
  if (!endedAtMs || endedAtMs <= 0) return 0
  const ms = nowMs - endedAtMs
  return ms > 0 ? Math.floor(ms / 86_400_000) : 0
}

/**
 * Пора ли отключать банковские подключения портала.
 *
 * ⚠ Метка ставится от ПЕРВОГО отказа и снимается при первом успехе — поэтому отдельный счётчик
 * «сколько ошибок подряд» не нужен: срок сам служит порогом. Блип на пару часов снимется
 * следующим удачным вызовом задолго до отсечки, а устойчивое молчание её переживёт. Счётчик
 * попыток дал бы то же самое, но со своим хранением и своей возможностью разъехаться.
 *
 * ⚠ Метка из БУДУЩЕГО (разъехались часы реплик) даёт `0` дней, то есть отсрочку, а не досрочное
 * отключение: ошибаться надо в сторону «подержим дольше».
 */
export function subscriptionCutoffDue(
  endedAtMs: number | null | undefined, nowMs: number, days = SUBSCRIPTION_CUTOFF_DAYS
): boolean {
  return deadDays(endedAtMs, nowMs) >= days
}

/**
 * Сколько подключений отключаем за один прогон.
 *
 * ⚠ Потолок здесь про ЧУЖИЕ данные, а не про нагрузку: сработай правило ошибочно, за прогон
 * пострадает считанное число порталов, и у нас будет сутки на то, чтобы это заметить в логе.
 */
export const MAX_SUBSCRIPTION_CUTOFF_PER_RUN = 5

/**
 * Насколько берём выборку шире потолка.
 *
 * ⚠ Тот же довод, что у `REAP_OVERFETCH` (#574): выборка отсортирована по метке ASC, поэтому
 * строки, на которых выборка и правило разошлись, — самые давние, то есть первые в КАЖДОМ
 * прогоне. Без запаса они съедали бы весь бюджет вечно, и ни один настоящий кандидат не был бы
 * отключён никогда.
 */
export const SUBSCRIPTION_CUTOFF_OVERFETCH = 3

/** Итог одного прогона автоотключения — для строки лога и тестов. */
export interface SubscriptionCutoffFacts {
  /** Сколько порталов молчат дольше порога. */
  candidates: number
  /** У скольких порталов отключили банк. */
  cutoff: number
  /** Сколько банковских строк при этом стёрто (у портала их может быть несколько). */
  connections: number
  /** Отказы базы. */
  failed: number
  /** Отключать было уже нечего — банковских строк нет (метку при этом снимаем). */
  skipped: number
  /** Выборка и правило разошлись — чинится в коде, а не на сервере. */
  diverged: number
  /** Упёрлись в потолок за прогон. */
  capped: boolean
  /** Предохранитель по доле флота сработал — не тронули никого. */
  breach: boolean
  /** Порог в днях, по которому шёл этот прогон. */
  days: number
}

/**
 * Строка итога прогона.
 *
 * ⚠ Печатается ВСЕГДА, даже когда отключать некого: молчащий автомат неотличим от невзведённого,
 * а этот — единственный, кто рвёт связь с банком без участия человека.
 */
export function subscriptionCutoffLogLine(f: SubscriptionCutoffFacts): string {
  if (f.breach) {
    return `порог ${f.days} дн.: без подписки выглядят ${f.candidates} порталов — это слишком большая `
      + `доля флота. Так выглядит наша поломка (метку ставит РЕГУЛЯРКА по тексту ошибки), а не `
      + `массовый уход клиентов. НИЧЕГО не отключено`
  }
  const head = `порог ${f.days} дн.: кандидатов ${f.candidates}`
  const done = `, отключено порталов ${f.cutoff} (подключений ${f.connections})`
  const bad = f.failed ? `, НЕ УДАЛОСЬ отключить ${f.failed}` : ''
  // «Отключать было нечего» — не отказ: банк уже сняли, а метка осталась. Считается отдельно,
  // иначе такой портал каждый прогон печатался бы как настоящее отключение.
  const sk = f.skipped ? `, ${f.skipped} уже без банка (метка снята)` : ''
  const div = f.diverged ? `, ${f.diverged} — выборка разошлась с правилом (пропущены)` : ''
  const cap = f.capped ? `, за прогон не больше ${MAX_SUBSCRIPTION_CUTOFF_PER_RUN} — остальные в следующий` : ''
  return `${head}${done}${bad}${sk}${div}${cap}`
}
