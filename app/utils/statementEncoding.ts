// Кодировка загруженного файла выписки: CP866 или windows-1251 (#700).
//
// ⚠ ЗАЧЕМ. Декод был ЖЁСТКО windows-1251 — и это верно ровно до тех пор, пока форматов два.
// Звёздочный формат Паритетбанка выгружается в CP866, а прочитанный как CP1251 он разбирается
// СТРУКТУРНО ВЕРНО: звёздочки, цифры, номера счетов и суммы лежат в ASCII и в обеих кодировках
// совпадают байт в байт. Ломается только кириллица — то есть назначение платежа и имя плательщика
// приезжают мусором В CRM КЛИЕНТА, при полностью зелёном импорте и без единого сообщения об
// ошибке. Это худший исход из возможных: не отказ, который видно, а тихо неверные данные.
//
// ⚠ РАЗЛИЧАЕМ ПО РАСПРЕДЕЛЕНИЮ БАЙТ, и границы не выдуманы, а ЗАМЕРЕНЫ. В CP866 кириллица «А»–«п»
// занимает 0x80–0xAF, в CP1251 тот же диапазон отдан типографике («…», «—», «№», кавычки), которая
// в банковской выписке единична. Замер на боевых файлах: у CP866-выписок байт в 0x80–0xBF ВТРОЕ
// больше, чем в 0xC0–0xFF (например 9058 против 2512); у всех наших CP1251-фикстур в 0x80–0xBF
// от 0 до 2 байт при сотнях в 0xC0–0xFF. Разрыв — три порядка, поэтому порог «строго больше»
// стоит с огромным запасом с обеих сторон.
//
// ⚠ Файл без старших байт (чистый ASCII) читается как CP1251 — для ASCII обе кодировки совпадают,
// так что выбор тут ни на что не влияет, и незачем заводить третий исход.

/** Кодировки, в которых доезжают текстовые выписки. */
export type StatementEncoding = 'utf-8' | 'cp866' | 'windows-1251'

/** UTF-8 BOM. Его ставит, в частности, «Блокнот» Windows. */
const BOM = [0xEF, 0xBB, 0xBF] as const

/**
 * Похож ли буфер на UTF-8 — структурно, а не статистически: многобайтовые последовательности
 * UTF-8 устроены жёстко (`110xxxxx 10xxxxxx` и т.д.), и однобайтовая кодировка кириллицы им
 * почти никогда не удовлетворяет — там старшие байты идут подряд и вперемешку.
 *
 * ⚠ Требуется ХОТЯ БЫ ОДНА многобайтовая последовательность: файл из чистого ASCII формально
 * валиден и как UTF-8, но решать по нему нечего — все три кодировки на ASCII совпадают, и объявив
 * его UTF-8, мы просто завели бы третий исход там, где разницы нет.
 */
function looksLikeUtf8(bytes: Uint8Array): boolean {
  let multibyte = 0
  let i = 0
  while (i < bytes.length) {
    const b = bytes[i]!
    if (b < 0x80) {
      i += 1
      continue
    }
    // 0x80–0xC1 и 0xF5+ ведущим байтом в UTF-8 невозможны вовсе.
    const len = b >= 0xC2 && b <= 0xDF ? 2 : b >= 0xE0 && b <= 0xEF ? 3 : b >= 0xF0 && b <= 0xF4 ? 4 : 0
    if (len === 0 || i + len > bytes.length) return false
    for (let k = 1; k < len; k += 1) {
      const c = bytes[i + k]!
      if (c < 0x80 || c > 0xBF) return false
    }
    multibyte += 1
    i += len
  }
  return multibyte > 0
}

/**
 * Какой кодировкой читать этот файл.
 *
 * ⚠ Смотрит на ВЕСЬ буфер, а не на первые килобайты: шапка выписки — сплошь латиница и цифры
 * (`*0*260601*BY10DEMO…`), кириллица начинается только в назначениях платежей ниже. Проба по
 * началу файла отвечала бы «ASCII» на любой выписке и выбирала бы кодировку монеткой.
 *
 * ⚠ UTF-8 ПРОВЕРЯЕТСЯ ПЕРВЫМ, и это не запас на будущее: «Блокнот» Windows сохраняет в UTF-8 по
 * умолчанию, то есть человек, открывший выписку и нажавший «Сохранить», приносит именно такой
 * файл. Статистикой он не различается — у UTF-8 ведущий байт попадает в один диапазон, а
 * продолжение в другой, поэтому счётчики выходят почти равными, и исход решала бы разница в
 * один байт (замерено на наших же фикстурах, пересохранённых в UTF-8: 489/489 и 785/784).
 * Структурная проверка отвечает на это определённо.
 *
 * ⚠ Ничья между CP866 и CP1251 отдаётся windows-1251 намеренно: так решается файл без обычной
 * кириллицы (валютная выписка, где назначения набраны латиницей, а из не-ASCII только «ёлочки»,
 * `№` и тире) — там ставка на прежнее поведение честнее, чем на новое.
 */
export function detectStatementEncoding(buffer: ArrayBuffer | Uint8Array): StatementEncoding {
  const bytes = buffer instanceof Uint8Array ? buffer : new Uint8Array(buffer)
  if (bytes.length >= 3 && bytes[0] === BOM[0] && bytes[1] === BOM[1] && bytes[2] === BOM[2]) {
    return 'utf-8'
  }
  if (looksLikeUtf8(bytes)) return 'utf-8'
  let cp866Range = 0
  let cp1251Range = 0
  // ⚠ Индексный цикл, а не `for…of`: итератор `Uint8Array` на 2 МБ стоит ~36 мс против ~5 мс,
  // то есть ВТРОЕ дороже самого декода, который он предваряет, — и всё это синхронно в браузере.
  for (let i = 0; i < bytes.length; i += 1) {
    const b = bytes[i]!
    if (b >= 0x80 && b <= 0xBF) cp866Range += 1
    else if (b >= 0xC0) cp1251Range += 1
  }
  return cp866Range > cp1251Range ? 'cp866' : 'windows-1251'
}
