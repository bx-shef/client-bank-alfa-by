// Счётчик Яндекс.Метрики: какой вставлять в лендинг и на какой слать цели.

/** Счётчик НАШЕГО лендинга. */
export const DEFAULT_METRIKA_ID = '109399587'

/**
 * Id счётчика: заданный (только цифры) или наш — наш только вне локального режима.
 *
 * ⚠ Зовётся В ДВУХ местах, и в этом смысл функции: `nuxt.config.ts` вставляет по ней сниппет, а
 * `useMetrikaGoal` шлёт по ней цели. Пока цели брали id прямо из конфига, пустая переменная
 * сборки обнуляла его (у пустой переменной приоритет над умолчанием конфига), а сниппет
 * подставлял наш: счётчик на проде работал, а цели с #701 (2026-09-13) не уходили ни одной
 * (замерено 2026-09-27: `metrikaId:""` в `__NUXT__.config` рядом с `ym(109399587,'init',…)`).
 *
 * ⚠ В локальном режиме (клон у клиента) нашего счётчика нет: иначе трафик чужой установки уходил бы
 * в НАШУ аналитику, вместе с записью сессий. Свой счётчик клон задаёт переменной.
 *
 * Заданное нецифровое значение (например `off`) и нули (`0` — самый естественный способ
 * написать «выключить») дают пусто — счётчик выключен явно. Иначе `0` вставлял бы сниппет
 * `ym(0,…)` с записью сессий, а цели (`Number('0')`) молчали бы. Значение бывает числом: сборка
 * разбирает переменные через `destr`.
 */
export function resolveMetrikaId(value: unknown, localMode: boolean): string {
  const raw = String(value ?? '').trim()
  if (!raw) return localMode ? '' : DEFAULT_METRIKA_ID
  const digits = raw.replace(/\D/g, '')
  return /^0*$/.test(digits) ? '' : digits
}
