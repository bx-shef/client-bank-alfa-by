// Чистый слой раскладки PDF: позиционированные обрывки текста → строки и колонки (#737).
//
// ⚠ ПОЧЕМУ ЭТОТ СЛОЙ ВООБЩЕ ЕСТЬ. Остальные пять форматов приложения — построчные: у них строка
// файла и есть запись банка. У PDF записи нет вовсе: страница это набор обрывков с координатами,
// и «строка» — наш вывод из их взаимного расположения. Замерено на боевых выписках МБАНКа и
// Бакай Банка: чтение ПОТОКОМ текста (то, что даёт любой готовый экстрактор) склеивает итог в
// `12,437.20 30,000.00` — два числа без разделителя — и разрывает `30,000.00` переносом на
// `30,000.0` + `0`. То есть поток даёт число, которое выглядит достоверным и неверно.
//
// ⚠ Слой НАМЕРЕННО не знает про pdfjs и вообще про PDF: на вход — голые `{x, y, text}`. Поэтому
// парсеры банков тестируются без единого PDF-файла, на синтетических координатах, а реальные
// выписки клиентов (ПДн) в публичный репозиторий не попадают. Сам pdfjs закрыт отдельным
// адаптером (`pdfExtract.ts`) и одним смоком.

/** Обрывок текста со страницы: `x`/`y` — левый нижний угол в точках PDF (y растёт ВВЕРХ). */
export interface PdfTextItem {
  x: number
  y: number
  text: string
}

/** Страница: размеры в точках плюс её обрывки текста. */
export interface PdfPage {
  width: number
  height: number
  items: PdfTextItem[]
}

/** Ячейка строки — обрывок, привязанный к своей горизонтальной позиции. */
export interface PdfCell {
  x: number
  text: string
}

/** Визуальная строка: одна вертикальная позиция, ячейки слева направо. */
export interface PdfLine {
  /** Координата `y` строки (наибольшая среди слипшихся обрывков). */
  y: number
  cells: PdfCell[]
}

/**
 * Насколько обрывки могут разойтись по вертикали и всё-таки считаться одной строкой, в точках.
 *
 * ⚠ Число ЗАМЕРЕНО, а не выбрано: у Бакай Банка ячейки одной записи стоят на `y` 336, 333 и 342
 * (подпись, счёт и дата набраны разным кеглем и выровнены по разным базовым линиям), у МБАНКа
 * разброс внутри записи доходит до 3 точек. При этом СОСЕДНИЕ строки таблицы отстоят на 6 точек
 * и больше. Порог обязан лежать между этими величинами; шире — склеит две записи в одну, уже —
 * разорвёт сумму и её дату.
 */
export const LINE_TOLERANCE_PT = 4

/**
 * Собрать обрывки страницы в строки.
 *
 * Обрывки идут сверху вниз (по убыванию `y`), ячейки внутри строки — слева направо. Пустые и
 * пробельные обрывки отбрасываются: они не несут смысла, но ломают определение границ колонки.
 *
 * ⚠ Группировка идёт ЖАДНО от верхней строки вниз, а не округлением `y` к сетке. Округление
 * (`Math.round(y / tol)`) разрезает пару обрывков, попавшую по разные стороны границы ячейки
 * сетки, — то есть результат зависел бы от абсолютной позиции таблицы на странице, а не от
 * расстояния между строками.
 */
export function groupLines(items: PdfTextItem[], tolerance = LINE_TOLERANCE_PT): PdfLine[] {
  const meaningful = items.filter(it => it.text.trim() !== '')
  const sorted = [...meaningful].sort((a, b) => b.y - a.y)
  const lines: PdfLine[] = []
  for (const it of sorted) {
    const last = lines[lines.length - 1]
    if (last && last.y - it.y <= tolerance) {
      last.cells.push({ x: it.x, text: it.text })
      continue
    }
    lines.push({ y: it.y, cells: [{ x: it.x, text: it.text }] })
  }
  for (const line of lines) line.cells.sort((a, b) => a.x - b.x)
  return lines
}

/** Весь текст строки слева направо, ячейки через пробел. */
export function lineText(line: PdfLine): string {
  return line.cells.map(c => c.text.trim()).filter(Boolean).join(' ')
}

/**
 * Текст колонки `[from, to)` в одной строке.
 *
 * ⚠ Границы — полуинтервал, и это несущее: у обеих выписок числа выровнены по ПРАВОМУ краю, то
 * есть их `x` плавает внутри колонки и упирается в левый край соседней. Замкнутый справа интервал
 * захватывал бы первую ячейку следующей колонки — «пополнение» читалось бы как «списание».
 */
export function columnText(line: PdfLine, from: number, to: number): string {
  return line.cells
    .filter(c => c.x >= from && c.x < to)
    .map(c => c.text.trim())
    .filter(Boolean)
    .join(' ')
}

/**
 * Текст колонки `[from, to)`, собранный по НЕСКОЛЬКИМ строкам сверху вниз, без пробела между
 * кусками.
 *
 * ⚠ Ради этого слой и написан: банк переносит длинное число внутри узкой ячейки, и замерено, что
 * `30,000.00` приходит как `30,000.0` на одной строке и `0` на следующей. Склейка ПРОБЕЛОМ дала бы
 * `30,000.0 0` — мусор; склейка встык даёт исходное число. Для текстовых колонок (назначение,
 * контрагент) есть {@link joinColumnText}, он, наоборот, ставит пробел.
 */
export function columnTextGlued(lines: PdfLine[], from: number, to: number): string {
  return lines.map(l => columnText(l, from, to)).filter(Boolean).join('')
}

/**
 * Похожа ли ячейка на кусок числа — только цифры, разделители и знак.
 *
 * ⚠ Проверяем ФОРМУ ячейки, а не разбираем её как сумму: кусок переноса (`30,000.0`, а следом
 * `0`) сам по себе числом быть не обязан, его смысл появляется только после склейки.
 */
export function looksNumeric(text: string): boolean {
  const t = text.trim()
  return t !== '' && /^[-\d\s.,]+$/.test(t)
}

/**
 * Сумма из колонки: склеены ВСТЫК только числовидные ячейки.
 *
 * ⚠ Фильтр несущий, и он закрывает сразу две замеренные беды. Первая: широкое назначение платежа
 * вылезает за середину между заголовками и попадает в колонку суммы — у Бакай Банка хвост
 * `NIa USLU` оказывался ровно там, и склейка со всем подряд давала `NIa USLU434 000,00`, то есть
 * нечитаемую сумму у исправной записи. Вторая: служебная строка «Остаток на конец 434 000,00»
 * стоит В КОЛОНКЕ СУММ и числом не является — её текст отсекается тем же правилом.
 */
export function amountColumnText(lines: PdfLine[], from: number, to: number): string {
  return lines
    .flatMap(l => l.cells.filter(c => c.x >= from && c.x < to))
    .filter(c => looksNumeric(c.text))
    .map(c => c.text.trim())
    .join('')
}

/**
 * Текст из колонки: через пробел и только НЕчисловидные ячейки.
 *
 * ⚠ Зеркало {@link amountColumnText}: сумма, случайно попавшая в текстовую колонку (у Бакая
 * остаток стоит правее назначения), не должна приклеиться к назначению платежа — оно уезжает в
 * карточку клиента, и лишнее число там читается как часть платёжного поручения.
 */
export function textColumnText(lines: PdfLine[], from: number, to: number): string {
  return lines
    .map(l => l.cells
      .filter(c => c.x >= from && c.x < to && !looksNumeric(c.text))
      .map(c => c.text.trim())
      .filter(Boolean)
      .join(' '))
    .filter(Boolean)
    .join(' ')
}

/** Текст колонки по нескольким строкам, куски через пробел — для назначения и контрагента. */
export function joinColumnText(lines: PdfLine[], from: number, to: number): string {
  return lines.map(l => columnText(l, from, to)).filter(Boolean).join(' ')
}

/**
 * Найти `x` заголовка колонки: первая ячейка, чей текст начинается с образца.
 *
 * ⚠ Колонки ищем ПО ЗАГОЛОВКУ, а не по зашитым координатам, по той же причине, по которой CSV
 * разбирается по именам колонок (#707): координаты — свойство одной замеренной выгрузки, и после
 * смены ширины поля разбор по числам молча брал бы сумму из соседней колонки. Не нашли заголовок
 * — `null`, и вызывающий обязан отказаться, а не подставить умолчание.
 */
export function headerX(lines: PdfLine[], startsWith: string): number | null {
  const needle = startsWith.toLowerCase()
  for (const line of lines) {
    for (const cell of line.cells) {
      if (cell.text.trim().toLowerCase().startsWith(needle)) return cell.x
    }
  }
  return null
}

/**
 * Насколько высок двухэтажный заголовок таблицы, в точках.
 *
 * ⚠ Замерено у МБАНКа: «Дата» стоит на `y=666`, «Документ» на `660`, «операции» на `657` — то
 * есть шапка таблицы занимает 9 точек и набрана тремя строками. Ближайшая строка НАД ней
 * («Входящий остаток», `705`) отстоит на 39, ближайшая запись под ней — на 18. Окно обязано
 * лежать между 9 и 18.
 */
export const HEADER_BAND_PT = 12

/**
 * Найти `x` заголовка РЯДОМ с опорной строкой шапки таблицы.
 *
 * ⚠ Это не украшение, а замер: слово «Дата» встречается в выписке РАНЬШЕ таблицы — «Дата
 * формирования информации» в шапке документа. Поиск по всему листу брал его, и колонка «Дата
 * операции» уезжала на 70 точек вправо, забирая себе весь текст корреспондента. Дефект при этом
 * НЕ молчаливый только потому, что рядом стоит сверка сальдо: без неё разбор выглядел бы
 * работающим.
 */
export function headerXNear(
  lines: PdfLine[],
  startsWith: string,
  anchorY: number,
  band = HEADER_BAND_PT
): number | null {
  const needle = startsWith.toLowerCase()
  for (const line of lines) {
    if (Math.abs(line.y - anchorY) > band) continue
    for (const cell of line.cells) {
      if (cell.text.trim().toLowerCase().startsWith(needle)) return cell.x
    }
  }
  return null
}

/** Все `x`, где рядом с опорной строкой стоит заголовок с таким текстом, слева направо. */
export function headerXsNear(
  lines: PdfLine[],
  startsWith: string,
  anchorY: number,
  band = HEADER_BAND_PT
): number[] {
  const needle = startsWith.toLowerCase()
  const xs: number[] = []
  for (const line of lines) {
    if (Math.abs(line.y - anchorY) > band) continue
    for (const cell of line.cells) {
      if (cell.text.trim().toLowerCase().startsWith(needle)) xs.push(cell.x)
    }
  }
  return xs.sort((a, b) => a - b)
}

/** Весь текст страницы одной строкой — для опознания формата (какой это банк). */
export function pageText(page: PdfPage): string {
  return groupLines(page.items).map(lineText).join('\n')
}

/**
 * Насколько ячейка записи выступает ВВЕРХ над своей якорной строкой, в точках.
 *
 * ⚠ Замерено на обеих выписках: у МБАНКа имя плательщика стоит на `y=639` при якоре `636`
 * (нависание 3), у Бакай Банка первая строка детализации — на `345` при якоре `336` (нависание
 * 9). Так выходит потому, что высокая ячейка выровнена по своему верхнему краю, а якорная строка
 * с суммой — по середине записи. При этом СОСЕДНИЕ записи отстоят друг от друга на 36 точек и
 * больше, так что допуск обязан лежать между 9 и 36.
 */
export const TOP_OVERHANG_PT = 12

/**
 * Разрезать строки таблицы на блоки-записи вокруг ЯКОРНЫХ строк.
 *
 * Якорь — строка, по которой видно, что здесь начинается запись банка. Строка относится к якорю,
 * если стоит не выше него более чем на {@link TOP_OVERHANG_PT} и при этом ниже такого же порога
 * у СЛЕДУЮЩЕГО якоря.
 *
 * ⚠ Правило «отдать БЛИЖАЙШЕМУ якорю» выглядит проще и НЕВЕРНО — проверено на живом файле.
 * Ячейки записи не центрированы относительно якоря: они начинаются чуть выше него и тянутся
 * ВНИЗ на всю высоту записи. У МБАНКа хвост реквизитов записи (`y=552`) оказывался ближе к
 * якорю СЛЕДУЮЩЕЙ записи (`534`, расстояние 18), чем к своему (`579`, расстояние 27), — то есть
 * банковский счёт одного плательщика приписывался платежу другого. Ошибка того же класса, что и
 * разъехавшиеся колонки: данные настоящие, но не той записи.
 *
 * ⚠ Строки ВЫШЕ первого якоря и ниже последнего остаются при крайних записях — зона таблицы
 * задаётся вызывающим, и обрезать её здесь значило бы делать это дважды.
 */
export function splitIntoBlocks(
  lines: PdfLine[],
  isAnchor: (line: PdfLine) => boolean,
  overhang = TOP_OVERHANG_PT
): PdfLine[][] {
  const anchorYs = lines.filter(isAnchor).map(l => l.y).sort((a, b) => b - a)
  if (anchorYs.length === 0) return []
  const blocks: PdfLine[][] = anchorYs.map(() => [])
  for (const line of lines) {
    // Первый сверху якорь, чья зона накрывает строку: зона якоря — всё ниже `y + overhang`.
    let slot = anchorYs.findIndex(y => line.y > y + overhang) - 1
    if (slot < -1) slot = anchorYs.length - 1 // ниже всех порогов — последняя запись
    if (slot < 0) slot = 0 // выше первого якоря — его же запись
    blocks[slot]!.push(line)
  }
  for (const block of blocks) block.sort((a, b) => b.y - a.y)
  return blocks
}

/**
 * Границы колонок из `x` их заголовков: граница между соседними колонками — СЕРЕДИНА между
 * заголовками.
 *
 * ⚠ Середина, а не «заголовок минус допуск», и это ЗАМЕР. Числа в обеих выписках выровнены по
 * ПРАВОМУ краю, поэтому их `x` смещён влево от заголовка на ширину самого числа — насколько
 * именно, зависит от суммы. У Бакай Банка заголовок «Остаток» стоит на `x=759`, а его число — на
 * `750`; при допуске в несколько точек остаток попал бы в колонку «Списание», то есть приход
 * клиента прочитался бы как расход. Середина между «Списание» (692) и «Остаток» (759) разводит
 * их без единого зашитого числа.
 */
export function columnBounds(headers: number[]): Array<{ from: number, to: number }> {
  const xs = [...headers].sort((a, b) => a - b)
  const byX = new Map<number, { from: number, to: number }>()
  xs.forEach((x, i) => {
    byX.set(x, {
      from: i === 0 ? Number.NEGATIVE_INFINITY : (xs[i - 1]! + x) / 2,
      to: i === xs.length - 1 ? Number.POSITIVE_INFINITY : (x + xs[i + 1]!) / 2
    })
  })
  // ⚠ Возвращаем В ПОРЯДКЕ ВХОДА, а не отсортированном. Первая редакция отдавала отсортированный
  // список, и вызывающий, разобравший его по своим именам колонок, получал чужие границы, если
  // заголовки в файле идут не по возрастанию `x`. Поймала сверка сальдо, а не тест.
  return headers.map(x => byX.get(x)!)
}
