// Сообщение администратору, когда не удалось назначить счёт подключению (#509).
//
// Зачем отдельный чистый модуль, а не `frameFetchError`: тот подклеивает к подводке текст ошибки
// СЕРВЕРА, а он английский (`this account is already connected`). Пока исходов было два и оба
// означали тупик, это было терпимо. Теперь появился третий — «занято, повторите через несколько
// секунд», — и он единственный, ради которого сообщение вообще читают: он говорит, что делать
// дальше. Совет, набранный на языке, которого читатель может не знать, не работает.
//
// Форма — как у `loginError.ts`: маппинг статуса в текст, чистый и под тестом.

/** HTTP-статус из отказа `$fetch` (FetchError) либо axios-подобной ошибки. */
export function setAccountErrorStatus(e: unknown): number | undefined {
  const err = e as { statusCode?: number, response?: { status?: number } } | null | undefined
  return err?.statusCode ?? err?.response?.status
}

/**
 * Текст для администратора по статусу ответа `/api/bank/set-account`.
 *
 * ⚠ 503 и 409 разведены намеренно: 409 — «так не будет никогда» (номер уже занят другим
 * подключением, надо менять номер), 503 — «сейчас занято, через несколько секунд пройдёт»
 * (строку держит обновление токена). Один текст на оба приучил бы либо повторять там, где повтор
 * бесполезен, либо сдаваться там, где хватило бы второго клика.
 */
export function setAccountErrorMessage(e: unknown): string {
  const status = setAccountErrorStatus(e)
  if (status === 503) return 'Подключение сейчас обновляется — повторите через несколько секунд.'
  if (status === 409) return 'Этот счёт уже подключён — выберите другой номер.'
  if (status === 404) return 'Подключение не найдено: возможно, его уже отключили. Обновите список.'
  if (status === 403) return 'Привязывать счёт может только администратор портала.'
  return 'Не удалось привязать счёт — попробуйте ещё раз.'
}
