// Свои блоки на карточке дела — `crm.activity.layout.blocks.set` (#729).
//
// ЗАЧЕМ. Всё, что приложение знало о платеже, лежало ОДНИМ куском BB-текста в описании: семь
// подписанных строк подряд. Читать в ленте это тяжело, а главное — назначение платежа, ради
// которого карточку и открывают, стояло седьмым. Блоки дают порталу СТРУКТУРУ (подпись → значение),
// поэтому реквизиты уезжают в таблицу, а в комментарии остаётся ровно то, что человек читает
// текстом.
//
// ⚠ ПУТЬ ТОЛЬКО ОДИН, И ОН OAuth. `crm.activity.layout.blocks.set` требует контекста приложения
// (вебхуком не вызвать) и работает ТОЛЬКО по запланированному делу — у нас это `todo.add`.
// Замерено 2026-09-16: на системном деле запасного носителя (#722) он отвечает `This activity type
// is not supported for adding layout blocks`. Значит на старом портале блоков не будет НИКОГДА, и
// описание там обязано остаться самодостаточным (см. `buildActivityDescription`, режим `full`).
//
// ⚠ БЛОКИ — ОТДЕЛЬНЫЙ ВЫЗОВ ПОСЛЕ создания дела, то есть могут не дойти. Поэтому сюда не кладётся
// ничего, чего нет больше нигде: сумма, направление и контрагент дублируются заголовком дела, а
// назначение живёт в описании. Отказ блоков ухудшает вид карточки и не теряет сведений.
//
// ⚠ ЗНАЧЕНИЯ ПЛАТЕЛЬЩИКА ВСЁ РАВНО НЕЙТРАЛИЗУЮТСЯ. Блок — структурный JSON, а не BB-разметка,
// поэтому `[url=…]` в назначении или в имени контрагента скорее всего отрисуется буквально. Но
// «скорее всего» здесь не измерено: как портал рендерит текст блока, по ответу REST не видно, а
// цена ошибки — живая ссылка в карточке клиента, которую вписал плательщик. `neutralizeBb` стоит
// один проход по строке, поэтому ответ на этот вопрос не нужен.
//
// ⚠ СЛОВАРЬ ЗАКРЫТ, И ЭТО НЕ НАШЕ РЕШЕНИЕ. Портал принимает шесть типов блоков (`text`,
// `largeText`, `link`, `deadline`, `withTitle`, `lineOfBlocks`), до 20 штук, вложенность РОВНО на
// один уровень, цвета только `base_50`/`base_60`/`base_70`/`base_90`, размеры `xs`/`sm`/`md`.
// Отсюда и форма «таблицы»: `withTitle` + вложенный `text` на каждое поле.

import type { BankProviderId, StatementItem } from '~/types/statement'
import { formatIsoDate, neutralizeBb } from '~/utils/activity'
import { type PortalCurrencyFormats, formatAmountWithPortal } from '~/utils/currencyFormat'

/** REST-метод, который вешает наши блоки на существующее дело. */
export const ACTIVITY_BLOCKS_SET_METHOD = 'crm.activity.layout.blocks.set'

/** Потолок портала на число блоков в одном layout. */
export const MAX_LAYOUT_BLOCKS = 20

/** Блок разметки в том виде, в каком его принимает портал. */
export interface LayoutBlock {
  type: string
  properties: Record<string, unknown>
}

/**
 * Откуда приехала операция.
 *
 * ⚠ Это НЕ банк контрагента (он в выписке отдельным полем и к источнику отношения не имеет), а
 * наш путь получения: два онлайн-подключения и ручная загрузка файла. Прежний блок назывался
 * «Банк» и показывал банк плательщика — на вопрос «откуда это взялось в моей CRM» он не отвечал.
 *
 * ⚠ Для ручной загрузки банк НЕ НАЗЫВАЕТСЯ, хотя формат файла его знает (`detectManualFormat`
 * различает выгрузки Альфы, Приорбанка и Паритетбанка). Причина не в лени: `StatementItem` такого
 * поля не несёт вовсе, и протащить его — значит тронуть модель и все шесть парсеров. Назвать банк
 * наугад нельзя: «Ручная загрузка из Альфа-Банка» на файле Паритетбанка — прямая ложь в карточке
 * клиента, и опровергнуть её человеку нечем.
 */
export const SOURCE_LABEL: Record<BankProviderId, string> = {
  'alfa-by': 'Автозагрузка из Альфа-Банка',
  'prior-by': 'Автозагрузка из Приорбанка',
  'manual': 'Ручная загрузка выписки'
}

/** Подпись источника. Неизвестный провайдер описывается честно, а не подставляется первым из
 *  списка: строка «Автозагрузка из Альфа-Банка» на операции из другого банка — ложь. */
export function sourceLabel(providerId: BankProviderId | undefined): string {
  return (providerId && SOURCE_LABEL[providerId]) || 'Импорт выписки'
}

/** Строка таблицы: подпись слева, значение справа. `inline` — иначе портал переносит значение
 *  на следующую строку и таблица перестаёт читаться колонками. */
function row(title: string, value: string, props: Record<string, unknown> = {}): LayoutBlock {
  return {
    type: 'withTitle',
    properties: { title, inline: true, block: { type: 'text', properties: { value, ...props } } }
  }
}

/**
 * Собрать блоки карточки для одной операции.
 *
 * ПОРЯДОК ПОЛЕЙ — решение владельца 2026-09-16: сумма, контрагент, УНП, документ, источник.
 * Он не алфавитный и не «как в выписке»: сверху то, по чему платёж узнают (сколько и от кого),
 * ниже — то, по чему его сверяют, и в самом низу — откуда он у нас взялся.
 *
 * ⚠ В ТАБЛИЦЕ НЕТ ДВУХ ПОЛЕЙ, И ОБА УБРАНЫ ОСОЗНАННО (решение владельца 2026-09-16) — они живут в
 * КОММЕНТАРИИ, под текстом назначения:
 *   • **назначение** — единственное поле, которое читают целиком, а не сверяют взглядом: длинное,
 *     произвольной длины, написано человеком; в таблице реквизитов оно ломало бы колонки;
 *   • **счёт контрагента** — идёт следом за назначением как его основание.
 *
 * ⚠ У счёта есть ВТОРАЯ, несущая причина жить в описании, и она не про вид: «Очистка» умеет стирать
 * дела по счёту ПЛАТЕЛЬЩИКА (#591) и берёт его РАЗБОРОМ строки `[B]Счёт:[/B]` из описания — в
 * маркере лежит НАШ счёт, а не его. Пока счёт был только блоком, этот фильтр не находил новые дела
 * вовсе: блоки читаются лишь поштучным вызовом на каждое дело, то есть пучком их не отобрать.
 * Перенести счёт обратно в таблицу — значит снова сломать необратимое действие, и молча.
 *
 * ⚠ Пустые поля НЕ рисуются: строка «УНП: —» занимает место и ничего не сообщает. У выписки
 * Паритетбанка имени контрагента нет вовсе (#700), так что пустые поля — обычное дело, а не брак.
 */
export function buildActivityBlocks(
  item: StatementItem,
  providerId?: BankProviderId,
  /** Справочник валют ПОРТАЛА: у BYN там подпись «руб.», у USD символ стоит перед суммой. Без него
   *  сумма показывается кодом («1 840,50 BYN») — хуже, но дело всё равно записано. */
  currencies?: PortalCurrencyFormats
): LayoutBlock[] {
  const cp = item.counterparty
  const blocks: LayoutBlock[] = []

  // Сумма — единственное, что выделено: в ленте по ней находят нужный платёж.
  blocks.push(row(
    item.direction === 'credit' ? 'Приход' : 'Расход',
    formatAmountWithPortal(item.amount, item.currency, currencies),
    { bold: true, color: 'base_90' }
  ))

  const name = neutralizeBb(cp.name)
  if (name) blocks.push(row('Контрагент', name))

  const unp = neutralizeBb(cp.unp)
  if (unp) blocks.push(row('УНП', unp))

  blocks.push(row('Документ', item.docNum
    ? `#${neutralizeBb(item.docNum)} от ${formatIsoDate(item.acceptDate)}`
    : `от ${formatIsoDate(item.acceptDate)}`))

  blocks.push(row('Источник', sourceLabel(providerId), { color: 'base_60', size: 'xs' }))

  // Потолок портала недостижим при шести полях, но срезаем здесь: молча отвергнутый вызов оставил
  // бы карточку без блоков вообще, а лишний блок дороже усечённой таблицы.
  return blocks.slice(0, MAX_LAYOUT_BLOCKS)
}

/**
 * Параметры `crm.activity.layout.blocks.set`.
 *
 * ⚠ Адресуется ТРОЙКОЙ владелец+дело, а не одним `activityId`: портал проверяет по ней права на
 * запись, и владелец здесь обязан совпадать с владельцем дела — иначе вызов отвергается.
 */
export function buildActivityBlocksCall(
  activityId: string,
  ownerTypeId: number,
  ownerId: number,
  blocks: LayoutBlock[]
): { method: string, params: Record<string, unknown> } {
  return {
    method: ACTIVITY_BLOCKS_SET_METHOD,
    params: { entityTypeId: ownerTypeId, entityId: ownerId, activityId, layout: { blocks } }
  }
}
