//
// ⚠ ЗАЧЕМ. Форк приложения (свой CI + свой GHCR) — та же функциональность, но без НАШИХ
// промо/брендинг-баннеров: карточки «Нужна доработка», карточки Маркета, визитки ИП Шевчик и
// попапа «оцените приложение». Суть импорта выписки не меняется — убираются только баннеры.
//
// ⚠ Флаг BUILD-TIME (`NUXT_PUBLIC_LOCAL_MODE`, build-arg): статика лендинга и in-portal UI
// пререндерятся на сборке, поэтому runtime-переменная фронтом бы не подхватилась. На бэке флаг
// поведения НЕ меняет (баннеров там нет) — он валидируется в `envCheck` и прокидывается в оба
// образа только ради согласованности сборки (решение владельца).

/**
 * Включён ли локальный режим. Истина ТОЛЬКО для явного включения (`1`/`true`/`yes`/`on`,
 * регистронезависимо); всё прочее — обычный режим.
 *
 * ⚠ Fail-safe в сторону «показывать наш брендинг»: сомнительное/пустое/кривое значение НЕ прячет
 * промо — иначе опечатка в переменной молча выпустила бы обезличенный билд там, где его не хотели.
 *
 * ⚠ Число `1` и булево `true` — ТЕ ЖЕ документированные значения, а не мусор: переменные
 * `NUXT_PUBLIC_*` сборка разбирает через `destr`, и в конфиг `NUXT_PUBLIC_LOCAL_MODE=1` приходит
 * числом. Пока функция признавала только строки, флаг не делал на клоне НИЧЕГО (замерено
 * 2026-09-27: `localMode:1` в `__NUXT__.config`, а на лендинге наша карточка Маркета и наш
 * счётчик) — строку он получал лишь при чтении окружения напрямую (`envCheck`, `nuxt.config.ts`).
 */
export function isLocalMode(value: unknown): boolean {
  if (value === 1 || value === true) return true
  if (typeof value !== 'string') return false
  const v = value.trim().toLowerCase()
  return v === '1' || v === 'true' || v === 'yes' || v === 'on'
}
