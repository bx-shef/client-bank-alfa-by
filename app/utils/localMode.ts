// образа только ради согласованности сборки (решение владельца).

/**
 * Включён ли локальный режим. Истина ТОЛЬКО для явного включения (`1`/`true`/`yes`/`on`,
 * регистронезависимо); всё прочее — обычный режим.
 *
 * ⚠ Fail-safe в сторону «показывать наш брендинг»: сомнительное/пустое/кривое значение НЕ прячет
 * промо — иначе опечатка в переменной молча выпустила бы обезличенный билд там, где его не хотели.
 */
export function isLocalMode(value: unknown): boolean {
  if (typeof value !== 'string') return false
  const v = value.trim().toLowerCase()
  return v === '1' || v === 'true' || v === 'yes' || v === 'on'
}
