// Чистое ядро уборщика мёртвых порталов (#574).
//
// ⚠ САМОЕ ОПАСНОЕ, что есть в этом приложении: единственный механизм, который стирает данные
// клиента БЕЗ его действия. Всё остальное удаление событийное (`ONAPPUNINSTALL`) или возрастное по
// агрегатам. Поэтому здесь важнее не «поймать всех», а «не тронуть живого».
//
// ⚠ Зачем вообще. Портал может исчезнуть не по-штатному — удалён без доставки события, сменил
// домен, — и тогда `import_result`/`metrics_counter` уйдут по TTL, а `portal_tokens` и
// `bank_tokens` останутся.
//
// ⚠ Продлевают их РАЗНЫЕ механизмы, и путать их нельзя (правка по ревью). `tokenKeepAlive` (#175)
// читает и пишет ТОЛЬКО `portal_tokens`. Банковские токены продлевает отдельный
// `bankTokenKeepAlive` (#488/#489) со своим таймером, и его выборка — голый `SELECT ... FROM
// bank_tokens`: он не смотрит на грант портала ВООБЩЕ. То есть банковские доступы ушедшего
// клиента освежаются независимо от того, жив ли его портал, и именно это делает задачу
// приватностью (`docs/PRIVACY.md`), а не уборкой мусора. Прежняя редакция этого комментария
// приписывала продление банковских кредов #175 и отправляла бы читателя чинить не тот механизм.
//
// ⚠ Асимметрия цены названа прямо и определяет каждое решение ниже: «подержали лишнюю неделю» —
// неприятно; «стёрли живого клиента» — потеря его подключений к банку, за которыми стоит поход
// ВЛАДЕЛЬЦА СЧЁТА в интернет-банк. Поэтому сигнал узкий, порог длинный, и на один прогон стоит
// потолок.

/**
 * Код ответа OAuth, означающий, что грант МЁРТВ: вернуться по нему нельзя никак, только
 * переустановкой приложения.
 *
 * ⚠ Список УЖЕ, чем у `verifyInstallMember` (`invalid_grant`/`invalid_token`/`expired_token`), и
 * это не забывчивость. Там ошибка в сторону «не смогли проверить» безопасна — установка просто не
 * запишется. Здесь направление ОБРАТНОЕ: ошибка классификации стирает данные живого клиента.
 * Поэтому берём единственный код, который однозначно значит «этот refresh_token больше не грант», —
 * и ничего сверх.
 *
 * ⚠ `PAYMENT_REQUIRED` сюда НЕ входит, и это не мелочь: истёкший триал значит «клиент жив, но не
 * платит». Стереть его банковские доступы за неуплату — не уборка, а вред.
 *
 * ⚠ Сеть, 5xx, таймаут, `wrong_client` (наша конфигурация) — тоже не сигнал. Они говорят «не
 * смогли спросить», а не «нам отказали».
 */
const GRANT_DEAD_CODE = 'invalid_grant'

/**
 * Отказ означает мёртвый грант?
 *
 * Читает МАШИННЫЙ код, а не текст: SDK бросает `RefreshTokenError` с `code` из тела ответа OAuth
 * (`code = responseData.error`, проверено по `oauth/auth.mjs` установленной версии), а описание
 * приходит на языке сервера. Общая читалка кода — `portalErrorCode` (#572).
 */
export function isGrantDead(code: string): boolean {
  return code === GRANT_DEAD_CODE
}

/** Нижняя граница порога, ниже которой опустить его НЕЛЬЗЯ никакой настройкой. */
export const MIN_REAP_DAYS = 14
/** Значение по умолчанию: месяц молчания при мёртвом гранте. */
export const DEFAULT_REAP_DAYS = 30
/**
 * Сколько порталов максимум стирается за один прогон.
 *
 * ⚠ Это не про нагрузку, а про КЛАСС ошибок: если классификатор однажды начнёт считать мёртвым
 * что-то живое, потолок превращает «снесли всех за один тик» в «снесли троих, и это видно».
 *
 * ⚠ ЗАМЕРЕНО, и прежнее обоснование было НЕВЕРНЫМ: здесь стояло «прогон идёт раз в сутки», а
 * уборщик висел на свип-тике, у которого дефолт — 30 МИНУТ (`STATEMENT_SWEEP_INTERVAL_MIN`,
 * кламп от 1 мин). То есть потолок «3 за прогон» означал до ~144 порталов в сутки — ровно тот
 * масштаб, которым сам комментарий пугал как невозможным. Потолок за прогон в принципе не может
 * ограничить ущерб, пока частота прогонов задаётся чужой переменной, поэтому теперь у уборщика
 * СВОЯ каденция (`REAP_MIN_INTERVAL_MS`), а от общей причины защищает не он, а предохранитель
 * по доле флота (`fleetBreach`).
 */
export const MAX_REAP_PER_RUN = 3

/**
 * Порог из настройки: только ЦЕЛОЕ число дней, не ниже пола.
 *
 * ⚠ Кламп ВВЕРХ от пола, а не в обе стороны: занизить порог — единственный способ превратить
 * уборщик в оружие, а завысить его безвредно (подержим дольше). Мусор и пустое значение дают
 * умолчание, а не ноль: `Number('')` это 0, и без явной ветки опечатка в переменной окружения
 * означала бы «стирать немедленно».
 */
export function resolveReapDays(raw: string | undefined): number {
  const n = Number(String(raw ?? '').trim())
  if (!Number.isFinite(n) || n <= 0) return DEFAULT_REAP_DAYS
  return Math.max(MIN_REAP_DAYS, Math.floor(n))
}

/** Решение по одному порталу. Отдельный тип, потому что «почему НЕ стёрли» нужно в логе не меньше,
 *  чем «стёрли»: молчаливый уборщик неотличим от невзведённого. */
export type ReapVerdict = 'reap' | 'too-early' | 'alive'

/**
 * Пора ли стирать портал.
 *
 * @param revokedAtMs когда грант ПЕРВЫЙ раз ответил «мёртв»; `0`/`null` — такого не было.
 * @param nowMs часы (инъектируются).
 * @param days порог в днях (уже прошедший `resolveReapDays`).
 *
 * ⚠ Отсчёт от ПЕРВОГО отказа, а не от последнего: иначе каждый новый тик отодвигал бы срок, и
 * портал не был бы стёрт никогда — уборщик выглядел бы рабочим и не работал.
 *
 * ⚠ Метка обязана СБРАСЫВАТЬСЯ при любом удачном обновлении (это делает вызывающий). Без сброса
 * один транзиентный `invalid_grant` — а такое бывает при гонке ротации — приговаривал бы портал
 * навсегда, и никакое последующее здоровье его бы не спасло.
 *
 * ⚠ Часы будущего не боимся: `revokedAtMs > nowMs` даёт отрицательный возраст и `too-early`, то
 * есть отсрочку, а не досрочное удаление.
 */
export function reapVerdict(revokedAtMs: number | null | undefined, nowMs: number, days: number): ReapVerdict {
  if (!revokedAtMs || revokedAtMs <= 0) return 'alive'
  const ageMs = nowMs - revokedAtMs
  return ageMs >= days * 86_400_000 ? 'reap' : 'too-early'
}

/** Что уборщик сделал за прогон — для строки лога и для экрана оператора. */
export interface ReapRunFacts {
  /** Сколько порталов помечено мёртвым грантом дольше порога. */
  candidates: number
  /** Сколько реально стёрто. */
  reaped: number
  /** Сколько удалений не прошло. */
  failed: number
  /** Упёрлись в потолок за прогон. */
  capped: boolean
  /** Удаление выключено (`PORTAL_REAP_ENABLED`) — только считаем и показываем. */
  observeOnly: boolean
  /** Сработал предохранитель по доле флота — не стёрли НИЧЕГО. */
  breach: boolean
  /** Порог в днях. */
  days: number
}

/**
 * Строка лога о прогоне уборщика.
 *
 * ⚠ Печатается ВСЕГДА, даже когда стирать нечего. Уборщик, который молчит, неотличим от
 * невзведённого — а узнать, что он не работал, хочется до того, как это выяснится проверкой
 * приватности, а не после.
 *
 * ⚠ `failed` попал в строку по ревью: раньше он не доезжал сюда ВООБЩЕ, и отказ удаления был виден
 * только в отдельной строке по конкретному порталу. Стоило той строке потеряться — и провал
 * становился полностью невидимым, включая сводку прогона.
 */
export function reaperLogLine(f: ReapRunFacts): string {
  if (f.breach) {
    return `порог ${f.days} дн.: кандидатов ${f.candidates} — это слишком большая доля флота, `
      + `НИЧЕГО не стёрто. Похоже на нашу общую поломку, а не на уход клиентов`
  }
  const head = `порог ${f.days} дн.: кандидатов ${f.candidates}`
  if (f.observeOnly) {
    return f.candidates
      ? `${head}, удаление ВЫКЛЮЧЕНО (PORTAL_REAP_ENABLED) — только наблюдаем`
      : `${head}, удаление выключено (PORTAL_REAP_ENABLED)`
  }
  const cap = f.capped ? `, за прогон стёрто не больше ${MAX_REAP_PER_RUN} — остальные в следующий` : ''
  const bad = f.failed ? `, НЕ УДАЛОСЬ стереть ${f.failed}` : ''
  return `${head}, стёрто ${f.reaped}${bad}${cap}`
}

/**
 * Сколько ждать между прогонами уборщика.
 *
 * ⚠ СВОЯ каденция, а не свип-тик, и это не косметика. Уборщик висел на `runSweep`, чья частота
 * задаётся ЧУЖОЙ переменной `STATEMENT_SWEEP_INTERVAL_MIN` (дефолт 30 мин, кламп от 1 мин) и
 * заведена совсем про другое — про чистку payload'ов выписки. Пока частота приходит оттуда,
 * потолок «N за прогон» не ограничивает ущерб ни в каком смысле: оператор, ускоривший чистку
 * выписок, молча ускорял бы необратимое удаление порталов.
 */
export const REAP_MIN_INTERVAL_MS = 24 * 60 * 60 * 1000

/** Прошло ли достаточно с прошлого прогона. `null` — прогонов ещё не было. */
export function reapDue(lastRunMs: number | null, nowMs: number, minIntervalMs = REAP_MIN_INTERVAL_MS): boolean {
  if (lastRunMs === null) return true
  // Часы будущего не боимся: отрицательная разница читается как «ещё рано», то есть отсрочка.
  return nowMs - lastRunMs >= minIntervalMs
}

/** Ниже этого числа порталов доля не считается — на крошечном флоте она бессмысленна. */
export const FLEET_BREACH_MIN_PORTALS = 5
/** Доля флота, выше которой уборщик отказывается работать. */
export const FLEET_BREACH_SHARE = 0.34

/**
 * Похоже ли, что «мёртвыми» стали не клиенты, а МЫ.
 *
 * ⚠ Это главный предохранитель, и он существует потому, что потолок за прогон защищает не от того.
 * Потолок ограничивает ошибку классификатора на ОДНОМ портале; он бессилен против ОДНОЙ причины,
 * ударившей по ВСЕМ сразу, — та просто размажется по прогонам и выкосит флот за несколько дней.
 *
 * ⚠ Конкретный повод ЗАМЕРЕН, и, вопреки нашему же рантбуку, оказался НЕ страшным: неверный
 * `B24_CLIENT_SECRET` даёт `invalid_client` (HTTP 400), а `invalid_grant` приходит только на
 * реально мёртвый грант при ВЕРНОМ секрете. То есть известная общая причина сигнал не подделывает.
 * Предохранитель оставлен именно поэтому: он закрывает не измеренную причину, а НЕИЗВЕСТНЫЕ —
 * смену поведения Б24, нашу будущую правку классификатора, массовую блокировку приложения. От
 * измеренного мы защищены знанием, от неизмеренного — только отказом действовать.
 *
 * ⚠ Порог доли, а не абсолютное число: «10 мёртвых» значит разное на флоте в 12 порталов и в 500.
 * На совсем маленьком флоте (< `FLEET_BREACH_MIN_PORTALS`) доля не считается вовсе — там «двое из
 * трёх» это нормальный исход двух ушедших клиентов, а не авария.
 */
export function fleetBreach(candidates: number, totalPortals: number): boolean {
  if (totalPortals < FLEET_BREACH_MIN_PORTALS) return false
  return candidates > totalPortals * FLEET_BREACH_SHARE
}
