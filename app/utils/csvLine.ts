// Разбор строки CSV-выписки на ячейки. Общий для обоих банковских CSV (#707).
//
// ⚠ ЗАЧЕМ НЕ `split(';')`. Разделитель `;`, а назначение платежа и имя контрагента пишет
// ПЛАТЕЛЬЩИК — то есть в поле приходит текст, который мы не контролируем. Замерено на голом
// `split`: назначение «ОПЛАТА; СЧЕТ 5 ОТ 01.08.2026» превращается в «ОПЛАТА», хвост исчезает
// МОЛЧА — ни отказа, ни счётчика, ни строки в логе. Сверка оборотов такой случай не ловит по
// построению: суммы стоят ЛЕВЕЕ назначения и не сдвигаются.
//
// ⚠ Цена потери не косметическая: назначение — вход распознавания номеров (§4), а номер счёта или
// заказа живёт как раз в хвосте после точки с запятой. Исчезнув, он даёт «клиент не опознан» /
// «цель не найдена» — то есть симптом всплывает в СОВЕРШЕННО другом месте (чат ошибок, экран
// готовности), и связать его с разделителем некому.
//
// Два правила закрывают это:
//   1. КАВЫЧКИ. Поле в двойных кавычках может содержать разделитель; `""` внутри — экранированная
//      кавычка (правило RFC 4180, его же реализует Excel). Банки уже пишут кавычки в именах
//      (`ООО "ДЕМОКЛИЕНТ"`), просто пока не как экранирование — день, когда добавят, наступит без
//      предупреждения.
//   2. ХВОСТ. Разделители в ПОСЛЕДНЕЙ содержательной колонке склеиваются обратно: у обоих банков
//      последняя колонка — назначение, и именно в нём текст плательщика. Это то же, что делает
//      любой CSV-читатель без кавычек, и снимает самый частый случай.

/** Ячейки строки CSV. Поля в кавычках сохраняются целиком, `""` разворачивается в `"`. */
export function splitCsvLine(line: string, sep = ';'): string[] {
  const cells: string[] = []
  let cur = ''
  let quoted = false
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i]!
    if (quoted) {
      if (ch !== '"') {
        cur += ch
        continue
      }
      // `""` внутри поля — это одна кавычка, а не конец поля.
      if (line[i + 1] === '"') {
        cur += '"'
        i += 1
        continue
      }
      quoted = false
      continue
    }
    // ⚠ Кавычка открывает поле ТОЛЬКО в его начале. Иначе `ООО "ДЕМО" СЕРВИС;…` — обычное имя с
    // кавычками посередине — было бы прочитано как экранирование, и разделитель за ним перестал
    // бы разделять: строка схлопнулась бы в одну ячейку.
    if (ch === '"' && cur === '') {
      quoted = true
      continue
    }
    if (ch === sep) {
      cells.push(cur)
      cur = ''
      continue
    }
    cur += ch
  }
  cells.push(cur)
  return cells
}

/**
 * Значение ПОСЛЕДНЕЙ содержательной колонки: всё, что осталось справа, склеенное обратно.
 *
 * ⚠ Нужна потому, что кавычки закрывают лишь половину беды: банк, ставящий `;` в назначение и НЕ
 * квотирующий поле, сдвинет всё вправо. У обоих замеренных форматов после назначения идут только
 * пустые служебные колонки, поэтому склейка хвоста восстанавливает текст целиком.
 * ⚠ Пустые хвостовые ячейки отбрасываются, иначе назначение оканчивалось бы вереницей `;`.
 */
export function tailCell(cells: string[], from: number, sep = ';'): string {
  const tail = cells.slice(from)
  while (tail.length > 1 && (tail[tail.length - 1] ?? '').trim() === '') tail.pop()
  return tail.join(sep).trim()
}
