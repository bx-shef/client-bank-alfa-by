// Shared money helpers — one place for the "round once after summing, no IEEE-754 drift"
// rule so the display aggregators (demoExtract «суммы по валютам», importStats #62) don't
// each carry their own copy. Pure, no DOM.

/**
 * Round a money amount to 2 decimals (kopecks), avoiding float drift
 * (`0.1 + 0.2 → 0.3`, not `0.30000000000000004`). A non-finite input (NaN/Infinity — a bad
 * row) is coerced to `0` so it can't poison a total shown to the user.
 */
export function round2(n: number): number {
  if (!Number.isFinite(n)) return 0
  return Math.round((n + Number.EPSILON) * 100) / 100
}

/**
 * Сумма из банковской записи: `1054,89`, `1 800,00`, `10 000.00`.
 *
 * ⚠ Разделители У КАЖДОГО БАНКА СВОИ, и это ЗАМЕРЕНО на боевых выгрузках (#707): звёздочный
 * формат и CSV Приорбанка пишут копейки через ЗАПЯТУЮ, CSV Альфа-Банка — через ТОЧКУ, тысячи оба
 * отбивают пробелом. Поэтому правило одно на все форматы: пробелы убираем, запятую приводим к
 * точке, и лишь затем проверяем МАСКОЙ.
 *
 * ⚠ Маска обязательна — `parseFloat` здесь не годится: он читает `18,28abc` как 18, `1e3` как
 * 1000, а `--18` как `NaN` лишь случайно. Мусор обязан быть отличим от нуля, иначе нечитаемая
 * сумма превращается в операцию «0,00» либо в служебную запись банка.
 *
 * ⚠ **Американская форма `1,234.56` (#737)** — оба знака в одном числе, и тысячи отбивает
 * ЗАПЯТАЯ. Замерено на PDF-выписках МБАНКа: `3,109.30` и итог `12,437.20`. Прежнее правило
 * («запятая → точка») давало `3.109.30`, то есть честный `NaN`, — не соврало, но и прочитать не
 * могло. Разводит их ПОСЛЕДНИЙ разделитель: он десятичный, все предыдущие — разрядные. Правило
 * не зависит от банка и потому живёт здесь, а не в парсере одного формата.
 *
 * ⚠ Одна только запятая по-прежнему ДЕСЯТИЧНАЯ (замерено у Приорбанка и звёздочного формата), и
 * менять это нельзя: `1,00` там ровно рубль. Поэтому `1,433,000` без копеек — НЕ число для нас
 * (`NaN`), и это осознанный недобор: принять его значило бы решать монеткой между «одна тысяча
 * четыреста тридцать три» и «миллион с лишним».
 *
 * Возвращает `NaN` на всём, что не разобралось; что это значит — решает вызывающий.
 */
export function parseBankAmount(raw: string): number {
  const t = normalizeSeparators((raw ?? '').trim().replace(/\s/g, ''))
  if (!/^-?\d+(\.\d+)?$/.test(t)) return Number.NaN
  return Number(t)
}

/** Свести разделители к одной десятичной точке: последний из `.`/`,` — десятичный, все
 *  предыдущие — разрядные и удаляются. Одиночный разделитель остаётся десятичным (прежнее,
 *  замеренное поведение обоих белорусских форматов). */
function normalizeSeparators(t: string): string {
  const last = Math.max(t.lastIndexOf('.'), t.lastIndexOf(','))
  if (last < 0) return t
  const head = t.slice(0, last)
  const tail = t.slice(last + 1)
  // Разрядные знаки убираем ТОЛЬКО когда их тип отличается от десятичного: у `1.234.567`
  // последний знак того же вида, и это по-прежнему не число (маска отвергнет) — угадывать,
  // копейки там или разряды, мы не беремся.
  const sep = t[last]
  const other = sep === '.' ? ',' : '.'
  return `${head.split(other).join('')}.${tail}`
}
