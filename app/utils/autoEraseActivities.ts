// Чистое ядро АВТОМАТИЧЕСКОГО удаления дел, созданных приложением (#722).
//
// ⚠ ЭТО НЕ ВТОРАЯ КОПИЯ «Очистки» (#576 п.4). У той отбор задаёт человек (период, наши счета,
// счета контрагентов), она идёт в один HTTP-запрос и её исход человек видит на экране. Здесь
// отбор один и тот же на все порталы, прогон идёт без свидетелей и повторяется каждые сутки —
// поэтому и правила другие, и границы безопасности другие. Общее у них ровно одно, и оно вынесено,
// а не продублировано: подтверждение НАШЕГО `ORIGINATOR_ID` в ОТВЕТЕ портала
// (`selectDeletable` в `eraseActivities.ts`).
//
// ⚠ ДАТА — СОЗДАНИЯ ДЕЛА (`CREATED`), А НЕ ПЛАТЕЖА (`DEADLINE`), и это не придирка к полям.
// Замерено на боевом портале 2026-09-16: из 17 наших дел у ЧЕТЫРЁХ даты расходятся (создано
// 09-09, платёж 09-07/09-08). Разрыв берётся из двух источников сразу: банк проводит операцию
// задним числом, а ручная загрузка старой выписки создаёт СЕГОДНЯШНИЕ дела для платежей любой
// давности. Удаляй мы по дате платежа — загруженная мартовская выписка исчезла бы на первом же
// тике, до того как её кто-то открыл. Отсчёт от создания отвечает на вопрос «сколько это провисело
// у человека перед глазами», а именно его и задаёт настройка.
//
// ⚠ ПОРОГ ВЫВОДИТСЯ ИЗ ОКНА ОПРОСА, А НЕ ЗАШИТ. Маркер дедупа живёт НА САМОМ ДЕЛЕ (#259): удалили
// дело — удалили маркер, и если операция ещё попадает в окно опроса (`CRON_LOOKBACK_DAYS`),
// следующий же опрос запишет её заново. Зашитая пятёрка на портале с недельным окном дала бы
// вечную карусель «удалили → импортировали → удалили», сжигающую лимиты и банка, и Bitrix24.
// Рантбук описывает ровно этот симптом как ручную ошибку («Стёрли дела, а они вернулись» —
// `OPERATIONS.md`); автомату повторять её нельзя по построению.

import { ACTIVITY_ORIGIN, PORTAL_TZ_OFFSET } from './activity'

/**
 * Сколько суток дело живёт ПОСЛЕ того, как перестало быть доступным для повторного импорта.
 *
 * ⚠ Это человеческая величина — время бухгалтера на «увидеть и разобрать», — и она НЕ должна
 * сокращаться оттого, что оператор сузил окно опроса: это разные вопросы к одному числу.
 */
export const AUTO_ERASE_GRACE_DAYS = 2

/**
 * Пол порога в сутках (решение владельца 2026-09-16: «3 + 2»).
 *
 * ⚠ Стоит ОТДЕЛЬНО от `AUTO_ERASE_GRACE_DAYS`, хотя оба про человека, потому что отвечают на
 * разное: пол — «сколько дней дело обязано провисеть в любом случае» (длинные выходные плюс
 * рабочий день), надбавка — «сколько сверх окна». На портале с окном в сутки (умолчание
 * `CRON_LOOKBACK_DAYS`) одна надбавка дала бы три дня, то есть пятницу-субботу-воскресенье, и
 * платёж исчез бы ровно к возвращению человека.
 */
export const AUTO_ERASE_MIN_DAYS = 5

/** Потолок порога — защита от опечатки в `CRON_LOOKBACK_DAYS` (значение читается из env). */
export const AUTO_ERASE_MAX_DAYS = 400

/**
 * Через сколько суток после СОЗДАНИЯ дело подлежит удалению.
 *
 * `max(пол, окно + надбавка)` — оба условия обязаны выполниться:
 *   · `окно + надбавка` — машинное: удалённое дело не должно вернуться следующим опросом;
 *   · `пол` — человеческое: меньше пяти суток владелец не хочет ни при каком окне.
 *
 * ⚠ Нечитаемое/отрицательное окно трактуется как ноль, а не как отказ: настройка живёт в env на
 * нашей стороне, и опечатка в ней не должна выключать удаление молча — она упрётся в пол.
 */
export function autoEraseThresholdDays(lookbackDays: number): number {
  const lookback = Number.isFinite(lookbackDays) && lookbackDays > 0 ? Math.floor(lookbackDays) : 0
  return Math.min(AUTO_ERASE_MAX_DAYS, Math.max(AUTO_ERASE_MIN_DAYS, lookback + AUTO_ERASE_GRACE_DAYS))
}

/**
 * Календарный день в поясе ПОРТАЛА (UTC+3), сдвинутый на `daysBack` назад.
 *
 * ⚠ Считается арифметикой над сдвинутой меткой, а не `toISOString()` от локальных часов процесса:
 * контейнер живёт в UTC, и ранним утром по Минску UTC-дата ещё вчерашняя — граница уехала бы на
 * сутки в сторону УДАЛЕНИЯ ЛИШНЕГО. Та же причина, по которой `toPortalDeadline` штампует пояс
 * руками (#10/#90).
 */
export function portalDayBack(nowMs: number, daysBack: number): string {
  const OFFSET_MS = 3 * 60 * 60 * 1000
  const shifted = nowMs + OFFSET_MS - Math.max(0, Math.floor(daysBack)) * 86_400_000
  return new Date(shifted).toISOString().slice(0, 10)
}

/** Граница удаления: дела, созданные СТРОГО РАНЬШЕ этого дня (по времени портала), подлежат сносу. */
export interface AutoEraseCutoff {
  /** Календарный день `YYYY-MM-DD` — начало суток, до которых удаляем. */
  day: string
  /** Тот же момент в миллисекундах — для перепроверки `CREATED` из ответа портала. */
  ms: number
  /** Порог в сутках, из которого день получен (идёт в лог и в интерфейс). */
  thresholdDays: number
}

/** Построить границу удаления от текущего момента и окна опроса. */
export function autoEraseCutoff(nowMs: number, lookbackDays: number): AutoEraseCutoff {
  const thresholdDays = autoEraseThresholdDays(lookbackDays)
  const day = portalDayBack(nowMs, thresholdDays)
  return { day, ms: Date.parse(`${day}T00:00:00${PORTAL_TZ_OFFSET}`), thresholdDays }
}

/**
 * Фильтр `crm.activity.list` для автоудаления.
 *
 * ⚠ `ORIGINATOR_ID` подставляется ВСЕГДА и не параметризуется — ровно как в ручной «Очистке»: он и
 * есть граница между нашими делами и всей остальной CRM клиента.
 *
 * ⚠ Фильтр по `<=CREATED` ЗАМЕРЕН на живом портале 2026-09-16 (граница 09-10 отдала 8 дел из 17,
 * все с датой создания 09-09). Документация Bitrix24 про фильтруемость `CREATED` не говорит
 * ничего, поэтому это измерение, а не вывод из типа поля.
 *
 * ⚠ Значение НАИВНОЕ (без смещения пояса) — тот же вид, в котором работает `>=DEADLINE` у ручной
 * очистки. Портал трактует его в СВОЁМ поясе, и день считается в том же поясе (`portalDayBack`).
 */
export function buildAutoEraseFilter(cutoff: AutoEraseCutoff): Record<string, unknown> {
  return { 'ORIGINATOR_ID': ACTIVITY_ORIGIN, '<=CREATED': `${cutoff.day}T00:00:00` }
}

/** Строка дела, как её отдаёт `crm.activity.list` с нашим `select` для автоудаления. */
export interface AutoEraseRow {
  id: string
  originatorId: string
  /** `CREATED` как его вернул портал (ISO со смещением пояса). */
  created: string
}

/**
 * ВТОРАЯ граница безопасности — перепроверка ВОЗРАСТА по ответу портала.
 *
 * ⚠ Ручная «Очистка» перепроверяет только `ORIGINATOR_ID`, и для неё этого хватает: период задал
 * человек, он же видит число перед нажатием. Здесь свидетеля нет, и промах повторяется каждые
 * сутки на каждом согласившемся портале, поэтому проверяется и дата.
 *
 * ⚠ Это не перестраховка «на случай если Bitrix сломается». Ровно этот отказ случился при первом
 * же замере: `<=CREATED` в неэкранированном виде (`<` и `=` в имени ключа) портал принял МОЛЧА и
 * вернул ПОЛНЫЙ список — то есть фильтр, который выглядит рабочим и не сужает ничего. Одной
 * опечатки в сборке параметров хватило бы, чтобы автомат снёс сегодняшние дела; здесь такая
 * опечатка даёт пустой результат.
 *
 * ⚠ Строка с НЕЧИТАЕМОЙ датой создания НЕ удаляется. «Дату разобрать не удалось» — это незнание
 * возраста, а не разрешение: единственный безопасный исход для необратимого действия.
 */
export function selectAutoErasable(rows: readonly AutoEraseRow[], cutoff: AutoEraseCutoff): AutoEraseRow[] {
  return rows.filter((r) => {
    if (r.originatorId !== ACTIVITY_ORIGIN) return false
    if (!r.id) return false
    const createdMs = Date.parse(r.created)
    if (!Number.isFinite(createdMs)) return false
    return createdMs < cutoff.ms
  })
}

/** Итог прогона по одному порталу. */
export interface AutoErasePortalResult {
  deleted: number
  /** Сколько ещё подпадает под отбор (правда из портала, а не наша арифметика). */
  remaining: number
}

/** Итог прогона по всему флоту — то, что печатается одной строкой. */
export interface AutoEraseFacts {
  /** Сколько порталов вообще рассмотрено (есть след импорта). */
  considered: number
  /** У скольких настройка включена. */
  enabled: number
  /** У скольких удалось прочитать настройку (остальные пропущены fail-closed). */
  unreadable: number
  /** Сколько порталов реально что-то потеряли. */
  touched: number
  /** Сколько дел удалено всего. */
  deleted: number
  /** У скольких порталов остался хвост на следующий прогон. */
  withRemainder: number
  /** Сколько порталов упало на удалении. */
  failed: number
  /** Упёрлись в потолок порталов за прогон. */
  capped: boolean
  /** Порог в сутках, по которому шёл прогон. */
  thresholdDays: number
}

/**
 * Сколько порталов обрабатываем за один прогон.
 *
 * ⚠ Потолок здесь НЕ предохранитель от нашей ошибки (от неё защищает перепроверка даты выше), а
 * бюджет времени: прогон идёт на том же тике, что и остальные свипы, и не должен растягиваться на
 * часы. Остаток берётся следующим прогоном — порядок выборки стабилен.
 */
export const MAX_AUTO_ERASE_PORTALS = 50

/** Сколько дел стираем у ОДНОГО портала за прогон; остальное — в следующие сутки. */
export const MAX_AUTO_ERASE_PER_PORTAL = 300

/**
 * Строка итога для лога.
 *
 * ⚠ Печатается ВСЕГДА, даже когда удалять было нечего, — по той же причине, по которой безусловна
 * строка итога `crm-sync` (#498): молчание автомата, который удаляет данные клиента, неотличимо от
 * «автомат не запускался», а различать эти два состояния приходится именно тогда, когда что-то
 * пошло не так.
 */
export function autoEraseLogLine(f: AutoEraseFacts): string {
  const parts = [
    `порталов рассмотрено ${f.considered}`,
    `включено ${f.enabled}`,
    `удалено дел ${f.deleted} на ${f.touched} портал(ах)`,
    `порог ${f.thresholdDays} сут.`
  ]
  if (f.unreadable > 0) parts.push(`⚠ ${f.unreadable} пропущено — настройку прочитать не удалось`)
  if (f.failed > 0) parts.push(`⚠ ${f.failed} с ошибкой удаления`)
  if (f.withRemainder > 0) parts.push(`${f.withRemainder} с хвостом на следующий прогон`)
  if (f.capped) parts.push('⚠ упёрлись в потолок порталов за прогон')
  return parts.join(', ')
}
