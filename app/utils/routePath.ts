// Сравнение путей маршрута с точностью до хвостового слэша.
//
// ⚠ Заведено не «для аккуратности»: строгое `!==` стоило живой регрессии (#537). Фрейм слайдера
// приезжает по адресу с хвостовым слэшем (`/app/` — так отдаёт статику веб-сервер), а маршрут
// резолвится без него, и отложенный редирект отменял сам себя, решив, что пользователь ушёл со
// страницы. Снаружи это было неотличимо от исходной поломки: слайдер снова показывал главный экран.
// Правило вынесено сюда, чтобы у него был собственный тест — внутри мидлвара оно проверялось бы
// только косвенно.

/** Один и тот же путь? `/app` и `/app/` — да; корень остаётся корнем. */
export function isSamePath(a: string, b: string): boolean {
  return trimTrailingSlash(a) === trimTrailingSlash(b)
}

/** Хвостовой слэш долой — кроме самого корня, где слэш и есть весь путь. */
export function trimTrailingSlash(path: string): string {
  return path.length > 1 && path.endsWith('/') ? path.slice(0, -1) : path
}
