// Ссылка, открывающая ЭКРАН ПРИЛОЖЕНИЯ, — точка встраивания `REST_APP_URI` (#19).
//
// Механика (apidocs.bitrix24.ru/api-reference/widgets/universal/app-url.html): приложение
// регистрирует ОДИН обработчик методом `placement.bind`, после чего любой внутренний адрес вида
// `/marketplace/view/<код приложения>/` открывает этот обработчик СЛАЙДЕРОМ поверх той страницы,
// с которой по нему перешли. Ссылку можно положить куда угодно, где Битрикс24 рисует внутренний
// адрес ссылкой: сообщение чата, комментарий ленты, описание задачи.
//
// ⚠ ЭТО ВТОРОЙ, ПАРАЛЛЕЛЬНЫЙ ВХОД, а не замена первому. Первый — кнопка «Загрузить выписку» на
// `/app`, которая зовёт `openSliderAppPage({ place })` (см. `config/b24.ts`, `APP_SLIDER_*`); он
// работает ВНУТРИ уже открытого приложения и никуда отсюда не завязан. Этот — ссылка, по которой
// приложение открывают СНАРУЖИ, из любого места портала. Ломать друг друга они не могут: у первого
// адрес задаёт SDK, у второго — портал по зарегистрированному обработчику.
//
// ⚠ ПАРАМЕТРЫ ЕДУТ ТОЛЬКО В КЛЮЧЕ `params`. Голые ключи строки запроса до обработчика НЕ доезжают
// вовсе — в `PLACEMENT_OPTIONS` попадает только то, что лежало в `params[...]`. Это первая по
// частоте ошибка из раздела «типовые ошибки» документации, и снаружи она выглядит как «слайдер
// открылся, но не туда».
//
// ⚠ Значения приходят СТРОКАМИ — числа и булевы превращаются в строки по дороге, поэтому на той
// стороне их разбирает вызывающий.
//
// ⚠ Ключ `URI` Битрикс24 добавляет сам (адрес страницы, с которой перешли), но ЧУЖОЕ значение не
// перезаписывает. Свой ключ с таким именем мы не шлём: он нужен нам ровно как диагностика «откуда
// пришли», а подменив его, мы потеряли бы единственный источник этого знания.

/** Код точки встраивания. Регистрируется `placement.bind`, приходит обратно в `PLACEMENT`. */
export const APP_URI_PLACEMENT = 'REST_APP_URI'

/**
 * Маска кода приложения.
 *
 * ⚠ В ссылке нужен КОД ПРИЛОЖЕНИЯ, а не идентификатор регистрации обработчика: у тиражного это
 * символьный код из карточки в кабинете разработчика (`vendor.app`), у локального — `client_id`
 * из раздела «Разработчикам» (`local.66ba434d853c87.18550109`). Перепутать их легко, и симптом
 * тихий — открывается пустой слайдер.
 *
 * ⚠ Слэш маской ЗАПРЕЩЁН намеренно: код подставляется в ПУТЬ, и значение с `/` или `..` увело бы
 * ссылку на чужой адрес портала. Код мы берём у самого портала (`app.info` → `CODE`), но проверять
 * его всё равно обязаны — он приходит извне.
 */
const APP_CODE_RE = /^[A-Za-z0-9][A-Za-z0-9._-]*$/

/** Годен ли код приложения для подстановки в путь ссылки. */
export function isValidAppCode(code: string | undefined | null): boolean {
  const c = (code ?? '').trim()
  return c.length > 0 && c.length <= 128 && APP_CODE_RE.test(c)
}

/**
 * Путь ссылки ВНУТРИ портала: `/marketplace/view/<код>/?params[ключ]=значение`.
 *
 * Возвращает `null` на негодном коде — fail-safe: лучше не показать ссылку вовсе, чем показать
 * ведущую в пустой слайдер (или, при коде со слэшем, куда-то ещё).
 *
 * ⚠ Кодируем и ИМЯ ключа, и значение. Имя задаём мы сами и сегодня оно безопасно, но `params[…]` —
 * это скобки в строке запроса, то есть место, где незакодированное имя однажды съедет молча.
 */
export function buildAppUriPath(code: string, params: Record<string, string> = {}): string | null {
  if (!isValidAppCode(code)) return null
  const base = `/marketplace/view/${encodeURIComponent(code.trim())}/`
  const pairs = Object.entries(params)
    .filter(([k, v]) => k.trim() !== '' && v !== undefined && v !== null)
    .map(([k, v]) => `params[${encodeURIComponent(k)}]=${encodeURIComponent(String(v))}`)
  return pairs.length ? `${base}?${pairs.join('&')}` : base
}

/**
 * Та же ссылка, но АБСОЛЮТНАЯ — её человек копирует и пересылает.
 *
 * ⚠ Домен нужен именно портальный (`client.bitrix24.by`), а не наш: ссылка живёт внутри Битрикс24 и
 * открывается его слайдером. Пустой/негодный домен ⇒ `null`, как и негодный код: полупустая ссылка
 * хуже отсутствующей — её пошлют коллеге, и разбираться будет он.
 */
export function buildAppUriLink(
  portalDomain: string, code: string, params: Record<string, string> = {}
): string | null {
  const host = (portalDomain ?? '').trim().replace(/^https?:\/\//i, '').replace(/\/+$/, '')
  // Хост портала — только имя: со слэшем внутри это уже не хост, а чужой путь.
  if (!host || /[/\\?#\s]/.test(host)) return null
  const path = buildAppUriPath(code, params)
  return path ? `https://${host}${path}` : null
}
