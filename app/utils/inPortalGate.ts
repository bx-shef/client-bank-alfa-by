// Решение «показывать ли страницу приложения» (#414) — чистое ядро.
//
// Страницы `/app`, `/import`, `/install` осмысленны только внутри Bitrix24: снаружи у них нет
// фрейм-токена, значит ни настроек, ни статуса, ни записи в CRM — интерфейс выглядит рабочим,
// но не работает. Хуже того, до этой правки он показывал выдуманные цифры (демо-мок статуса).
//
// Вынесено из компонента, потому что здесь легко ошибиться в пользу «показать»: fail-open на гейте
// — это ровно тот случай, когда пользователь видит пустую панель и считает, что приложение
// сломано.

export type PortalGateState = 'checking' | 'ok' | 'outside'

export interface PortalGateInput {
  /** Проверка присутствия во фрейме уже завершилась (`useB24().init()` асинхронный). */
  resolved: boolean
  /** Мы внутри портала Bitrix24. */
  inPortal: boolean
  /** Явный обход для разработки/скриншотов: `?preview=1`. */
  preview: boolean
}

/**
 * Что рендерить. Пока проверка не завершилась — `checking`: без этого состояния интерфейс мелькнул
 * бы и схлопнулся в заглушку (или наоборот), а это читается как поломка.
 *
 * `preview` сознательно перекрывает всё: без него покраснели бы тесты, монтирующие страницы вне
 * фрейма, и перестали бы сниматься скриншоты — то есть отвалилась бы вся визуальная приёмка.
 */
export function portalGateState(input: PortalGateInput): PortalGateState {
  if (input.preview) return 'ok'
  if (!input.resolved) return 'checking'
  return input.inPortal ? 'ok' : 'outside'
}

/**
 * Значение `preview` из query роутера означает обход.
 *
 * Берём именно роутер, а не `window.location.search`: на гидратации пререндеренной страницы адрес
 * на миг теряет строку запроса, и чтение из `location` возвращало пустоту (обход не работал).
 *
 * Массив — это `?preview=1&preview=0`; засчитываем, если хотя бы одно значение равно `1`, но
 * голый `?preview` без значения (`null`) обходом НЕ считается: случайная ссылка не должна
 * открывать неработающее снаружи приложение.
 */
export function isPreviewQuery(value: unknown): boolean {
  if (Array.isArray(value)) return value.some(isPreviewQuery)
  return value === '1'
}
