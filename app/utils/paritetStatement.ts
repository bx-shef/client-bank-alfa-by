// Звёздочный текстовый экспорт выписки (замерено на выгрузках Паритетбанка, #700) — третий формат
// ручной загрузки рядом с `1CClientBankExchange` и client-bank `***** ^Type=`.
//
// Файл — построчный, каждая строка `*<тип>*<поле>*…*`, обрамлённая звёздочками с обеих сторон.
// Типов четыре, и порядок их обязателен:
//   `*0*` — шапка: дата, наш счёт, валюта счёта, вид сальдо, входящее сальдо в валюте и в BYN;
//   `*1*` — операция (21 поле, разбор ниже);
//   `*2*` — подвал: то же, что шапка, но сальдо исходящее;
//   `*3*` — сколько было строк операций.
//
// ⚠ КОДИРОВКА CP866, а не windows-1251, которой живут остальные два формата. Прочитанный как
// CP1251 такой файл разбирается СТРУКТУРНО ВЕРНО — цифры, звёздочки и номера счетов лежат в ASCII
// и совпадают, — а назначение платежа превращается в мусор и в таком виде уезжает в CRM клиента.
// Поэтому кодировку определяет `decodeUploadText` (`importUpload.ts`) ДО разбора, а не этот
// модуль: он получает уже готовую строку, как и остальные парсеры.
//
// ⚠ Нумерация полей в этом файле — ИНДЕКСЫ `parts[N]` после `split('*')`, а НЕ «N-е поле, если
// считать глазами». Они отличаются на единицу, и этот сдвиг здесь уже один раз дал неверный вывод
// при анализе; человеческая нумерация — в `docs/PARITET_FORMAT.md`.
//
// ⚠ ИМЕНИ КОНТРАГЕНТА В ФОРМАТЕ НЕТ ВОВСЕ. Есть счёт, БИК и УНП — по счёту приложение и ищет
// компанию в CRM (`findCompanyByAccount`), так что опознание работает; но подставлять в имя номер
// счёта или УНП нельзя — в карточке это читалось бы как название компании. Имя остаётся пустым,
// и заголовок дела обязан это пережить (`buildActivityTitle`).

import type { NormalizeContext, StatementItem, OperationDirection } from '~/types/statement'
import { currencyFromNumericCode } from '~/utils/clientBankStatement'
import { round2 } from '~/utils/money'

/** Тот же потолок ввода, что у соседнего текстового формата (DoS-гард #19). */
export const MAX_PARITET_CHARS = 20_000_000

/** Маркер формата — первая строка файла всегда шапка. */
const HEADER_PREFIX = '*0*'

/** Сколько элементов даёт `split('*')` на строке операции: 21 поле плюс пустышки по краям. */
const PARITET_ROW_FIELDS = 21

/** Разобранная строка операции: поля под теми же номерами, что в файле (1 — тип). */
export interface ParitetRow {
  /** Дата операции, `ГГГГ-ММ-ДД`. */
  date: string
  /** Наш счёт (поле 3). */
  account: string
  /** Числовой ISO валюты НАШЕГО счёта (поле 4). */
  currencyCode: string
  /** БИК банка контрагента (поле 5). */
  bic: string
  /** Счёт контрагента (поле 6) — ключ поиска компании в CRM. */
  counterpartyAccount: string
  /** Код операции / вид документа (поле 11). */
  operCode: string
  /** Номер документа (поле 12). ⚠ НЕ уникален сам по себе — см. `paritetDocId`. */
  docNum: string
  /** УНП контрагента (поле 13). */
  unp: string
  /** Признак направления (поле 15): `4` — приход, `1` — расход. */
  directionCode: string
  /** Сумма в валюте НАШЕГО счёта (поле 16). */
  amount: string
  /** Сумма в BYN — эквивалент по курсу из поля 17 (поле 18). */
  amountByn: string
  /** Назначение платежа (поле 19). */
  purpose: string
}

export interface ParitetParsed {
  /** Наш счёт из шапки. */
  account: string
  /** Числовой ISO валюты счёта из шапки. */
  currencyCode: string
  rows: ParitetRow[]
}

/** Похож ли текст на этот формат: первая непустая строка — шапка. */
export function isParitetText(text: string): boolean {
  return firstMeaningfulLine(text).startsWith(HEADER_PREFIX)
}

function firstMeaningfulLine(text: string): string {
  for (const line of text.slice(0, 4096).split(/\r?\n/)) {
    const t = line.trim()
    if (t) return t
  }
  return ''
}

/**
 * Поля строки разбиваются по `*`, при этом строка ОБРАМЛЕНА звёздочками — значит первый и
 * последний элемент пустые, а поле N файла лежит в `parts[N]`. Нумерацию не сдвигаем намеренно:
 * весь разбор этого формата сверяется с полями, посчитанными глазами в файле, и сдвиг на единицу
 * здесь уже один раз дал неверный вывод при анализе.
 */
function fields(line: string): string[] {
  return line.split('*')
}

/** `ГГГГММДД` из `ГГММДД`. Век — 2000-е: формат несёт двузначный год, а выписки банка, которому
 *  нет ста лет, однозначны. Невалидная дата отдаётся пустой строкой — решает вызывающий. */
function isoDate(yymmdd: string): string {
  if (!/^\d{6}$/.test(yymmdd)) return ''
  const y = 2000 + Number(yymmdd.slice(0, 2))
  const m = yymmdd.slice(2, 4)
  const d = yymmdd.slice(4, 6)
  const dt = new Date(Date.UTC(y, Number(m) - 1, Number(d)))
  if (dt.getUTCFullYear() !== y || dt.getUTCMonth() !== Number(m) - 1 || dt.getUTCDate() !== Number(d)) return ''
  return `${y}-${m}-${d}`
}

/** Число из банковской записи `1054,89`. Мусор/пусто ⇒ `NaN` (вызывающий решает, что это значит). */
function money(raw: string): number {
  const t = (raw ?? '').trim().replace(/\s/g, '').replace(/,/g, '.')
  if (!/^-?\d+(\.\d+)?$/.test(t)) return Number.NaN
  return Number(t)
}

/**
 * Ключ идемпотентности операции.
 *
 * ⚠ ГОЛОГО НОМЕРА ДОКУМЕНТА НЕ ХВАТАЕТ, и это ЗАМЕРЕНО: на пяти боевых файлах (251 операция)
 * номер повторяется 44 раза — банк нумерует свои комиссии сквозным счётчиком, который сбрасывается
 * и повторяется в разные дни. Ключ приложения — `<наш счёт>|<docId>`, поэтому голый номер молча
 * схлопнул бы 44 операции из 251: на экране «разобрано 207», в CRM недостача, и ни одного
 * сообщения об ошибке. Дата снимает все повторы (замерено: 0 дублей на тех же 251 строке).
 */
export function paritetDocId(row: ParitetRow): string {
  // ⚠ Пустой номер даёт ПУСТОЙ ключ, а не «дата|» — иначе все операции одного дня получили бы
  // ОДИН ключ и схлопнулись бы в одну. Пустой `docId` включает хеш-сигнатуру содержимого в
  // `dedupKey` (#430 C1) — страховку, заведённую ровно на этот случай; ключ вида «дата|» её
  // обходил бы, потому что формально не пуст. В замеренных файлах пустых номеров нет (0 из 251),
  // но держаться это должно на проверке, а не на надежде, что банк пришлёт поле.
  if (!row.docNum) return ''
  return `${row.date}|${row.docNum}`
}

/**
 * Разобрать файл. Бросает на пустом/чужом содержимом и на РАСХОЖДЕНИИ ЧИСЛА СТРОК с подвалом.
 *
 * ⚠ Подвал `*3*N*` сверяется намеренно: обрезанная на полпути выгрузка (оборванная закачка,
 * подмонтированный диск) остаётся синтаксически корректной, и без сверки приложение молча
 * импортировало бы ЧАСТЬ выписки — а частичная выписка выглядит как полная и расходится с банком
 * только при сверке сальдо, то есть много позже. Банк сам говорит, сколько строк он выгрузил;
 * не воспользоваться этим значило бы выбросить единственную бесплатную проверку целостности.
 */
export function parseParitetText(content: string, maxChars = MAX_PARITET_CHARS): ParitetParsed {
  const text = content.length > maxChars ? content.slice(0, maxChars) : content
  const lines = text.split(/\r?\n/).map(l => l.trim()).filter(Boolean)
  if (!lines.length || !lines[0]!.startsWith(HEADER_PREFIX)) {
    throw new Error('Файл не похож на звёздочный формат выписки (первая строка должна быть «*0*…»)')
  }

  const head = fields(lines[0]!)
  const account = (head[3] ?? '').trim()
  const currencyCode = (head[4] ?? '').trim()

  const rows: ParitetRow[] = []
  let malformed = 0
  let declared: number | null = null
  for (const line of lines) {
    const p = fields(line)
    const kind = p[1]
    if (kind === '1') {
      // ⚠ Строка операции — РОВНО 21 поле. Разделитель здесь `*`, и назначение платежа пишет
      // плательщик: попади звёздочка в назначение, поля сдвинулись бы, а `p[19]` вернул бы
      // ОБРЕЗАННОЕ назначение — ровно ту его часть, по которой работает распознавание номеров
      // (§4). Строка при этом осталась бы строкой типа 1, поэтому сверка с подвалом такой случай
      // НЕ ловит. Отбрасываем: обрезанное назначение в CRM хуже отсутствующей строки, потому что
      // выглядит достоверным. В замеренных файлах таких строк нет — банк звёздочку не пропускает.
      if (p.length !== PARITET_ROW_FIELDS) {
        malformed += 1
        continue
      }
      rows.push({
        date: isoDate((p[2] ?? '').trim()),
        account: (p[3] ?? '').trim(),
        currencyCode: (p[4] ?? '').trim(),
        bic: (p[5] ?? '').trim(),
        counterpartyAccount: (p[6] ?? '').trim(),
        operCode: (p[11] ?? '').trim(),
        docNum: (p[12] ?? '').trim(),
        unp: (p[13] ?? '').trim(),
        directionCode: (p[15] ?? '').trim(),
        amount: (p[16] ?? '').trim(),
        amountByn: (p[18] ?? '').trim(),
        purpose: (p[19] ?? '').trim()
      })
    } else if (kind === '3') {
      // ⚠ Маска, а не `Number()`: у пустого поля `Number('')` = 0, и корректный файл падал бы с
      // «банк указал операций — 0»; у мусора — `NaN`, и гард молча выключался бы.
      const raw = (p[2] ?? '').trim()
      if (/^\d+$/.test(raw)) declared = Number(raw)
    }
  }

  // ⚠ Подвал ОБЯЗАТЕЛЕН. Первая редакция сверяла его «если он есть» — и защищала ровно НЕ от того
  // случая, который назван в мотивации: при оборванной закачке теряется ХВОСТ файла, то есть сам
  // подвал, `declared` остаётся пустым, и проверка не выполняется вовсе. Требование наличия
  // возвращает заявленную защиту; во всех замеренных выгрузках подвал есть.
  if (declared === null) {
    throw new Error(
      'Выписка без завершающей строки с числом операций — скорее всего файл выгрузился не до '
      + 'конца. Выгрузите его заново.'
    )
  }
  // ⚠ Битые строки считаются здесь же: банк насчитал N операций, и если часть мы отбраковали по
  // форме, итог обязан не сойтись — иначе «выгрузка цела» утверждалось бы о файле, часть которого
  // мы не смогли прочитать.
  if (declared !== rows.length + malformed) {
    throw new Error(
      `Выписка неполная: банк указал операций — ${declared}, в файле — ${rows.length + malformed}. `
      + 'Скорее всего файл выгрузился не до конца, выгрузите его заново.'
    )
  }
  if (malformed > 0) {
    throw new Error(
      `Строк с неожиданным числом полей: ${malformed}. Похоже, формат выписки изменился — `
      + 'пришлите файл нам, мы поправим разбор.'
    )
  }

  return { account, currencyCode, rows }
}

/**
 * Направление операции.
 *
 * ⚠ `4` — ПРИХОД, `1` — РАСХОД, и это выведено не из документации, а СВЕДЕНИЕМ САЛЬДО на боевых
 * файлах: «входящее + Σ(код 4) − Σ(код 1)» сошлось с исходящим сальдо до копейки на трёх файлах из
 * пяти (оставшиеся два имеют нулевые сальдо с обеих сторон и направление не различают вовсе).
 * Обратная гипотеза на тех же трёх файлах расходится на миллионы.
 * ⚠ Проверка ЯВНАЯ на обе стороны, а не «всё, что не 4 — расход»: неизвестный код значит, что банк
 * поменял формат, и тогда молчаливое «расход» показало бы приход расходом — не потеря строки, а
 * НЕВЕРНОЕ число в карточке компании, которое выглядит достоверным.
 */
export function paritetDirection(code: string): OperationDirection | null {
  if (code === '4') return 'credit'
  if (code === '1') return 'debit'
  return null
}

/**
 * Развернуть разобранный файл в операции (контракт `StatementNormalizer`).
 *
 * ⚠ Строки с НУЛЕВОЙ суммой в валюте счёта отбрасываются. Это не «потеря данных»: замерено, что
 * все 65 таких строк из 251 — «Переоценка по счету …», то есть пересчёт рублёвого эквивалента
 * валютного остатка. Денег по счёту не двигалось, направления у такой записи нет по смыслу, к
 * счёту или сделке её не привязать (разнесение сверяет СУММУ), а в CRM это 65 дел, каждое из
 * которых бухгалтеру нужно закрыть руками. Считаем их в `skipped`, чтобы число на экране
 * объяснялось, а не расходилось с файлом молча.
 * ⚠ Сумма берётся в ВАЛЮТЕ СЧЁТА (поле 16), а не BYN-эквивалент (поле 18) — то же решение, что
 * принято для валютных выписок client-bank (#169): эквивалент считает банк по своему курсу на
 * свою дату, и в CRM он спорил бы с суммой счёта, выставленного клиенту.
 * ⚠ Неизвестное направление или нечитаемая сумма — строка ОТБРАСЫВАЕТСЯ со счётом в `skipped`, а
 * не пишется наугад: см. `paritetDirection`.
 */
export function normalizeParitetRows(
  parsed: ParitetParsed,
  ctx: NormalizeContext
): { items: StatementItem[], nonPayment: number, unreadable: number } {
  const items: StatementItem[] = []
  let nonPayment = 0
  let unreadable = 0

  for (const row of parsed.rows) {
    const direction = paritetDirection(row.directionCode)
    const raw = money(row.amount)
    // ⚠ Округляем ДО сравнения с нулём: при обратном порядке сумма 0,004 проходила проверку
    // «> 0» и превращалась в дело «Приход 0,00 BYN» — то самое нулевое дело, которого правило
    // этого модуля не допускает.
    const amount = round2(raw)

    // ⚠ Финитность проверяется по СЫРОМУ числу, а не по округлённому: `round2` приводит
    // нефинитное к нулю, и нечитаемая сумма попадала в «служебные записи банка» вместо «не
    // распознано» — то есть человеку сообщали бы «это переоценка» про строку, которую мы просто
    // не смогли прочесть. Соседний гард её тоже не ловит: `NaN <= 0` — это `false`.
    if (!direction || !Number.isFinite(raw) || !row.date) {
      unreadable += 1
      continue
    }
    // Переоценка: сумма по счёту нулевая. Это НЕ отказ разбора — считаем отдельно.
    if (amount === 0) {
      nonPayment += 1
      continue
    }
    if (amount < 0) {
      unreadable += 1
      continue
    }
    // ⚠ Валюта строки, а не только шапки: поля совпадают на всех замеренных файлах, но строка
    // описывает свою операцию, и при расхождении честнее верить ей.
    // ⚠ НЕИЗВЕСТНЫЙ код валюты — ОТКАЗ, та же доктрина, что у направления. Пустая `currency`
    // доехала бы до заголовка дела («Приход 4 800,00 »), до реестра и до разнесения, которое
    // сверяет валюту и не нашло бы цель НИКОГДА, не сказав почему. Фолбэк «раз счёт белорусский,
    // значит BYN» здесь тем более нельзя: формат несёт код явно, и подменять его догадкой — это
    // выдать неверную валюту за банковскую.
    const currency = currencyFromNumericCode(row.currencyCode)
      ?? currencyFromNumericCode(parsed.currencyCode)
      ?? (ctx.currency ?? '')
    if (!currency) {
      unreadable += 1
      continue
    }
    items.push({
      account: ctx.account || row.account || parsed.account,
      docId: paritetDocId(row),
      docNum: row.docNum,
      direction,
      amount,
      currency,
      purpose: row.purpose,
      acceptDate: row.date,
      counterparty: {
        // ⚠ Имени в формате нет — оставляем пустым. Подстановка счёта/УНП сюда показала бы в
        // карточке компании номер вместо названия, то есть выдала бы догадку за факт.
        name: '',
        unp: row.unp,
        account: row.counterpartyAccount,
        bic: row.bic
      }
      // ⚠ `operCodeName` НЕ ставим: у нас есть КОД операции (`46`, `6`, `1`), а не его название, и
      // расшифровки кодов у нас нет. В поле с именем «…Name» код нарисовался бы в раскрытой строке
      // как «Код операции: 46» — та же подмена догадки фактом, что и счёт в имени контрагента.
    })
  }

  return { items, nonPayment, unreadable }
}

/** Контракт `StatementNormalizer` — только операции. Отброшенные с разбивкой по причинам отдаёт
 *  `normalizeParitetRows`, и вызывающий обязан их ПОКАЗАТЬ: иначе человек, загрузивший выписку из
 *  44 строк, видит «разобрано: 9» без объяснения, куда делись остальные 35. */
export function normalizeParitet(parsed: ParitetParsed, ctx: NormalizeContext): StatementItem[] {
  return normalizeParitetRows(parsed, ctx).items
}
