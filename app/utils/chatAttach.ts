// Вложение сообщения Битрикс24 (`ATTACH`) — ровно тот кусок формата, который использует приложение.
//
// ⚠ ФОРМА ВЛОЖЕНИЯ — МАССИВ БЛОКОВ, а не объект. Документация даёт две формы: полную
// (`{ID, COLOR_TOKEN, BLOCKS:[…]}`) и краткую — просто массив блоков, где КАЖДЫЙ элемент это
// объект с ОДНИМ ключом верхнего уровня, и этот ключ называет тип блока. Первая редакция слала
// `{IMAGE:[…]}`, то есть не подходящее ни под одну: ни `BLOCKS`, ни массива. Портал такое
// принимает МОЛЧА и картинок не показывает.
//
// ⚠ А ЛЕЖИТ ОНО В РАЗНЫХ МЕСТАХ У РАЗНЫХ МЕТОДОВ, и это главная ловушка: у `im.message.*` —
// параметр `ATTACH` верхнего уровня, у методов чат-бота `imbot.v2.*` — ВНУТРИ `fields.attach`.
// Сказано в документации дословно; проверено дорого — сообщение при неверном месте доходит
// ТЕКСТОМ, без картинок и без единой ошибки, поэтому отказ выглядит как «картинки не работают».

/** Блок с изображениями. Одного блока хватает на несколько картинок — но тогда портал рисует их
 *  плиткой в ряд с обрезкой (замер владельца 2026-09-26), поэтому снимки шагов идут по одному. */
export interface ChatImageBlock {
  IMAGE: { NAME: string, LINK: string, PREVIEW: string, WIDTH: number, HEIGHT: number }[]
}

/** Текстовый блок. Поддерживает BB-коды; перенос строки внутри — `[BR]`, а НЕ `\n`: так велит
 *  документация блока (`BR` стоит в списке его кодов отдельной строкой). */
export interface ChatMessageBlock {
  MESSAGE: string
}

/** Блок вложения. Список типов расширяется по мере надобности. */
export type ChatAttachBlock = ChatImageBlock | ChatMessageBlock

/** Краткая форма вложения — массив блоков. Портал рисует их в том порядке, в каком они перечислены. */
export type ChatAttach = ChatAttachBlock[]

/**
 * Вложение В ПАРЕ с полным текстом на случай, когда оно не дошло (#19).
 *
 * ⚠ Пара заведена потому, что вложение перестало быть бонусом. Пока в нём лежали одни картинки,
 * текст сообщения был самодостаточен, и отказ портала лечился повтором ТОГО ЖЕ текста без
 * вложения. Теперь во вложение переехали сами шаги инструкции — шаг и сразу его снимок (решение
 * владельца 2026-09-26), а в тексте остались вступление, ссылка и предупреждения. Повтор того же
 * текста без вложения доставил бы инструкцию БЕЗ ШАГОВ: владелец счёта получил бы ссылку и не
 * узнал бы, где выпустить ключ.
 *
 * ⚠ Поэтому вложение передаётся ТОЛЬКО вместе с запасным текстом: отдельным параметром его можно
 * было бы забыть, а без `fallbackText` этот объект не соберётся.
 */
export interface ChatAttachment {
  attach: ChatAttach
  /** Что отправить вместо сообщения с вложением, если портал вложение не принял (или прикладывать
   *  нечего). Обязан быть самодостаточным — вложения при нём не будет. */
  fallbackText: string
}

/**
 * Есть ли что прикладывать.
 *
 * ⚠ Пустой массив ТОЖЕ значит «нечего»: в JS он истинен, а портал считает пустую коллекцию блоков
 * негодной формой и отвечает `ATTACH_ERROR` — то есть проверка «просто на истинность» заворачивала
 * бы сообщение целиком ровно тогда, когда прикладывать было нечего.
 */
export function hasAttachBlocks(attach: ChatAttach | null | undefined): attach is ChatAttach {
  return Array.isArray(attach) && attach.length > 0
}
