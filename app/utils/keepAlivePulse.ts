// Пульс keep-alive банковских токенов (#504): «когда механизм продления последний раз отработал».
//
// ЗАЧЕМ. Продление (#489) — это голый `setInterval` в крон-плагине, а не задача очереди, поэтому
// его остановка невидима всеми существующими способами: Telegram-алертинг читает только очереди из
// `QUEUE_NAMES`, экран готовности красит «Банк подключён» по факту строки, бейдж в настройках видит
// только тот, кто открыл слайдовер. Остаётся `console.warn` — то самое «лог требует, чтобы кто-то
// уже смотрел», ради которого и заводили пуш-канал.
//
// ⚠ ЧТО ЭТО ЛОВИТ И ЧЕГО НЕ ЛОВИТ — важно не переоценить. Пульс и проверка здоровья очередей живут
// в ОДНОМ процессе, поэтому «пульс протух» означает «продление встало, пока остальное работает»
// (исключение на каждом тике, кривой интервал из env, отвалившаяся БД под сканом). Смерть всего
// крон-инстанса он не поймает — её ловит внешний watchdog (#466), и это отдельная задача.
//
// ⚠ Косвенно остановка продления видна и без пульса: строки перестают перештамповываться, токены
// уходят в `due` → `expired`, и мёртвые подключения уже уезжают в Telegram (#497 §3). Но это
// задержка на целую полосу обновления (у Альфы ~2 ч) и **другой диагноз**: «банк нас отверг» вместо
// «наша машинерия встала». Лечится это разными действиями, поэтому и сигналы разные.
//
// Чистое ядро: ни I/O, ни часов — время передаётся. Модуль в `app/utils`, потому что одну и ту же
// метку показывает экран оператора и судит серверное правило; разъехавшись, они дали бы спокойный
// экран при поднятой тревоге.

/** Итог одного прогона — ровно то, что возвращает `runBankKeepAlive`. */
export interface KeepAlivePulseSummary {
  selected: number
  refreshed: number
  skipped: number
  failed: number
  unrefreshable: number
  expired: number
}

export interface KeepAlivePulse {
  /** Когда прогон ЗАВЕРШИЛСЯ. */
  atMs: number
  summary: KeepAlivePulseSummary
}

/**
 * Сколько тиков подряд можно пропустить, прежде чем это авария.
 *
 * ⚠ Не единица: один пропуск — это штатная жизнь (перезапуск контейнера, выкат, тик, попавший в
 * недоступную на секунду базу). Тревога на первом же пропуске приучает канал игнорировать, а он
 * заведён ради редкого случая. Три тика при часовой каденции — это три часа, что заметно меньше
 * ночи, за которую умирает подключение Альфы, и заметно больше любого штатного перерыва.
 */
export const MISSED_TICKS_BEFORE_ALARM = 3

export type PulseState = 'never' | 'ok' | 'stale'

/**
 * Состояние пульса. `never` — прогонов ещё не было; это НЕ «всё хорошо» и не «сломалось»: сразу
 * после старта процесса так и должно быть, а вот через сутки это значит, что таймер не завёлся.
 * Различать их обязан вызывающий — по возрасту процесса, а не по этому значению.
 */
export function pulseState(
  pulse: KeepAlivePulse | null,
  nowMs: number,
  intervalMs: number,
  opts: { startedAtMs?: number | null, missedTicks?: number } = {}
): PulseState {
  const missedTicks = opts.missedTicks ?? MISSED_TICKS_BEFORE_ALARM
  const window = intervalMs * missedTicks
  const sane = Number.isFinite(intervalMs) && intervalMs > 0
  if (!pulse) {
    // ⚠ «Прогонов не было» ЭСКАЛИРУЕТ по возрасту процесса, и это не мелочь. Без эскалации
    // регрессия, при которой таймер не завёлся вовсе (или падает на каждом прогоне с первого
    // тика), давала бы тишину НАВСЕГДА — тот же «умерли в пятницу, узнали в понедельник», ради
    // которого всё и написано, только зайдя с другого конца. Через окно молчания это уже не
    // «только запустились», а «не запускается».
    if (!sane || opts.startedAtMs == null) return 'never'
    const up = nowMs - opts.startedAtMs
    return Number.isFinite(up) && up > window ? 'stale' : 'never'
  }
  // Кривой интервал (0/NaN/отрицательный) НЕ превращаем в «всё протухло»: это сделало бы опечатку в
  // env неотличимой от настоящей аварии. Такой интервал — сам по себе повод для envCheck, а не для
  // ложной тревоги здесь.
  if (!sane) return 'ok'
  const age = nowMs - pulse.atMs
  // Часы, ушедшие назад (правка времени, подмена в тесте), не должны читаться как древний пульс.
  if (!Number.isFinite(age) || age < 0) return 'ok'
  return age > window ? 'stale' : 'ok'
}

/** Возраст пульса в миллисекундах, `null` — прогонов не было. */
export function pulseAgeMs(pulse: KeepAlivePulse | null, nowMs: number): number | null {
  if (!pulse) return null
  const age = nowMs - pulse.atMs
  return Number.isFinite(age) && age >= 0 ? age : null
}
