// Один счёт, подключённый из НЕСКОЛЬКИХ порталов Bitrix24 (#615) — чистое правило.
//
// ⚠ Требование владельца прямое: «один и тот же счёт, подключённый из двух разных Б24, должен
// работать». Сегодня работает наполовину — каждый портал опрашивает банк СВОИМ подключением:
//   1. лимит запросов банка тратится КРАТНО числу порталов (у Приора одна задача ≈ 11 HTTP);
//   2. Альфа ротирует refresh при каждом обновлении, а лок берётся ПЕР-ПОРТАЛЬНО, поэтому портал Б
//      предъявляет банку токен, который портал А уже сжёг → `400` → грант мёртв (#488).
//
// ⚠ ПОДТВЕРЖДЕНИЕ БАНКОМ — НЕСУЩЕЕ УСЛОВИЕ, А НЕ ПРИДИРКА. Первая редакция сопоставляла порталы по
// ВВЕДЁННОМУ номеру счёта, и это была утечка между клиентами: номер админ вписывает руками, и мы
// его нигде не проверяем (`isValidAccountKey` — только набор символов; ни выбор счёта, ни
// добавление в банк не ходят). Пока каждый портал опрашивает банк сам, вписанный чужой номер
// безвреден — задача просто падает. А с раздачей админ портала X проходит НАСТОЯЩИЙ OAuth своим
// счётом, вписывает ЧУЖОЙ IBAN (он есть на любом счёте-фактуре) — и выписка портала Y уезжает
// делами в его CRM: контрагенты, счета, УНП, назначения, суммы.
//
// Ровно об этом задача #615 предупреждала своими словами: «того, что он ввёл такой же номер,
// недостаточно». Поэтому объединяются ТОЛЬКО строки, про которые сам банк сказал, что этот номер
// принадлежит их гранту (`accountConfirmedAt`). Неподтверждённая строка живёт как раньше — сама
// опрашивает свой счёт и никому ничего не раздаёт.

import type { BankProviderId } from '../types/statement'
import { connectionHealth, type ConnectionLike, needsHumanHealth } from './bankTokenLifetime'

/**
 * Чем адресуется подключение и подтвердил ли банк его счёт.
 *
 * ⚠ Отдельно от `SharedAccountRow`: раздача НЕ смотрит на свежесть токена (см.
 * `portalsSharingAccount`), и потребуй она полей здоровья, вызывающему пришлось бы читать более
 * тяжёлую выборку ради данных, которые не используются.
 */
export interface AccountOwner {
  memberId: string
  provider: BankProviderId
  accountKey: string
  /** Epoch ms, когда БАНК назвал этот номер среди счетов гранта. `0` — не подтверждён. */
  accountConfirmedAt: number
}

/** Минимум для ВЫБОРА ПОЛЛЕРА: адрес, подтверждение и свежесть подключения. */
export interface SharedAccountRow extends ConnectionLike, AccountOwner {}

/** Ключ «это один и тот же счёт». Банк — ЧАСТЬ ключа: один номер у разных банков это разные счета. */
export function sharedAccountKey(provider: BankProviderId, accountKey: string): string {
  return `${provider}|${accountKey}`
}

/**
 * Подтвердил ли банк этот счёт для гранта этой строки.
 *
 * ⚠ ЕДИНСТВЕННЫЙ вход в правило «можно ли считать эту строку доказанным владельцем счёта».
 * Обе функции ниже спрашивают только его — иначе одна из них однажды начнёт доверять номеру.
 */
export function isAccountConfirmed(row: Pick<AccountOwner, 'accountConfirmedAt'>): boolean {
  return Number.isFinite(row.accountConfirmedAt) && row.accountConfirmedAt > 0
}

/**
 * Свернуть ПОДТВЕРЖДЁННЫЕ строки так, чтобы на счёт осталась одна — та, чьим токеном идём в банк.
 *
 * Неподтверждённые строки возвращаются КАК ЕСТЬ, каждая сама по себе: их нельзя ни объединять с
 * чужими, ни отбрасывать. Отбрось мы их — портал, чей счёт банк ещё не подтвердил, молча перестал
 * бы получать выписку вовсе.
 *
 * Порядок выбора среди подтверждённых:
 *   1. **живое важнее свежего.** Портал, чей грант банк уже отверг (`expired`/`no-refresh`),
 *      опрашивать бесполезно: задача упадёт, а счёт останется без выписки у ВСЕХ. Это и есть
 *      требование «умер — переключаемся на следующий портал»;
 *   2. среди живых — самое **свежее** подключение: у него больше запаса до истечения refresh;
 *   3. при равенстве — по `memberId`, чтобы выбор был ДЕТЕРМИНИРОВАННЫМ. Порядок строк из Postgres
 *      при равных значениях не определён, и без явного разрыва ничьей поллер дрейфовал бы от тика
 *      к тику: подключения по очереди ротировали бы refresh — та самая гонка, ради устранения
 *      которой всё написано.
 *
 * ⚠ Если живых нет вовсе — берём одну строку всё равно (самую свежую из мёртвых), а не пропускаем
 * счёт. Один падающий запрос честнее тишины: он попадёт в лог и в состояние подключения, тогда как
 * молча пропущенный счёт неотличим от «операций не было».
 *
 * ⚠ Вход обязан быть УЖЕ отфильтрован «можно ли это опрашивать» (`isPollableAccount`): пауза,
 * ожидающий ключ и демо-счёт снимаются ДО выбора. Иначе поллером стало бы приостановленное
 * подключение, а весь счёт — молча не опрашиваемым, хотя паузу ставил один портал из нескольких.
 */
export function pickAccountPollers<T extends SharedAccountRow>(rows: readonly T[], nowMs: number): T[] {
  const best = new Map<string, T>()
  const solo: T[] = []
  for (const row of rows) {
    if (!isAccountConfirmed(row)) {
      solo.push(row)
      continue
    }
    const key = sharedAccountKey(row.provider, row.accountKey)
    const prev = best.get(key)
    if (!prev || betterPoller(row, prev, nowMs)) best.set(key, row)
  }
  return [...best.values(), ...solo]
}

/** Строго ли `a` лучше `b` как поллер. Выделено ради читаемости порядка сравнений. */
function betterPoller(a: SharedAccountRow, b: SharedAccountRow, nowMs: number): boolean {
  const aDead = needsHumanHealth(connectionHealth(a, nowMs))
  const bDead = needsHumanHealth(connectionHealth(b, nowMs))
  if (aDead !== bDead) return !aDead
  if (a.connectedAt !== b.connectedAt) return a.connectedAt > b.connectedAt
  return a.memberId < b.memberId
}

/**
 * Кому раздавать выписку по этому счёту.
 *
 * ⚠ ТОЛЬКО порталам, чей счёт ПОДТВЕРДИЛ БАНК. Введённый номер доказательством не является — см.
 * шапку модуля. Это и есть граница, отделяющая «раздали своим» от «показали чужие деньги».
 *
 * ⚠ Опрашивавший портал НЕ добавляется сюда искусственно: если он сам не подтверждён, он и не
 * должен был становиться поллером совместного счёта (`pickAccountPollers` его не сворачивает), а
 * значит раздаёт он только себе — вызывающий берёт этот список как есть.
 *
 * ⚠ Состояние подключения здесь НЕ смотрим, в отличие от выбора поллера. Портал с истёкшим
 * банковским грантом всё равно имеет право на СВОИ операции: доступ к счёту он доказал, а мёртвый
 * токен мешает ходить в банк — не получать то, что уже принесли. Отними мы у него выписку, и
 * починка «переподключите банк» перестала бы отличаться от «мы вас отключили».
 *
 * ⚠ Отсортировано и без повторов: список попадает в лог и в число задач, а недетерминированный
 * порядок читался бы как «каждый тик по-разному».
 */
export function portalsSharingAccount(
  rows: readonly AccountOwner[], provider: BankProviderId, accountKey: string
): string[] {
  const key = sharedAccountKey(provider, accountKey)
  const ids = new Set<string>()
  for (const row of rows) {
    if (!isAccountConfirmed(row)) continue
    if (sharedAccountKey(row.provider, row.accountKey) === key) ids.add(row.memberId)
  }
  return [...ids].sort()
}

/**
 * Строка лога про совместные счета. `null` — сворачивать было нечего, молчим.
 *
 * ⚠ Печатаем ЧИСЛА, а не номера счетов и не `member_id`: строка идёт в общий лог (`docs/PRIVACY.md`).
 */
export function sharedAccountsLogLine(before: number, after: number): string | null {
  if (before <= after) return null
  return `совместных счетов: опрос сокращён с ${before} задач до ${after} — выписка раздаётся `
    + `порталам, чей счёт ПОДТВЕРДИЛ банк (#615)`
}

/**
 * Чьи подключения имеет смысл переспросить у банка (#615).
 *
 * ⚠ Спрашиваем НЕ про все счета подряд, а только про те, что заявлены БОЛЕЕ ЧЕМ ОДНИМ порталом и
 * при этом ещё не подтверждены. Портал с уникальным счётом опрашивает его сам, раздавать некому —
 * тратить на него запрос к банку незачем. Поэтому на обычном флоте (у каждого свой счёт) проход
 * не делает НИ ОДНОГО обращения.
 *
 * ⚠ Порталы, а не строки: список счетов банк отдаёт целиком на портал, одним запросом.
 *
 * ⚠ Уже подтверждённые строки в счёт спорящих ВХОДЯТ (иначе портал, подтверждённый первым, не дал
 * бы повода переспросить второго), но сами повторно не переспрашиваются.
 */
export function portalsNeedingConfirm(rows: readonly AccountOwner[]): string[] {
  const holders = new Map<string, Set<string>>()
  for (const r of rows) {
    const key = sharedAccountKey(r.provider, r.accountKey)
    const set = holders.get(key) ?? new Set<string>()
    set.add(r.memberId)
    holders.set(key, set)
  }
  const need = new Set<string>()
  for (const r of rows) {
    if (isAccountConfirmed(r)) continue
    if ((holders.get(sharedAccountKey(r.provider, r.accountKey))?.size ?? 0) > 1) need.add(r.memberId)
  }
  return [...need].sort()
}
