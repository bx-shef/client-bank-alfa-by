// Один счёт, подключённый из НЕСКОЛЬКИХ порталов Bitrix24 (#615) — чистое правило.
//
// ⚠ Требование владельца прямое: «один и тот же счёт, подключённый из двух разных Б24, должен
// работать». Сегодня работает наполовину — каждый портал опрашивает банк СВОИМ подключением, и в
// плане крона это видно буквально: `alfa-by: 1 accounts | prior-by: 1 accounts | alfa-by: 1 accounts`,
// где две строки Альфы — два портала с одним номером счёта.
//
// Следствий два, и второе тяжелее первого:
//   1. лимит запросов банка тратится КРАТНО числу порталов (у Приора одна задача ≈ 11 HTTP);
//   2. гонка за refresh: Альфа ротирует токен при каждом обновлении, лок берётся ПЕР-ПОРТАЛЬНО
//      (`bankRefreshLockKey` начинается с `memberId`), поэтому портал Б предъявляет банку токен,
//      который портал А уже сжёг → `400 Bad Request` → грант мёртв. Это и наблюдалось как
//      «Альфа умирает каждый день» (#488).
//
// Решение: опрашивать счёт ОДИН раз и раздавать результат всем порталам, у которых он подключён.
// Гонка при этом исчезает НЕ потому, что мы стали аккуратнее блокировать, а потому что второго
// обновления больше нет — по построению.
//
// ⚠ РАЗДАЁМ ТОЛЬКО ПОРТАЛАМ С СОБСТВЕННЫМ ПОДКЛЮЧЕНИЕМ к этому счёту, и это несущее правило, а не
// формальность. Каждый из них сам прошёл авторизацию в банке и тем ДОКАЗАЛ доступ к счёту. Раздать
// выписку порталу, который не подключался, значило бы показать чужие деньги на чужом экране — того,
// что кто-то ввёл такой же номер, для этого недостаточно.

import type { BankProviderId } from '../types/statement'
import { connectionHealth, type ConnectionLike, needsHumanHealth } from './bankTokenLifetime'

/**
 * Чем адресуется подключение. Ровно три поля — больше раздаче знать не нужно.
 *
 * ⚠ Отдельно от `SharedAccountRow` намеренно: раздача НЕ смотрит на состояние подключения (см.
 * `portalsSharingAccount`), и потребуй она полей свежести, вызывающему пришлось бы читать более
 * тяжёлую выборку ради данных, которые не используются.
 */
export interface AccountOwner {
  memberId: string
  provider: BankProviderId
  accountKey: string
}

/** Минимум, которого хватает ВЫБОРУ ПОЛЛЕРА: адрес плюс свежесть подключения. */
export interface SharedAccountRow extends ConnectionLike, AccountOwner {}

/** Ключ «это один и тот же счёт». Банк — ЧАСТЬ ключа: один номер у разных банков это разные счета. */
export function sharedAccountKey(provider: BankProviderId, accountKey: string): string {
  return `${provider}|${accountKey}`
}

/**
 * Оставить по ОДНОЙ строке на счёт — та, чьим токеном пойдём в банк.
 *
 * Правило выбора, по порядку:
 *   1. **живое подключение важнее свежего.** Портал, чей грант банк уже отверг (`expired` /
 *      `no-refresh`), опрашивать бесполезно: его задача упадёт, а счёт останется без выписки у ВСЕХ
 *      порталов. Ровно это и означает требование «умер — переключаемся на следующий портал».
 *   2. среди живых — **самое свежее** подключение (`connectedAt`): у него больше всего запаса до
 *      истечения refresh, то есть меньше всего шансов, что оно умрёт между планом и исполнением.
 *   3. при равенстве — по `memberId`, чтобы выбор был ДЕТЕРМИНИРОВАННЫМ. Порядок строк из
 *      Postgres при равных значениях не определён, и без явного разрыва ничьей поллер дрейфовал бы
 *      от тика к тику: подключения по очереди ротировали бы refresh, то есть мы вернули бы ту самую
 *      гонку, ради устранения которой всё написано.
 *
 * ⚠ Если ЖИВЫХ нет вовсе — берём всё равно одну строку (самую свежую из мёртвых), а не пропускаем
 * счёт. Один падающий запрос честнее тишины: он попадёт в лог и в состояние подключения, тогда как
 * молча пропущенный счёт неотличим от «операций не было».
 *
 * ⚠ Вход обязан быть УЖЕ отфильтрован «можно ли это опрашивать» (`isPollableAccount`): пауза,
 * ожидающий ключ и демо-счёт снимаются ДО выбора. Иначе поллером стало бы приостановленное
 * подключение, а весь счёт — молча не опрашиваемым, хотя другой портал его паузу не ставил.
 */
export function pickAccountPollers<T extends SharedAccountRow>(rows: readonly T[], nowMs: number): T[] {
  const best = new Map<string, T>()
  for (const row of rows) {
    const key = sharedAccountKey(row.provider, row.accountKey)
    const prev = best.get(key)
    if (!prev || betterPoller(row, prev, nowMs)) best.set(key, row)
  }
  return [...best.values()]
}

/** Строго ли `a` лучше `b` как поллер. Выделено ради читаемости порядка сравнений. */
function betterPoller(a: SharedAccountRow, b: SharedAccountRow, nowMs: number): boolean {
  const aDead = needsHumanHealth(connectionHealth(a, nowMs))
  const bDead = needsHumanHealth(connectionHealth(b, nowMs))
  if (aDead !== bDead) return !aDead
  if (a.connectedAt !== b.connectedAt) return a.connectedAt > b.connectedAt
  return a.memberId < b.memberId
}

/**
 * Кому раздавать выписку по этому счёту: все порталы с СОБСТВЕННЫМ подключением.
 *
 * ⚠ Отсортировано и без повторов — список попадает в лог и в число задач, а недетерминированный
 * порядок читался бы как «каждый тик по-разному».
 *
 * ⚠ Состояние подключения здесь НЕ смотрим, в отличие от выбора поллера. Портал с истёкшим
 * банковским грантом всё равно имеет право на СВОИ операции: доступ к счёту он доказал, когда
 * подключался, а мёртвый токен мешает ходить в банк — не получать то, что уже принесли. Отними мы
 * у него выписку, и починка «переподключите банк» перестала бы отличаться от «мы вас отключили».
 */
export function portalsSharingAccount(
  rows: readonly AccountOwner[], provider: BankProviderId, accountKey: string
): string[] {
  const key = sharedAccountKey(provider, accountKey)
  const ids = new Set<string>()
  for (const row of rows) {
    if (sharedAccountKey(row.provider, row.accountKey) === key) ids.add(row.memberId)
  }
  return [...ids].sort()
}

/**
 * Строка лога про совместные счета. `null` — делить нечего, молчим.
 *
 * ⚠ Печатаем ЧИСЛА, а не номера счетов и не `member_id`: строка идёт в общий лог (`docs/PRIVACY.md`).
 */
export function sharedAccountsLogLine(before: number, after: number): string | null {
  if (before <= after) return null
  return `совместных счетов: опрос сокращён с ${before} задач до ${after} — `
    + `выписка раздаётся всем порталам, у которых счёт подключён (#615)`
}
