import { defineConfig, devices } from '@playwright/test'

// Визуальные регресс-тесты (#3). «Зрение» у нас было только ручным (`pnpm screenshot`), поэтому
// поехавшая вёрстка ловилась лишь тем, что кто-то догадался посмотреть на пиксели. Здесь тот же
// снимок, но сравниваемый с эталоном на каждом PR.
//
// ⚠ Эталоны привязаны к КОНКРЕТНОЙ сборке Chromium (её пинит версия playwright) и к рендерингу
// шрифтов в окружении. Поэтому джоба в CI ставит браузер тем же `playwright install`, а не берёт
// системный: иначе эталоны, снятые локально, не сойдутся с CI ни разу и тест выродится в шум.
export default defineConfig({
  testDir: './tests/visual',
  outputDir: './tests/visual/.artifacts',
  // `{platform}` в имени: растеризация шрифтов идёт через системный слой (FreeType / DirectWrite /
  // CoreText), поэтому одинаковая сборка Chromium не гарантирует одинаковые пиксели на разных ОС.
  // Без разделения `--update-snapshots` на macOS перезаписал бы линуксовые эталоны своим рендером,
  // и в PR прилетела бы пачка бинарных blob'ов «ни о чём». ⚠ Linux-песочница и linux-раннер, как
  // выяснилось, сходятся почти байт-в-байт: межплатформенное разделение здесь страховка, а не
  // ответ на измеренную проблему — той оказалась подгрузка внешнего iframe, а не шрифты.
  snapshotPathTemplate: '{testDir}/__screenshots__/{platform}/{arg}{ext}',
  fullyParallel: true,
  forbidOnly: !!process.env.CI,
  // Ретраи НЕ ставим: визуальный тест детерминирован по построению, и «со второго раза сошлось»
  // означало бы, что снимок мигает — то есть эталон бесполезен и это надо чинить, а не прятать.
  retries: 0,
  workers: process.env.CI ? 2 : undefined,
  reporter: process.env.CI ? [['github'], ['html', { open: 'never' }]] : [['list']],
  // Трасса при падении: без неё в CI на руках остаётся одна diff-картинка, по которой не видно,
  // в каком состоянии была страница. `on-first-retry` здесь бессмыслен — ретраев нет.
  expect: {
    toHaveScreenshot: {
      // Допуск АБСОЛЮТНЫЙ, а не долевой — и это важно. Доля в 1% на лендинге (1280×5400) даёт
      // 69 000 пикселей: кнопка 150×40 занимает 6 000, то есть пропала бы совершенно незаметно,
      // причём тем незаметнее, чем длиннее (и важнее) страница. Абсолютный порог не растёт вместе
      // со снимком и оставляет запас ровно на сглаживание шрифтов.
      maxDiffPixels: 400,
      threshold: 0.2
    }
  },
  use: {
    ...devices['Desktop Chrome'],
    // Трасса при падении: без неё в CI остаётся одна diff-картинка, по которой не видно, в каком
    // состоянии была страница. `on-first-retry` здесь бессмыслен — ретраев нет.
    trace: 'retain-on-failure',
    // Анимации глушим на уровне браузера (плюс CSS-врезка в самом тесте): без этого снимок ловит
    // случайный кадр и «регрессия» появляется на ровном месте.
    //
    // ⚠ ИМЕННО через `contextOptions`. Написанное прямо в `use` слово `reducedMotion` Playwright
    // 1.62 не знает — такой опции у раннера нет вовсе, и она игнорировалась МОЛЧА: настройка
    // стояла в двух местах, читалась как рабочая и не делала ничего. Замерено (#542):
    // `use: { reducedMotion }` → `matchMedia('(prefers-reduced-motion: reduce)')` = **false**,
    // `contextOptions: { reducedMotion }` → **true**. Ошибку нашли типы, когда конфиг наконец
    // попал под `typecheck`, — до этого её не видел никто.
    //
    // ⚠ Это не дубль CSS-врезки: та гасит CSS-анимации, а `prefers-reduced-motion` читает ЕЩЁ И
    // JS — `ImportStatsChart` по нему выключает count-up цифр и анимацию ECharts, `HeroGraph`
    // рисует статичный кадр. Без него снимок ловил цифры на полпути.
    contextOptions: { reducedMotion: 'reduce' },
    timezoneId: 'Europe/Minsk',
    locale: 'ru-RU'
  }
})
