// Отпечаток токена приложения — отдельным модулем, без зависимостей.
//
// ⚠ Отдельно потому, что его берут ДВА слоя: чистый обработчик события (`b24EventsHandler.ts`)
// кладёт отпечаток в очередь, а сверка в воркере (`systemUser.ts`) считает его от токена в базе.
// Живя в `systemUser.ts`, он тащил в чистый обработчик логгер и всё остальное (находка ревью #783).

import { createHash } from 'node:crypto'

/**
 * sha256 токена приложения в hex — то, что едет в очередь вместо самого токена. Токен приложения —
 * секрет, которым проверяется и удаление приложения, и лежать открытым текстом в Redis ему незачем;
 * отпечаток высокоэнтропийного токена не обратить.
 */
export function applicationTokenHash(token: string): string {
  return createHash('sha256').update(token, 'utf8').digest('hex')
}
