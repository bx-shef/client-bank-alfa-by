// Каденция уборщика мёртвых банк-подключений (#599) — по образцу `portalReaperSchedule.ts`.
//
// ⚠ СВОЯ аренда в Postgres, а не память процесса, по той же причине, что у #574: свип-тик зовётся
// сразу на старте, поэтому метка в памяти разрешала бы прогон на КАЖДОМ рестарте — а контейнер в
// crash-loop стёр бы по потолку строк за перезапуск. Аренда переживает рестарт и разводит реплики.
//
// ⚠ ОТДЕЛЬНЫЙ ключ от портального уборщика: это разные операции с разной единицей (портал / строка),
// и общая аренда сериализовала бы их друг с другом без всякой причины.

import { acquireLease } from './singleFlightLease'
import type { QueryFn } from './tokenStore'

/** Ключ аренды. Один на весь сервис — уборщик не пер-портальный. */
export const BANK_REAP_LEASE_KEY = 'bank-reap'

/**
 * Можно ли прогонять уборщика прямо сейчас. Аренда берётся на `ttlSec` и НЕ снимается: пока жива,
 * следующий прогон не состоится. «Взята» = «в этом окне уже отработали».
 *
 * ⚠ Отказ базы = НЕ прогонять: механизм, стирающий данные клиента, не должен работать, когда мы не
 * смогли выяснить, отрабатывал ли он только что.
 */
export async function claimBankReapSlot(q: QueryFn, ttlSec: number, token: string): Promise<boolean> {
  try {
    return await acquireLease(q, BANK_REAP_LEASE_KEY, ttlSec, token) !== null
  } catch {
    return false
  }
}
