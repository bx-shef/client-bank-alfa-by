// Single-flight БЕЗ удержания соединения из пула (#538).
//
// Провижининг смарт-процессов и пересчёт распределения выполняются «по одному на портал». Раньше
// это давал `withAdvisoryLock`: он берёт соединение из пула, открывает транзакцию и держит их всё
// время работы `fn`. Здесь это плохо кончается, потому что внутри `fn` НЕТ НИ ОДНОГО запроса к
// базе — только REST-вызовы в Bitrix24. То есть соединение всё это время `idle in transaction`:
// занимает слот пула, не делая с базой ничего.
//
// ⚠ Величины несопоставимы. Провижининг — ~18 последовательных REST-вызовов (десятки секунд),
// пересчёт — список платежей плюс два вызова на КАЖДЫЙ, до `MAX_LEDGER_PAYMENTS`, то есть минуты.
// Ключ лока пер-портальный, поэтому разные порталы друг друга не сериализуют и каждый занимает
// СВОЁ соединение; пул — 10. Десяток одновременных провижинингов с разных порталов (все
// легитимные) выели бы пул целиком, и всё остальное, что ходит в базу — readiness-проба, приём
// `ONAPPINSTALL`, воркер очередей — ждало бы до `connectionTimeoutMillis` и падало.
//
// ⚠ Это ВЫВОД из чтения кода, а не наблюдение на проде: провижининг за гейтом
// `DISTRIBUTION_PROVISION_ENABLED`, выключенным по умолчанию, так что описанного инцидента не
// случалось. Чинить его до включения гейта клиентам — дешевле; выдавать за случившийся — нельзя.
//
// ⚠ Отдельно скверно, что симптом СОВРАЛ БЫ: `/api/ready` честно ответил бы «Postgres
// недоступен», хотя Postgres здоров и виноваты наши же удерживаемые соединения.
//
// Аренда снимает причину, а не следствие: соединение берётся дважды по одному короткому запросу
// (взять аренду / снять её), а REST-цепочка идёт БЕЗ соединения вовсе.
//
// ⚠ Цена размена названа честно: advisory-лок освобождался сам при смерти процесса, аренда — нет,
// её держит `expires_at`. Поэтому падение посреди операции оставляет портал в «занято» до конца
// срока. Это хуже для ОДНОГО портала и несопоставимо лучше для всех остальных: сегодняшний отказ
// выедает общий пул, то есть накрывает весь сервис.
//
// ⚠ Часы — ВСЕГДА базы (`now()` в SQL), а не процесса: реплик несколько, и разъехавшиеся на минуту
// часы двух инстансов означали бы, что второй считает чужую живую аренду просроченной и заходит
// внутрь — ровно то двойное создание смарт-процессов, ради запрета которого всё и написано.
//
// ⚠ Снятие адресуется ТОКЕНОМ, а не только ключом. Без токена запоздавшее снятие (операция
// пережила свой срок) удаляло бы аренду, которую к тому моменту взял уже кто-то другой, — и внутрь
// заходили бы двое.

import type { QueryFn } from './tokenStore'

/** Таблица аренд. Строк — не больше, чем порталов × число операций: просроченная не копится, её
 *  перезаписывает следующий же захват под тем же ключом. Поэтому свипа у неё нет. */
export const SINGLE_FLIGHT_LEASE_TABLE = 'single_flight_lease'

/**
 * Срок аренды. КОРОТКИЙ и ОДИН на обе операции — потому что он больше не пытается покрыть их
 * длительность: пока работа идёт, аренда ПРОДЛЕВАЕТСЯ (`renewLease`).
 *
 * ⚠ Первая версия ставила сроки «с запасом» под измеренную длительность (5 мин провижинингу,
 * 15 пересчёту) — и это было неверно ДВАЖДЫ. Во-первых, длительность не ограничена ничем: у
 * обычного SDK-вызова таймаута нет вовсе (`withTimeout` в `b24Sdk.ts` накинут только на рефреш),
 * поэтому один зависший вызов к порталу переживает любой запас. Во-вторых, запас у пересчёта был
 * куда меньше, чем казалось: он обходит `MAX_LEDGER_PAYMENTS` платежей, и «два вызова на платёж» —
 * НИЖНЯЯ граница (у платежа с числом строк распределения больше страницы их до `MAX_LEDGER_PAGES`),
 * то есть ≥404 последовательных вызова, а при потолке SDK в 2 req/s плюс латентность портала это
 * подходит к 900 с вплотную.
 *
 * ⚠ Цена ошибки тут не «подождём подольше», а ДУБЛИКАТЫ смарт-процессов в CRM клиента без кнопки
 * отката: пережившая свой срок операция теряет исключительность, второй админ входит внутрь, оба
 * промахиваются мимо title-probe, а завершающий `saveSettings` первого затирает id, записанные
 * вторым.
 *
 * С продлением срок означает только одно — сколько портал будет «занят», если процесс УМЕР
 * (продлевать станет некому). Отсюда и минута вместо четверти часа.
 */
export const SINGLE_FLIGHT_LEASE_SEC = 60

/**
 * Как часто продлевать. Треть срока — то есть подряд должны отказать ТРИ продления, прежде чем
 * аренда протухнет под живым держателем; одна неудачная секунда базы такого не делает.
 */
export const LEASE_RENEW_MS = Math.floor((SINGLE_FLIGHT_LEASE_SEC * 1000) / 3)

/**
 * Ключи аренд ПОРТАЛА — в одном месте, потому что читателей у них двое и вторым легко не стать.
 *
 * ⚠ Первый — роут, который аренду берёт. Второй — удаление приложения: контракт «`ONAPPUNINSTALL`
 * стирает для портала ВСЁ» (#77), и строка аренды из-под него выпадала. Для живого портала
 * рассуждение «просроченная не копится, её перезапишет следующий захват» верно, а для УДАЛЁННОГО
 * захвата больше не будет никогда — то есть `member_id` клиента, который нас удалил, оставался бы
 * в базе и в бэкапах навсегда.
 *
 * ⚠ Сборка ключей общая, а НЕ `LIKE '%:' || $1` при удалении: шаблон зависел бы от формы ключа
 * (появится третья операция с другим порядком частей — удаление молча перестанет её видеть) и
 * дополнительно требовал бы экранировать `%`/`_` в идентификаторе. Список закрыт тестом.
 */
export function provisionLeaseKey(memberId: string): string {
  return `provision-sp:${memberId}`
}

export function recomputeLeaseKey(memberId: string): string {
  return `distribution-recompute:${memberId}`
}

/**
 * Стирание дел портала (#576 п.4).
 *
 * ⚠ Нужна по той же причине, что и у соседей, только острее: операция НЕОБРАТИМА. Два
 * одновременных стирания (двойной клик из разных вкладок, повтор после долгого ответа) собирают
 * СВОЙ список идентификаторов, пока ни одно ещё ничего не удалило, а потом удаляют одно и то же:
 * второе получает «not found» и обрывается, а его отчёт человеку становится бессмысленным.
 *
 * ⚠ Хуже того, обход страниц идёт по смещению: удаления одного запроса, попавшие в ЛИСТИНГ
 * другого, сдвигают выборку, и часть дел молча не попадает в список — классический пропуск при
 * offset-пагинации по сжимающемуся набору. То есть без аренды «стереть всё» тихо стирало бы не всё.
 */
export function eraseLeaseKey(memberId: string): string {
  return `erase-activities:${memberId}`
}

/** Все аренды портала — то, что обязано исчезнуть вместе с порталом. */
export function portalLeaseKeys(memberId: string): string[] {
  return [provisionLeaseKey(memberId), recomputeLeaseKey(memberId), eraseLeaseKey(memberId)]
}

/** Снять все аренды портала (удаление приложения). Идемпотентно. */
export async function deleteLeasesForPortal(q: QueryFn, memberId: string): Promise<void> {
  await q(`DELETE FROM ${SINGLE_FLIGHT_LEASE_TABLE} WHERE key = ANY($1)`, [portalLeaseKeys(memberId)])
}

/** Отказ «операция уже идёт». Не ошибка: вызывающий отвечает 503 «занято», а не 5xx-аварией. */
export class SingleFlightBusyError extends Error {
  readonly key: string
  constructor(key: string) {
    super(`single-flight busy: ${key}`)
    this.name = 'SingleFlightBusyError'
    this.key = key
  }
}

/** Занято ли (а не сломалось). Отдельный предикат по образцу `isLockTimeout`. */
export function isSingleFlightBusy(e: unknown): boolean {
  return e instanceof SingleFlightBusyError
}

/**
 * Отказ НАШЕЙ базы на захвате аренды.
 *
 * ⚠ Заведён потому, что различать это по ТЕКСТУ невозможно, а последствие ошибки — конкретное:
 * исчерпание пула бросает `timeout exceeded when trying to connect`, недоступный Postgres —
 * `connect ECONNREFUSED …:5432`, и обе строки совпадают с ветками `classifyProvisionError`,
 * которые говорят «Портал не ответил вовремя». То есть админа уверенно отправляли искать причину
 * в Bitrix24 ровно тогда, когда лежала наша база. Ловить это перечислением текстов — гонка, в
 * которой список всегда отстаёт; поэтому происхождение помечается ТИПОМ в единственном месте, где
 * мы точно знаем, что говорили со своей базой.
 */
export class SingleFlightUnavailableError extends Error {
  readonly key: string
  constructor(key: string, cause: unknown) {
    super(`single-flight storage unavailable: ${key}`, { cause })
    this.name = 'SingleFlightUnavailableError'
    this.key = key
  }
}

/** Отказала НАША база (а не портал). */
export function isSingleFlightUnavailable(e: unknown): boolean {
  return e instanceof SingleFlightUnavailableError
}

/**
 * Взять аренду `key` на `ttlSec` секунд. Отдаёт токен снятия либо `null`, если аренда занята.
 *
 * Захват и проверка срока — ОДИН оператор: `ON CONFLICT … DO UPDATE … WHERE expires_at <= now()`
 * атомарен, поэтому два инстанса, пришедшие одновременно, не могут оба увидеть строку просроченной.
 * `RETURNING` пуст ровно тогда, когда чужая аренда ещё жива.
 *
 * ⚠ Замерено на живом Postgres 16, и именно в опасном случае — строка ПРОСРОЧЕНА, оба претендента
 * видят её таковой: второй блокируется на строке, после коммита первого перечитывает условие уже
 * по НОВОМУ сроку и получает ноль строк. Победитель ровно один.
 *
 * ⚠ Блокировка строки при этом НЕ растягивается на работу: транзакция захвата — один автокоммитный
 * оператор, она завершается за микросекунды, и `fn` идёт уже без неё. Тем аренда и отличается от
 * advisory-лока, который держал транзакцию (а с ней соединение пула) всю REST-цепочку.
 */
export async function acquireLease(q: QueryFn, key: string, ttlSec: number, token: string): Promise<string | null> {
  const rows = await q(
    `INSERT INTO ${SINGLE_FLIGHT_LEASE_TABLE} (key, token, expires_at)
     VALUES ($1, $2, now() + make_interval(secs => $3))
     ON CONFLICT (key) DO UPDATE
       SET token = EXCLUDED.token, expires_at = EXCLUDED.expires_at
       WHERE ${SINGLE_FLIGHT_LEASE_TABLE}.expires_at <= now()
     RETURNING token`,
    [key, token, safeTtl(ttlSec)]
  )
  return rows.length > 0 ? token : null
}

/**
 * Срок в секундах, который не может отключить взаимное исключение.
 *
 * ⚠ Ноль и отрицательное здесь не «без срока», а МОЛЧАЛИВОЕ ВЫКЛЮЧЕНИЕ: `now() + 0` делает условие
 * `expires_at <= now()` истинным немедленно, то есть внутрь заходит кто угодно — при том, что
 * захват вернул токен и вызывающий уверен, что держит аренду. Сегодня сроки захардкожены, но
 * функция общая, и первое же значение из env повторило бы ту же ошибку без единого симптома.
 */
function safeTtl(ttlSec: number): number {
  return Number.isFinite(ttlSec) ? Math.max(1, Math.floor(ttlSec)) : 1
}

/**
 * Продлить СВОЮ аренду. `false` = строки с нашим токеном больше нет: либо мы её уже потеряли
 * (аренда протухла и досталась другому), либо портал удалён. Вызывающий на это только перестаёт
 * продлевать и жалуется в лог — прервать середину REST-цепочки всё равно нечем.
 */
export async function renewLease(q: QueryFn, key: string, token: string, ttlSec: number): Promise<boolean> {
  const rows = await q(
    `UPDATE ${SINGLE_FLIGHT_LEASE_TABLE}
     SET expires_at = now() + make_interval(secs => $3)
     WHERE key = $1 AND token = $2
     RETURNING token`,
    [key, token, safeTtl(ttlSec)]
  )
  return rows.length > 0
}

/** Снять СВОЮ аренду. Чужую (взятую после истечения нашей) не трогает — отсюда `token` в WHERE. */
export async function releaseLease(q: QueryFn, key: string, token: string): Promise<void> {
  await q(`DELETE FROM ${SINGLE_FLIGHT_LEASE_TABLE} WHERE key = $1 AND token = $2`, [key, token])
}

export interface SingleFlightLeaseDeps {
  /** Короткий запрос к базе. В живой проводке — `dbQuery` (соединение берётся и отдаётся сразу). */
  query: QueryFn
  /** Токен снятия. Инъектируется ради детерминированного теста; живой — `randomUUID`. */
  newToken: () => string
  /** Аренду потеряли посреди работы (продление не нашло своей строки). Только след в логе. */
  onLeaseLost?: (key: string) => void
}

/**
 * Выполнить `fn` под арендой `key`. Занято ⇒ `SingleFlightBusyError` (вызывающий отвечает «занято»),
 * ждать НЕ пытаемся: держателя всё равно не дождаться, а второму вызывающему нечего делать —
 * первый выполняет ту же самую работу.
 *
 * ⚠ Пока `fn` работает, аренда ПРОДЛЕВАЕТСЯ. Без продления срок обязан был бы покрывать
 * длительность операции — а она не ограничена ничем: у обычного SDK-вызова таймаута нет, и один
 * зависший запрос к порталу переживает любой запас. Пережившая свой срок операция теряет
 * исключительность МОЛЧА: второй админ входит внутрь, оба промахиваются мимо title-probe, и в CRM
 * клиента появляются дубликаты смарт-процессов, откатить которые в проде нечем.
 *
 * ⚠ Продление не делает аренду вечной — ровно наоборот, оно позволяет держать срок КОРОТКИМ:
 * умер процесс ⇒ продлевать некому ⇒ портал свободен через минуту, а не через четверть часа.
 * Таймер `unref`-ится (не держит процесс живым) и снимается в `finally`.
 *
 * ⚠ Потерю аренды (`renewLease` вернул `false` — истекла и досталась другому, или портал удалён)
 * мы только фиксируем в логе и перестаём продлевать: прервать середину REST-цепочки нечем, а
 * тихое продолжение хотя бы оставляет след для разбора.
 *
 * ⚠ Снятие идёт в `finally` и его собственный отказ ГЛОТАЕТСЯ: результат операции важнее, а
 * неснятая аренда самозаживает по сроку (минута, а не 15 — см. выше). Пробросив ошибку снятия, мы
 * превратили бы успешный провижининг в 502, и админ пошёл бы создавать смарт-процессы второй раз.
 */
export async function withSingleFlightLease<T>(
  deps: SingleFlightLeaseDeps,
  key: string,
  ttlSec: number,
  fn: () => Promise<T>
): Promise<T> {
  let token: string | null
  try {
    token = await acquireLease(deps.query, key, ttlSec, deps.newToken())
  } catch (e) {
    // Своя база, а не портал — см. докстринг `SingleFlightUnavailableError`.
    throw new SingleFlightUnavailableError(key, e)
  }
  if (!token) throw new SingleFlightBusyError(key)

  const held = token
  const renewEveryMs = Math.max(1000, Math.floor((safeTtl(ttlSec) * 1000) / 3))
  const timer = setInterval(() => {
    void renewLease(deps.query, key, held, ttlSec)
      .then((stillOurs) => {
        if (!stillOurs) {
          deps.onLeaseLost?.(key)
          clearInterval(timer)
        }
      })
      // Отказ базы на продлении — не повод падать: до истечения ещё две попытки.
      .catch(() => undefined)
  }, renewEveryMs)
  timer.unref?.()

  try {
    return await fn()
  } finally {
    clearInterval(timer)
    try {
      await releaseLease(deps.query, key, held)
    } catch {
      // аренда истечёт сама — см. докстринг
    }
  }
}
