// Single-flight БЕЗ удержания соединения из пула (#538).
//
// Провижининг смарт-процессов и пересчёт распределения выполняются «по одному на портал». Раньше
// это давал `withAdvisoryLock`: он берёт соединение из пула, открывает транзакцию и держит их всё
// время работы `fn`. Здесь это плохо кончается, потому что внутри `fn` НЕТ НИ ОДНОГО запроса к
// базе — только REST-вызовы в Bitrix24. То есть соединение всё это время `idle in transaction`:
// занимает слот пула, не делая с базой ничего.
//
// ⚠ Величины несопоставимы. Провижининг — ~18 последовательных REST-вызовов (десятки секунд),
// пересчёт — список платежей плюс два вызова на КАЖДЫЙ, до `MAX_LEDGER_PAYMENTS`, то есть минуты.
// Ключ лока пер-портальный, поэтому разные порталы друг друга не сериализуют и каждый занимает
// СВОЁ соединение; пул — 10. Десяток одновременных провижинингов с разных порталов (все
// легитимные) выедают пул целиком, и всё остальное, что ходит в базу — readiness-проба, приём
// `ONAPPINSTALL`, воркер очередей — ждёт до `connectionTimeoutMillis` и падает.
//
// ⚠ Отдельно скверно, что симптом ВРЁТ: `/api/ready` в этот момент честно ответит «Postgres
// недоступен», хотя Postgres здоров и виноваты наши же удерживаемые соединения.
//
// Аренда снимает причину, а не следствие: соединение берётся дважды по одному короткому запросу
// (взять аренду / снять её), а REST-цепочка идёт БЕЗ соединения вовсе.
//
// ⚠ Цена размена названа честно: advisory-лок освобождался сам при смерти процесса, аренда — нет,
// её держит `expires_at`. Поэтому падение посреди операции оставляет портал в «занято» до конца
// срока. Это хуже для ОДНОГО портала и несопоставимо лучше для всех остальных: сегодняшний отказ
// выедает общий пул, то есть накрывает весь сервис.
//
// ⚠ Часы — ВСЕГДА базы (`now()` в SQL), а не процесса: реплик несколько, и разъехавшиеся на минуту
// часы двух инстансов означали бы, что второй считает чужую живую аренду просроченной и заходит
// внутрь — ровно то двойное создание смарт-процессов, ради запрета которого всё и написано.
//
// ⚠ Снятие адресуется ТОКЕНОМ, а не только ключом. Без токена запоздавшее снятие (операция
// пережила свой срок) удаляло бы аренду, которую к тому моменту взял уже кто-то другой, — и внутрь
// заходили бы двое.

import type { QueryFn } from './tokenStore'

/** Таблица аренд. Строк — не больше, чем порталов × число операций: просроченная не копится, её
 *  перезаписывает следующий же захват под тем же ключом. Поэтому свипа у неё нет. */
export const SINGLE_FLIGHT_LEASE_TABLE = 'single_flight_lease'

/** Срок аренды провижининга. ~18 последовательных вызовов при потолке SDK в 2 запроса в секунду —
 *  это секунды; пять минут дают запас на медленный портал и ретраи внутри SDK. */
export const PROVISION_LEASE_SEC = 300

/** Срок аренды пересчёта. До `MAX_LEDGER_PAYMENTS` платежей по два вызова при тех же 2 req/s —
 *  это минуты, поэтому запас втрое больше провижининга. */
export const RECOMPUTE_LEASE_SEC = 900

/** Отказ «операция уже идёт». Не ошибка: вызывающий отвечает 503 «занято», а не 5xx-аварией. */
export class SingleFlightBusyError extends Error {
  readonly key: string
  constructor(key: string) {
    super(`single-flight busy: ${key}`)
    this.name = 'SingleFlightBusyError'
    this.key = key
  }
}

/** Занято ли (а не сломалось). Отдельный предикат по образцу `isLockTimeout`. */
export function isSingleFlightBusy(e: unknown): boolean {
  return e instanceof SingleFlightBusyError
}

/**
 * Взять аренду `key` на `ttlSec` секунд. Отдаёт токен снятия либо `null`, если аренда занята.
 *
 * Захват и проверка срока — ОДИН оператор: `ON CONFLICT … DO UPDATE … WHERE expires_at <= now()`
 * атомарен, поэтому два инстанса, пришедшие одновременно, не могут оба увидеть строку просроченной.
 * `RETURNING` пуст ровно тогда, когда чужая аренда ещё жива.
 *
 * ⚠ Замерено на живом Postgres 16, и именно в опасном случае — строка ПРОСРОЧЕНА, оба претендента
 * видят её таковой: второй блокируется на строке, после коммита первого перечитывает условие уже
 * по НОВОМУ сроку и получает ноль строк. Победитель ровно один.
 *
 * ⚠ Блокировка строки при этом НЕ растягивается на работу: транзакция захвата — один автокоммитный
 * оператор, она завершается за микросекунды, и `fn` идёт уже без неё. Тем аренда и отличается от
 * advisory-лока, который держал транзакцию (а с ней соединение пула) всю REST-цепочку.
 */
export async function acquireLease(q: QueryFn, key: string, ttlSec: number, token: string): Promise<string | null> {
  const rows = await q(
    `INSERT INTO ${SINGLE_FLIGHT_LEASE_TABLE} (key, token, expires_at)
     VALUES ($1, $2, now() + make_interval(secs => $3))
     ON CONFLICT (key) DO UPDATE
       SET token = EXCLUDED.token, expires_at = EXCLUDED.expires_at
       WHERE ${SINGLE_FLIGHT_LEASE_TABLE}.expires_at <= now()
     RETURNING token`,
    [key, token, ttlSec]
  )
  return rows.length > 0 ? token : null
}

/** Снять СВОЮ аренду. Чужую (взятую после истечения нашей) не трогает — отсюда `token` в WHERE. */
export async function releaseLease(q: QueryFn, key: string, token: string): Promise<void> {
  await q(`DELETE FROM ${SINGLE_FLIGHT_LEASE_TABLE} WHERE key = $1 AND token = $2`, [key, token])
}

export interface SingleFlightLeaseDeps {
  /** Короткий запрос к базе. В живой проводке — `dbQuery` (соединение берётся и отдаётся сразу). */
  query: QueryFn
  /** Токен снятия. Инъектируется ради детерминированного теста; живой — `randomUUID`. */
  newToken: () => string
}

/**
 * Выполнить `fn` под арендой `key`. Занято ⇒ `SingleFlightBusyError` (вызывающий отвечает «занято»),
 * ждать НЕ пытаемся: держателя всё равно не дождаться, а второму вызывающему нечего делать —
 * первый выполняет ту же самую работу.
 *
 * ⚠ Снятие идёт в `finally` и его собственный отказ ГЛОТАЕТСЯ: результат операции важнее, а
 * неснятая аренда самозаживает по сроку. Пробросив ошибку снятия, мы превратили бы успешный
 * провижининг в 502 — и админ пошёл бы создавать смарт-процессы второй раз.
 */
export async function withSingleFlightLease<T>(
  deps: SingleFlightLeaseDeps,
  key: string,
  ttlSec: number,
  fn: () => Promise<T>
): Promise<T> {
  const token = await acquireLease(deps.query, key, ttlSec, deps.newToken())
  if (!token) throw new SingleFlightBusyError(key)
  try {
    return await fn()
  } finally {
    try {
      await releaseLease(deps.query, key, token)
    } catch {
      // аренда истечёт сама — см. докстринг
    }
  }
}
