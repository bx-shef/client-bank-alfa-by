// Автоотключение банка у портала без подписки на REST (#614, часть 3) — сшивка правила с базой.
//
// ⚠ Зачем вообще автомат, если есть кнопка у оператора: пока подключение висит, портал продолжает
// ОПРАШИВАТЬ банк (`accountsForPolling` про REST не знает вовсе) и продлевать банковский токен —
// то есть тратит лимит запросов банка и гоняется за ротацией refresh с другими порталами, у
// которых тот же счёт (#615). Записать при этом он не может НИЧЕГО: REST мёртв. Ждать здесь
// человека значит месяцами ломать чужие рабочие подключения ради портала, который не работает.
//
// ⚠ Стираем ТОЛЬКО банковские подключения, а НЕ портал. Портал установлен законно, у него просто
// кончилась оплата REST; удали мы грант — вернувшийся клиент обнаружил бы приложение снесённым.
// Плата за наше действие названа владельцем и принята: «клиент ничего не теряет, только
// переподключить всё» — то есть повторный вход владельца счёта в интернет-банк.
//
// ⚠ КЛИЕНТУ МЫ ОБ ЭТОМ НЕ СООБЩАЕМ, и это не забывчивость: единственный канал до бухгалтера —
// чат ошибок портала, а он идёт через тот самый REST, которого нет. Попытка отправки дала бы
// гарантированный отказ и запись в лог о нём. Клиент узнаёт двумя другими путями: пока срок не
// вышел, подключение видно оператору с обратным отсчётом, а после возврата подписки — по пустому
// списку подключений и красной строке экрана готовности.
//
// ⚠ ПРЕДОХРАНИТЕЛЬ ПО ДОЛЕ ФЛОТА ЗДЕСЬ НЕСУЩИЙ, сильнее чем у соседей #574/#599. У тех сигнал —
// ответ сервера (`invalid_grant`) или дата банка; здесь метку ставит РЕГУЛЯРКА по тексту ошибки
// (`SUBSCRIPTION_ENDED_RE`), потому что машинного кода Bitrix24 на этот отказ не даёт. Смени банк
// формулировку или расширь кто-нибудь маску — и «мёртвыми» станут все разом. Массовое отключение
// по нашей же опечатке обязано упереться в стену раньше, чем дойдёт до клиентов.

import { fleetBreach } from '../../app/utils/portalReaper'
import {
  MAX_SUBSCRIPTION_CUTOFF_PER_RUN,
  SUBSCRIPTION_CUTOFF_OVERFETCH,
  type SubscriptionCutoffFacts,
  subscriptionCutoffDue,
  subscriptionCutoffLogLine
} from '../../app/utils/portalSubscription'
import { portalHash } from './telemetryAttributes'

/** Инъектируемые side-effects — правило тестируется без базы. */
export interface SubscriptionCutoffDeps {
  now: () => number
  /** Сколько порталов молчат дольше границы (числитель предохранителя). */
  countDue: (beforeMs: number) => Promise<number>
  /** Сколько порталов у нас всего — знаменатель предохранителя. */
  countPortals: () => Promise<number>
  /** Кандидаты: самые давние первыми, не больше `limit`. Отдаёт и метку — её перечитывает правило. */
  selectDue: (beforeMs: number, limit: number) => Promise<{ memberId: string, endedAtMs: number }[]>
  /** Стереть ВСЕ банковские подключения портала; возвращает сколько строк убрано. */
  disconnectBanks: (memberId: string) => Promise<number>
  /**
   * ПЕРЕСПРОСИТЬ портал прямо сейчас: подписка правда всё ещё мертва?
   *
   * ⚠ Без этого автомат отключал бы по МЕТКЕ, а метка бывает устаревшей — и не в теории. Снимает
   * её сегодня ровно один путь: удачно завершённый прогон `crm-sync`. На ТИХОМ счёте (за четверо
   * суток ни одной операции — выходные, праздники, малый оборот) `crm-sync` не запускается вовсе,
   * потому что опрос вернул пустую выписку. Значит клиент, оплативший подписку на второй день,
   * метку не снимает НИЧЕМ, и на пятые сутки мы отключаем банк у исправного, платящего портала.
   *
   * ⚠ Это же снимает и вторую, более тонкую опасность: метку ставит регулярка по ТЕКСТУ ошибки, а
   * текст мы иногда отправляем сами (назначение платежа пишет плательщик и едет в параметры
   * записи). Отражённая обратно строка поставила бы ложную метку. Живой перезапрос отвечает
   * «жив» — и ложная метка снимается, не дойдя до необратимого шага.
   *
   * ⚠ Стоит РЯДОМ с отключением, а не вместо метки: метка отвечает «кого имеет смысл
   * переспрашивать» (иначе пришлось бы опрашивать весь флот), перезапрос — «правда ли».
   *
   * `unknown` (сеть моргнула, портал не ответил) — НЕ повод отключать: не знаем ⇒ не рвём.
   */
  probeSubscription: (memberId: string) => Promise<'alive' | 'dead' | 'unknown'>
  /**
   * Снять метку подписки после отключения.
   *
   * ⚠ Без этого автомат ЗАКЛИНИВАЕТ. Метка живёт в `portal_tokens` и переживает удаление
   * банковских строк, а выборка отсортирована по ней ASC — то есть уже отключённый портал
   * оказывается ПЕРВЫМ в каждом следующем прогоне: он навсегда занимает место в бюджете и
   * раздувает числитель предохранителя, а настоящие кандидаты за ним не отключаются никогда.
   *
   * ⚠ Про ШУМ В ЛОГЕ речи НЕ идёт, хотя так и просится написать: у отключённого портала
   * `disconnectBanks` вернёт `0`, и прогон уйдёт в тихий `skipped`, а не в громкое «банк
   * отключён» (оно печатается только при `removed > 0`). Да и прогон идёт РАЗ В СУТКИ, а не
   * каждые полчаса: свип-тик тикает часто, но аренда `subscription-cutoff` держится
   * `REAP_MIN_INTERVAL_MS`. Первая редакция комментария утверждала и то, и другое — то есть
   * объясняла верное решение несуществующим сценарием.
   */
  clearMark: (memberId: string) => Promise<boolean>
  log?: (msg: string) => void
  warn?: (msg: string) => void
}

/**
 * Один прогон автоотключения.
 *
 * @param days порог в днях (`SUBSCRIPTION_CUTOFF_DAYS`, если вызывающий не задал своё).
 *
 * ⚠ Флага «только считать» тут НЕТ, в отличие от #574. Там наблюдение оправдано тем, что сигнал
 * ещё не подтверждён на живом флоте; здесь он подтверждён — строку `Subscription has been ended`
 * мы читали в боевом логе, — а бездействие само по себе вредит (см. шапку). Аварийный выключатель
 * есть и он один: порог. Поставь его заведомо большим — и автомат замолчит.
 */
export async function runSubscriptionCutoff(
  deps: SubscriptionCutoffDeps, days: number
): Promise<SubscriptionCutoffFacts> {
  const nowMs = deps.now()
  // Граница считается ЗДЕСЬ и уходит в SQL готовой: база не знает про политику, а тест не
  // подсовывает в неё часы.
  const beforeMs = nowMs - days * 86_400_000
  const candidates = await deps.countDue(beforeMs)
  const s: SubscriptionCutoffFacts = {
    candidates, cutoff: 0, connections: 0, failed: 0, skipped: 0, recovered: 0, unknown: 0,
    diverged: 0, capped: false, breach: false, days
  }

  if (candidates > 0 && fleetBreach(candidates, await deps.countPortals())) {
    s.breach = true
    deps.warn?.(`автоотключение ОСТАНОВЛЕНО: без подписки выглядят ${candidates} порталов — слишком `
      + `большая доля флота. Метку ставит регулярка по тексту ошибки, поэтому это почти наверняка `
      + `наша поломка, а не уход клиентов. Ничего не отключено`)
    deps.log?.(subscriptionCutoffLogLine(s))
    return s
  }

  const due = await deps.selectDue(beforeMs, MAX_SUBSCRIPTION_CUTOFF_PER_RUN + SUBSCRIPTION_CUTOFF_OVERFETCH)
  for (const row of due) {
    // ⚠ ВТОРАЯ, независимая проверка тем же чистым правилом, которое показывает обратный отсчёт
    // оператору. Разойдись они — оператор видел бы «отключим через 2 дня», а отключение случилось
    // бы сегодня; поэтому расхождение считается ОТДЕЛЬНО от отказов базы (чинится в коде, а не на
    // сервере) и никогда не приводит к отключению.
    if (!subscriptionCutoffDue(row.endedAtMs, nowMs, days)) {
      s.diverged++
      deps.warn?.(`портал ${portalHash(row.memberId)} НЕ отключён: выборка и правило разошлись `
        + `(метка ${row.endedAtMs}, порог ${days} дн.)`)
      continue
    }
    if (s.cutoff >= MAX_SUBSCRIPTION_CUTOFF_PER_RUN) {
      s.capped = true
      break
    }
    // ⚠ ПОСЛЕДНЯЯ проверка перед необратимым — живая, у самого портала. Порог и метка отвечают
    // «кого стоит переспросить», и только этот вызов — «правда ли». Он же чинит две дыры разом:
    // устаревшую метку на тихом счёте и ложную метку от отражённого текста (см. `probeSubscription`).
    let verdict: 'alive' | 'dead' | 'unknown'
    try {
      verdict = await deps.probeSubscription(row.memberId)
    } catch {
      verdict = 'unknown'
    }
    if (verdict === 'alive') {
      // Подписку вернули, а сказать нам об этом было нечем. Снимаем метку и НЕ трогаем банк.
      s.recovered++
      try {
        await deps.clearMark(row.memberId)
      } catch { /* повторим в следующий прогон — отключение всё равно не состоится */ }
      continue
    }
    if (verdict === 'unknown') {
      // ⚠ Не знаем — не рвём. Метку оставляем: следующий прогон переспросит.
      s.unknown++
      continue
    }
    try {
      const removed = await deps.disconnectBanks(row.memberId)
      if (removed > 0) {
        s.cutoff++
        s.connections += removed
        // ⚠ Каждое отключение — отдельной ГРОМКОЙ строкой, а не только числом в итоге: мы рвём
        // связь с банком без участия человека, и вопрос «у кого именно» встанет позже, когда
        // клиент вернётся с вопросом. «Отключено 3» на него не отвечает.
        //
        // ⚠ Портал назван необратимой меткой, а не сырым `member_id` — прецедент канала
        // `[deletion]` и уборщика #574: строки, связывавшие портал с банковскими кредами, в этот
        // момент исчезают, и лог остаётся единственным пережившим упоминанием этой связи.
        deps.warn?.(`портал ${portalHash(row.memberId)}: подписка Б24 молчит дольше ${days} дн. — `
          + `банк отключён (подключений ${removed}). Клиенту не сообщали: чат ошибок идёт через тот же REST`)
      } else {
        // ⚠ Отключать было нечего — банк сняли раньше (оператором, `ONAPPUNINSTALL`, уборщиком
        // #599), а метка осталась. Это НЕ отключение и не отказ: громкая строка здесь врала бы о
        // событии, которого не было, а тихий счётчик показывает, что автомат работает вхолостую.
        s.skipped++
      }
    } catch (e) {
      s.failed++
      deps.warn?.(`не удалось отключить банк у портала ${portalHash(row.memberId)}: ${(e as Error)?.message ?? String(e)}`)
      // Метку НЕ снимаем: отключение не состоялось, и следующий прогон обязан повторить.
      continue
    }
    // ⚠ Снятие — СВОЕЙ попыткой и ПОСЛЕ отключения, а не до. До — значит потерять метку при
    // упавшем отключении, то есть оставить банк подключённым навсегда. Отдельной попыткой —
    // потому что отказ снятия не отменяет уже состоявшегося отключения и не должен считаться
    // «не удалось отключить»: следующий прогон повторит (удаление идемпотентно, уйдёт в `skipped`)
    // и снимет метку тогда.
    try {
      await deps.clearMark(row.memberId)
    } catch (e) {
      deps.warn?.(`банк у портала ${portalHash(row.memberId)} отключён, но метку снять не удалось `
        + `(повторим в следующий прогон): ${(e as Error)?.message ?? String(e)}`)
    }
  }
  deps.log?.(subscriptionCutoffLogLine(s))
  return s
}
