// Загрузчик pdf.js для ВОРКЕРА (#737) — разбор загруженного файла на сервере.
//
// ⚠ Сборка `legacy` — не «на всякий случай»: обычная рассчитана на браузер и поднимает воркер,
// которого в Nitro нет. Пара «браузерная в `app/utils/pdfjsClient.ts` / серверная здесь» держится
// раздельно, чтобы бандлер не тянул одну в среду другой.
//
// ⚠ Воркер здесь не отключается флагом: в этой версии pdf.js такого параметра нет, а `legacy`
// сборка в Node сама разбирает в текущем потоке. Возвращать `disableWorker` не нужно — он не
// существует и не собирается по типам.
//
// ⚠ Сервер — ЕДИНСТВЕННЫЙ авторитет разбора (то же правило, что у текстовых форматов): браузерный
// разбор это предпросмотр, а в CRM попадает то, что прочитал воркер. Поэтому обе сборки обязаны
// давать одинаковый результат, и проверяет это не сборка, а общий чистый слой над ними — раскладку
// и парсеры банков обе среды делят дословно.

import type { PdfDocumentLike, PdfLoader } from '../../app/utils/pdfExtract'

/** Поднять документ pdf.js в Node. */
export const loadPdfOnServer: PdfLoader = async (data) => {
  const pdfjs = await import('pdfjs-dist/legacy/build/pdf.mjs')
  const doc = await pdfjs.getDocument({
    data,
    // ⚠ Шрифты не трогаем вовсе: нам нужен ТЕКСТ и его координаты, а не отрисовка. pdf.js пишет
    // при этом предупреждение про `standardFontDataUrl` — текст он отдаёт полностью, проверено на
    // обеих боевых выписках.
    useSystemFonts: false,
    disableFontFace: true
  }).promise
  return doc as unknown as PdfDocumentLike
}
