/** Последняя ли это попытка джобы — дальше BullMQ уже не переспросит.
 *
 * Нужно там, где неудача сообщается ЧЕЛОВЕКУ (#417): показать сотруднику «не разобралось», а через
 * минуту молча передумать — хуже, чем подождать. `attemptsMade` инкрементируется уже после
 * обработки, поэтому на первой попытке он 0. Очередь без `attempts` (наш `crm-sync`) ретраев не
 * делает вовсе — тогда первая попытка и есть последняя.
 */
export function isFinalAttempt(job: { attemptsMade: number, opts?: { attempts?: number } }): boolean {
  return job.attemptsMade + 1 >= (job.opts?.attempts ?? 1)
}
