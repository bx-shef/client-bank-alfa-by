//
// ⚠ ЗАЧЕМ ОТДЕЛЬНАЯ ПАМЯТЬ, когда дедуп всего конвейера держит маркер дела в Б24 (#259). Потому что
// у операции, которую записать НЕКУДА (не нашлось ни компании-плательщика, ни «моей компании» по
// нашему счёту), дела не создаётся вовсе — значит маркера нет, и верхний гейт `getActivityId` её не
// отсекает. Она проходит полный путь на каждом прогоне и объявляется заново. Замерено на боевом
// портале 2026-09-14: ~191 уникальная операция дала 5999 сообщений за 12,5 часов.
//
// ⚠ ПОСТАВИТЬ МАРКЕР «НА ВСЯКИЙ СЛУЧАЙ» НЕЛЬЗЯ — отсутствие дела это не дефект, а несущее свойство:
// именно благодаря ему операция подтянется сама, когда админ заведёт реквизит. Маркер закрыл бы ей
// эту дорогу навсегда.
//
// ⚠ ПОЧЕМУ REDIS, А НЕ ТАБЛИЦА. Проект осознанно снёс Postgres-стор дедупа дел (#259) в пользу
// маркера в Б24, и заводить его обратно ради вспомогательного признака — шаг назад. Здесь не нужна
// ни надёжность, ни история: потеря ключа стоит ОДНОГО лишнего сообщения. Плюс `crm-sync` вообще не
// запускается без Redis, так что «хранилища может не быть» — невозможное состояние на этом пути.
// Тот же приём уже применён в `programFeedbackCap`.
//
// ⚠ КЛЮЧ ДЕДУПА ХЕШИРУЕТСЯ. В открытом виде это `<наш счёт>|<номер документа>`, то есть номер счёта
// клиента, и лежал бы он дольше, чем payload'ы выписок, которые мы специально подметаем по возрасту
// (#245, PRIVACY.md). Конкретного срока здесь НЕ называем — он рядом, у самой константы, и вторая
// копия числа разошлась бы молча (так и вышло при 30 → 7 → 3, находка панели ревью 2026-09-15).
// Сравнение нужно только на равенство, поэтому хеша достаточно.

import { createHash } from 'node:crypto'

/**
 * Срок жизни отметки. Это ЧИСЛО ДЛЯ СБОРКИ МУСОРА, а не политика «напоминать раз в N дней»: отметка
 * нужна ровно столько, сколько операция остаётся в окне опроса (`CRON_LOOKBACK_DAYS`). Вышедшая из
 * окна операция не вернётся никогда, и её ключ — мусор.
 *
 * ⚠ ОКНО ЗАДАНО КАЛЕНДАРЁМ, а не вкусом оператора (решение владельца, 2026-09-15): перекрывать
 * нужно максимум субботу, воскресенье и один рабочий день — трое суток. Значений вроде 10 или 30
 * не бывает, и подпирать срок доводом «а вдруг поставят больше» значит выводить число из свободы,
 * которой нет: первая редакция так и сделала и получила 30 суток, то есть месяц мусора в Redis.
 *
 * ⚠ ЗАПАСА НЕТ, И ЭТО НАЗВАНО ЧЕСТНО. Срок равен окну, а отсчёт идёт от ПЕРВОГО сообщения, поэтому
 * у операции, попавшей в выписку в свой же день, ключ истекает внутри последних суток её жизни в
 * окне. Цена ровно одна: одно повторное сообщение о такой операции на границе. Платить за неё
 * лишними сутками мусора незачем — это не потеря данных и не поток, ради которого всё написано.
 */
export const UNMATCHED_NOTICE_TTL_SEC = 3 * 24 * 60 * 60

/** Ключ отметки. Портал — открытым текстом (он и так `member_id`, как у соседних ключей), ключ
 *  операции — хешем (см. шапку). */
export function unmatchedNoticeKey(memberId: string, dedupKey: string): string {
  // ⚠ Это НЕ полное имя ключа в Redis: `claimCooldownSlot` добавляет свой префикс `cooldown:`.
  // Полная форма названа в `PRIVACY.md` — искать в Redis по ней, а не по этой строке.
  const digest = createHash('sha256').update(dedupKey).digest('hex').slice(0, 16)
  return `unmatched-notice:${memberId}:${digest}`
}
