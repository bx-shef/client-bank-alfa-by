// Ключ advisory-лока, сериализующего запись в ОДНУ строку `bank_tokens` (#509).
//
// Отдельный модуль ради одной причины: ключ нужен ДВУМ сторонам, и они пишут в строку по-разному.
// `ensureBankToken` обновляет секреты (`WHERE … account_key = $3`), а `renameBankTokenAccount`
// меняет сам `account_key` — то есть ровно то поле, по которому первая сторона свою строку и
// находит. Разойдись они в написании ключа хоть на символ — лок был бы взят «не тот», обе стороны
// продолжили бы работать параллельно, и внешне ничего бы не изменилось: тесты зелёные, ошибок нет,
// а подключение умирает через сутки. Поэтому строка ключа существует в одном месте, и её
// единственность закреплена тестом (`tests/bankRefreshLockChokePoint.test.ts`).

import type { BankProviderId } from '../../app/types/statement'

/**
 * Лок на конкретное банковское подключение: портал + банк + ключ счёта.
 *
 * ⚠ `accountKey` — часть ключа НАМЕРЕННО, а не для красоты: подключений у портала много (счета,
 * два банка), и общий пер-портальный лок сериализовал бы обновление независимых счетов, растянув
 * часовой скан на сумму сетевых задержек.
 *
 * ⚠ Переименование обязано брать лок по СТАРОМУ ключу — по тому, под которым строку сейчас видит
 * обновляющая сторона. Взятый по новому, он не пересечётся с ней ни разу и будет бесполезен.
 */
export function bankRefreshLockKey(memberId: string, provider: BankProviderId, accountKey: string): string {
  return `bankrefresh:${memberId}:${provider}:${accountKey}`
}

/**
 * Код Postgres, которым `lock_timeout` сообщает «ждал и не дождался» (`55P03`, lock_not_available).
 *
 * ⚠ Это НЕ авария и не повод для 500. Ожидание упирается в потолок `lock_timeout` (10 с), а
 * держатель лока — обновление токена, которому банк отвечает до 15 с; то есть «не дождался»
 * штатно случается при живом, исправно работающем обновлении. Единственный честный ответ
 * человеку — «занято, повторите», а не сообщение об ошибке.
 */
export const PG_LOCK_TIMEOUT = '55P03'

/** Был ли отказ вызван ожиданием лока (а не настоящей ошибкой БД). */
export function isLockTimeout(e: unknown): boolean {
  return (e as { code?: string } | null)?.code === PG_LOCK_TIMEOUT
}
