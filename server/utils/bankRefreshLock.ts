// Ключ advisory-лока, сериализующего запись в ОДНУ строку `bank_tokens` (#509).
//
// Отдельный модуль ради одной причины: ключ нужен ДВУМ СПОРЯЩИМ сторонам, пишущим в строку по-разному.
// `ensureBankToken` обновляет секреты (`WHERE … account_key = $3`), а `renameBankTokenAccount`
// меняет сам `account_key` — то есть ровно то поле, по которому первая сторона свою строку и
// находит. Разойдись они в написании ключа хоть на символ — лок был бы взят «не тот», обе стороны
// продолжили бы работать параллельно, и внешне ничего бы не изменилось: тесты зелёные, ошибок нет,
// а подключение умирает через сутки. Поэтому строка ключа существует в одном месте, и её
// единственность закреплена тестом (`tests/bankRefreshLock.test.ts`).
//
// ⚠ ПИШУЩИХ В `bank_tokens` ФУНКЦИЙ ПЯТЬ, А НЕ ДВЕ — «две стороны» это те, кто СПОРИТ за живую
// строку, и путать это опасно. Остальные три обоснованы, а не забыты:
//   • `deleteBankToken` / `deleteBankTokensForPortal` — удаление терминально, порядок не важен:
//     обновление увидит пропажу (UPDATE-only вернёт `false`) и ничего не воскресит (#505);
//   • `saveBankToken` (OAuth-колбэк) — пишет под ключом из криптослучайного nonce, а
//     `isValidAccountKey` запрещает `~` в присланном ключе, поэтому подсунуть снаружи
//     существующий `~pending:`-ключ нельзя: борьбы за живую строку не возникает.
// ⚠ Верно ПОКА подключение всегда заводит НОВУЮ строку. Первая же кнопка «переподключить именно
// этот счёт» сделает колбэк третьим спорщиком — с той же тихой потерей ротированного refresh.
// Список писателей закрыт тестом именно поэтому: шестого (или изменение пятого) молча не добавить.

import type { BankProviderId } from '../../app/types/statement'

/**
 * Лок на конкретное банковское подключение: портал + банк + ключ счёта.
 *
 * ⚠ `accountKey` — часть ключа НАМЕРЕННО, а не для красоты: подключений у портала много (счета,
 * два банка), и общий пер-портальный лок сериализовал бы обновление независимых счетов, растянув
 * часовой скан на сумму сетевых задержек.
 *
 * ⚠ Переименование обязано брать лок по СТАРОМУ ключу — по тому, под которым строку сейчас видит
 * обновляющая сторона. Взятый по новому, он не пересечётся с ней ни разу и будет бесполезен.
 */
export function bankRefreshLockKey(
  memberId: string, provider: BankProviderId, accountKey: string, grantId = ''
): string {
  // ⚠ ЕСТЬ ГРАНТ — ЛОК ПО ГРАНТУ (#23). Счета одного согласия делят пару токенов, и обновление
  // пишет ротированную сразу во все его строки (`updateBankTokenSecrets`). Лок по СЧЁТУ здесь
  // ничего не сериализует: два счёта одного гранта взяли бы РАЗНЫЕ локи, пошли бы в банк
  // параллельно, и второй потратил бы refresh, который первый уже сжёг. То есть ровно та тихая
  // ночная смерть, ради предотвращения которой лок и существует, — но теперь при взятом локе.
  //
  // ⚠ Пустой грант — «не размечено», и склеивать такие строки нельзя: общий лок на них
  // сериализовал бы независимые подключения портала (см. `grantId` в `bankTokenStore`).
  if (grantId !== '') return `bankrefresh:${memberId}:${provider}:grant:${grantId}`
  return `bankrefresh:${memberId}:${provider}:${accountKey}`
}

/**
 * Код Postgres, которым `lock_timeout` сообщает «ждал и не дождался» (`55P03`, lock_not_available).
 *
 * ⚠ Это НЕ авария и не повод для 500. Ожидание упирается в потолок `lock_timeout` (10 с), а
 * держатель лока — обновление токена, которому банк отвечает до 15 с; то есть «не дождался»
 * штатно случается при живом, исправно работающем обновлении. Единственный честный ответ
 * человеку — «занято, повторите», а не сообщение об ошибке.
 */
export const PG_LOCK_TIMEOUT = '55P03'

/** Был ли отказ вызван ожиданием лока (а не настоящей ошибкой БД). */
export function isLockTimeout(e: unknown): boolean {
  return (e as { code?: string } | null)?.code === PG_LOCK_TIMEOUT
}
