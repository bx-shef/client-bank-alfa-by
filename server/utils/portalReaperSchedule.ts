// Каденция уборщика мёртвых грантов (#574) — вынесена из плагина, чтобы проверяться вызовом.
//
// ⚠ Живёт ОТДЕЛЬНО от свип-тика по двум разным причинам, и обе замерены на ревью.
//
// 1. Частота. Свип-тик задаётся `STATEMENT_SWEEP_INTERVAL_MIN` (дефолт 30 мин, кламп от 1 мин) и
//    заведён про чистку payload'ов выписки. Пока частота приходила оттуда, потолок «3 портала за
//    прогон» означал до ~144 в сутки — то есть не ограничивал ущерб ни в каком смысле.
//
// 2. Переживание рестарта. Первая правка держала метку последнего прогона В ПАМЯТИ, и это было
//    хуже исходной беды: `runSweep` зовётся сразу на старте, поэтому КАЖДЫЙ рестарт (выкат,
//    Watchtower, OOM, crash-loop) снова разрешал прогон. Контейнер, перезапускающийся раз в
//    полминуты, стёр бы весь флот по три портала за раз. Аналогия с пульсом продления (#504) была
//    неверной: там забывчивость отказывает БЕЗОПАСНО (лишняя тревога), здесь — ОПАСНО.
//
// Поэтому каденция держится арендой в Postgres: она переживает рестарт и заодно разводит реплики.

import { acquireLease } from './singleFlightLease'
import type { QueryFn } from './tokenStore'

/** Ключ аренды. Один на весь сервис — уборщик не пер-портальный. */
export const REAP_LEASE_KEY = 'portal-reap'

/**
 * Можно ли прогонять уборщика прямо сейчас.
 *
 * Аренда берётся на `ttlSec` и НЕ снимается: пока она жива, следующий прогон не состоится. То есть
 * «аренда взята» здесь читается как «в этом окне уже отработали», а не как «идёт работа».
 *
 * ⚠ Отказ базы = НЕ прогонять. Единственный механизм, необратимо стирающий данные клиента, не
 * должен работать, когда мы не смогли выяснить, отрабатывал ли он только что.
 */
export async function claimReapSlot(q: QueryFn, ttlSec: number, token: string): Promise<boolean> {
  try {
    return await acquireLease(q, REAP_LEASE_KEY, ttlSec, token) !== null
  } catch {
    return false
  }
}
