// Живой перезапрос «подписка на REST правда всё ещё мертва?» (#614) — транспорт.
//
// ⚠ Зачем отдельный вызов, если есть метка. Метку снимает ровно один путь — удачно завершённый
// прогон `crm-sync`. На ТИХОМ счёте (за четверо суток ни одной операции) он не запускается вовсе:
// опрос вернул пустую выписку, писать нечего. Значит клиент, оплативший подписку на второй день,
// метку не снимает ничем — и на пятые сутки автомат отключил бы банк у исправного портала. Метка
// отвечает на вопрос «кого имеет смысл переспросить», этот вызов — «правда ли».
//
// ⚠ Зовётся ТОЛЬКО перед необратимым шагом и не чаще потолка за прогон, поэтому цена — единицы
// запросов в сутки, а не нагрузка на флот.

import type { RestCall } from './companyLookup'
import { isSubscriptionEnded } from '../../app/utils/portalSubscription'

/** Самый дешёвый метод, который есть у ЛЮБОГО портала и не зависит от настройки CRM. */
export const SUBSCRIPTION_PROBE_METHOD = 'profile'

export type SubscriptionVerdict = 'alive' | 'dead' | 'unknown'

/**
 * Спросить портал напрямую.
 *
 * ⚠ Три исхода, а не два, и `unknown` здесь несущий: сеть моргнула, портал отвечает 500, токен
 * не загрузился — всё это НЕ доказывает, что подписки нет. Не знаем ⇒ не рвём.
 *
 * ⚠ «Мертва» произносим ТОЛЬКО когда отказ говорит именно о подписке. Любая другая ошибка
 * (`QUERY_LIMIT_EXCEEDED`, недовыданные права, мёртвый грант) — `unknown`: у неё свои механизмы,
 * и отключать банк за неё нельзя.
 */
export async function probeSubscriptionVia(call: RestCall | null): Promise<SubscriptionVerdict> {
  if (!call) return 'unknown' // токена нет — судить не по чему
  try {
    await call(SUBSCRIPTION_PROBE_METHOD, {})
    return 'alive'
  } catch (e) {
    return isSubscriptionEnded(e) ? 'dead' : 'unknown'
  }
}
