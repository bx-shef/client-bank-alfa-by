// Каденция автоотключения банка при мёртвой подписке (#614) — по образцу `bankReaperSchedule.ts`.
//
// ⚠ СВОЯ аренда в Postgres, а не метка в памяти: свип-тик зовётся сразу на старте, поэтому память
// разрешала бы прогон на КАЖДОМ рестарте — контейнер в crash-loop отключил бы по потолку порталов
// за перезапуск. Аренда переживает рестарт и разводит реплики между собой.
//
// ⚠ ОТДЕЛЬНЫЙ ключ от обоих уборщиков: разные операции с разной единицей (портал / строка / банк
// портала), и общая аренда сериализовала бы их друг с другом без всякой причины — а хуже того,
// один прогон «съедал» бы окно другого, и отключение молча не наступало бы никогда.

import { acquireLease } from './singleFlightLease'
import type { QueryFn } from './tokenStore'

/** Ключ аренды. Один на весь сервис — автомат не пер-портальный. */
export const SUBSCRIPTION_CUTOFF_LEASE_KEY = 'subscription-cutoff'

/**
 * Можно ли прогонять автоотключение прямо сейчас. Аренда берётся на `ttlSec` и НЕ снимается: пока
 * жива, следующий прогон не состоится. «Взята» = «в этом окне уже отработали».
 *
 * ⚠ Отказ базы = НЕ прогонять: автомат, рвущий связь клиента с банком, не должен работать, когда
 * мы не смогли выяснить, отрабатывал ли он только что.
 */
export async function claimSubscriptionCutoffSlot(q: QueryFn, ttlSec: number, token: string): Promise<boolean> {
  try {
    return await acquireLease(q, SUBSCRIPTION_CUTOFF_LEASE_KEY, ttlSec, token) !== null
  } catch {
    return false
  }
}
