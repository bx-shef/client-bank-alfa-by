// Каденция подтверждения счетов банком (#615) — по образцу соседей (#574/#599/#614).
//
// ⚠ Аренда нужна НЕ ради корректности данных: проход идемпотентен, повтор ничего не портит.
// Она ограничивает ЧАСТОТУ обращений к ВНЕШНЕМУ ресурсу — лимиту запросов банка, то есть ровно к
// тому, что #615 и призван экономить. Свип-тик зовётся сразу на старте процесса, поэтому без
// аренды контейнер в цикле рестартов спрашивал бы банк на КАЖДОМ старте: потолок за прогон
// ограничивает пачку, но не число прогонов. Замечание ревью — и оно верное: у соседей аренда
// стоит по той же причине, а не «для единообразия».
//
// ⚠ Отдельный ключ от всех трёх уборщиков: это другая операция, и общая аренда означала бы, что
// один прогон съедает окно другого — то есть подтверждение молча не наступало бы никогда.

import { acquireLease } from './singleFlightLease'
import type { QueryFn } from './tokenStore'

/** Ключ аренды. Один на весь сервис — проход не пер-портальный. */
export const ACCOUNT_CONFIRM_LEASE_KEY = 'account-confirm'

/**
 * Можно ли прогонять подтверждение прямо сейчас. Аренда берётся на `ttlSec` и НЕ снимается: пока
 * жива, следующий прогон не состоится. «Взята» = «в этом окне уже отработали».
 *
 * ⚠ Отказ базы = НЕ прогонять. Здесь это мягче, чем у уборщиков (ничего не удаляется), но вывод
 * тот же: не выяснив, ходили ли мы в банк только что, идти туда снова не надо.
 */
export async function claimAccountConfirmSlot(q: QueryFn, ttlSec: number, token: string): Promise<boolean> {
  try {
    return await acquireLease(q, ACCOUNT_CONFIRM_LEASE_KEY, ttlSec, token) !== null
  } catch {
    return false
  }
}
