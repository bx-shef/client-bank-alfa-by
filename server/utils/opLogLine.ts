// Построение строки `[op]` — вместе с решением, печатать ли её вообще (#498).
//
// ⚠ Почему это отдельный модуль, а не тело колбэка в `worker.ts`. Гейт объёма жил прямо в
// `onOperation`, и проверить его можно было только ГЛАЗАМИ или архитектурным тестом по тексту
// исходника. Ревью показало цену: мутация `if (false && !shouldLogOperation(…)) return` оставляет
// весь набор зелёным — подстрока на месте, порядок верный, а гейт мёртв, и построчный лог молча
// возвращается к прежнему объёму, то есть регрессия #498 целиком. Текстовый тест такое не ловит
// принципиально: он не знает, что значит `false &&`.
//
// Здесь решение и текст — одна чистая функция, у которой есть исполняемый тест. Обезвредить гейт,
// не уронив его, больше нельзя: `null` против строки проверяется вызовом, а не поиском подстроки.
//
// Санитизация внешних полей (`logSafe`) остаётся здесь же — она часть построения строки, и
// разносить её с текстом значило бы завести второе место, где про неё нужно помнить.

import type { StatementItem } from '../../app/types/statement'
import { shouldLogOperation, type OpLogMode, type OpLogOutcome } from '../../app/utils/opLogPolicy'
import { logSafe } from './logSafe'

/** Сколько символов назначения раскрывать под `STATEMENT_DEBUG_LOG`. Длиннее дефолта `logSafe`
 *  (128), потому что реальное назначение обычно несёт несколько номеров документов, и сидят они
 *  в хвосте — обрезав там, спрятали бы ровно то, ради чего флаг включают. */
export const MAX_LOGGED_PURPOSE = 300

/** Что известно об операции к моменту логирования. */
export interface OpLogInput extends OpLogOutcome {
  /** Сколько номеров распознано В ЭТОЙ операции. */
  recognized: number
}

/**
 * Строка `[op]` — или `null`, если печатать её не надо.
 *
 * ⚠ `null` это НЕ ошибка и не пустая строка: вызывающий обязан различать «нечего печатать» и
 * «печатать пустое». Пустая строка в `console.log` дала бы пустую строку в логе — мусор, который
 * занимает место ровно там, где мы его экономим.
 *
 * Следует `docs/PRIVACY.md` §Логи: счёт, docId и счёт контрагента логируются, СУММЫ НЕТ, а
 * назначение — только за опт-ин флагом.
 */
export function buildOpLogLine(
  item: StatementItem,
  outcome: OpLogInput,
  memberId: string,
  mode: OpLogMode,
  revealPurpose: boolean
): string | null {
  if (!shouldLogOperation(outcome, mode)) return null
  const owner = outcome.owner === 'client'
    ? 'company'
    : outcome.owner === 'my-company' ? 'my-company (fallback)' : 'NO OWNER'
  // Назначение платежа — самый широкий неконтролируемый текст, который мы держим, и §Логи держит
  // его вне лога. Но написать маску для нумерации, которую ни разу не видел, нельзя, поэтому оно
  // доступно опт-ином — тем же порядком, что уровень error-лога крипто-шлюза (#460): включили на
  // прогон, выключили обратно.
  const purpose = revealPurpose ? ` purpose="${logSafe(item.purpose, MAX_LOGGED_PURPOSE)}"` : ''
  // ⚠ `currency` тоже через logSafe: у Альфы и Приора это СЫРОЙ проброс из JSON банка
  // (`row.currIso`/`tx.currency`, только trim), а не наш enum — в отличие от `direction`, который
  // нормализаторы вычисляют сами. Обойти это поле легко именно потому, что рядом стоит безопасный
  // сосед.
  const op = `${logSafe(item.account)}|${logSafe(item.docId)}`
  const from = logSafe(item.counterparty.account) || 'счёт не указан'
  // ⚠ Названо `intents`, а НЕ `recognized`, хотя поле зовётся так: в сводке прогона `recognized`
  // считает ОПЕРАЦИИ, у которых распознан хотя бы один номер, а здесь — сколько номеров распознано
  // в ЭТОЙ операции. Оператор, сверяющий строки лога со сводкой (ровно то, ради чего строка и
  // заведена), сложил бы одно с другим и не сошёлся — тем более что сводочный счётчик растёт и для
  // дедуп-пропущенных операций, которых в построчном логе нет вовсе.
  const tail = `intents ${outcome.recognized}, activity ${outcome.activityId ?? '—'}`
  // ⚠ Маркер `[op]` печатает КАНАЛ логгера (#529), здесь его быть не должно — иначе строка выйдет
  // как `[op] INFO: [op] portal …`.
  return `portal ${memberId}, op ${op}: ${item.direction} ${logSafe(item.currency, 8)} `
    + `← ${from} → ${owner}, ${tail}${purpose}`
}
