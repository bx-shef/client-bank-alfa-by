// Каденция автоудаления дел (#722) — по образцу `subscriptionCutoffSchedule.ts`.
//
// ⚠ СВОЯ аренда в Postgres, а не метка в памяти: свип-тик зовётся сразу на старте, поэтому память
// разрешала бы прогон на КАЖДОМ рестарте — контейнер в crash-loop выкашивал бы по потолку дел за
// перезапуск. Аренда переживает рестарт и разводит реплики между собой.
//
// ⚠ ОТДЕЛЬНЫЙ ключ от уборщиков и автоотключения: операции разные, и общая аренда сериализовала бы
// их без причины — хуже того, один прогон «съедал» бы окно другого, и удаление молча не наступало
// бы никогда.

import { acquireLease } from './singleFlightLease'
import type { QueryFn } from './tokenStore'

/** Ключ аренды. Один на весь сервис — прогон не пер-портальный. */
export const AUTO_ERASE_LEASE_KEY = 'auto-erase'

/**
 * Можно ли прогонять автоудаление прямо сейчас. Аренда берётся на `ttlSec` и НЕ снимается: пока
 * жива, следующий прогон не состоится. «Взята» = «в этом окне уже отработали».
 *
 * ⚠ Отказ базы = НЕ прогонять: автомат, удаляющий дела в CRM клиента, не должен работать, когда мы
 * не смогли выяснить, отрабатывал ли он только что.
 */
export async function claimAutoEraseSlot(q: QueryFn, ttlSec: number, token: string): Promise<boolean> {
  try {
    return await acquireLease(q, AUTO_ERASE_LEASE_KEY, ttlSec, token) !== null
  } catch {
    return false
  }
}
