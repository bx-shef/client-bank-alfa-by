#!/usr/bin/env bash
# Лестница пауз для ЛЮБОГО из трёх поставщиков: какой простой между обновлениями он терпит (#488).
#
# ЗАЧЕМ. Измерено: на паузе 2 минуты обновление проходит, на 5 ч 48 мин — банк отвечает
# `invalid_grant: User session not alive`. Граница между ними НЕИЗВЕСТНА, а от неё зависит, как
# часто продлевать: раз в час (дорого и наверняка) или раз в 4-5 часов (дёшево, если банк терпит).
# Подбирать интервал «на глаз» — то же самое, что писать код по памяти.
#
# ⚠ МЕРЯЕМ ПАУЗУ МЕЖДУ ОБНОВЛЕНИЯМИ, А НЕ ВРЕМЯ ОТ ПОДКЛЮЧЕНИЯ. Каждое удачное обновление выдаёт
# новую пару и сбрасывает отсчёт простоя, поэтому лестница «через час, через два, через три от
# старта» после первого успеха проверяла бы всегда один и тот же часовой интервал. Здесь каждая
# ступень — пауза ОТ ПРЕДЫДУЩЕГО обновления, и она растёт.
#
# ⚠ ОСТАНОВ НА ПЕРВОЙ ОШИБКЕ — это и есть результат: последняя удавшаяся пауза безопасна, первая
# упавшая — нет. Продолжать после отказа бессмысленно: грант уже мёртв, все следующие ступени
# упадут по той же причине и только зашумят журнал.
#
# ⚠ Обновление делает ТОТ ЖЕ скрипт, что и `make alfa-refresh-now`, а не своя копия запроса. Иначе
# лестница отвечала бы на вопрос о себе, а не о продукте.
#
# Использование:
#   P=alfa|prior|b24 make refresh-ladder      # запустить в фоне (переживает выход из ssh)
#   P=alfa|prior|b24 make refresh-ladder-log   # смотреть журнал
#   P=alfa|prior|b24 make refresh-ladder-stop  # остановить
#
# ⚠ Журнал и pid — СВОИ на поставщика: три лестницы идут параллельно и не мешают друг другу.
# Общий файл склеил бы их ступени в одну кашу, а именно сравнение по ступеням и есть цель.
#
# Свой набор пауз:
#   GAPS="1m 30m 1h 2h" P=prior make refresh-ladder
set -u

BASE="${BASE:-/home/bitrix/bank-import}"
cd "$BASE" 2>/dev/null || true
P="${P:-alfa}"
LOG="$BASE/refresh-ladder-$P.log"
PIDF="$BASE/refresh-ladder-$P.pid"
RAW_URL="${RAW_URL:-}"
GAPS="${GAPS:-1m 30m 1h 2h 3h 4h 5h 6h 7h 8h 9h 10h 11h}"

# ⚠ ЖИВУЮ ЛЕСТНИЦУ ИЩЕМ ПО МЕТКЕ В КОМАНДНОЙ СТРОКЕ, А НЕ ПО PID-ФАЙЛУ. 2026-09-07 сторож
# пропустил второй запуск Альфы поверх идущего, и на один грант работали ДВЕ лестницы. Это не
# косметика: пока одна спит свои 30 минут, вторая обновляет токен на третьей — «пауза 30m» на деле
# оказывается 27-минутной, и граница выходит выдуманной. То есть замер молча отвечает не про ту
# паузу, про которую отчитывается.
# Pid-файл этого не держит: его стирает и сам прогон в конце, и `--stop`, который мог не попасть
# по процессу, — а метка есть ровно у живого и ровно одна на поставщика.
TAG="refresh-ladder-$P"
alive() { pgrep -f "LADDER_TAG=$TAG" 2>/dev/null; }

if [ "${1:-}" = "--stop" ]; then
  pids=$(alive)
  if [ -n "$pids" ]; then
    # shellcheck disable=SC2086
    kill $pids 2>/dev/null
    echo "лестница [$P] остановлена (процессов: $(echo "$pids" | wc -l))"
  else
    echo "запущенной лестницы [$P] не нашёл"
  fi
  rm -f "$PIDF"
  exit 0
fi

if [ "${1:-}" = "--log" ]; then
  [ -f "$LOG" ] || { echo "журнала ещё нет — лестница не запускалась"; exit 0; }
  tail -n 200 "$LOG"
  exit 0
fi

running=$(alive)
if [ -n "$running" ]; then
  echo "лестница [$P] УЖЕ идёт (pid $(echo "$running" | tr '\n' ' ')). Журнал: P=$P make refresh-ladder-log"
  echo "Остановить: P=$P make refresh-ladder-stop"
  echo "⚠ Второй прогон на тот же грант ИСПОРТИЛ БЫ ЗАМЕР: обновления двух лестниц перемешались бы,"
  echo "  и измеренная пауза оказалась бы короче объявленной."
  exit 0
fi

# ⚠ Обновлятель скачиваем ОДИН раз на весь прогон: он длится сутками, а `main` за это время
# меняется. Лестница обязана мерить одну и ту же версию запроса от первой ступени до последней.
ONCE=$(mktemp /tmp/alfa-once.XXXXXX.sh)
if [ -n "$RAW_URL" ]; then
  curl -fsSL -o "$ONCE" "$RAW_URL/oauth-refresh-probe.sh" || { echo "не скачал oauth-refresh-probe.sh"; exit 2; }
else
  echo "не задан RAW_URL — запускайте через 'make alfa-refresh-schedule'"; exit 2
fi

# Что записать про ступень и продолжать ли лестницу. Возврат: 0 — идём дальше, 1 — стоп.
#
# ⚠ Решает КОД ВОЗВРАТА пробы, а не поиск слова в её выводе. 2026-09-07 лестница грепала
# «ОБНОВЛЕНИЕ ПРОШЛО» и на отсутствующем в базе подключении Альфы объявила «банк НЕ терпит 1m» —
# то есть выдала уверенный вердикт о банке, которого не спрашивали. Слова в прозе меняются молча;
# исходов же ровно три, и «не смогли попробовать» обязан отличаться от «банк сказал нет».
#
# ⚠ НЕИЗВЕСТНЫЙ код — тоже «не состоялось», а не отказ: так падает стенд (не поднят контейнер,
# нет базы), и записать это отказом банка значило бы закончить опыт выдуманной границей.
report_step() {
  local rc="$1" step="$2" gap="$3"
  case "$rc" in
    0)
      echo ">>> ступень $step ($gap): УСПЕХ — банк терпит паузу $gap"
      return 0
      ;;
    1)
      echo
      echo "########################################################"
      echo ">>> ступень $step ($gap): ОТКАЗ БАНКА. Это и есть ответ."
      echo ">>> Банк терпит паузу до предыдущей ступени и НЕ терпит $gap."
      echo ">>> Останавливаюсь: грант мёртв, дальнейшие ступени упали бы по той же причине."
      echo ">>> Подключение придётся создать заново, прежде чем повторять опыт."
      echo "########################################################"
      return 1
      ;;
    *)
      echo
      echo "########################################################"
      echo ">>> ступень $step ($gap): ЗАМЕР НЕ СОСТОЯЛСЯ — обмена с банком НЕ БЫЛО."
      echo ">>> Про паузу $gap банк ничего не сказал: его не спрашивали."
      echo ">>> Причина — выше в выводе пробы (нет строки подключения в базе, нет ключа"
      echo ">>> расшифровки, нет переменных окружения, не поднят стенд)."
      echo ">>> Устраните её и запустите лестницу заново."
      echo "########################################################"
      return 1
      ;;
  esac
}

run_ladder() {
  echo "=== ЛЕСТНИЦА ПАУЗ [$P], старт $(date '+%Y-%m-%d %H:%M:%S') ===" >> "$LOG"
  echo "ступени: $GAPS" >> "$LOG"
  echo "цель: найти самую длинную паузу между обновлениями, которую банк ещё терпит" >> "$LOG"
  echo >> "$LOG"
  local step=0
  for gap in $GAPS; do
    step=$((step + 1))
    echo "--- ступень $step: пауза $gap, засыпаю в $(date '+%H:%M:%S') ---" >> "$LOG"
    sleep "$gap" || { echo "sleep прерван — выходим" >> "$LOG"; break; }
    echo "--- ступень $step: пауза $gap ПРОШЛА, обновляю в $(date '+%H:%M:%S') ---" >> "$LOG"
    out=$(bash "$ONCE" "$P" docker-compose.prod.yml 2>&1); rc=$?
    echo "$out" >> "$LOG"
    report_step "$rc" "$step" "$gap" >> "$LOG" || break
    echo >> "$LOG"
  done
  echo "=== ЛЕСТНИЦА ЗАВЕРШЕНА $(date '+%Y-%m-%d %H:%M:%S') ===" >> "$LOG"
  rm -f "$ONCE" "$PIDF"
}

# ⚠ `setsid` + отвязка от терминала: прогон идёт сутками, а запускают его с телефона. Без этого
# лестница умирала бы вместе с ssh-сессией — то есть на первой же ступени длиннее пары минут.
setsid bash -c "LADDER_TAG=$TAG; $(declare -f report_step run_ladder); LOG='$LOG'; PIDF='$PIDF'; ONCE='$ONCE'; GAPS='$GAPS'; P='$P'; run_ladder" \
  </dev/null >/dev/null 2>&1 &
echo $! > "$PIDF"
echo "Лестница [$P] запущена (pid $(cat "$PIDF")). Она переживёт выход из ssh."
echo "Ступени: $GAPS"
echo
echo "Смотреть:     P=$P make refresh-ladder-log"
echo "Остановить:   P=$P make refresh-ladder-stop"
echo
echo "⚠ Первая ступень — через минуту. Дальше паузы растут; на первой ошибке прогон встанет,"
echo "  и последняя удавшаяся ступень будет ответом «какой простой банк терпит»."
