#!/usr/bin/env bash
# Разовая проба: правда ли `pageRowCount=0` у Альфы значит «все» (#561).
#
# ⚠ Зачем отдельная команда, если код уже ходит по страницам (#566). Обход даёт ответ на СЛЕДУЮЩЕМ
# «сотенном» дне, а он может не наступить неделю. Проба даёт его за минуту и по УЖЕ прошедшему дню,
# про который известно, что дел в CRM было ровно сто. Это разница между «подождём и увидим» и
# «спросим и узнаем» — а от ответа зависит, оставлять ли навсегда удвоенную стоимость задачи.
#
# ⚠ ЧТО ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ. Два GET выписки (страницы 0 и 1) тем же access-токеном, который уже
# лежит в `bank_tokens`. Не пишет ничего: ни в базу, ни в банк. **Refresh-токен не трогает вовсе** —
# банк ротирует его при обновлении, и ручное обновление рассинхронизировало бы нашу базу с банком
# (#505/#509). Ровно по той же причине так устроен `prior-host-probe.sh`.
#
# ⚠ Access-токен живёт около часа. Если проба скажет «токен отвергнут» — дождаться очередного опроса
# (он обновит сам) и повторить. Обновлять руками НЕЛЬЗЯ, см. выше.
#
# ⚠ Номер счёта в выводе замаскирован: команду набирают с мобильного терминала и вывод пересылают.
#
# Использование (из каталога со стеком):
#   bash prod-alfa-page-probe.sh                 # за вчера
#   bash prod-alfa-page-probe.sh 2026-08-18      # за конкретный день

set -u

DAY="${1:-}"
if [ -n "$DAY" ]; then
  case "$DAY" in
    [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]) ;;
    *) echo "✗ день «$DAY» — нужен формат ГГГГ-ММ-ДД"; exit 2;;
  esac
else
  DAY="$(date -u -d 'yesterday' +%Y-%m-%d 2>/dev/null)" || DAY="$(date -u -v-1d +%Y-%m-%d)"
fi

COMPOSE="docker-compose.prod.yml"
[ -f "$COMPOSE" ] || { echo "✗ $COMPOSE не найден — запускайте из каталога со стеком"; exit 1; }
DC="docker compose -f $COMPOSE"

section() { printf '\n\033[1m── %s ──\033[0m\n' "$1"; }
mask() { printf '%s' "$1" | sed -E 's/^(.{4}).*(.{4})$/\1…\2/'; }

echo "День: $DAY (UTC)"

# ── Адрес API банка ──────────────────────────────────────────────────────────
# ⚠ И база, и префикс берутся из `.env` теми же именами, что читает `bankApiConfig`. Захардкоженный
# префикс молча разошёлся бы с боевой настройкой, и проба спрашивала бы не тот эндпоинт — то есть
# отвечала бы «страница 1 пуста» про адрес, которого нет.
API_BASE=""
API_PREFIX=""
if [ -f .env ]; then
  API_BASE="$(sed -nE 's/^ALFA_OAUTH_API_BASE=[[:space:]]*(.*)$/\1/p' .env | tail -1)"
  API_PREFIX="$(sed -nE 's/^ALFA_OAUTH_API_PREFIX=[[:space:]]*(.*)$/\1/p' .env | tail -1)"
fi
[ -n "$API_BASE" ] || API_BASE="https://developerhub.alfabank.by:8273"
[ -n "$API_PREFIX" ] || API_PREFIX="/partner/1.2.0"
API_BASE="${API_BASE%/}"
case "$API_PREFIX" in /*) ;; *) API_PREFIX="/$API_PREFIX";; esac
API_PREFIX="${API_PREFIX%/}"

section "Счёт и токен"
echo "  API банка: ${API_BASE}${API_PREFIX}/accounts/statement"

# ── Счёт и access-токен из базы (ТОЛЬКО чтение) ──────────────────────────────
# ⚠ `~pending:` пропускаем: у банка нет такого «номера» — это подключение без выбранного счёта,
# по нему опрашивать нечего (та же причина, по которой его пропускает и сам опрос).
ROW="$($DC exec -T db psql -U app -d app -At -F'|' -c \
  "SELECT account_key, access_token FROM bank_tokens
    WHERE provider = 'alfa-by' AND account_key NOT LIKE '~pending:%'
    ORDER BY updated_at DESC LIMIT 1" 2>/dev/null | tr -d '\r')"

if [ -z "$ROW" ]; then
  printf '  \033[33m✗ в bank_tokens нет подключённого счёта Альфы — пробовать нечего\033[0m\n'
  exit 1
fi
ACCOUNT="${ROW%%|*}"
TOKEN="${ROW#*|}"
if [ -z "$TOKEN" ] || [ "$TOKEN" = "$ACCOUNT" ]; then
  printf '  \033[33m✗ у счёта %s пустой access-токен — дождитесь опроса и повторите\033[0m\n' "$(mask "$ACCOUNT")"
  exit 1
fi
echo "  Счёт: $(mask "$ACCOUNT")"

# ── Две страницы ─────────────────────────────────────────────────────────────
D="$(printf '%s' "$DAY" | awk -F- '{print $3"."$2"."$1}')"
P0=""
P1=""

section "Ответ банка"
for N in 0 1; do
  URL="${API_BASE}${API_PREFIX}/accounts/statement?number=${ACCOUNT}&dateFrom=${D}&dateTo=${D}&transactions=0&pageNo=${N}&pageRowCount=0"
  BODY="$(curl -sS --max-time 45 -H "Authorization: Bearer ${TOKEN}" "$URL" 2>&1)"
  if [ -z "$BODY" ]; then
    printf '  \033[33mстраница %s: банк не ответил\033[0m\n' "$N"
    continue
  fi
  case "$BODY" in
    *invalid_token*|*Unauthorized*|*expired_token*|*'"401"'*)
      printf '  \033[31mстраница %s: токен отвергнут банком\033[0m\n' "$N"
      echo "  Дождитесь очередного опроса (он обновит токен сам) и повторите."
      echo "  ⚠ Обновлять токен руками НЕЛЬЗЯ — банк ротирует refresh, база и банк разъедутся (#505/#509)."
      exit 2;;
  esac
  # ⚠ Вердикт строится на ПУСТОТЕ `page[]`, а не на подсчёте строк: без jq точный счёт пришлось бы
  # угадывать по необязательному полю, а решение «есть ли вторая страница» этого не требует вовсе.
  FLAT="$(printf '%s' "$BODY" | tr -d ' \n\t\r')"
  case "$FLAT" in
    *'"page":[]'*) EMPTY=1;;
    *'"page":['*)  EMPTY=0;;
    *)             EMPTY=-1;;
  esac
  # Счёт строк — ПРИБЛИЗИТЕЛЬНЫЙ (по маркеру операции), только для чтения человеком.
  ROWS="$(printf '%s' "$FLAT" | grep -o '"operType"' | wc -l | tr -d ' ')"
  ERRS="$(printf '%s' "$FLAT" | grep -o '"errors":\[[^]]*\]' | head -1)"
  case "$EMPTY" in
    1)  echo "  страница $N: page[] пуст ${ERRS:+| $ERRS}";;
    0)  echo "  страница $N: page[] непуст, операций ≈$ROWS ${ERRS:+| $ERRS}";;
    *)  printf '  \033[33mстраница %s: в ответе нет ключа page[] — банк ответил чем-то другим\033[0m\n' "$N"
        echo "  первые 200 символов: $(printf '%s' "$BODY" | cut -c1-200)";;
  esac
  [ "$N" = "0" ] && P0="$EMPTY" || P1="$EMPTY"
done

# ── Вердикт ──────────────────────────────────────────────────────────────────
section "Вердикт"
if [ "$P0" = "-1" ] || [ "$P1" = "-1" ] || [ -z "$P0" ] || [ -z "$P1" ]; then
  printf '  \033[33mНеполный ответ — вердикта нет. Повторите; при повторе смотрите строки выше.\033[0m\n'
elif [ "$P1" = "0" ]; then
  printf '  \033[31m«0» означает СТРАНИЦУ.\033[0m За %s на второй странице ЕСТЬ операции —\n' "$DAY"
  echo "  до постраничного обхода (#561) они терялись молча."
  echo "  Дальше: сверить import_result с банком за прошедшие дни; стоимость задачи Альфы"
  echo "  (REQUESTS_PER_ACCOUNT) оставить 2."
elif [ "$P0" = "0" ]; then
  printf '  \033[32m«0» означает ВСЕ.\033[0m Страница 0 непуста, страница 1 пуста — потерь не было.\n'
  echo "  Дальше: стоимость задачи Альфы можно вернуть к 1, иначе удвоенный расход бюджета банка"
  echo "  останется навсегда просто по инерции."
else
  printf '  \033[33mЗа %s операций нет вовсе — проба ничего не доказывает.\033[0m\n' "$DAY"
  echo "  Возьмите день, в котором дел в CRM было ровно 100:"
  echo "    make alfa-page-probe DAY=ГГГГ-ММ-ДД"
fi
