#!/usr/bin/env bash
# Разовая проба: правда ли `pageRowCount=0` у Альфы значит «все» (#561).
#
# ⚠ Зачем отдельная команда, если код уже ходит по страницам (#566). Обход даёт ответ на СЛЕДУЮЩЕМ
# «сотенном» дне, а он может не наступить неделю; окно опроса — `CRON_LOOKBACK_DAYS` (дефолт 1),
# то есть спросить про 18 августа он не умеет в принципе. Проба даёт ответ за минуту и по УЖЕ
# прошедшему дню, про который известно, что дел в CRM было ровно сто. Это разница между
# «подождём и увидим» и «спросим и узнаем» — а от ответа зависит, оставлять ли навсегда удвоенную
# стоимость задачи Альфы (лимит банка общий на весь `client_id`, на все порталы разом).
#
# ⚠ ЧТО ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ. Два GET выписки (страницы 0 и 1) тем же access-токеном, который
# уже лежит в `bank_tokens`. Не пишет ничего: ни в базу, ни в банк. **Refresh-токен не трогает
# вовсе** — он даже не выбирается запросом, так что это свойство структурное, а не обещание. Банк
# ротирует refresh при обновлении, и ручное обновление рассинхронизировало бы нашу базу с банком
# (#505/#509). Ровно по той же причине так устроен `prior-host-probe.sh`.
#
# ⚠ Access-токен живёт около часа. Если проба скажет «токен отвергнут» — дождаться очередного
# опроса (он обновит сам) и повторить. Обновлять руками НЕЛЬЗЯ, см. выше.
#
# ⚠ Ни токен, ни номер счёта не уходят в аргументы `curl`: заголовок и URL передаются конфигом
# через stdin (`-K -`). Аргументы видны любому процессу через `/proc/<pid>/cmdline` и оседают в
# журнале аудита `execve` — на машине рядом с банковской интеграцией это постоянная запись.
#
# ⚠ Номер счёта в выводе замаскирован: команду набирают с мобильного терминала и вывод пересылают.
#
# Использование (из каталога со стеком):
#   bash prod-alfa-page-probe.sh                 # за вчера
#   bash prod-alfa-page-probe.sh 2026-08-18      # за конкретный день

set -u

# ── Чистые функции (их же грузит tests/prodAlfaPageProbe.test.ts через sed-вырезку) ─────────────

# Тот же разбор `.env`, что у `env-value` в Makefile и `envv` в prior-host-probe.sh: снимает
# `export`, хвостовой комментарий и кавычки, берёт ПЕРВОЕ вхождение.
# ⚠ Свой упрощённый `sed 's/^KEY=(.*)/\1/'` тут уже был и был неправ: `.env` для Compose штатно
# содержит значения в кавычках, и они уезжали ВНУТРЬ значения — `curl` получал
# `"https://host:8273"/partner/...` и отвечал «Port number was not a decimal number», то есть
# ошибка указывала на порт, а не на кавычки, и оператор на телефоне искал не там.
envv() {
  sed -n "s/^[[:space:]]*\(export[[:space:]][[:space:]]*\)\{0,1\}$1[[:space:]]*=//p" ./.env 2>/dev/null \
    | head -1 \
    | sed -e "s/^[[:space:]]*//" -e "s/[[:space:]][[:space:]]*#.*$//" -e "s/[[:space:]]*$//" \
          -e "s/^\"\(.*\)\"$/\1/" -e "s/^'\(.*\)'$/\1/"
}

# Маска номера счёта: первые/последние 4 знака.
# ⚠ Длина проверяется ЯВНО. Голый `sed 's/^(.{4}).*(.{4})$/\1…\2/'` на значении из 8 знаков
# показывает все восемь, а на более коротком не матчится и возвращает вход целиком — то есть
# создаёт ВИДИМОСТЬ маскировки («…» на месте) при нуле скрытых знаков. Оператор, увидев такое,
# обоснованно перешлёт строку дальше.
mask() {
  if [ "${#1}" -ge 12 ]; then printf '%s…%s' "$(printf '%s' "$1" | cut -c1-4)" "$(printf '%s' "$1" | rev | cut -c1-4 | rev)"
  else printf '****'; fi
}

# Состояние страницы по сырому телу ответа: 1 = `page[]` пуст, 0 = непуст, -1 = ключа нет вовсе.
page_state() {
  local flat
  flat="$(printf '%s' "${1:-}" | tr -d ' \n\t\r')"
  case "$flat" in
    *'"page":[]'*) printf '1' ;;
    *'"page":['*)  printf '0' ;;
    *)             printf -- '-1' ;;
  esac
}

# Вердикт по состояниям двух страниц и признаку их РАВЕНСТВА → одно слово.
# ⚠ Непустая страница 1 сама по себе НЕ доказывает «`0` значит страницу» — первый живой прогон
# показал ровно это: при прочтении «0 = все» банк на `pageNo=1` повторяет ту же выдачу, и страница 1
# непуста В ОБОИХ прочтениях. Различает только сравнение содержимого (`same`: тела страниц
# байт-идентичны после схлопывания пробелов) — тот же принцип, по которому обход #566 останавливается
# на ПОВТОРЕ сырой страницы, а не на её пустоте. RED = «страница 1 непуста И отличается», и он
# по-прежнему проверяется первым: доказанная потеря важнее любых оценок полноты ответа.
verdict() {
  local p0="${1:-}" p1="${2:-}" same="${3:-}"
  # ⚠ Неполнота — первой, и это НЕ возврат к ошибке из ревью #569. Тогда RED зависел только от
  # непустоты страницы 1 и проверка неполноты его глушила зря; теперь RED опирается на СРАВНЕНИЕ
  # двух прочитанных страниц, а сравнение мусора с данными — не сравнение двух страниц: страница 0,
  # не разобравшаяся при живой странице 1, — транзиент, а не доказательство потери.
  if [ -z "$p0" ] || [ -z "$p1" ] || [ "$p0" = "-1" ] || [ "$p1" = "-1" ]; then printf 'INCONCLUSIVE'
  elif [ "$p1" = "0" ] && [ "$same" = "0" ]; then printf 'RED'
  elif [ "$p1" = "0" ] && [ "$same" = "1" ]; then printf 'GREEN-REPEAT'
  elif [ "$p1" = "0" ]; then printf 'INCONCLUSIVE'
  elif [ "$p0" = "0" ]; then printf 'GREEN'
  else printf 'NODATA'; fi
}

# ── Дальше — ввод-вывод ─────────────────────────────────────────────────────────────────────────

DAY="${1:-}"
if [ -z "$DAY" ]; then
  DAY="$(date -u -d 'yesterday' +%Y-%m-%d 2>/dev/null)"
  [ -n "$DAY" ] || DAY="$(date -u -v-1d +%Y-%m-%d 2>/dev/null)"
fi
# ⚠ Проверяется ИТОГОВОЕ значение, а не только аргумент: если обе ветки `date` откажут (BusyBox не
# знает ни `-d yesterday`, ни `-v`), `DAY` останется пустым, и в банк уйдёт `dateFrom=&dateTo=` —
# осмысленно выглядящий запрос с бессмысленным окном.
case "$DAY" in
  [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]) ;;
  '') echo "✗ не смог определить «вчера» — задайте день явно: make alfa-page-probe DAY=ГГГГ-ММ-ДД"; exit 2;;
  *)  echo "✗ день «$DAY» — нужен формат ГГГГ-ММ-ДД"; exit 2;;
esac

COMPOSE="docker-compose.prod.yml"
[ -f "$COMPOSE" ] || { echo "✗ $COMPOSE не найден — запускайте из каталога со стеком"; exit 1; }
DC="docker compose -f $COMPOSE"

section() { printf '\n\033[1m── %s ──\033[0m\n' "$1"; }

echo "День: $DAY (UTC)"

# ── Адрес API банка ──────────────────────────────────────────────────────────
# ⚠ И база, и префикс берутся из `.env` теми же именами, что читает `bankApiConfig`. Захардкоженный
# префикс молча разошёлся бы с боевой настройкой, и проба спрашивала бы не тот эндпоинт — то есть
# отвечала бы «страница 1 пуста» про адрес, которого нет.
API_BASE=""
API_PREFIX=""
if [ -f .env ]; then
  API_BASE="$(envv ALFA_OAUTH_API_BASE)"
  API_PREFIX="$(envv ALFA_OAUTH_API_PREFIX)"
fi
[ -n "$API_BASE" ] || API_BASE="https://developerhub.alfabank.by:8273"
[ -n "$API_PREFIX" ] || API_PREFIX="/partner/1.2.0"
API_BASE="$(printf '%s' "$API_BASE" | sed -E 's#/+$##')"
case "$API_PREFIX" in /*) ;; *) API_PREFIX="/$API_PREFIX";; esac
API_PREFIX="$(printf '%s' "$API_PREFIX" | sed -E 's#/+$##')"

section "Счёт и токен"
echo "  API банка: ${API_BASE}${API_PREFIX}/accounts/statement"

# ── Счёт и access-токен из базы (ТОЛЬКО чтение) ──────────────────────────────
# ⚠ `~pending:` пропускаем: у банка нет такого «номера» — это подключение без выбранного счёта,
# по нему опрашивать нечего (та же причина, по которой его пропускает и сам опрос).
# ⚠ stderr НЕ гасим: упавший `psql` (контейнер `db` не поднят) иначе неотличим от честного
# «подключений нет», и оператор пойдёт чинить не то.
PSQL_ERR="$(mktemp /tmp/alfa-probe-err.XXXXXX)"
CURL_ERR=""
# ⚠ Сигналы в trap перечислены ЯВНО, не только EXIT: самое вероятное прерывание — Ctrl-C во время
# 45-секундного запроса к банку, и на голом EXIT временный файл curl оставался бы в /tmp.
# ⚠ И обработчик сигнала ОБЯЗАН выйти сам. Без `exit` он лишь чистит и возвращает управление, то
# есть проба становится непрерываемой: Ctrl-C убивал текущий curl, сносил временный файл — и цикл
# спокойно уходил во ВТОРОЙ 45-секундный запрос к банку, а `sed` читал уже удалённый `$CURL_ERR`.
# Замерено A/B. 130 — принятый код «прервано с клавиатуры».
cleanup() { rm -f "$PSQL_ERR" ${CURL_ERR:+"$CURL_ERR"}; }
trap cleanup EXIT
trap 'cleanup; exit 130' INT TERM HUP
# ⚠ Код возврата берём У PSQL, а не у конца конвейера. `$?` после `psql … | tr` — это код `tr`, а он
# успешен почти всегда: упавший psql давал `PSQL_RC=0` и пустой `ROW`, скрипт уходил в ветку «нет
# подключённого счёта Альфы» — то есть ровно в ту ложную диагностику, которую комментарий выше
# обещает не допускать, а блок с текстом ошибки не выполнялся никогда.
# ⚠ ФИЛЬТР ПО ПОРТАЛУ ОБЯЗАТЕЛЕН, если порталов больше одного. Первая редакция брала `LIMIT 1`
# по `updated_at DESC` без `member_id` — то есть на сервере с четырьмя Битриксами проба молча
# уходила к тому счёту Альфы, чей токен обновлялся последним, и КАКОЙ ИМЕННО, оператор увидеть не
# мог: номер на экране замаскирован. Вердикт получался про один портал, а читался как про Альфу
# вообще. Портал задаётся его адресом: `B24=xxx.bitrix24.by make alfa-page-probe`.
PORTAL_DOMAIN="${B24:-}"
if [ -n "$PORTAL_DOMAIN" ]; then
  # Одинарные кавычки в адресе исключены — иначе он не адрес; на всякий случай удваиваем их.
  DOM_SQL="$(printf '%s' "$PORTAL_DOMAIN" | sed "s/'/''/g")"
  PORTAL_WHERE="AND b.member_id = (SELECT member_id FROM portal_tokens WHERE domain = '$DOM_SQL')"
else
  PORTAL_WHERE=""
fi
RAW_ROW="$($DC exec -T db psql -U app -d app -At -F'|' -c \
  "SELECT b.account_key, b.access_token,
          (SELECT count(*) FROM bank_tokens
             WHERE provider = 'alfa-by' AND account_key NOT LIKE '~pending:%')
     FROM bank_tokens b
    WHERE b.provider = 'alfa-by' AND b.account_key NOT LIKE '~pending:%' $PORTAL_WHERE
    ORDER BY b.updated_at DESC LIMIT 1" 2>"$PSQL_ERR")"
PSQL_RC=$?
ROW="$(printf '%s' "$RAW_ROW" | tr -d '\r')" 

if [ "$PSQL_RC" -ne 0 ]; then
  printf '  \033[31m✗ не смог прочитать базу (код %s)\033[0m\n' "$PSQL_RC"
  sed 's/^/    /' "$PSQL_ERR" | head -5
  exit 1
fi
if [ -z "$ROW" ]; then
  if [ -n "$PORTAL_DOMAIN" ]; then
    printf '  \033[33m✗ у портала %s нет подключённого счёта Альфы — проверьте адрес\033[0m\n' "$PORTAL_DOMAIN"
  else
    printf '  \033[33m✗ в bank_tokens нет подключённого счёта Альфы — пробовать нечего\033[0m\n'
  fi
  exit 1
fi
ACCOUNT="${ROW%%|*}"
REST="${ROW#*|}"
TOKEN="${REST%%|*}"
TOTAL_ALFA="${REST##*|}"
# ⚠ Неоднозначность НЕ разрешаем сами: подключений Альфы несколько, портал не назван — значит
# «какой счёт проверяем» решает случайный порядок обновления токенов, а вердикт этой пробы
# определяет, оставлять ли навсегда удвоенный расход общего лимита банка. Отказ дешевле.
if [ -z "$PORTAL_DOMAIN" ] && [ "${TOTAL_ALFA:-1}" != "1" ]; then
  printf '  \033[33m✗ подключений Альфы на сервере: %s — какое проверять, неясно\033[0m\n' "$TOTAL_ALFA"
  echo "  Назовите портал его адресом:"
  echo "    B24=xxx.bitrix24.by make alfa-page-probe DAY=$DAY"
  echo "  ⚠ Адрес ставится ПЕРЕД make, а не после — параметр после make раскрывается ещё до"
  echo "  шелла и исполняет то, что в него подставлено (см. CLAUDE.md, раздел про make)."
  exit 1
fi
if [ -z "$TOKEN" ] || [ "$TOKEN" = "$ACCOUNT" ]; then
  printf '  \033[33m✗ у счёта %s не удалось прочитать access-токен — дождитесь опроса и повторите\033[0m\n' "$(mask "$ACCOUNT")"
  exit 1
fi
echo "  Счёт: $(mask "$ACCOUNT")"

# ── Две страницы ─────────────────────────────────────────────────────────────
D="$(printf '%s' "$DAY" | awk -F- '{print $3"."$2"."$1}')"
P0=""
P1=""
FLAT0=""
FLAT1=""

section "Ответ банка"
for N in 0 1; do
  # ⚠ Номер счёта кодируем, хотя оба писателя `account_key` уже держат его алфавитно-цифровым
  # (`isValidAccountKey`/`ACCOUNT_KEY_RE`): это инвариант ДРУГОГО модуля, здесь он не проверяется,
  # и если он когда-нибудь ослабнет, этот скрипт унаследовал бы дыру молча.
  ACC_ENC="$(printf '%s' "$ACCOUNT" | sed -e 's/%/%25/g' -e 's/&/%26/g' -e 's/ /%20/g' -e 's/#/%23/g' -e 's/+/%2B/g')"
  URL="${API_BASE}${API_PREFIX}/accounts/statement?number=${ACC_ENC}&dateFrom=${D}&dateTo=${D}&transactions=0&pageNo=${N}&pageRowCount=0"
  # ⚠ stderr держим ОТДЕЛЬНО от тела: слитый в тело `2>&1` текст ошибки curl («connection refused»)
  # уходил в разбор как «ответ банка» и печатался как «банк ответил чем-то другим» — то есть
  # сетевой сбой на нашей стороне выдавался за странный ответ банка.
  CURL_ERR="$(mktemp /tmp/alfa-probe-curl.XXXXXX)"
  BODY="$(printf 'url = "%s"\nheader = "Authorization: Bearer %s"\nsilent\nshow-error\nmax-time = 45\n' \
            "$URL" "$TOKEN" | curl -K - 2>"$CURL_ERR")"
  if [ -z "$BODY" ]; then
    printf '  \033[33mстраница %s: банк не ответил\033[0m\n' "$N"
    sed 's/^/    /' "$CURL_ERR" | head -3
    rm -f "$CURL_ERR"; CURL_ERR=""
    continue
  fi
  rm -f "$CURL_ERR"; CURL_ERR=""
  case "$BODY" in
    *invalid_token*|*Unauthorized*|*expired_token*)
      printf '  \033[31mстраница %s: токен отвергнут банком\033[0m\n' "$N"
      echo "  Дождитесь очередного опроса (он обновит токен сам) и повторите."
      echo "  ⚠ Обновлять токен руками НЕЛЬЗЯ — банк ротирует refresh, база и банк разъедутся (#505/#509)."
      exit 2;;
  esac
  STATE="$(page_state "$BODY")"
  FLAT="$(printf '%s' "$BODY" | tr -d ' \n\t\r')"
  # Счёт строк — ПРИБЛИЗИТЕЛЬНЫЙ (по маркеру операции), только для чтения человеком.
  ROWS="$(printf '%s' "$FLAT" | grep -o '"operType"' | wc -l | tr -d ' ')"
  # ⚠ Из `errors[]` берём КОДЫ и ИМЕНА полей, а не сырой текст банка. Это единственное место, где
  # на фотографируемый экран попадала бы чужая свободная строка: сообщение банка вида «account
  # BY13… not found» напечатало бы номер счёта в открытую — рядом с тем самым `Счёт:`, который
  # секцией выше намеренно замаскирован (`docs/PRIVACY.md`, вывод операторских команд пересылают).
  ERR_RAW="$(printf '%s' "$FLAT" | grep -o '"errors":\[[^]]*\]' | head -1)"
  if [ "$ERR_RAW" = '"errors":[]' ] || [ -z "$ERR_RAW" ]; then
    ERRS="$ERR_RAW"
  else
    # ⚠ Печатаем ИМЕНА ПОЛЕЙ, а не коды: «account not found» и «rate limit» дадут одинаковую
    # строку, и это осознанная цена — сообщение банка пишем не мы, в него уже попадал номер счёта
    # в открытую. Чем ответил банк на самом деле — в логах backend (`make poll-check`), где вывод
    # не пересылают снимком экрана.
    ERR_FIELDS="$(printf '%s' "$ERR_RAW" | grep -o '"[A-Za-z_][A-Za-z0-9_]*":' | sort -u | tr -d '\":' | tr '\n' ' ')"
    ERRS="errors[]: поля — ${ERR_FIELDS:-<не разобрал>} (что именно ответил банк — в make poll-check)"
  fi
  # ⚠ statistics[] — встроенная сверка банка (остатки/обороты за период), которую мы пока не
  # читаем в коде: её ФОРМАТ нигде не задокументирован, а моделировать сверку по выдуманным полям
  # значит получить ложное «недосчитались» на исправном проде. Поэтому проба печатает КЛЮЧИ
  # блока — по ним сверка моделируется уже не вслепую (#561). Ключи, не значения: в блоке суммы
  # оборотов, а вывод этой команды пересылают (docs/PRIVACY.md).
  STAT_KEYS="$(printf '%s' "$FLAT" | grep -o '"statistics":\[{[^]]*' | head -1 | grep -o '"[A-Za-z_][A-Za-z0-9_]*":' | sort -u | tr -d '":' | tr '\n' ' ')"
  case "$STATE" in
    1)  echo "  страница $N: page[] пуст ${ERRS:+| $ERRS}";;
    0)  echo "  страница $N: page[] непуст, операций ≈$ROWS ${ERRS:+| $ERRS}"
        [ -n "$STAT_KEYS" ] && echo "    statistics[]: ключи — $STAT_KEYS";;
    *)  printf '  \033[33mстраница %s: в ответе нет ключа page[] — банк ответил чем-то другим\033[0m\n' "$N"
        # ⚠ Печатаем КЛЮЧИ ответа, а не его текст. Форму банк мог сменить как угодно, и сырые
        # 200 символов однажды унесли бы в мессенджер назначение платежа или контрагента — вывод
        # этой команды пересылают (`docs/PRIVACY.md`). Ключей хватает, чтобы понять, что пришло.
        KEYS="$(printf '%s' "$FLAT" | grep -o '"[A-Za-z_][A-Za-z0-9_]*":' | sort -u | tr -d '":' | tr '\n' ' ')"
        echo "  ключи ответа: ${KEYS:-<не JSON>}";;
  esac
  if [ "$N" = "0" ]; then
    P0="$STATE"
    FLAT0="$FLAT"
  else
    P1="$STATE"
    FLAT1="$FLAT"
    # ⚠ Совпадение тел доказывает «банк проигнорировал pageNo» ТОЛЬКО когда на странице что-то
    # есть. На дне без операций обе страницы пусты, и они идентичны по скучной причине — сравнивать
    # было нечего. Первая редакция печатала вывод безусловно и на пустом дне уверенно сообщала
    # «банк проигнорировал pageNo», хотя вердиктом пятью строками ниже сама же говорила, что проба
    # ничего не доказывает. Замерено на живом проде 2026-08-18 (день без операций).
    if [ -n "$FLAT0" ] && [ "$FLAT1" = "$FLAT0" ]; then
      if [ "$P0" = "0" ]; then
        printf '  страница 1 ПОВТОРЯЕТ страницу 0 байт-в-байт — банк проигнорировал pageNo\n'
      elif [ "$P0" = "1" ]; then
        printf '  операций в ответе нет ни на той, ни на другой странице — тела совпали, но это\n'
        printf '  ничего не значит: сравнивать было нечего\n'
      else
        # ⚠ Третья ветка обязательна: сюда попадает и «в ответе нет ключа page[]». Назвать такой
        # ответ «пустой страницей» значило бы спорить со строкой, напечатанной двумя строками
        # выше («банк ответил чем-то другим»), — та же болезнь, что чинил #561.
        printf '  оба ответа не разобрались одинаково — это не пустые страницы, а неопознанный\n'
        printf '  ответ банка; смотрите строки выше\n'
      fi
    fi
  fi
done

# 1 = тела страниц идентичны (банк повторился), 0 = различаются, пусто = сравнивать нечего.
SAME=""
if [ -n "$FLAT0" ] && [ -n "$FLAT1" ]; then
  [ "$FLAT0" = "$FLAT1" ] && SAME="1" || SAME="0"
fi

