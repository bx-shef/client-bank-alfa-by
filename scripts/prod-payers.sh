#!/usr/bin/env bash
# Кого именно приложение не может опознать — и каким номером счёта это чинится (#501).
#
# ⚠ Зачем. Цепочка «банк → очередь → разбор → поиск компании → запись дела» на боевом стенде
# отработала сотни раз, но ни один платёж не попал в карточку КЛИЕНТА: у компаний-контрагентов в
# CRM нет банковских реквизитов, искать не по чему. Лечится это одним действием владельца —
# вписать счёт плательщика в реквизит компании, — но прежде надо узнать, КАКОЙ счёт и чей.
#
# Прежний порядок был ручным: открыть в портале конкретное дело, найти в теле строку «Счёт:»,
# перепечатать номер. То есть 28 знаков, набранных с экрана, в поле, где сравнение посимвольное.
# Здесь то же самое берётся из лога, где приложение уже напечатало номер само.
#
# ⚠ Данные для этого на сервере УЖЕ ЕСТЬ: строка `[op]` несёт счёт контрагента, и по умолчанию
# (`STATEMENT_OP_LOG=notable`) печатается ровно для операций, которые НИКУДА не приземлились. То
# есть скрипт ничего не добывает — он читает то, что и так пишется, и складывает в порядок частоты.
#
# ⚠ ТОЛЬКО ЧТЕНИЕ. Ни в портал, ни в банк не ходит: границы #501 требуют, чтобы прогон ничего не
# менял в чужой CRM. Вписывает реквизит человек.
#
# Использование (из каталога со стеком):
#   bash prod-payers.sh          # за 24 часа
#   bash prod-payers.sh 3h       # за произвольное окно (формат docker: 30m, 2h, 1h30m)

set -u
SINCE="${1:-24h}"
# ⚠ Окно проверяется ДО обращения к docker — иначе `docker compose logs` вернёт ошибку, список
# выйдет пустым, и «никого не опознали» будет неотличимо от «всё опознано».
case "${SINCE,,}" in
  *[!0-9smh]*|'') echo "✗ окно «$SINCE» docker не примет: только s/m/h, например 30m, 2h, 24h"; exit 2;;
esac

COMPOSE="docker-compose.prod.yml"
[ -f "$COMPOSE" ] || { echo "✗ $COMPOSE не найден — запускайте из каталога со стеком"; exit 1; }
DC="docker compose -f $COMPOSE"

printf '\n\033[1m── Плательщики, которых приложение не опознало (за %s) ──\033[0m\n' "$SINCE"

# ⚠ Берём строки `[op]`, где владельца не нашли ВООБЩЕ (`NO OWNER`) либо сработал фолбэк в «мою
# компанию». Оба случая означают одно: компания-контрагент по счёту не найдена. Приземлившиеся к
# клиенту (`company`) сюда не попадают — они и так работают.
raw="$($DC logs --since "$SINCE" worker backend 2>&1 | grep -F '[op]' || true)"

if [ -z "$raw" ]; then
  printf '  \033[33m(за %s не было ни одной строки [op])\033[0m\n' "$SINCE"
  echo '  Причин ровно три, и они разные:'
  echo '    • операций не было — смотрите секцию [fetch] в `make poll-check`;'
  echo '    • все операции приземлились к клиентам — тогда #501 уже закрыт;'
  echo '    • STATEMENT_OP_LOG=off — построчный лог выключен, включите notable.'
  exit 0
fi

# ⚠ Счёт вырезаем ИМЕННО из формы `← <счёт> →`, а не «третьим словом»: в строке есть и наш счёт
# (в `op <наш>|<докид>`), и валюта, и направление. Спутать их — значит выдать владельцу для
# вписывания в реквизит контрагента НАШ собственный номер.
#
# ⚠ `[^ ]+` заодно отсекает операции БЕЗ счёта плательщика: приложение печатает там «счёт не
# указан», а это три слова с пробелами, и под шаблон номера они не подходят. Отдельного фильтра
# не нужно — но и полагаться на случайность нельзя, поэтому связь шаблона с форматом строки
# закреплена тестом `tests/prodPayers.test.ts` на выводе НАСТОЯЩЕГО `buildOpLogLine`.
list="$(printf '%s\n' "$raw" \
  | grep -E 'NO OWNER|my-company \(fallback\)' \
  | grep -oE '← [^ ]+ →' \
  | sed 's/^← //; s/ →$//' \
  | sort | uniq -c | sort -rn || true)"

if [ -z "$list" ]; then
  printf '  \033[32mвсе операции за окно приземлились к компаниям-клиентам — чинить нечего\033[0m\n'
  exit 0
fi

total="$(printf '%s\n' "$list" | awk '{s+=$1} END {print s+0}')"
uniq_n="$(printf '%s\n' "$list" | grep -c . || true)"
printf '  не опознано операций: %s, уникальных плательщиков: %s\n\n' "$total" "$uniq_n"
printf '  \033[1m%8s  %s\033[0m\n' 'платежей' 'счёт плательщика'
# ⚠ Показываем не всех: у боевого портала уникальных плательщиков сотни, и длинный список в
# мобильном терминале хоронит начало — а чинить имеет смысл с самых частых.
printf '%s\n' "$list" | head -15 | while read -r n acc; do
  printf '  %8s  %s\n' "$n" "$acc"
done
[ "$uniq_n" -gt 15 ] && printf '  … и ещё %s (показаны 15 самых частых)\n' "$((uniq_n - 15))"

cat <<'HINT'

Что с этим делать:
  1. Выберите счёт сверху — это плательщик, который чаще других не опознаётся.
  2. Найдите его компанию в CRM (или заведите) и впишите номер в реквизит,
     поле «Номер счёта» (RQ_ACC_NUM).
  3. Дождитесь СЛЕДУЮЩЕГО платежа от него — уже записанные дела дедуп не тронет.

  ⚠ Вписывать РОВНО как здесь: без пробелов и переносов. Поиск сравнивает
    посимвольно, поэтому «BY00 BANK …» и «BY00BANK…» для приложения РАЗНЫЕ счета,
    и реквизит с пробелами не найдётся никогда — молча, без ошибки.

  ⚠ Не всякий плательщик — клиент. Налоговая, банки, эквайринг, связь, топливо
    заводить в CRM незачем: их платежи так и будут падать в «мою компанию»
    (решение по #562 — оставить как есть).
HINT
