#!/usr/bin/env bash
# Что реально происходит с опросом банков прямо сейчас (#522, диагностика после переключения хоста).
#
# ⚠ Зачем отдельный скрипт, а не `grep` руками. Крон печатает строку планирования КАЖДЫЕ 5 минут,
# и она содержит слова `prior-by`/`alfa-by`. Любой греп по названию банка тонет в ней: за час это
# 12 длинных строк, за три часа — 36, и `tail -30` показывает только их, вытесняя ровно то, ради
# чего смотрели. Здесь сигнал разделён по секциям, а планирование исключено намеренно.
#
# Использование (из каталога со стеком):
#   bash prod-poll-check.sh          # за 3 часа
#   bash prod-poll-check.sh 30m      # за произвольное окно (формат docker: 30m, 2h, 1h30m)

set -u
SINCE="${1:-3h}"
# ⚠ Окно проверяется ДО первого обращения к docker. Неверное значение (`3d` — суток docker не
# принимает) иначе роняет КАЖДУЮ секцию по отдельности: все `docker compose logs` возвращают
# ошибку, все секции печатают «(ничего)», и на этом фоне тревога о продлении кричит о поломке,
# которой нет. Одна понятная строка вместо семи пустых и одной ложной.
case "${SINCE,,}" in
  *[!0-9smh]*|'') echo "✗ окно «$SINCE» docker не примет: только s/m/h, например 30m, 2h, 1h30m"; exit 2;;
esac

COMPOSE="docker-compose.prod.yml"
[ -f "$COMPOSE" ] || { echo "✗ $COMPOSE не найден — запускайте из каталога со стеком"; exit 1; }
DC="docker compose -f $COMPOSE"

section() { printf '\n\033[1m── %s ──\033[0m\n' "$1"; }

# Окно docker (`30m`, `2h`, `1h30m`, `90s`) → минуты. Нужно, чтобы отличить «продление не работает»
# от «окно короче его периода»: без этого короткий прогон `SINCE=30m` кричал бы об аварии впустую.
#
# ⚠ Регистр НЕ имеет значения, и это не косметика: владелец смотрит с мобильного терминала, где
# автокапитализация превращает `2h` в `2H`. С регистрозависимым разбором `2H` давала ноль, ветка
# тревоги не срабатывала, и вместо красного «продление не работало» печаталось успокаивающее
# «окно короче часа» — то есть скрипт врал ровно в том сценарии, ради которого написан.
#
# ⚠ Суток (`d`) в списке НЕТ намеренно: docker их не принимает («failed to parse value as time or
# duration: 3d»), и обещать их здесь значило бы звать оператора в тупик, где ВСЕ секции пусты (все
# `docker compose logs` падают), а эта — ещё и кричит о несуществующей аварии.
minutes_of() {
  local w="${1,,}" total=0 n u
  while [[ "$w" =~ ^([0-9]+)([smh])(.*)$ ]]; do
    n="${BASH_REMATCH[1]}"; u="${BASH_REMATCH[2]}"; w="${BASH_REMATCH[3]}"
    case "$u" in
      s) total=$(( total + n / 60 ));;
      m) total=$(( total + n ));;
      h) total=$(( total + n * 60 ));;
    esac
  done
  echo "$total"
}
# Печатает найденное или честное «ничего», чтобы пустая секция не читалась как обрыв вывода.
show() {
  local out; out="$(cat)"
  if [ -n "$out" ]; then echo "$out" | tail -"${1:-10}" | sed 's/^/  /'
  else printf '  \033[33m(ничего)\033[0m\n'; fi
}

echo "Окно: последние $SINCE"

section "Опросы, дошедшие до банка   [fetch]"
# Единственное безусловное доказательство, что банк ответил: провайдер, счёт, окно, число операций.
#
# ⚠ КОНТЕЙНЕРА ДВА, и это исправление по находке ревью. Задачи опроса разбирает `worker`, но
# крон-тик живёт на `backend` — и именно он печатает причину холостого прогона (#488). Секция,
# читавшая только `worker`, была слепа ровно к той строке, ради которой её и завели.
#
# ⚠ А ВОТ СЧИТАТЬ эту строку за опрос НЕЛЬЗЯ: `fetch_n` — доказательство, что банк ответил, и на
# нём стоит вердикт «продлевает ОПРОС». Засчитай мы сюда «опрашивать нечего» — вернулась бы ровно
# та ложь, которую этот скрипт и чинит. Настоящий опрос всегда сообщает число операций (`N ops`,
# `worker.ts`), холостой тик — никогда; форма закреплена тестом на строке НАСТОЯЩЕГО логгера.
fetch_n="$($DC logs --since "$SINCE" worker backend 2>&1 | grep -cE '\[fetch\].*[0-9]+ ops' || true)"
$DC logs --since "$SINCE" worker backend 2>&1 | grep -F '[fetch]' | show 12

section "Пауза автоопроса            [bank-connect]"
# ⚠ Третья причина «опрос пустой», и снаружи она НЕОТЛИЧИМА от первых двух (нет счетов /
# CRON_REAL_POLL=0): администратор клиента поставил подключение на паузу (#576). Разница в том, что
# чинится это в портале, а не у нас, — и без этой секции оператор шёл бы искать поломку на нашей
# стороне. Пусто здесь — норма: строка печатается только в момент переключения.
$DC logs --since "$SINCE" backend 2>&1 | grep -F 'автоопрос' | show 6

section "Итоги обработки             [crm-sync]"
# Безусловная строка на каждый прогон: сколько обработано/создано/приземлилось.
$DC logs --since "$SINCE" worker 2>&1 | grep -F '[crm-sync]' | show 8

section "Операции без результата     [op]"
# По умолчанию печатаются только НЕ приземлившиеся — то есть здесь либо пусто, либо проблема.
$DC logs --since "$SINCE" worker 2>&1 | grep -F '[op]' | show 8

section "ПАДЕНИЯ задач               [queue-job-failed] / [queue-worker-error]"
# ⚠ Самая важная секция. `FINAL` значит, что задача исчерпала все попытки и больше не повторится.
$DC logs --since "$SINCE" worker 2>&1 | grep -E '\[queue-job-failed\]|\[queue-worker-error\]' | show 12

section "Ретраи                      [queue-job-retry]"
# Единичные — норма (сеть). Поток одинаковых — уже симптом.
$DC logs --since "$SINCE" worker 2>&1 | grep -F '[queue-job-retry]' | show 8

section "Продление банк-токенов      [bank-keepalive]"
# ⚠ ЗДЕСЬ ПУСТО — ПЛОХО, и раньше эта подсказка утверждала обратное. Сводка прогона
# (`selected=… refreshed=… failed=… expired=…`) печатается БЕЗУСЛОВНО, раз в час, на каждом
# завершённом скане. Значит тишина за окно длиннее часа означает не «обновилось молча», а
# «продление не отработало НИ РАЗУ» — то есть ровно тот отказ (#504), из-за которого подключение
# Альфы и умирало за ночь. Подсказка, которая называет этот случай нормой, вредна именно тогда,
# когда на неё смотрят.
# ⚠ Маркера ДВА, и у второго другой префикс: `[queue] bank keep-alive run failed` печатается,
# когда упал сам список счетов ДО прогона. Симптом снаружи тот же — полная тишина по первому
# маркеру, — а причина другая, и греп только по `[bank-keepalive]` её не покажет (OPERATIONS.md).
ka="$($DC logs --since "$SINCE" worker backend 2>&1 | grep -E '\[bank-keepalive\]|bank keep-alive run failed')"
echo "$ka" | grep -v '^$' | show 8
if [ -z "$ka" ]; then
  # Окно короче часа ничего не доказывает: скан просто мог ещё не наступить.
  if [ "$(minutes_of "$SINCE")" -ge 70 ]; then
    printf '  \033[31m⚠ за %s не было НИ ОДНОГО прогона продления — оно запускается раз в час.\033[0m\n' "$SINCE"
    printf '    Проверьте, что крон-инстанс поднят (QUEUE_CRON) и процесс не падает при старте.\n'
  else
    printf '  \033[33m(окно короче часа — отсутствие строки ни о чём не говорит, продление ежечасное)\033[0m\n'
  fi
fi

section "КТО продлевает банк-токен  (#488/#489)"
# ⚠ Ради этой секции всё и затевалось. Подключение может жить, а ПОЧЕМУ — из факта его жизни не
# следует: токен обновляет и крон продления (#489), и сам опрос по дороге (`ensureFresh` →
# `ensureBankToken` в `bankFetch.ts`) — то есть ровно тот старый путь, который #488 назвал
# ненадёжным. Наблюдаемое «живёт шестые сутки» одинаково хорошо объясняется обоими, и спорить об
# этом бессмысленно: различает только сводка прогона, а не дела в CRM.
#
# Правило чтения, и оно не самоочевидно:
#   refreshed > 0            → крон РЕАЛЬНО продлевал. #489 работает.
#   selected = 0 везде       → крон ходил, но продлевать было НЕЧЕГО: токен ни разу не постарел до
#                              полосы обновления. Раз он при этом свежий — освежает его ОПРОС, и
#                              подключение держится ровно тем механизмом, который признан ненадёжным.
#   selected > 0, refreshed 0 → крон пытался и не смог: смотреть failed/expired выше.
# ⚠ ЗАМЕР 2026-08-24 на живом стенде поймал дыру в прежней редакции этой секции: она смотрела
# только на `selected`/`refreshed` и на `selected=0` уверенно отвечала «продлевает опрос». А в
# реальном логе было `selected=0 ... expired=2`, то есть обе строки ПОХОРОНЕНЫ и потому не
# отбираются — вывод «токен всё время свежий» был не просто неверен, он маскировал единственную
# настоящую поломку в выводе. Отсюда `expired`/`unrefreshable` читаются наравне с остальными.
# ⚠ СКЛАДЫВАТЬ МОЖНО НЕ ВСЁ, и живой прогон 2026-08-25 поймал это больно: `expired` и
# `unrefreshable` — СНИМКИ состояния («сколько строк сейчас в этом состоянии»), они пересчитываются
# каждым прогоном заново. Сумма по 14 прогонам дала «похоронено: 28» при ДВУХ реальных
# подключениях — то есть диагностика пугала числом, которого не существует. Складывать имеет смысл
# только счётчики ДЕЙСТВИЙ: `refreshed`, `failed` и (как число попыток) `selected`. Снимки берём из
# ПОСЛЕДНЕГО прогона.
# ⚠ `total=` — НЕОБЯЗАТЕЛЬНОЕ поле, и это не запас прочности, а обычное состояние стенда: скрипты
# приезжают на сервер через `make self-update`, а бэкенд — отдельным docker-образом, поэтому новый
# скрипт штатно встречает ещё не выкаченный бэкенд. С жёстким `total=` в шаблоне такая пара давала
# НОЛЬ разобранных строк, а ноль прогонов — уверенное «контейнер пересоздавали, вердикта нет»,
# то есть постоянный ложный диагноз ровно в момент выката (находка ревью).
ka_lines="$($DC logs --since "$SINCE" worker backend 2>&1 | grep -F '[bank-keepalive]' \
  | grep -oE '(total=[0-9]+ )?selected=[0-9]+ refreshed=[0-9]+ skipped=[0-9]+ failed=[0-9]+ unrefreshable=[0-9]+ expired=[0-9]+')"
# ⚠ Разбор ПО ИМЕНИ поля, а не по позиции. Позиционный `awk -F'[= ]'` пришлось бы пересчитывать при
# каждом добавлении поля — и один раз это уже съехало молча (тестовый близнец разбирал `total` как
# `selected` и проходил зелёным, потому что в фикстурах числа совпадали). Имя переживает и сдвиг,
# и отсутствие поля: `total=-1` означает «бэкенд старый, поле не печатается» — это НЕ ноль счетов.
acts="$(echo "$ka_lines" | grep -v '^$' \
  | awk '{
      t = -1; sl = 0; rf = 0; fl = 0
      for (i = 1; i <= NF; i++) {
        split($i, kv, "=")
        if (kv[1] == "total") t = kv[2] + 0
        else if (kv[1] == "selected") sl = kv[2] + 0
        else if (kv[1] == "refreshed") rf = kv[2] + 0
        else if (kv[1] == "failed") fl = kv[2] + 0
      }
      sel += sl; ref += rf; fai += fl; tot = t; n++
    }
    END {print (n?n:0), (sel?sel:0), (ref?ref:0), (fai?fai:0), (n?tot:-1)}')"
runs="$(echo "$acts" | cut -d" " -f1)"; sel="$(echo "$acts" | cut -d" " -f2)"
ref="$(echo "$acts" | cut -d" " -f3)"; fail="$(echo "$acts" | cut -d" " -f4)"
total="$(echo "$acts" | cut -d" " -f5)"
# Снимок — из последней строки, а не сумма.
last_ka="$(echo "$ka_lines" | grep -v '^$' | tail -1)"
unref="$(echo "$last_ka" | grep -oE 'unrefreshable=[0-9]+' | grep -oE '[0-9]+')"
expd="$(echo "$last_ka" | grep -oE 'expired=[0-9]+' | grep -oE '[0-9]+')"
printf '  прогонов продления за %s: %s   попыток: %s   продлено: %s   отказов банка: %s\n' \
  "$SINCE" "${runs:-0}" "${sel:-0}" "${ref:-0}" "${fail:-0}"
printf '  сейчас похоронено: %s   без refresh-токена: %s   (состояние на последний прогон)\n' \
  "${expd:-0}" "${unref:-0}"
# ⚠ Сколько строк подключений видит продление ВООБЩЕ. Без этого числа сводка из одних нулей
# читалась одинаково в двух разных мирах: «подключений нет» и «все свежие» (#488).
# ⚠ Сентинел «не знаем» приходит из `awk` (`n?tot:-1`), а не из подстановки ниже: подстановка
# срабатывает только на ПУСТОЙ переменной, а пустой `total` бывает ровно тогда, когда пуст и
# `runs`, то есть до этой ветки дело не доходит. Замерено мутацией — менять надо awk, не здесь.
if [ "${runs:-0}" -gt 0 ] && [ "${total:--1}" -eq 0 ]; then
  printf '  \033[31m⚠ подключённых счетов НЕТ НИ ОДНОГО — продлевать и опрашивать нечего.\033[0m\n'
  printf '    Это не поломка продления: сперва подключите банк в настройках портала.\n'
  printf '    Куда делись прежние — секция «КТО ОТКЛЮЧАЛ БАНК» ниже (#641).\n'
fi

# Похороненные подключения — ОТДЕЛЬНЫЙ вопрос от «кто продлевает», и он важнее: их не чинит ни
# крон, ни опрос, только повторный вход владельца счёта в интернет-банк.
if [ "${expd:-0}" -gt 0 ]; then
  printf '  \033[31m⚠ %s подключени(й) ПОХОРОНЕНО: продлевать их уже нечем.\033[0m\n' "$expd"
  printf '    Чинится ТОЛЬКО повторной авторизацией владельца счёта в интернет-банке —\n'
  printf '    ни крон, ни опрос тут не помогут. Какие именно — в строке [bank-keepalive] выше.\n'
fi

# ⚠ ПОКРЫТИЕ ОКНА ПРОВЕРЯЕТСЯ ПЕРВЫМ, и это исправление по живому прогону 2026-08-26. Продление
# идёт раз в час, значит за сутки прогонов должно быть ~24. Один — значит контейнер пересоздавали,
# логи прежнего ушли вместе с ним, и «за 24 часа» на самом деле означает «за минуты». Прежняя
# редакция печатала уверенный ВЕРДИКТ, а оговорку про перезапуск — строкой НИЖЕ, то есть после
# того, как читатель уже принял ответ. На таком окне `selected=0` не значит ничего.
# ⚠ Каденция берётся ИЗ `.env`, а не зашита часом (замечание ревью). `BANK_KEEPALIVE_MINUTES`
# настраивается и законно доходит до 150 (потолок — половина самой узкой полосы обновления). При
# зашитом часе такой стенд давал бы `runs` вдвое-втрое меньше ожидаемого НА ИСПРАВНОЙ работе, то
# есть вечное «ВЕРДИКТА НЕТ, контейнер пересоздавали» — тот же класс постоянного ложного диагноза,
# что и жёсткий `total=` выше. Файла нет / значение кривое ⇒ час, как в коде по умолчанию.
ka_min="$(sed -n 's/^[[:space:]]*BANK_KEEPALIVE_MINUTES[[:space:]]*=[[:space:]]*\([0-9]\{1,\}\).*/\1/p' .env 2>/dev/null | tail -1)"
case "${ka_min:-}" in ''|*[!0-9]*) ka_min=60;; esac
[ "$ka_min" -ge 1 ] 2>/dev/null || ka_min=60
expected_runs="$(( $(minutes_of "$SINCE") / ka_min ))"
covered=1
if [ "$expected_runs" -ge 3 ] && [ "${runs:-0}" -lt $(( expected_runs / 2 )) ]; then
  covered=0
fi

# ⚠ ПОРЯДОК ВЕТОК — ЭТО СОДЕРЖАНИЕ, а не оформление, и первая редакция ошиблась в нём дважды
# (находки ревью).
#
#   1. «Прогонов не было» проверяется РАНЬШЕ покрытия. При `runs=0` и окне от трёх часов условие
#      непокрытия истинно ВСЕГДА, поэтому гейт перехватывал этот случай и печатал «контейнер
#      пересоздавали» — при том, что секция выше в тот же момент честно говорит «продление не
#      отработало НИ РАЗУ, проверьте QUEUE_CRON». Два взаимно исключающих диагноза об одном логе,
#      причём заметная строка называла менее вероятную причину.
#
#   2. Гейт покрытия гасит ТОЛЬКО выводы из ОТСУТСТВИЯ работы (`selected=0`). Прямые наблюдения —
#      «крон продлил» (`refreshed>0`) и «крон отбирал и не продлил» (`selected>0`) — стоят ВЫШЕ
#      него: короткое окно не делает случившееся неслучившимся. Замолчать их значило бы терять
#      единственный содержательный ответ ровно после выката, когда его чаще всего и спрашивают.
#      Ниже гейта `selected` заведомо ноль, поэтому остаются ровно те ветки, которые рассуждают
#      о свежести токена по тому, что крон никого НЕ отобрал.
if [ "${runs:-0}" -eq 0 ]; then
  printf '  \033[33m(вердикта нет: прогонов не было — см. секцию выше)\033[0m\n'
elif [ "${ref:-0}" -gt 0 ]; then
  printf '  \033[32m✔ ОТВЕТ: продлевает КРОН (#489). Механизм работает.\033[0m\n'
elif [ "${sel:-0}" -gt 0 ]; then
  # Тоже ПРЯМОЕ наблюдение: крон отобрал счета и не продлил ни одного. Стоит выше гейта покрытия
  # по той же причине, что и предыдущая ветка, — короткое окно не делает случившееся неслучившимся.
  printf '  \033[31m⚠ ОТВЕТ: крон отбирал счета, но НЕ продлил ни одного — смотрите failed выше.\033[0m\n'
elif [ "$covered" -eq 0 ]; then
  printf '  \033[33m⚠ ВЕРДИКТА НЕТ: за %s ожидалось ~%s прогонов продления, а в логе %s.\033[0m\n' \
    "$SINCE" "$expected_runs" "${runs:-0}"
  printf '    Контейнер пересоздавали — логи прежнего ушли вместе с ним, и окно на деле короче\n'
  printf '    заявленного. Судить по нему нельзя: повторите через час-другой непрерывной работы.\n'
elif [ "${sel:-0}" -eq 0 ] && [ "${expd:-0}" -eq 0 ] && [ "${unref:-0}" -eq 0 ] && [ "${fetch_n:-0}" -gt 0 ]; then
  printf '  \033[31m⚠ ОТВЕТ: продлевает ОПРОС, а не крон.\033[0m\n'
  printf '    Крон отработал %s раз и ни разу никого не отобрал — значит токен всё время свежий,\n' "${runs:-0}"
  printf '    и освежает его опрос по дороге. Это ровно тот путь, который #488 назвал ненадёжным:\n'
  printf '    выключите опрос (CRON_REAL_POLL=0) — и подключение умрёт за срок refresh (~10 ч у Альфы).\n'
elif [ "${sel:-0}" -eq 0 ] && [ "${expd:-0}" -eq 0 ] && [ "${unref:-0}" -eq 0 ]; then
  # ⚠ ЭТА ВЕТКА — ИСПРАВЛЕНИЕ ЛЖИ (живой прогон 2026-08-26). Прежде тот же вход давал уверенное
  # «продлевает ОПРОС», хотя `[fetch]` в логе не было НИ ОДНОГО: вывод «токен освежает опрос»
  # делался из `selected=0`, то есть из ОТСУТСТВИЯ работы у крона, и ничем не подкреплялся. Ответ
  # звучал успокаивающе ровно там, где не работало вообще ничего.
  printf '  \033[31m⚠ ОТВЕТ: токен не продлевал НИКТО.\033[0m\n'
  printf '    Крон отработал %s раз и никого не отобрал, а опроса за окно не было ни одного\n' "${runs:-0}"
  printf '    ([fetch] пуст) — значит освежать токен было и некому, и нечем.\n'
  printf '    Причин ровно две, и они проверяются по очереди:\n'
  printf '      • подключённых счетов нет вовсе — тогда и продлевать нечего (настройки → Подключение банка);\n'
  printf '      • опрос выключен (CRON_REAL_POLL=0 в ./.env) — тогда выписка не забирается совсем,\n'
  printf '        и это отдельная поломка, более крупная, чем срок токена.\n'
else
  # Сюда доходит только `sel=0` при ненулевых `expired`/`unrefreshable`: все строки исключены из
  # отбора, поэтому «ноль отобранных» ничего не говорит о свежести живых подключений.
  printf '  \033[33m(вердикта о том, КТО продлевает, нет: все строки исключены как похороненные\033[0m\n'
  printf '   \033[33m или без refresh-токена, поэтому «ноль отобранных» ничего не говорит о свежести)\033[0m\n'
fi

section "ВОРОНКА платежа            (#501)"
# ⚠ Числа берутся из ИТОГОВОЙ строки `[crm-sync]`, а не подсчётом строк лога, и это исправление
# по живому прогону 2026-08-24. Прежняя редакция считала строки маркеров и печатала «[fetch] 15 →
# [op] 4» как воронку — а это несравнимые величины: `[fetch]` пишется на каждый опрос (по три
# строки), `[op]` — только на операции, которые НИКУДА не приземлились. На живом стенде вышло
# «15 → 4» при 296 реально обработанных, то есть воронка вводила в заблуждение на два порядка.
# Приложение считает эти числа само и печатает их в одной строке — её и разбираем.
sum_line="$($DC logs --since "$SINCE" worker backend 2>&1 | grep -F '[crm-sync]' | tail -1)"
if [ -z "$sum_line" ]; then
  printf '  \033[33m(за %s не было ни одного прогона обработки — смотрите секцию [fetch] выше)\033[0m\n' "$SINCE"
else
  fld() { echo "$sum_line" | grep -oE "[0-9]+ $1" | grep -oE '^[0-9]+' | tail -1; }
  n_proc=$(fld 'обработано'); n_made=$(fld 'создано'); n_land=$(fld 'приземлилось')
  n_nocli=$(fld 'без клиента'); n_notgt=$(fld 'без цели'); n_rec=$(fld 'с распознанным номером')
  printf '  обработано операций          %s\n' "${n_proc:-0}"
  printf '  из них: создано дел          %s\n' "${n_made:-0}"
  printf '          приземлилось к цели  %s\n' "${n_land:-0}"
  printf '          клиент НЕ опознан    %s\n' "${n_nocli:-0}"
  printf '          номер распознан      %s\n' "${n_rec:-0}"
  printf '          цель не найдена      %s\n' "${n_notgt:-0}"

  # ⚠ Распознавание и опознание клиента — ДВА НЕЗАВИСИМЫХ предусловия, и приземление требует обоих.
  # Прежняя редакция выбирала одно «место обрыва» и молчала о втором; на живом стенде это дало
  # «обрыв на распознавании» при том, что клиент тоже не был опознан.
  if [ "${n_proc:-0}" -eq 0 ]; then
    printf '  \033[33m(операций в прогоне не было — банк отдал пустое окно)\033[0m\n'
  else
    ok=1
    if [ "${n_rec:-0}" -eq 0 ]; then
      ok=0
      printf '  \033[31m⚠ НОМЕР не распознан ни в одном назначении.\033[0m\n'
      printf '    Либо не настроена карта распознавания (Настройки → «Карта распознавания»),\n'
      printf '    либо в назначениях этих платежей номеров действительно нет. Проверять — глазами\n'
      printf '    по нескольким назначениям, прежде чем крутить матрицы.\n'
    fi
    if [ "${n_nocli:-0}" -gt 0 ]; then
      ok=0
      printf '  \033[31m⚠ КЛИЕНТ не опознан у %s операций — они ушли в «мою компанию» (фолбэк).\033[0m\n' "$n_nocli"
      printf '    Компания-плательщик ищется по расчётному счёту в реквизитах. Нет реквизита в CRM —\n'
      printf '    искать не по чему. Это НЕ настройка распознавания: без компании поиск цели вообще\n'
      printf '    не запускается (company-скоуп против IDOR).\n'
    fi
    if [ "${n_notgt:-0}" -gt 0 ]; then
      printf '  \033[33m⚠ ЦЕЛЬ не найдена у %s операций: номер распознан и клиент есть, а счёта/сделки под него нет.\033[0m\n' "$n_notgt"
    fi
    if [ "$ok" -eq 1 ] && [ "${n_land:-0}" -gt 0 ]; then
      printf '  \033[32m✔ цепочка проходит до конца: %s операций приземлились к цели\033[0m\n' "$n_land"
    fi
  fi
fi

