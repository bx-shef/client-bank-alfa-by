else
  printf '  %s\n' "$(echo "$sub_line" | sed 's/.*\[sub-cutoff\][^:]*: //')"
  if [ "${sub_cut:-0}" -gt 0 ]; then
    # ⚠ Красным: это необратимо для клиента — ему придётся заново входить в интернет-банк.
    printf '  \033[31mОТКЛЮЧЕНО подключений: %s — клиенту нужен повторный вход в интернет-банк\033[0m\n' "$sub_cut"
  fi
fi

