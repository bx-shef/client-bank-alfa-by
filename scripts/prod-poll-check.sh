#!/usr/bin/env bash
# Что реально происходит с опросом банков прямо сейчас (#522, диагностика после переключения хоста).
#
# ⚠ Зачем отдельный скрипт, а не `grep` руками. Крон печатает строку планирования КАЖДЫЕ 5 минут,
# и она содержит слова `prior-by`/`alfa-by`. Любой греп по названию банка тонет в ней: за час это
# 12 длинных строк, за три часа — 36, и `tail -30` показывает только их, вытесняя ровно то, ради
# чего смотрели. Здесь сигнал разделён по секциям, а планирование исключено намеренно.
#
# Использование (из каталога со стеком):
#   bash prod-poll-check.sh          # за 3 часа
#   bash prod-poll-check.sh 30m      # за произвольное окно (формат docker: 30m, 2h, 1h30m)

set -u
SINCE="${1:-3h}"
# ⚠ Окно проверяется ДО первого обращения к docker. Неверное значение (`3d` — суток docker не
# принимает) иначе роняет КАЖДУЮ секцию по отдельности: все `docker compose logs` возвращают
# ошибку, все секции печатают «(ничего)», и на этом фоне тревога о продлении кричит о поломке,
# которой нет. Одна понятная строка вместо семи пустых и одной ложной.
case "${SINCE,,}" in
  *[!0-9smh]*|'') echo "✗ окно «$SINCE» docker не примет: только s/m/h, например 30m, 2h, 1h30m"; exit 2;;
esac

COMPOSE="docker-compose.prod.yml"
[ -f "$COMPOSE" ] || { echo "✗ $COMPOSE не найден — запускайте из каталога со стеком"; exit 1; }
DC="docker compose -f $COMPOSE"

section() { printf '\n\033[1m── %s ──\033[0m\n' "$1"; }

# Окно docker (`30m`, `2h`, `1h30m`, `90s`) → минуты. Нужно, чтобы отличить «продление не работает»
# от «окно короче его периода»: без этого короткий прогон `SINCE=30m` кричал бы об аварии впустую.
#
# ⚠ Регистр НЕ имеет значения, и это не косметика: владелец смотрит с мобильного терминала, где
# автокапитализация превращает `2h` в `2H`. С регистрозависимым разбором `2H` давала ноль, ветка
# тревоги не срабатывала, и вместо красного «продление не работало» печаталось успокаивающее
# «окно короче часа» — то есть скрипт врал ровно в том сценарии, ради которого написан.
#
# ⚠ Суток (`d`) в списке НЕТ намеренно: docker их не принимает («failed to parse value as time or
# duration: 3d»), и обещать их здесь значило бы звать оператора в тупик, где ВСЕ секции пусты (все
# `docker compose logs` падают), а эта — ещё и кричит о несуществующей аварии.
minutes_of() {
  local w="${1,,}" total=0 n u
  while [[ "$w" =~ ^([0-9]+)([smh])(.*)$ ]]; do
    n="${BASH_REMATCH[1]}"; u="${BASH_REMATCH[2]}"; w="${BASH_REMATCH[3]}"
    case "$u" in
      s) total=$(( total + n / 60 ));;
      m) total=$(( total + n ));;
      h) total=$(( total + n * 60 ));;
    esac
  done
  echo "$total"
}
# Печатает найденное или честное «ничего», чтобы пустая секция не читалась как обрыв вывода.
show() {
  local out; out="$(cat)"
  if [ -n "$out" ]; then echo "$out" | tail -"${1:-10}" | sed 's/^/  /'
  else printf '  \033[33m(ничего)\033[0m\n'; fi
}

echo "Окно: последние $SINCE"

section "Опросы, дошедшие до банка   [fetch]"
# Единственное безусловное доказательство, что банк ответил: провайдер, счёт, окно, число операций.
$DC logs --since "$SINCE" worker 2>&1 | grep -F '[fetch]' | show 12

section "Пауза автоопроса            [bank-connect]"
# ⚠ Третья причина «опрос пустой», и снаружи она НЕОТЛИЧИМА от первых двух (нет счетов /
# CRON_REAL_POLL=0): администратор клиента поставил подключение на паузу (#576). Разница в том, что
# чинится это в портале, а не у нас, — и без этой секции оператор шёл бы искать поломку на нашей
# стороне. Пусто здесь — норма: строка печатается только в момент переключения.
$DC logs --since "$SINCE" backend 2>&1 | grep -F 'автоопрос' | show 6

section "Итоги обработки             [crm-sync]"
# Безусловная строка на каждый прогон: сколько обработано/создано/приземлилось.
$DC logs --since "$SINCE" worker 2>&1 | grep -F '[crm-sync]' | show 8

section "Операции без результата     [op]"
# По умолчанию печатаются только НЕ приземлившиеся — то есть здесь либо пусто, либо проблема.
$DC logs --since "$SINCE" worker 2>&1 | grep -F '[op]' | show 8

section "ПАДЕНИЯ задач               [queue-job-failed] / [queue-worker-error]"
# ⚠ Самая важная секция. `FINAL` значит, что задача исчерпала все попытки и больше не повторится.
$DC logs --since "$SINCE" worker 2>&1 | grep -E '\[queue-job-failed\]|\[queue-worker-error\]' | show 12

section "Ретраи                      [queue-job-retry]"
# Единичные — норма (сеть). Поток одинаковых — уже симптом.
$DC logs --since "$SINCE" worker 2>&1 | grep -F '[queue-job-retry]' | show 8

section "Продление банк-токенов      [bank-keepalive]"
# ⚠ ЗДЕСЬ ПУСТО — ПЛОХО, и раньше эта подсказка утверждала обратное. Сводка прогона
# (`selected=… refreshed=… failed=… expired=…`) печатается БЕЗУСЛОВНО, раз в час, на каждом
# завершённом скане. Значит тишина за окно длиннее часа означает не «обновилось молча», а
# «продление не отработало НИ РАЗУ» — то есть ровно тот отказ (#504), из-за которого подключение
# Альфы и умирало за ночь. Подсказка, которая называет этот случай нормой, вредна именно тогда,
# когда на неё смотрят.
# ⚠ Маркера ДВА, и у второго другой префикс: `[queue] bank keep-alive run failed` печатается,
# когда упал сам список счетов ДО прогона. Симптом снаружи тот же — полная тишина по первому
# маркеру, — а причина другая, и греп только по `[bank-keepalive]` её не покажет (OPERATIONS.md).
ka="$($DC logs --since "$SINCE" worker backend 2>&1 | grep -E '\[bank-keepalive\]|bank keep-alive run failed')"
echo "$ka" | grep -v '^$' | show 8
if [ -z "$ka" ]; then
  # Окно короче часа ничего не доказывает: скан просто мог ещё не наступить.
  if [ "$(minutes_of "$SINCE")" -ge 70 ]; then
    printf '  \033[31m⚠ за %s не было НИ ОДНОГО прогона продления — оно запускается раз в час.\033[0m\n' "$SINCE"
    printf '    Проверьте, что крон-инстанс поднят (QUEUE_CRON) и процесс не падает при старте.\n'
  else
    printf '  \033[33m(окно короче часа — отсутствие строки ни о чём не говорит, продление ежечасное)\033[0m\n'
  fi
fi

section "КТО продлевает банк-токен  (#488/#489)"
# ⚠ Ради этой секции всё и затевалось. Подключение может жить, а ПОЧЕМУ — из факта его жизни не
# следует: токен обновляет и крон продления (#489), и сам опрос по дороге (`ensureFresh` →
# `ensureBankToken` в `bankFetch.ts`) — то есть ровно тот старый путь, который #488 назвал
# ненадёжным. Наблюдаемое «живёт шестые сутки» одинаково хорошо объясняется обоими, и спорить об
# этом бессмысленно: различает только сводка прогона, а не дела в CRM.
#
# Правило чтения, и оно не самоочевидно:
#   refreshed > 0            → крон РЕАЛЬНО продлевал. #489 работает.
#   selected = 0 везде       → крон ходил, но продлевать было НЕЧЕГО: токен ни разу не постарел до
#                              полосы обновления. Раз он при этом свежий — освежает его ОПРОС, и
#                              подключение держится ровно тем механизмом, который признан ненадёжным.
#   selected > 0, refreshed 0 → крон пытался и не смог: смотреть failed/expired выше.
sums="$($DC logs --since "$SINCE" worker backend 2>&1 \
  | grep -F '[bank-keepalive]' | grep -oE 'selected=[0-9]+ refreshed=[0-9]+' \
  | awk -F'[= ]' '{sel+=$2; ref+=$4; n++} END {print (n?n:0), (sel?sel:0), (ref?ref:0)}')"
runs="$(echo "$sums" | cut -d" " -f1)"; sel="$(echo "$sums" | cut -d" " -f2)"; ref="$(echo "$sums" | cut -d" " -f3)"
printf '  прогонов продления за %s: %s   отобрано: %s   реально продлено: %s\n' "$SINCE" "${runs:-0}" "${sel:-0}" "${ref:-0}"
if [ "${runs:-0}" -eq 0 ]; then
  printf '  \033[33m(вердикта нет: прогонов не было — см. секцию выше)\033[0m\n'
elif [ "${ref:-0}" -gt 0 ]; then
  printf '  \033[32m✔ ОТВЕТ: продлевает КРОН (#489). Механизм работает, #488/#489 закрываются замером.\033[0m\n'
elif [ "${sel:-0}" -eq 0 ]; then
  printf '  \033[31m⚠ ОТВЕТ: продлевает ОПРОС, а не крон.\033[0m\n'
  printf '    Крон отработал %s раз и ни разу никого не отобрал — значит токен всё время свежий,\n' "${runs:-0}"
  printf '    и освежает его опрос по дороге. Это ровно тот путь, который #488 назвал ненадёжным:\n'
  printf '    выключите опрос (CRON_REAL_POLL=0) — и подключение умрёт за срок refresh (~10 ч у Альфы).\n'
  printf '    ⚠ Окно короче суток тут слабое доказательство: берите SINCE=24h и больше.\n'
else
  printf '  \033[31m⚠ ОТВЕТ: крон отбирал счета, но НЕ продлил ни одного — смотрите failed/expired выше.\033[0m\n'
fi

section "ВОРОНКА платежа            (#501)"
# ⚠ Отвечает на вопрос «докуда дошёл платёж», который по отдельным секциям не собирается. Первый
# боевой прогон показал цену его отсутствия: транспорт отработал безупречно, 208 операций доехали,
# а до карточки не добрался НИ ОДИН — и узнали мы это из счётчиков в Postgres, а не из приложения.
#
# ⚠ Маркеры условны, и условия у них РАЗНЫЕ — на этом и держится диагностика:
#   [recognize] — распознан хоть один номер в назначении;
#   [resolve]   — распознан номер И найдена компания-клиент (без неё нет company-скоупа против
#                 IDOR, и поиск цели не запускается вовсе);
#   [allocate]  — плюс поиск реально что-то нашёл.
# Значит «recognize есть, resolve нет» — это НЕ поломка распознавания, а «клиент не опознан».
cnt() { $DC logs --since "$SINCE" worker backend 2>&1 | grep -cF "$1" || true; }
f_fetch=$(cnt '[fetch]'); f_op=$(cnt '[op]'); f_rec=$(cnt '[recognize]')
f_res=$(cnt '[resolve]'); f_all=$(cnt '[allocate]')
printf '  банк ответил      [fetch]      %s\n' "$f_fetch"
printf '  операций разобрано[op]         %s   (по умолчанию печатаются только НЕ приземлившиеся)\n' "$f_op"
printf '  номер распознан   [recognize]  %s\n' "$f_rec"
printf '  цель искали       [resolve]    %s\n' "$f_res"
printf '  цель нашли        [allocate]   %s\n' "$f_all"
if [ "$f_fetch" -eq 0 ]; then
  printf '  \033[31m⚠ ОБРЫВ на шаге 1: банк не отвечал или опрос не шёл — секции выше.\033[0m\n'
elif [ "$f_rec" -eq 0 ]; then
  printf '  \033[31m⚠ ОБРЫВ на шаге «распознавание»: ни в одном назначении не нашлось номера.\033[0m\n'
  printf '    Настройки → «Карта распознавания». Пустые матрицы = распознавать нечем.\n'
elif [ "$f_res" -eq 0 ]; then
  printf '  \033[31m⚠ ОБРЫВ на шаге «клиент»: номер распознан, а компания-плательщик НЕ найдена.\033[0m\n'
  printf '    Поиск цели без неё не запускается (company-скоуп против IDOR), поэтому платёж уходит\n'
  printf '    в фолбэк «моя компания». Лечится реквизитом контрагента в CRM, а не настройками.\n'
elif [ "$f_all" -eq 0 ]; then
  printf '  \033[33m⚠ ОБРЫВ на шаге «цель»: клиент найден, номер распознан, а счёта/сделки под него нет.\033[0m\n'
else
  printf '  \033[32m✔ цепочка проходит до конца\033[0m\n'
fi

section "Ошибки, упоминающие банк"
# Широкий невод на случай, если сломалось там, где своего маркера нет (TLS, DNS, отказ хоста).
$DC logs --since "$SINCE" worker backend 2>&1 \
  | grep -iE 'priorbank|crypto-gw|certificate|ECONNREFUSED|ENOTFOUND|ETIMEDOUT|self.signed' \
  | grep -v 'real poll' | show 12

section "Планирование крона (последняя строка)"
# Показываем ОДНУ для контекста: сколько счетов и какое окно. Остальные 36 копий не нужны.
# ⚠ Регулярка, а не -F: между каналом и текстом стоит УРОВЕНЬ (`[queue] INFO: real poll:`) —
# с #529 строку печатает логгер, а не console. Точную форму стережёт тест, который прогоняет
# ЭТОТ ЖЕ шаблон по строке, отрендеренной настоящим форматтером.
$DC logs --since "$SINCE" backend 2>&1 | grep -E '\[queue\][^:]*: real poll' | show 1

cat <<'HINT'

Как читать:
  • [fetch] есть, падений нет            → опрос работает, хост в порядке.
  • [fetch] НЕТ, падений НЕТ             → задачи не доходят до воркера: смотреть Redis
                                            (/api/ready → checks.redis) и что воркер поднят.
  • [fetch] НЕТ, есть FINAL-падения      → банк не отвечает или отвергает: текст ошибки в секции
                                            падений скажет, дело в TLS, DNS или отказе хоста.
  • [crm-sync] «0 создано» при живом [fetch] → банк отвечает, а в CRM не пишется: это уже
                                            настройка портала (реквизиты компаний), не транспорт.
  • [bank-keepalive] НЕТ за окно > часа   → продление не работает вовсе. Подключения доживут
                                            до конца срока refresh и умрут — у Альфы это ~10 часов.
  • секция «КТО продлевает» (#488/#489)   → отвечает словами. «Живёт шестые сутки» само по себе НЕ
                                            доказывает, что работает крон: тот же результат даёт
                                            опрос, обновляющий токен по дороге. Берите SINCE=24h.
HINT
