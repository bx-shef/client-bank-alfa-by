section "Автоотключение по подписке   (#614)"
# ⚠ Секция существует потому, что этот автомат — ЕДИНСТВЕННЫЙ, кто рвёт связь клиента с банком без
# участия человека, а докладывает он в тот же пассивный лог, который никто не читает без повода.
