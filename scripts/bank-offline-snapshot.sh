#!/usr/bin/env bash
# Оффлайн-копия работающих образов.
#
# Зачем: источник образов может исчезнуть — доступ к клиентскому репозиторию отозван,
# репозиторий удалён, GHCR недоступен. Работающие контейнеры это переживают, а вот
# ПЕРЕСОЗДАНИЕ контейнера (перезагрузка сервера с чисткой, ручной `up -d --force-recreate`,
# сбой диска) требует, чтобы образ был на месте. Копия закрывает этот случай независимо
# от того, как реестр поведёт себя после удаления репозитория.
#
# ⚠ Копируются образы РАБОТАЮЩИХ контейнеров, а не то, что записано в .env: именно они
# доказали свою работоспособность, а тег в файле мог уже уехать вперёд.
#
# Восстановление:  docker load -i <файл>.tar
#                  docker compose up -d
set -Eeuo pipefail

STACK_DIR="${1:-/home/bitrix/bank-import}"
OUT_DIR="${2:-/var/backups/bank-app}"

cd "$STACK_DIR" || { echo "нет каталога стека $STACK_DIR" >&2; exit 1; }
mkdir -p "$OUT_DIR"

images="$(docker compose ps -q | xargs -r docker inspect -f '{{.Config.Image}}' | sort -u)"
[ -n "$images" ] || { echo "стек не запущен — копировать нечего" >&2; exit 1; }

# Имя по дате: снимки не затирают друг друга, и видно, насколько копия свежая.
out="$OUT_DIR/bank-app-$(date +%Y%m%d-%H%M%S).tar"
echo "сохраняю в $out:"
printf '  %s\n' $images
# shellcheck disable=SC2086
docker save -o "$out" $images
chmod 600 "$out"
ls -lh "$out"

# Держим последние три. Больше не нужно: копия нужна на случай «источник исчез»,
# а не как история версий — история живёт в git и в реестре, пока они доступны.
ls -1t "$OUT_DIR"/bank-app-*.tar 2>/dev/null | tail -n +4 | xargs -r rm -f
