import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

// Гард операторского входа (замечание владельца, 2026-08-20).
//
// ⚠ `Makefile` — единственный интерфейс к серверу: репозитория там нет, только он, `.env` и
// `docker-compose.prod.yml`. Пока цель не описана и не видна в `make help`, оператор о ней не
// узнает и наберёт сырую команду руками — что и происходило: я раз за разом диктовал
// `docker compose …` и `curl … | bash` там, где уже была готовая цель.
//
// Ловушка не гипотетическая: описание `##` и сама цель разъезжаются молча. Вставь новый блок между
// ними — и цель пропадает из справки, оставаясь рабочей. Так уже случилось дважды за одну правку.

const ROOT = join(import.meta.dirname, '..')
const MAKEFILE = readFileSync(join(ROOT, 'Makefile'), 'utf8')

/** Цели, объявленные в файле (левая часть до двоеточия, в начале строки). */
function targets(): string[] {
  return [...MAKEFILE.matchAll(/^([a-z][a-z-]*):/gm)].map(m => m[1]!)
}

/** Цели, у которых описание `## …` стоит ВПЛОТНУЮ (тем же приёмом, что и `make help`: последняя
 *  строка `##` достаётся ближайшей следующей цели). */
function documented(): string[] {
  const out: string[] = []
  let desc = ''
  for (const line of MAKEFILE.split('\n')) {
    if (line.startsWith('## ')) desc = line.slice(3)
    else {
      const m = /^([a-z][a-z-]*):/.exec(line)
      if (m && desc) {
        out.push(m[1]!)
        desc = ''
      }
    }
  }
  return out
}

/** Цели, которые оператор набирает на СЕРВЕРЕ. Каждая обязана быть в `make help`. */
const OPERATOR = ['prod-up', 'prod-down', 'prod-pull', 'prod-redeploy', 'logs', 'ps',
  'doctor', 'queue-stats', 'prior-probe', 'prior-switch', 'poll-check', 'self-update', 'help',
  'gw-stop', 'gw-start', 'compose-update', 'alfa-page-probe']

/** Цели, которые запускают ИЗ РЕПОЗИТОРИЯ, а не с сервера — справка сервера их не касается. */
const SERVICE = ['dev', 'build-local']

describe('операторские цели Makefile видны в `make help`', () => {
  it('файл читается и цели находятся', () => {
    expect(targets().length).toBeGreaterThan(8)
    expect(targets()).toContain('doctor')
  })

  it('каждая операторская цель ОПИСАНА и попадёт в справку', () => {
    const shown = documented()
    for (const t of OPERATOR) {
      expect(targets(), `цели ${t} нет в Makefile`).toContain(t)
      expect(shown, `цель ${t} не попадёт в make help — описание оторвано от цели`).toContain(t)
    }
  })

  it('список операторских целей ЗАКРЫТ — новая обязана получить решение', () => {
    // ⚠ Без этого «закрытый список» закрывал только сам себя: он проверял, что ПЕРЕЧИСЛЕННЫЕ цели
    // описаны, и молчал о цели, которую в него не внесли. То есть ровно тот случай, ради которого
    // гард написан — новая цель, о которой оператор не узнает, — проходил зелёным. Замерено:
    // добавление цели в Makefile без правки списка не роняло ни одного теста.
    const unclassified = targets().filter(t => !OPERATOR.includes(t) && !SERVICE.includes(t))
    expect(unclassified, 'цель не отнесена ни к операторским, ни к служебным — решите, кто её запускает')
      .toEqual([])
  })

  it('`self-update` существует — без него остальные цели на сервер не доедут', () => {
    // ⚠ Корень исходной проблемы. Makefile кладётся на сервер один раз и дальше живёт своей
    // жизнью, поэтому новая цель в репозитории на сервере просто не существует.
    expect(MAKEFILE).toContain('self-update:')
    // Обновление обязано сохранять копию и проверять скачанное ДО замены: битый Makefile лишает
    // сервер единственного интерфейса. Чем именно проверяет — в отдельном тесте ниже.
    // ⚠ Проверяется САМА КОМАНДА копирования, а не строка `Makefile.bak-`: та встречается ещё и в
    // присваивании переменной, и в тексте echo, поэтому вырезанный `cp` мутацию переживал —
    // `self-update` перестал бы сохранять копию, а тест этого не замечал.
    expect(MAKEFILE, 'self-update не копирует прежний Makefile').toMatch(/cp \.\/Makefile "\$\$b"/)
  })

  it('обновляющие цели проверяют скачанное ДО замены', () => {
    // ⚠ Обе тянут файл, от которого зависит управляемость сервера. Битый ответ прокси (HTML вместо
    // файла) молча оставил бы стенд без рабочего Makefile или без валидного compose — и выяснилось
    // бы это в следующий раз, когда что-то понадобится срочно.
    const su = MAKEFILE.slice(MAKEFILE.indexOf('\nself-update:'), MAKEFILE.indexOf('\n## Остановить крипто-шлюз'))
    expect(su, 'self-update не проверяет скачанное').toMatch(/grep -q '\^\\\.PHONY:'/)
    // ⚠ Проверка обязана переживать ЛЮБУЮ версию файла: первая редакция сверялась по цели `help`,
    // добавленной той же правкой, и bootstrap на живом сервере отказался ставить обновление,
    // потому что для установки новой цели ему требовалась новая цель.
    expect(su, 'self-update сверяется по свежей цели, а не по давней').toMatch(/prod-redeploy/)
    expect(su).not.toMatch(/make -n -f "\$\$t" help/)
    const cu = MAKEFILE.slice(MAKEFILE.indexOf('\ncompose-update:'))
    expect(cu, 'compose-update не валидирует compose').toMatch(/config -q/)
    // Замена только по явному подтверждению: файл правят руками, слепая замена уничтожила бы
    // настройку, о которой никто не помнит.
    // ⚠ Пинится САМО УСЛОВИЕ, а не упоминание переменной: слово `CONFIRM` встречается ещё и в
    // подсказке «Применить: make compose-update CONFIRM=1», поэтому проверка на вхождение
    // проходила даже при условии, выключённом в `if true` (поймано мутацией).
    expect(cu, 'compose-update заменяет без подтверждения').toMatch(/if \[ "\$\(CONFIRM\)" = "1" \]; then/)
    // ⚠ И условия МАЛО. Второе мутационное ревью показало обход, которого срез не видит вовсе:
    // `CONFIRM ?= 1`, объявленный ГДЕ УГОДНО выше по файлу, делает подтверждение значением по
    // умолчанию — и `make compose-update` без единого аргумента начинает заменять боевой compose.
    // Проверка среза этого не ловит по построению, поэтому смотрим на ВЕСЬ файл.
    expect(MAKEFILE, 'CONFIRM объявлен переменной — подтверждение стало умолчанием')
      .not.toMatch(/^\s*CONFIRM\s*[?:+]?=/m)
    expect(cu).toMatch(/\.bak-/)
    // ⚠ Диф НЕ обрезается. Первая редакция резала его на 80-й строке, а один только блок
    // `crypto-gw` даёт больше семидесяти строк YAML — хвост уходил за срез МОЛЧА, и оператор
    // подтверждал замену, не увидев её половины. Обрезанная страховка хуже отсутствующей.
    expect(cu, 'диф компоуза обрезается — оператор не увидит хвост').not.toMatch(/sed -n '\d+,\d+p'/)
    expect(cu, 'не печатает размер дифа').toMatch(/строк \(- сервер/)
  })

  it('REF НЕ задаётся из командной строки — это вектор исполнения кода', () => {
    // ⚠ Проверено вживую (ревью безопасности): `make -n doctor REF='$(shell touch pwned)'`
    // ВЫПОЛНЯЕТ код — при `-n`, то есть в режиме «только показать»: раскрытие макроса происходит до
    // всякого шелла и до curl. А `REF='../../чужой/репозиторий/main'` уводит скачивание в чужой
    // публичный репозиторий: curl схлопывает `/../` в пути САМ, до отправки запроса.
    // ⚠ Передача через окружение НЕ спасает: присваивание раскрывает значение так же. Раскрытие и
    // есть исполнение — единственная надёжная защита в том, чтобы переменную нельзя было задать.
    expect(MAKEFILE, 'REF снова задаётся снаружи').toMatch(/^override REF := main$/m)
    expect(MAKEFILE, 'REF объявлен переопределяемым').not.toMatch(/^REF\s*[?:]?=/m)
  })

  it('валидация compose ищет .env В КАТАЛОГЕ ПРОЕКТА, а не рядом с временным файлом', () => {
    // ⚠ Проверено исполнением (ревью-программист): `docker compose -f /tmp/… config -q` берёт
    // «project directory» от каталога файла `-f`, поэтому обязательные интерполяции `${VAR:?}`
    // не резолвятся и валидация проваливалась ВСЕГДА — цель была нерабочей полностью, ещё до
    // показа дифа. Текстовым чтением это не ловится, только запуском.
    expect(MAKEFILE, 'compose-update снова валидирует без --project-directory')
      .toMatch(/docker compose --project-directory \. -f "\$\$t" config -q/)
  })

  it('замена файла НЕ происходит, если бэкап не удался', () => {
    // ⚠ Было `cp бэкап; cp замена` через `;` — падение бэкапа (диск полон, права) не мешало
    // замене, и скрипт ещё и печатал «копия прежнего: …», которой не существует.
    for (const [name, block] of [
      ['self-update', MAKEFILE.slice(MAKEFILE.indexOf('\nself-update:'), MAKEFILE.indexOf('\n## Остановить крипто-шлюз'))],
      ['compose-update', MAKEFILE.slice(MAKEFILE.indexOf('\ncompose-update:'))]
    ] as Array<[string, string]>) {
      // ⚠ Проверяется, что между копированием бэкапа и заменой стоит `&&`, а не `;` — на той же
      // строке или через продолжение, форма не важна, важна связь.
      expect(block, `${name}: бэкап и замена соединены ; вместо &&`)
        .toMatch(/cp [^\n]*"\$\$b"\s*(?:\\\n\s*)?&& cp "\$\$t"/)
    }
  })

  it('временные файлы удаляются по trap во ВСЕХ скачивающих целях', () => {
    // Иначе на сервере копятся /tmp/Makefile.XXXXXX при каждом запуске.
    const downloaders = [...MAKEFILE.matchAll(/^([a-z][a-z-]*):\n(?:\t.*\n)+/gm)]
      .filter(m => m[0].includes('curl -fsSL'))
    expect(downloaders.length).toBeGreaterThan(4)
    for (const m of downloaders) {
      expect(m[0], `${m[1]}: нет trap на удаление временного файла`).toMatch(/trap 'rm -f "\$\$t"' EXIT/)
    }
  })

  it('TO= сопоставляется с ФЛАГОМ, а не просто упоминается', () => {
    // ⚠ Оба литерала `--to-direct` и `--to-gateway` есть в файле при любой перестановке, поэтому
    // проверка на вхождение инверсию не ловит. А перепутанное сопоставление означает, что
    // `make prior-switch TO=direct` в момент инцидента ВКЛЮЧИТ шлюз вместо отключения.
    expect(MAKEFILE).toMatch(/"\$\(TO\)" = "direct" \] && a="--to-direct"/)
    expect(MAKEFILE).toMatch(/"\$\(TO\)" = "gateway" \] && a="--to-gateway"/)
  })

  it('цели, зовущие скрипты, тянут их из того же REF', () => {
    // Иначе `self-update` обновит Makefile из одной ветки, а скрипты приедут из другой.
    // ⚠ Перебираем ВСЕ скачивающие цели, а не три названные руками: список из трёх имён устаревал
    // молча — новая цель качала бы скрипт откуда угодно, и тест этого не видел.
    // ⚠ Проверяем `$(REF)`, а не `$(RAW)`: `self-update` тянет сам Makefile из КОРНЯ репозитория,
    // а `$(RAW)` указывает в `scripts/`, так что требовать его от него было бы неверно. Общий
    // инвариант — одна и та же ветка, и `$(RAW)` её в себе и содержит.
    const downloaders = [...MAKEFILE.matchAll(/^([a-z][a-z-]*):\n(?:\t.*\n)+/gm)]
      .filter(m => m[0].includes('curl -fsSL'))
    expect(downloaders.length).toBeGreaterThan(4)
    for (const m of downloaders) {
      // ⚠ Смотрим на САМУ строку curl, а не на тело цели: в теле есть ещё `@echo "… из $(REF)"`,
      // и проверка по всему телу зеленела на этом echo при захардкоженной чужой ветке в curl.
      // Замерено мутацией — подмена URL в curl тест НЕ роняла.
      const curlLine = m[0].split('\n').find(l => l.includes('curl -fsSL'))!
      expect(curlLine, `${m[1]!} качает не из $(REF)`).toMatch(/\$\(RAW\)|\$\(REF\)/)
    }
  })
})
