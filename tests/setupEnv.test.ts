import { describe, expect, it } from 'vitest'

// Гард самого сетапа (#498): он обязан УДАЛЯТЬ переменные, а не подменять их строкой.
//
// ⚠ Заведён потому, что первая версия сетапа делала `process.env[name] = undefined`, и это
// проходило бы все тесты, оставляя переменную заданной со значением `"undefined"` (в Node
// присваивание приводит к строке). Совпадение спасало: `=== '1'` ложно, а мусор в
// `resolveOpLogMode` даёт `notable`. Следующий флаг с другим разбором на таком совпадении сломался
// бы молча — и искали бы в коде, а не в сетапе тестов.
describe('детерминированное окружение юнит-тестов', () => {
  it('флаги, читаемые на загрузке модуля, ОТСУТСТВУЮТ, а не равны строке «undefined»', () => {
    for (const name of ['STATEMENT_DEBUG_LOG', 'STATEMENT_OP_LOG']) {
      expect(name in process.env).toBe(false)
      expect(process.env[name]).toBeUndefined()
    }
  })
})
