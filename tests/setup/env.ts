// Детерминированное окружение для юнит-тестов (#498).
//
// ⚠ Зачем это существует. Часть модулей читает переменные окружения ОДИН РАЗ при загрузке —
// `const STATEMENT_DEBUG_LOG = process.env.STATEMENT_DEBUG_LOG === '1'` и его близнец
// `OP_LOG_MODE` в `server/queue/worker.ts`. Это осознанно (смена режима = перезапуск процесса, а
// не рантайм-ручка), но у такой формы есть побочный эффект: тест, проверяющий поведение по
// умолчанию, начинает зависеть от того, что выставлено в оболочке разработчика или на раннере.
//
// Замерено на этой самой ветке: `STATEMENT_OP_LOG=off pnpm vitest …` роняет два теста
// `liveHandlerDeps`, а `STATEMENT_DEBUG_LOG=1` — один. Причём второй флаг существовал ДО и был
// уязвим ровно так же, просто никто не проверял. Красный прогон при этом выглядит как настоящая
// поломка кода, и искать будут в коде, а не в своём `.env`.
//
// ⚠ Поэтому список — ИМЕНОВАННЫЙ, а не «почистим всё, что похоже на флаг». Тесты имеют полное
// право сами выставлять переменные (`checkBackendEnv` принимает окружение параметром, банковские
// креды подставляются явно); слепая чистка сломала бы их и заменила бы одну недетерминированность
// другой. Здесь только те флаги, которые читаются на загрузке модуля и меняют НАБЛЮДАЕМОЕ
// поведение в юнит-тестах.
//
// Заводя следующий такой флаг — добавь его сюда же.
// ⚠ `Reflect.deleteProperty`, а НЕ `process.env[name] = undefined`. Присваивание кладёт в
// переменную СТРОКУ `"undefined"` (проверено: `typeof process.env.X === 'string'`), то есть
// переменная остаётся заданной, просто с мусорным значением. Сегодня это сработало бы случайно
// (`=== '1'` ложно, `resolveOpLogMode('undefined')` даёт `notable` по ветке мусора), но держится
// на совпадении: любой будущий флаг с другим разбором получил бы строку там, где ожидает
// отсутствие. Прямой `delete` запрещён линтером на вычисляемом ключе — `Reflect` делает ровно то
// же самое и проходит.
const READ_AT_MODULE_LOAD = ['STATEMENT_DEBUG_LOG', 'STATEMENT_OP_LOG'] as const

for (const name of READ_AT_MODULE_LOAD) Reflect.deleteProperty(process.env, name)
