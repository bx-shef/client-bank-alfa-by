import { describe, expect, it } from 'vitest'
import { DEFAULT_LOCK_WAIT, MIN_LOCK_WAIT, resolveLockWait, SINGLE_FLIGHT_LOCK_WAIT } from '../server/utils/dbLock'

// ⚠ Гард ловушки в семантике самого Postgres: `lock_timeout = 0` ОТКЛЮЧАЕТ таймаут, то есть
// означает «ждать вечно», а не «не ждать». Это ровно наоборот тому, что имеет в виду тот, кто
// пишет `lockWait: '0'`, и отказ при этом тихий и тяжёлый: вместо быстрого «занято» ожидающий
// занимает соединение из пула (пул — 10) до конца работы держателя. Из этого же пула берут
// readiness-проба, события установки и все остальные порталы.

describe('ожидание advisory-лока (#516)', () => {
  it('пусто/не задано → умолчание для машинных вызывающих', () => {
    expect(resolveLockWait(undefined)).toBe(DEFAULT_LOCK_WAIT)
    expect(resolveLockWait('')).toBe(DEFAULT_LOCK_WAIT)
    expect(resolveLockWait('   ')).toBe(DEFAULT_LOCK_WAIT)
  })

  it('ЛЮБОЕ написание нуля превращается в минимальное ожидание, а не в «вечно»', () => {
    // ⚠ Список замерен на ЖИВОМ Postgres 16 (`set_config('lock_timeout', …)`), а не придуман: все
    // эти строки он принимает и все они значат одно — таймаут отключён, ждать вечно. Прежний гард
    // перечислял написания регуляркой и проигрывал каждому, которого в списке не оказалось: `+0`,
    // `-0`, `0.0s`, `.0s`, `0e0`, `0x0`, `0d` проходили насквозь. Поэтому ноль теперь РАЗБИРАЕТСЯ,
    // а тест держит именно те формы, на которых чёрный список сломался.
    const zeros = [
      '0', '00', '0s', '0ms', '0 s', '0min', '0h', '0d',
      ' 0 ', // ⚠ внешние пробелы: единственная защита — `.trim()` ДО разбора, и её надо закрепить
      '+0', '-0', // знак
      '0.0s', '0.0', '0.s', '.0s', '0.00', // десятичная точка
      '0e0', '0x0' // научная нотация и hex — `Number()` понимает обе, регулярка не понимала
    ]
    for (const zero of zeros) {
      expect(resolveLockWait(zero), `«${zero}» пропущено как есть — это «ждать вечно»`).toBe(MIN_LOCK_WAIT)
    }
  })

  it('нераспознанное значение проходит НАСКВОЗЬ — Postgres обязан отвергнуть его громко', () => {
    // ⚠ Подставить умолчание вместо опечатки значит превратить `10sec` в рабочий маршрут с
    // ожиданием в 100 мс: тихо и неверно. Ошибка на `SET lock_timeout` видна оператору сразу.
    for (const junk of ['10sec', '0 seconds', '00:00:00', 'abc']) {
      expect(resolveLockWait(junk)).toBe(junk)
    }
  })

  it('нормальные значения проходят как есть', () => {
    for (const v of ['2s', '10s', '500ms', '1min']) expect(resolveLockWait(v)).toBe(v)
  })

  it('минимум — не ноль', () => {
    // Иначе гард возвращал бы ровно ту величину, от которой защищает.
    expect(MIN_LOCK_WAIT).not.toMatch(/^0+/)
  })

  it('ожидание для долгих single-flight операций — короткое, но НЕ нулевое', () => {
    // ⚠ Рантайм от нуля защищён (`resolveLockWait` переводит его в минимум), поэтому мутация
    // «сделать константу нулём» и выжила. Но константа со значением, которое ЧИТАЕТСЯ как «не
    // ждать», а в Postgres значит «ждать вечно», вводит в заблуждение того, кто её правит следом.
    expect(SINGLE_FLIGHT_LOCK_WAIT).not.toMatch(/^0+\s*(ms|s|min|h)?$/)
    // И короткое: держатель здесь работает десятки секунд, ждать его бессмысленно, а ожидающий
    // всё это время занимает соединение из пула (пул — 10).
    expect(resolveLockWait(SINGLE_FLIGHT_LOCK_WAIT)).toBe(SINGLE_FLIGHT_LOCK_WAIT)
    expect(SINGLE_FLIGHT_LOCK_WAIT).toMatch(/^[1-3]s$|^\d{3,4}ms$/)
  })
})
