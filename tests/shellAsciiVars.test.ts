import { describe, expect, it } from 'vitest'
import { readFileSync, globSync } from 'node:fs'
import { join } from 'node:path'

// Гард: имена переменных в шелл-скриптах — только латиницей (#488, поймано боевым прогоном).
//
// ⚠ Не вкусовщина. `bash` в общем случае не принимает кириллическое имя переменной: на боевом
// стенде `акк=~pending:…` дало `command not found`, а `${акк:0:6}` — `bad substitution`, и строка
// подключения не отобразилась вовсе. Хуже всего, что скрипт при этом НЕ упал: он продолжил
// работать с пустым значением, то есть диагностика молча показала не то.
//
// ⚠ Русский текст в скриптах при этом ОСТАЁТСЯ — его читает владелец. Ограничение только на имена
// переменных и на подстановки, то есть на то, что исполняет шелл.

const ROOT = join(import.meta.dirname, '..')
const FILES = globSync('scripts/*.sh', { cwd: ROOT })

/**
 * Присваивание имени с не-ASCII символом либо подстановка такого имени.
 *
 * ⚠ Диапазон задан от печатаемого пробела, а не от `\x00`: управляющий символ в регулярке ESLint
 * запрещает (`no-control-regex`), а для нашей задачи он и не нужен — имя переменной из управляющих
 * символов состоять не может.
 */
const NON_ASCII_ASSIGN = /^\s*[^\u0020-\u007F][^=\s]*=/
const NON_ASCII_SUBST = /\$\{?[^\u0020-\u007F]/

describe('шелл-скрипты: имена переменных латиницей (#488)', () => {
  it('скрипты найдены — иначе гард охранял бы пустоту', () => {
    expect(FILES.length).toBeGreaterThan(3)
  })

  for (const f of FILES) {
    it(`${f}: нет нелатинских имён переменных`, () => {
      const bad: string[] = []
      readFileSync(join(ROOT, f), 'utf8').split('\n').forEach((line, i) => {
        if (NON_ASCII_ASSIGN.test(line) || NON_ASCII_SUBST.test(line)) bad.push(`${f}:${i + 1}`)
      })
      expect(bad, 'bash не принимает такое имя — значение молча теряется').toEqual([])
    })
  }
})
