import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

// Гард полноты: всё, что сервер кладёт в `/api/setup-status`, обязано доехать до клиента.
//
// ⚠ Заведён по РЕАЛЬНОЙ потере, а не «на всякий случай». `useSetupStatus.load()` пересобирает
// состояние по полям (сервер отдаёт `Partial`, доверять форме нельзя — это верно), и три поля
// молча не переносились:
//   • `pausedAccounts` — раздел «Очистка» видел 0 и предупреждал «опрос идёт» при ВСЕХ подключениях
//     на паузе;
//   • `unhealthyAccounts` — которого не было даже в клиентском типе, то есть счётчик нерабочих
//     подключений (#504) не показывался ни разу;
//   • `myCompany` — строка «моя компания» (#493) на экране готовности не рисовалась вовсе.
//
// ⚠ Ни один тест этого не ловил, потому что каждая сторона по отдельности корректна: сервер честно
// отдаёт, чистый `setupReadiness` честно читает, а теряется оно РОВНО в шве между ними. Такой шов
// и стережём — текстом, потому что типов тут нет: ответ приходит как `Partial<SetupStatus>` через
// сеть, и компилятор его не видит.
//
// ⚠ Смотрим ИМЕННО В ЛИТЕРАЛ присваивания, а не в файл целиком. Первая редакция искала имя поля по
// всему тексту клиента — и была ДЕКОРАЦИЕЙ: замерено мутацией, удаление `pausedAccounts` из
// маппинга оставило тест зелёным, потому что имя поля упоминается в соседнем комментарии,
// объясняющем эту самую потерю. Гард, который проходит на сломанном коде из-за собственной
// документации, хуже отсутствующего: он создаёт уверенность.
//
// ⚠ Проверка текстовая, и это её признанная слабость: она не увидит поле, переданное как
// `res['x']`, и не отличит перенос от переименования. Взамен она ловит ЕДИНСТВЕННЫЙ способ, которым
// эта потеря случается на практике — поле добавили на сервере и забыли в литерале клиента.

const SERVER = readFileSync('server/utils/setupStatus.ts', 'utf8')
const CLIENT = readFileSync('app/composables/useSetupStatus.ts', 'utf8')

/**
 * Тело присваивания `status.value = { … }` — только оно и есть перенос ответа в состояние.
 *
 * ⚠ КОММЕНТАРИИ ВЫРЕЗАЮТСЯ, и это не аккуратность. Замерено дважды: сперва гард смотрел в файл
 * целиком и проходил на сломанном коде, потому что имена полей упоминались в соседнем комментарии;
 * сузили до литерала — и он прошёл СНОВА, потому что тот же поясняющий комментарий стоит ВНУТРИ
 * литерала. Пока в тексте, по которому ищем, может оказаться проза, гард проверяет прозу, а не код.
 */
function clientMapping(): string {
  const start = CLIENT.indexOf('status.value = {')
  expect(start, 'в useSetupStatus.ts не найден литерал состояния — гард ослеп, почини его').toBeGreaterThan(0)
  const end = CLIENT.indexOf('\n      }', start)
  expect(end, 'литерал состояния не закрыт — гард ослеп').toBeGreaterThan(start)
  return CLIENT.slice(start, end)
    .split('\n')
    .filter(line => !line.trim().startsWith('//'))
    .join('\n')
}

/** Поля ответа `/api/setup-status`, собранные из серверного билдера тела. */
function serverFields(): string[] {
  // Тело ответа собирается одним литералом `body: { … }`; берём его и вытаскиваем ключи.
  const start = SERVER.indexOf('body: {')
  expect(start, 'в setupStatus.ts не найден литерал тела ответа — гард ослеп, почини его').toBeGreaterThan(0)
  const chunk = SERVER.slice(start, SERVER.indexOf('\n    }', start))
  const keys = [...chunk.matchAll(/^\s{6}(?:\.\.\.\(\w+\?\s*\{\s*)?([a-zA-Z][a-zA-Z0-9]*)\s*:/gm)].map(m => m[1]!)
  return [...new Set(keys)]
}

describe('поля /api/setup-status доезжают до клиента', () => {
  it('гард сам себя не обманывает — список полей не пуст', () => {
    // Без этой проверки регулярка, переставшая что-либо находить, сделала бы тест вечнозелёным.
    const fields = serverFields()
    expect(fields.length).toBeGreaterThanOrEqual(5)
    expect(fields).toContain('connectedAccounts')
  })

  it('литерал состояния найден и не пуст — иначе гард снова декорация', () => {
    const mapping = clientMapping()
    expect(mapping).toContain('connectedAccounts')
    expect(mapping.length).toBeGreaterThan(100)
  })

  it('каждое поле сервера переносится В ЛИТЕРАЛ состояния', () => {
    const mapping = clientMapping()
    const missing = serverFields().filter(f => !mapping.includes(f))
    expect(missing, `клиент теряет поля ответа: ${missing.join(', ')}`).toEqual([])
  })

  it('поля, из-за которых гард и написан, на месте поимённо', () => {
    // ⚠ Поимённо, а не только «список сошёлся»: у каждого своя жертва на экране, и регрессия
    // любого из трёх выглядит как «функция просто не работает», а не как ошибка.
    const mapping = clientMapping()
    // ⚠ `recognitionMisconfig` (#595) и `myCompany` уходят spread-условием (`...(x ? {…} : {})`),
    // а `serverFields()` его регуляркой не ловит (пробел перед `?`) — то есть автоматическая
    // половина гарда их не видит. Поэтому держим их ПОИМЕННО здесь: иначе поле, ради переноса
    // которого гард и написан, осталось бы без охраны.
    for (const field of ['pausedAccounts', 'unhealthyAccounts', 'myCompany', 'recognitionMisconfig']) {
      expect(mapping, `клиент снова потерял ${field}`).toContain(field)
    }
  })
})
