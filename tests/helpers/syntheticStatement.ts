// Общая проверка «этот файл выписки — синтетика, а не данные клиента».
//
// ⚠ ЖИВЁТ В ОДНОМ МЕСТЕ, и это не борьба с дублированием ради красоты. Гардов ДВА (публичные
// примеры `public/samples/` и фикстуры `tests/fixtures/`), они защищают одно и то же, а написаны
// были порознь — и разошлись немедленно: замерено ревью, что версия для фикстур пропускала
// название организации, УНП, телефон и счёт контрагента, потому что проверяла только форму счёта
// и чёрный список из семи слов, уже однажды утекавших. То есть слабая копия покрывала ровно тот
// каталог, куда файлы кладут чаще.
//
// ⚠ Репозиторий ПУБЛИЧНЫЙ. Утечка здесь — не «некрасивый тест», а публикация финансовых ПДн.

/** УНП, которые встречаются в синтетических примерах и фикстурах.
 *
 * ⚠ Список ЗАКРЫТЫЙ и проверяется ПО НЕМУ, а не маской: структурно настоящий и выдуманный УНП
 * неотличимы — обе девятизначные. Список заставляет автора нового примера ОСТАНОВИТЬСЯ и внести
 * номер руками — ровно тот момент, в который и надо спросить себя, откуда этот номер взялся. */
export const DEMO_UNPS = new Set([
  '100000000', '100000001', '100000002', '100000003', '100000004', '100777001',
  '190000000', '190000001', '190000002', '190000004', '190000005',
  '191009988', '191234567', '191667788',
  '200000001', '200000002', '200000003', '200000004'
])

/**
 * Номера счетов, найденные в тексте выписки.
 *
 * ⚠ Ищем на копии БЕЗ ПРОБЕЛОВ, и это несущее: Приорбанк пишет счёт контрагента как
 * `BY69 PJCB3012 0822301000000933`, а маска по сырому тексту такой счёт не видит вовсе. Замерено:
 * на боевой фикстуре маска по сырому тексту находила 1 счёт из 3, и невидимы ей были ровно счета
 * КОНТРАГЕНТОВ — то есть те, в которых и лежали бы чужие реквизиты.
 * ⚠ Вторая маска — голый 20-значный счёт: так их пишет формат 1С. Она идёт по СЫРОМУ тексту с
 * границами слова: на склеенной копии она поймала бы любой достаточно длинный хвост цифр.
 */
export function findAccounts(text: string): string[] {
  const flat = text.replace(/\s+/g, '')
  return [
    ...(flat.match(/BY\d{2}[A-Z]{4}[0-9A-Z]{20}/gi) ?? []),
    ...(text.match(/\b\d{20}\b/g) ?? [])
  ]
}

/**
 * Уронить тест, если файл похож на настоящую выписку.
 *
 * `label` — имя файла для сообщения; `text` — уже ДЕКОДИРОВАННЫЙ текст (выписки бывают в
 * windows-1251 и CP866, и проверка по сырым байтам смотрела бы мимо кириллицы).
 *
 * `expect` инъектируется, чтобы модуль оставался чистым и не тянул vitest в свой импорт.
 */
export function assertSyntheticStatement(
  label: string,
  text: string,
  expect: (value: unknown, message?: string) => {
    toEqual: (v: unknown) => void
    toMatch: (v: RegExp) => void
    toBeGreaterThan: (v: number) => void
    not: { toMatch: (v: RegExp) => void }
  }
): void {
  const accounts = findAccounts(text)
  // ⚠ Файл без единого счёта проверку НЕ проходит: пустой список иначе означал бы «нарушений
  // нет» ровно там, где маска перестала совпадать с форматом.
  expect(accounts.length, `${label}: счетов не найдено — маска разошлась с форматом`)
    .toBeGreaterThan(0)
  for (const a of accounts) {
    // Синтетический счёт узнаётся по длинной нулевой серии (у настоящего белорусского такой не
    // бывает) либо по прямой пометке DEMO в коде банка.
    expect(a, `${label}: ${a} не похож на синтетический`).toMatch(/0{10}|DEMO/i)
  }

  // Название организации ищем ТОЛЬКО В КАВЫЧКАХ: в выписке оно всегда закавычено (`ООО "…"`), а
  // вне кавычек той же формы бывают имена полей формата 1С («ВерсияФормата», «ДатаНачала») — они
  // к клиенту отношения не имеют. Признак настоящего названия — слипшийся CamelCase
  // («ТехноСервис»); демо-имена так не выглядят («Ромашка», «ДЕМОКЛИЕНТ»).
  // ⚠ Настоящего названия клиента нет и в ЭТОМ комментарии: привести его «для наглядности»
  // значило бы опубликовать ровно то, что мы прячем.
  const quoted = [...text.matchAll(/["«]([^"»]{2,60})["»]/g)].map(m => m[1]!)
  const proper = quoted.filter(q => /[А-ЯЁ][а-яё]+[А-ЯЁ]/.test(q))
  expect(proper, `${label}: похоже на настоящее название организации`).toEqual([])

  const unps = [...new Set(text.match(/\b\d{9}\b/g) ?? [])].filter(u => !DEMO_UNPS.has(u))
  expect(unps, `${label}: УНП не из списка демо-значений — откуда он?`).toEqual([])

  expect(text, `${label}: похоже на телефон`).not.toMatch(/\+375\d{9}/)
  expect(text, `${label}: похоже на e-mail`).not.toMatch(/[\w.-]+@[\w.-]+\.[a-z]{2,}/i)
}
